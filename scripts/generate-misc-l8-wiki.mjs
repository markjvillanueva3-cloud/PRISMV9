function renderCombo(n, gen) {
  const inputs = (n.inputs || []);
  const target = n.target || "(unknown)";
  const targetName = slug(String(target).split(".").pop());
  const inputRows = inputs.length
    ? inputs.slice(0, 25).map((id) => `- \`${id}\``).join("\n") + (inputs.length > 25 ? `\n- … +${inputs.length - 25} more` : "")
    : "_(no input list in graph)_";
  const xl = crossLinks(n);
  return `---
title: Combo synthesizer — ${cleanLabel(n.label)}
type: architecture
node_id: ${n.id}
parent_layer: L8
kind: combo
target_engine: ${target}
input_count: ${inputs.length}
status: ${n.status || "ghost"}
generated_by: scripts/generate-misc-l8-wiki.mjs
last_verified: ${gen}
tags: [architecture, system-viz, combo, synthesizer, fan-in]
related:
  - knowledge/wiki/architecture/layer-l8.md
  - knowledge/wiki/architecture/${targetName}.md
---

# Combo synthesizer — \`${cleanLabel(n.label)}\`

> A synthesizer engine that fans in from ${inputs.length} other engines. This is a **ghost** node — it represents an existing high-fan-in engine flagged for an explicit aggregation contract.

${AUTO_START}

| Field | Value |
|-------|-------|
| Node ID | \`${n.id}\` |
| Target engine | [[${targetName}]] (\`${target}\`) |
| Input engines | ${inputs.length} |
| Status | ${n.status || "ghost"} |
| Parent layer | [[layer-l8]] |

## Input engines (sample of 25)

${inputRows}

## Why this is flagged

A combo node is emitted when an engine consumes ≥10 other engines without a
declared aggregation/weighting policy. Risk: silent drift — if one input engine
degrades, the synthesizer has no inverse-variance or confidence weighting to
down-rank it. Fix: give the target engine an explicit fusion contract (Kalman /
inverse-variance ensemble, or a documented priority order).

${xl.length ? `## Related wiki entries\n\n${xl.join("\n")}` : ""}

${AUTO_END}

## See also

- L8 layer: [[layer-l8]]
- Target engine: [[${targetName}]]
`;
}

