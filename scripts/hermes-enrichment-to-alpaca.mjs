// U-HERMES-LORA-CORPUS (slot:india 2026-06-30).
//
// THE GAP IT CLOSES (same producer-alive/consumer-dead pattern just fixed for the
// tribal surfaces in U-HERMES-TRIBAL-INJECT): hermes-domain-enrichment-loop.mjs
// runs 6 parallel Grok agents and emits cited per-domain rules to staging
// (state/shared/staging/hermes-enrichment-loop-tips.json, capture-tip schema), but
// the fleet LoRA training corpus never consumed them -- assemble-fleet-lora-corpus.mjs
// pulls ONLY lora-training-jsonl sources registered in build-fleet-training-corpus-
// inventory.mjs, and the capture-tip staging had no Alpaca converter + no registration.
// This converts the staged rules to Alpaca {instruction,output} pairs and writes a
// lora-training-jsonl the inventory registers, so the Hermes per-domain knowledge
// reaches the "lora/qlora" surface (the work order's named target).
//
// SFT framing (non-degenerate -- gated by lora-corpus-quality-check.mjs):
//   instruction = domain + the rule's TOPIC (the title) + ask for specifics + source
//   output      = the body's formula/threshold detail + the real citation
// Each tip's title is distinct, so every instruction is unique (no contradiction); the
// output ADDS the formula/threshold + cite beyond the instruction (genuine recall task,
// not an echo). Unreviewed-cron advisory knowledge -> trained as recall, never a gate
// (consumers of the LoRA adapter are advisory, same boundary as the tribal lane).
//
// Pure / deterministic / idempotent (re-run regenerates the same jsonl from staging).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const STAGING = path.join(ROOT, "state", "shared", "staging", "hermes-enrichment-loop-tips.json");
export const OUT = path.join(ROOT, "state", "shared", "lora", "hermes-enrichment-dataset.jsonl");

/** Domain from a capture-tip's `domain:<x>` tag (fallback `category`, then "general"). */
export function tipDomain(tip) {
  const tags = Array.isArray(tip && tip.tags) ? tip.tags : [];
  for (const t of tags) {
    const m = /^domain:(.+)$/.exec(String(t || "").trim());
    if (m) return m[1].toLowerCase();
  }
  return (tip && typeof tip.category === "string" && tip.category.trim()) ? tip.category.trim().toLowerCase() : "general";
}

/** Strip the enrichment-loop cron marker suffix from a body, keep the rule + formula/threshold. */
export function cleanBody(body) {
  let b = String(body || "").trim();
  // bodies are "<rule> | formula/threshold: <x> | GENERATED BY ENRICHMENT-LOOP (cron) -- ..."
  b = b.replace(/\s*\|\s*GENERATED BY ENRICHMENT-LOOP.*$/i, "").trim();
  return b;
}

/** Pull the bare citation out of the source field ("hermes:enrichment-loop | cite: <X>" -> "<X>"). */
export function cleanCite(source) {
  const s = String(source || "").trim();
  const m = /cite:\s*(.+)$/i.exec(s);
  if (m) return m[1].trim();
  if (/^hermes:enrichment-loop$/i.test(s)) return ""; // no real cite present
  return s;
}

/**
 * One Hermes capture-tip -> one Alpaca {instruction, output, galaxy} row, or null if
 * it carries no usable rule text. The instruction names the domain + the rule topic
 * (the title) and asks for the specific guideline + source; the output supplies the
 * formula/threshold detail (the body) + the citation -- info BEYOND the instruction.
 */
export function hermesTipToAlpaca(tip) {
  if (!tip || typeof tip !== "object") return null;
  const title = String(tip.title || "").trim();
  if (!title) return null;
  const domain = tipDomain(tip);
  const body = cleanBody(tip.body) || title;
  const cite = cleanCite(tip.source);
  const instruction = `PRISM ${domain} machining best-practice. Topic: ${title} Give the specific guideline (with any formula or threshold) and cite the source.`;
  // strip any trailing dot(s) from the cite so we never emit a double period (cites often end in "p. 68.")
  const output = cite ? `${body}\nSource: ${cite.replace(/\.+$/, "")}.` : body;
  return { instruction, output, galaxy: domain };
}

/** Convert a parsed staging doc ({tips:[...]}) -> deduped Alpaca rows (by instruction). */
export function convertStaging(doc) {
  const tips = Array.isArray(doc && doc.tips) ? doc.tips : [];
  const byInstr = new Map();
  for (const t of tips) {
    const row = hermesTipToAlpaca(t);
    if (row) byInstr.set(row.instruction, row); // dedupe by instruction (stable last-wins)
  }
  return [...byInstr.values()];
}

const _isMain = (() => {
  try { return process.argv[1] && process.argv[1].replace(/\\/g, "/").endsWith("hermes-enrichment-to-alpaca.mjs"); }
  catch { return false; }
})();
if (_isMain) {
  (async () => {
    const stagingPath = process.argv[2] && !process.argv[2].startsWith("--") ? process.argv[2] : STAGING;
    const outPath = process.argv.includes("--out") ? process.argv[process.argv.indexOf("--out") + 1] : OUT;
    let doc;
    try { doc = JSON.parse(fs.readFileSync(stagingPath, "utf8")); }
    catch (e) { process.stderr.write(`[hermes-enrichment-to-alpaca] cannot read ${stagingPath}: ${e?.message || e}\n`); process.exit(1); }
    const rows = convertStaging(doc);
    let grade = null;
    try {
      const { gradeCorpus } = await import("./lib/lora-corpus-quality-check.mjs");
      grade = gradeCorpus(rows);
    } catch { /* guard optional */ }
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    const tmp = `${outPath}.tmp-${process.pid}`;
    fs.writeFileSync(tmp, rows.map((r) => JSON.stringify(r)).join("\n") + (rows.length ? "\n" : ""), "utf8");
    fs.renameSync(tmp, outPath);
    const byDom = {};
    for (const r of rows) byDom[r.galaxy] = (byDom[r.galaxy] || 0) + 1;
    process.stdout.write(JSON.stringify({
      ok: true, rows: rows.length, byDomain: byDom, out: outPath.replace(ROOT + path.sep, ""),
      quality: grade ? { verdict: grade.verdict, uniqueRatio: grade.uniqueRatio, contradictionRate: grade.contradictionRate } : "guard-unavailable",
    }, null, 2) + "\n");
  })();
}
