#!/usr/bin/env node
/**
 * prepare-hurco-job.mjs — ONE COMMAND → a complete, operator-ready job folder.
 *
 * PRISM's mission is shops with inexperienced machinists, so this automates every step between
 * "I want to run the demo part" and "everything I need is in one folder":
 *   1. Post the sample NC program (PRISM speeds/feeds + canned cycles baked in).
 *   2. Lint it against the Hurco dialect (fail loud on any ERROR).
 *   3. Generate the matching tool library (Fusion .tools) + WinMax tool-setup sheet.
 *   4. Generate the plain-language OPERATOR SETUP CARD.
 *   5. Write an index README tying it together.
 *
 * Everything lands in ONE folder the operator opens. Nothing to assemble by hand.
 *
 * Usage: node scripts/prepare-hurco-job.mjs [rich|basic] [outDir]
 */
import { writeFileSync, mkdirSync, readFileSync, existsSync } from "node:fs";
import { spawnSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { lintNc } from "./post-nc-dialect-lint.mjs";
import { buildPacket } from "./emit-operator-packet.mjs";
import { PROGRAMS, TOOLS } from "./lib/prism-base-job.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const NODE = process.execPath;

function step(label, fn) {
  try { const r = fn(); console.log(`  ✓ ${label}`); return { ok: true, ...r }; }
  catch (e) { console.log(`  ✗ ${label} — ${e.message}`); return { ok: false, error: e.message }; }
}

export function prepareJob(programKey = "rich", outDir) {
  const prog = PROGRAMS[programKey];
  if (!prog) throw new Error(`unknown program '${programKey}'`);
  outDir = outDir || path.join("C:/Users/wompu/OneDrive/Desktop", `PRISM-JOB-${programKey}`);
  mkdirSync(outDir, { recursive: true });

  console.log(`\nPreparing job '${programKey}' → ${outDir}`);
  const results = {};
  const ncPath = path.join(outDir, prog.file);

  // 1. post the NC
  results.post = step(`post ${prog.file}`, () => {
    const emitter = programKey === "rich" ? "emit-rich-sample-nc.mjs" : "emit-base-sample-nc.mjs";
    const r = spawnSync(NODE, [path.join(__dirname, emitter), ncPath], { encoding: "utf8" });
    if (r.status !== 0) throw new Error((r.stderr || r.stdout || "emit failed").trim().split("\n").pop());
    if (!existsSync(ncPath)) throw new Error("NC not written");
    return { lines: readFileSync(ncPath, "utf8").split("\n").length };
  });

  // 2. lint
  results.lint = step("lint NC (Hurco dialect)", () => {
    const c = lintNc(readFileSync(ncPath, "utf8"), { dialect: "hurco" }).counts;
    if (c.ERROR > 0) throw new Error(`${c.ERROR} lint ERROR(s)`);
    return { warn: c.WARN || 0 };
  });

  // 3. tool library + WinMax sheet
  results.tools = step("tool library + WinMax sheet", () => {
    const r = spawnSync(NODE, [path.join(__dirname, "emit-tool-library.mjs"), outDir], { encoding: "utf8" });
    if (r.status !== 0) throw new Error((r.stderr || "tool-lib failed").trim().split("\n").pop());
    if (!existsSync(path.join(outDir, "prism-base-tools.tools"))) throw new Error(".tools not written");
    return { tools: TOOLS.length };
  });

  // 4. operator setup card
  results.card = step("operator setup card", () => {
    writeFileSync(path.join(outDir, `OPERATOR-SETUP-CARD-${programKey}.md`), buildPacket(programKey));
    return { ops: prog.ops.length };
  });

  // 5. index README
  results.readme = step("index README", () => {
    writeFileSync(path.join(outDir, "README.md"), buildReadme(programKey, results));
    return {};
  });

  const allOk = Object.values(results).every((r) => r.ok);
  console.log(allOk ? "\n✅ JOB READY — open the folder, follow OPERATOR-SETUP-CARD" : "\n❌ JOB INCOMPLETE — see failures above");
  return { ok: allOk, outDir, results };
}

function buildReadme(programKey, r) {
  const prog = PROGRAMS[programKey];
  return `# PRISM Job — ${prog.title}

Everything to run this part is in this folder. **Start with OPERATOR-SETUP-CARD-${programKey}.md.**

| File | What it is |
|------|-----------|
| \`OPERATOR-SETUP-CARD-${programKey}.md\` | **Read this first.** Step-by-step setup for a new operator. |
| \`${prog.file}\` | The CNC program (${r.post.lines || "?"} lines). Load this in the control. |
| \`prism-base-tools.tools\` | Fusion CAM tool library (import if you post from Fusion). |
| \`PRISM-Base-Tool-Setup.md\` | Tool table to key into the control's Tool Setup page. |

PRISM computed the speeds + feeds and the safety limits — don't change them on the first run.
Lint: ${r.lint.ok ? "PASS (0 errors)" : "FAIL"}. Generated by \`prepare-hurco-job.mjs\`.
`;
}

// ── CLI ──
const isMain = process.argv[1] && /prepare-hurco-job\.mjs$/.test(process.argv[1].replace(/\\/g, "/"));
if (isMain) {
  const key = (process.argv[2] && PROGRAMS[process.argv[2]]) ? process.argv[2] : "rich";
  const res = prepareJob(key, process.argv[3]);
  process.exit(res.ok ? 0 : 1);
}
