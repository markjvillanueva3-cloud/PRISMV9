#!/usr/bin/env node
/**
 * generate-domain-wiki.mjs
 *
 * Generates one Obsidian wiki entry per engine-domain rollup at
 *   H:/prism/knowledge/wiki/architecture/domain-<slug>.md
 *
 * A "domain" is a top-level engine grouping (mill, lathe, cad, cam, wedm,
 * ai, knowledge, ...) as exposed by L5 rollup nodes in system-graph.json
 * (id pattern `eng.<domain>`, `count` field, `status` field).
 *
 * Cross-references:
 *   - Parent: [[layer-l5]]
 *   - Dispatchers: any L4 node whose id begins with `disp.<domain>` or
 *     whose label contains the domain name (manufacturing/system/business)
 *   - Drilled sample: top-N L5 atomic_engine children for this domain
 *
 * Idempotent — AUTO-START/END markers preserve human-added content.
 * Updates wiki/index.md ## architecture subsection in-place (ARCH-DOMAINS markers).
 */
