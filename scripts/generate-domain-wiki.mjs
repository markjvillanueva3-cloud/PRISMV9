function readJson(p) {
  return JSON.parse(readFileSync(p, "utf8"));
}

function ensureDir(d) {
  if (!existsSync(d)) mkdirSync(d, { recursive: true });
}

function slugify(d) {
  return d.toLowerCase().replace(/[^a-z0-9]+/g, "-");
}

function analyze(G) {
  const domains = new Map();
  // Domain rollup nodes have `id === eng.<domain>` exactly (no nested dots)
  // and a numeric `count` field. They appear once per status (wired/unwired/stub).
  const ROLLUP_RE = /^eng\.([a-z0-9_]+)$/;
  for (const n of G.nodes || []) {
    if (n.layer !== "L5") continue;
    const m = ROLLUP_RE.exec(n.id);
    if (!m) continue;
    if (typeof n.count !== "number") continue;
    const d = m[1];
    const cur = domains.get(d) || {
      domain: d,
      totalEngines: 0,
      byStatus: {},
      bySubgroup: {},
      rollupLabels: [],
    };
    cur.totalEngines += n.count;
    const st = n.status || "-";
    cur.byStatus[st] = (cur.byStatus[st] || 0) + n.count;
    const sg = n.subgroup || "-";
    cur.bySubgroup[sg] = (cur.bySubgroup[sg] || 0) + n.count;
    if (cur.rollupLabels.length < 4) cur.rollupLabels.push(n.label || n.id);
    domains.set(d, cur);
  }
  // Drilled children: atomic engines tagged by subgroup OR kind
  for (const n of G.nodes || []) {
    if (n.layer !== "L5") continue;
    const tag = n.subgroup || n.kind || "";
    if (tag !== "atomic_engine") continue;
    const m = /^eng\.([a-z0-9_]+)\./.exec(n.id);
    if (!m) continue;
    const d = m[1];
    const cur = domains.get(d);
    if (!cur) continue;
    cur.drilled = cur.drilled || [];
    if (cur.drilled.length < 12) cur.drilled.push(n.label || n.id);
  }
  // Connected dispatchers — L4 nodes whose id contains the domain keyword
  for (const n of G.nodes || []) {
    if (n.layer !== "L4") continue;
    const idLower = (n.id || "").toLowerCase();
    const labelLower = (n.label || "").toLowerCase();
    for (const [d, cur] of domains.entries()) {
      if (idLower.includes(d) || labelLower.includes(d)) {
        cur.dispatchers = cur.dispatchers || [];
        const entry = `\`${n.id}\` — ${n.label || "(unnamed)"}`;
        if (!cur.dispatchers.includes(entry)) cur.dispatchers.push(entry);
      }
    }
  }
  return domains;
}

function render(d, info, generatedAt, headline) {
  const purpose = DOMAIN_PURPOSE[d] || `${d} engines in the L5 layer.`;
  const statusRows = Object.entries(info.byStatus)
    .filter(([k]) => k !== "-")
    .sort((a, b) => b[1] - a[1])
    .map(([k, v]) => `| ${k} | ${v} |`)
    .join("\n") || "| (unclassified) | — |";
  const subgroupRows = Object.entries(info.bySubgroup)
    .filter(([k]) => k !== "-")
    .sort((a, b) => b[1] - a[1])
    .map(([k, v]) => `| ${k} | ${v} |`)
    .join("\n") || "| - | - |";
  const drilled = (info.drilled || []).map((l) => `- ${l.replace(/\n/g, " ")}`).join("\n") || "_(no atomic engines indexed)_";
  const dispatchers = (info.dispatchers || []).map((x) => `- ${x.replace(/\n/g, " ")}`).join("\n") || "_(no L4 dispatcher match — may need wiring)_";

  return `---
title: Domain — ${d}
type: architecture
domain: ${d}
parent_layer: L5
generated_by: scripts/generate-domain-wiki.mjs
last_verified: ${generatedAt}
tags: [architecture, system-viz, engine-domain, domain-${slugify(d)}]
related:
  - knowledge/wiki/architecture/layer-l5.md
  - knowledge/wiki/architecture/layer-l4.md
  - state/shared/system-viz/system-graph.json
---

# Engine domain — \`${d}\`

> ${purpose}

**Total engines in domain:** ${info.totalEngines}
**System headline:** ${headline.built ?? "?"} wired · ${headline.unwired ?? "?"} unwired across all domains

${AUTO_START}

## Engine status breakdown

| Status | Engines |
|--------|---------|
${statusRows}

## Wiring state

| Subgroup | Engines |
|----------|---------|
${subgroupRows}

## Connected dispatchers (L4 matches)

${dispatchers}

## Drilled atomic engines (sample)

${drilled}

## Rollup labels

${info.rollupLabels.map((l) => `- \`${l.replace(/\n/g, " | ")}\``).join("\n") || "_(none)_"}

${AUTO_END}

## See also

- Parent layer: [[layer-l5]]
- Dispatchers layer: [[layer-l4]]
- Live graph: \`state/shared/system-viz/system-graph.json\`
- Query: \`node scripts/system-viz-query.mjs coverage-by-domain\`
`;
}

function preserveHuman(existing, full) {
  if (!existing) return full;
  const sStart = existing.indexOf(AUTO_START);
  const sEnd = existing.indexOf(AUTO_END);
  const nStart = full.indexOf(AUTO_START);
  const nEnd = full.indexOf(AUTO_END);
  if (sStart === -1 || sEnd === -1) return full;
  const before = existing.slice(0, sStart);
  const after = existing.slice(sEnd + AUTO_END.length);
  const newAuto = full.slice(nStart, nEnd + AUTO_END.length);
  return before + newAuto + after;
}

function updateIndex(domainEntries) {
  if (!existsSync(WIKI_INDEX)) return null;
  const text = readFileSync(WIKI_INDEX, "utf8");
  const block = [
    "<!-- ARCH-DOMAINS-START -->",
    ...domainEntries.map(
      (e) => `- [[domain-${slugify(e.domain)}]] — engine domain \`${e.domain}\` (${e.totalEngines} engines)`
    ),
    "<!-- ARCH-DOMAINS-END -->",
  ].join("\n");

  if (text.includes("<!-- ARCH-DOMAINS-START -->")) {
    return text.replace(
      /<!-- ARCH-DOMAINS-START -->[\s\S]*?<!-- ARCH-DOMAINS-END -->/m,
      block
    );
  }
  // Insert right after the layer block (so layers + domains group under ## architecture)
  if (text.includes("<!-- ARCH-LAYERS-END -->")) {
    return text.replace(
      /<!-- ARCH-LAYERS-END -->/,
      "<!-- ARCH-LAYERS-END -->\n\n### Engine domains\n\n" + block
    );
  }
  // Fallback: append under ## architecture
  return text.trimEnd() + "\n\n### Engine domains\n\n" + block + "\n";
}

function main() {
  if (!existsSync(GRAPH_PATH)) {
    process.stderr.write(`graph missing at ${GRAPH_PATH}\n`);
    process.exit(2);
  }
  const G = readJson(GRAPH_PATH);
  const headline = (G.meta && G.meta.headline) || {};
  const generatedAt = new Date().toISOString().split("T")[0];
  const domains = analyze(G);

  ensureDir(WIKI_ARCH_DIR);
  const indexEntries = [];

  for (const [d, info] of [...domains.entries()].sort((a, b) => b[1].totalEngines - a[1].totalEngines)) {
    const outPath = join(WIKI_ARCH_DIR, `domain-${slugify(d)}.md`);
    const full = render(d, info, generatedAt, headline);
    const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
    const finalContent = preserveHuman(existing, full);
    if (FLAGS.dryRun) {
      process.stdout.write(`would write ${outPath} (${finalContent.length}b, ${info.totalEngines} engines)\n`);
    } else {
      writeFileSync(outPath, finalContent, "utf8");
    }
    indexEntries.push({ domain: d, totalEngines: info.totalEngines });
  }

  // --- Engine-only domain stubs ---------------------------------------------
  // generate-engine-wiki.mjs writes engines/<domain>/ for ~77 domains but only
  // ~38 have an eng.<domain> rollup node here. Emit a minimal stub entry for the
  // rest so their engine entries have a parent (kills ~600 wiki orphans).
  const enginesRoot = join(WIKI_ARCH_DIR, "engines");
  let stubCount = 0;
  if (existsSync(enginesRoot)) {
    const rollupSlugs = new Set([...domains.keys()].map((d) => slugify(d)));
    for (const e of readdirSync(enginesRoot, { withFileTypes: true })) {
      if (!e.isDirectory()) continue;
      const domain = e.name;
      const dSlug = slugify(domain);
      if (rollupSlugs.has(dSlug)) continue; // already has a full entry
      const dDir = join(enginesRoot, domain);
      const engSlugs = readdirSync(dDir).filter((f) => f.endsWith(".md")).map((f) => f.replace(/\.md$/, ""));
      if (!engSlugs.length) continue;
      const purpose = DOMAIN_PURPOSE[domain] || `Engine-only domain \`${domain}\` — ${engSlugs.length} atomic engines, no graph rollup node.`;
      const outPath = join(WIKI_ARCH_DIR, `domain-${dSlug}.md`);
      const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
      const body = [
        "## Engines in this domain",
        "",
        ...engSlugs.map((s) => `- [[${s}]]`),
      ].join("\n");
      const stub = `---
title: Domain — ${domain}
type: architecture
domain: ${domain}
parent_layer: L5
generated_by: scripts/generate-domain-wiki.mjs (stub)
last_verified: ${generatedAt}
tags: [architecture, system-viz, engine-domain, domain-${dSlug}, stub]
related:
  - knowledge/wiki/architecture/layer-l5.md
---

# Engine domain — \`${domain}\`

> ${purpose}

**Atomic engines:** ${engSlugs.length}  ·  **Graph rollup node:** none (engine-only domain)

${AUTO_START}

${body}

${AUTO_END}

## See also

- Parent layer: [[layer-l5]]
- Engine entries: \`knowledge/wiki/architecture/engines/${domain}/\`
`;
      const finalContent = preserveHuman(existing, stub);
      if (!FLAGS.dryRun) writeFileSync(outPath, finalContent, "utf8");
      stubCount++;
      indexEntries.push({ domain, totalEngines: engSlugs.length });
    }
  }

  const indexUpdated = updateIndex(indexEntries);
  if (indexUpdated && !FLAGS.dryRun) writeFileSync(WIKI_INDEX, indexUpdated, "utf8");
  if (stubCount) process.stdout.write(`  + ${stubCount} engine-only domain stubs\n`);

  process.stdout.write(
    `generated ${indexEntries.length} domain wiki entries · index ${indexUpdated ? "updated" : "skipped"}\n`
  );
}

main();
