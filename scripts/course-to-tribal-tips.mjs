#!/usr/bin/env node
// KNOWLEDGE-CONVERSION-MS0 / U-KC-B1 — Lane A direct-wire converter.
//
// Reads `state/shared/tribal-graph/course-content-candidates.jsonl` (advisory
// review queue from TRIBAL-GRAPH-MS0/U-CONTENT-MINE) and emits one
// `KnowledgeTip` per `candidateAsset` into `DOC_KNOWLEDGE_DIR` so
// `TribalKnowledgeEngine.loadDocumentLearnedTips()` picks them up on next init.
//
// Doctrine: advisory provenance is preserved in `source:` + `tags:` +
// `subcategory:`. Confidence = round(mfgRelevance × confidence × 100), reflecting
// the descriptor-layer distillation cost — these tips are honest about being
// distilled, not validated. Human-verify before relying.
//
// Re-runnable + deterministic with --frozen-time. Sorts inputs so byte-output
// stays stable across runs (idempotent for the auto-load contract).
//
// ENGINE OVERRIDES (TribalKnowledgeEngine.ts:685-718) — read these before
// trusting the emitted JSON's fields:
//   - `id` is GENERATED by the engine as `TK-DL-<docId>-<NNN>` where docId
//     is the output filename minus .json. The script does not emit id.
//   - `source` is OVERRIDDEN by the engine to `document:<docId>` — uniform
//     across every tip in this file. The per-record `source: mit-ocw:<courseId>`
//     we emit survives only for downstream readers that bypass the engine.
//     Per-record provenance also survives in `tags: ["course:<courseId>", ...]`
//     and in the `title:` and `body:` fields.
//   - `subcategory` is NOT copied through by loadDocumentLearnedTips(). The
//     asset.kind survives only via tags. We emit subcategory anyway for
//     direct-readers and as forward-compat with a future engine fix.
//   - `confidence: item.confidence || 70` falsy-promotes 0 → 70 in the engine.
//     We floor computed confidence at 1 to keep the honest-low signal.
//   - ID stability: engine IDs shift across runs if records insert/delete in
//     the upstream JSONL. Use (source, courseId, kind, name) from tags+title
//     for stable cross-reference, NOT the engine-assigned id.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..");

const DEFAULT_INPUT  = path.join(REPO_ROOT, "state/shared/tribal-graph/course-content-candidates.jsonl");
const DEFAULT_OUTPUT = path.join(REPO_ROOT, "cad-engine/knowledge_store/mit-ocw-course-tips.json");

// Tag-length cap. Long-tag-bombs are a known LLM-payload class (an asset.name
// or technique that contains a multi-paragraph rationale rather than a label).
// 80 chars is the longest legitimate tag we've seen in the existing tribal
// knowledge base; anything beyond that gets dropped from the tag set (the
// content still survives in title/body).
const MAX_TAG_LEN = 80;

// ISO date slice length: "YYYY-MM-DD" is 10 chars.
const ISO_DATE_LEN = 10;

// Domain → KnowledgeCategory mapping. Every VALUE here must be a valid member
// of the `KnowledgeCategory` union declared in TribalKnowledgeEngine.ts:104.
// The valid members are: setup, tooling, speeds_feeds, fixturing,
// surface_finish, thread, safety, maintenance, material_handling, quality,
// troubleshooting, programming, electronics, automation, metrology, design,
// materials_science, process_engineering, lean_manufacturing, additive,
// inspection, cam_strategy, optimization, post_processor, roughing, workflow,
// multi_axis, verification, simulation, mold_die, probing, general. The
// `__test_membership__` named export validates this table at test time.
//
// Keys are normalized (lowercase, trim, collapse separators to single space)
// before lookup, so the same key matches "process optimization",
// "process-optimization", and "Process_Optimization".
export const VALID_KNOWLEDGE_CATEGORIES = Object.freeze([
  "setup","tooling","speeds_feeds","fixturing","surface_finish","thread","safety",
  "maintenance","material_handling","quality","troubleshooting","programming",
  "electronics","automation","metrology","design","materials_science",
  "process_engineering","lean_manufacturing","additive","inspection","cam_strategy",
  "optimization","post_processor","roughing","workflow","multi_axis","verification",
  "simulation","mold_die","probing","general",
]);

export const DOMAIN_TO_CATEGORY = Object.freeze({
  cam:                  "cam_strategy",
  thermal:              "process_engineering",
  metrology:            "metrology",
  scheduling:           "workflow",
  control:              "automation",
  cad:                  "design",
  materials:            "materials_science",
  "tool life":          "tooling",
  "process optimization": "optimization",
  vibration:            "process_engineering",
  mill:                 "cam_strategy",
  lathe:                "cam_strategy",
  wedm:                 "cam_strategy",
  edm:                  "cam_strategy",
  multi:                "multi_axis",
  multiaxis:            "multi_axis",
  "5axis":              "multi_axis",
  simulation:           "simulation",
  inspection:           "inspection",
  probing:              "probing",
  safety:               "safety",
  quality:              "quality",
  programming:          "programming",
  software:             "programming",
  optimization:         "optimization",
  design:               "design",
});

// Normalize domain key: lowercase, trim, collapse runs of space/hyphen/underscore
// to a single space. Matches `"process optimization"` and `"process-optimization"`
// to the same lookup key.
export function normalizeDomainKey(s) {
  if (typeof s !== "string") return "";
  return s.toLowerCase().trim().replace(/[\s\-_]+/g, " ");
}

export function mapDomainsToCategory(domains) {
  if (!Array.isArray(domains) || domains.length === 0) return "general";
  for (const d of domains) {
    const key = normalizeDomainKey(d);
    if (!key) continue;
    if (DOMAIN_TO_CATEGORY[key]) return DOMAIN_TO_CATEGORY[key];
  }
  return "general";
}

// Read & parse the JSONL. Each line is one course-content-candidate record.
// Fails LOUDLY on a corrupt line (Karpathy R12) — silently dropping records
// would hide a regression in the upstream miner.
export function loadCandidates(jsonlPath) {
  if (!fs.existsSync(jsonlPath)) {
    throw new Error(`input not found: ${jsonlPath}`);
  }
  const raw = fs.readFileSync(jsonlPath, "utf-8").trim();
  if (raw.length === 0) return [];
  const lines = raw.split(/\r?\n/);
  const recs = [];
  for (let i = 0; i < lines.length; i++) {
    const ln = lines[i].trim();
    if (ln.length === 0) continue;
    let r;
    try {
      r = JSON.parse(ln);
    } catch (err) {
      throw new Error(`parse error at line ${i + 1}: ${err.message}`);
    }
    if (!r || typeof r !== "object") {
      throw new Error(`line ${i + 1}: expected object`);
    }
    if (r.kind && r.kind !== "course-content-candidate") {
      // Unknown record kind — skip with a warn-trace rather than aborting,
      // because the miner may version-bump this stream.
      process.stderr.write(`warn: line ${i + 1} kind=${r.kind} (expected course-content-candidate) — skipped\n`);
      continue;
    }
    recs.push(r);
  }
  return recs;
}

// Confidence math: mfgRelevance × confidence × 100, clamped to [1,100],
// rounded to integer. Missing/non-numeric/negative inputs → 1 (the honest-low
// floor). The floor is load-bearing: the consumer engine does
// `confidence: item.confidence || 70` (TribalKnowledgeEngine.ts:706), so an
// emitted 0 would falsy-promote to 70 — a silent provenance inversion. Floor
// at 1 means "near-noise" rather than "high-confidence default".
export function computeConfidence(record) {
  const r = Number(record?.mfgRelevance);
  const c = Number(record?.confidence);
  if (!Number.isFinite(r) || !Number.isFinite(c)) return 1;
  const pct = Math.round(r * c * 100);
  if (pct < 1) return 1;
  if (pct > 100) return 100;
  return pct;
}

// Tag set is deduped + sorted (so output is deterministic across runs).
// Includes: techniques, asset.kind, course-tag, prismDomains, and the
// provenance markers ("mit-ocw", "advisory").
export function buildTags(record, asset) {
  const seen = new Set();
  const tags = [];
  const push = (t) => {
    if (typeof t !== "string") return;
    const s = t.trim();
    if (s.length === 0) return;
    if (s.length > MAX_TAG_LEN) return;
    const key = s.toLowerCase();
    if (seen.has(key)) return;
    seen.add(key);
    tags.push(s);
  };
  for (const t of (record?.techniques || [])) push(t);
  for (const d of (record?.prismDomains || [])) push(d);
  push(asset?.kind);
  push("mit-ocw");
  push("advisory");
  if (record?.courseId) push(`course:${record.courseId}`);
  tags.sort();
  return tags;
}

// Build one KnowledgeTip from a (record, asset) pair. Pure — no I/O.
// `created_at` defaults to today (UTC date) but is overridable via `now` for
// frozen-time test runs.
export function assetToTip(record, asset, now = new Date()) {
  const courseId    = String(record?.courseId ?? "unknown");
  const courseTitle = String(record?.courseTitle ?? "");
  const kind        = String(asset?.kind ?? "tip");
  const name        = String(asset?.name ?? "(unnamed)").trim() || "(unnamed)";
  const rationale   = String(asset?.rationale ?? "").trim();

  const title = `MIT OCW ${courseId} — ${kind}: ${name}`;
  // Body is multi-clause so the operator who triages this can see ALL the
  // signal at once (rationale, course context, advisory caveat). When the
  // upstream miner emits an empty rationale, we fall back to the asset name +
  // kind so the body is never a low-information constant string.
  const bodyParts = [];
  if (rationale.length > 0) {
    bodyParts.push(rationale);
  } else {
    bodyParts.push(`Candidate ${kind}: ${name}.`);
  }
  if (courseTitle.length > 0) bodyParts.push(`Course: ${courseTitle}`);
  bodyParts.push("Source: MIT-OpenCourseWare descriptor-layer mining (advisory — human-verify before adoption).");
  const body = bodyParts.join(" ");

  return {
    title,
    body,
    category: mapDomainsToCategory(record?.prismDomains),
    subcategory: kind,            // queryable: filter by asset-kind
    tags: buildTags(record, asset),
    confidence: computeConfidence(record),
    source: `mit-ocw:${courseId}`,
    created_at: now.toISOString().slice(0, ISO_DATE_LEN),
  };
}

// Convert every record × every candidateAsset → KnowledgeTip. Output order is
// deterministic: sort records by courseId, then assets by `kindname`
// (U+001F is a non-displayable separator that never appears in real names —
// see [[reference_e1_ideablock_extractor_2026_05_15]] for the rationale).
export function convertAll(records, now = new Date()) {
  const sortedRecs = [...records].sort((a, b) => String(a.courseId ?? "").localeCompare(String(b.courseId ?? "")));
  const tips = [];
  const SEP = "";
  for (const rec of sortedRecs) {
    const assets = Array.isArray(rec.candidateAssets) ? [...rec.candidateAssets] : [];
    assets.sort((a, b) => {
      const ka = `${a?.kind ?? ""}${SEP}${a?.name ?? ""}`;
      const kb = `${b?.kind ?? ""}${SEP}${b?.name ?? ""}`;
      return ka.localeCompare(kb);
    });
    for (const asset of assets) {
      tips.push(assetToTip(rec, asset, now));
    }
  }
  return tips;
}

// Wrap tips with provenance envelope. `advisoryOnly` + `mustHumanVerify` +
// `caveat` mirror the upstream JSONL contract so a downstream consumer that
// reads the file directly (not via the engine) still sees the advisory mark.
export function buildEnvelope(tips, opts) {
  return {
    schemaVersion: "1.0.0",
    kind: "mit-ocw-course-tips",
    advisoryOnly: true,
    mustHumanVerify: true,
    caveat: "ADVISORY review queue distilled from MIT-OpenCourseWare resource-descriptor metadata (NOT full lecture text). KnowledgeTip[] format — TribalKnowledgeEngine.loadDocumentLearnedTips() auto-loads on init. NOT a substitute for human-vetted tribal knowledge. Best entries become real PRISM assets only via the human-gated /forge + scrutiny pipeline.",
    generatedAt: opts.now.toISOString(),
    sourceFile: opts.relativeSource,
    sourceRecords: opts.sourceRecords,
    sourceAssets: tips.length,
    generator: "scripts/course-to-tribal-tips.mjs",
    milestone: "KNOWLEDGE-CONVERSION-MS0",
    unit: "U-KC-B1",
    tips,
  };
}

// --- CLI ---------------------------------------------------------------------

function parseArgs(argv) {
  // limit:0 sentinel → "no limit" — but we now REJECT a literal --limit 0 from
  // the operator (P2 from scrutiny). The sentinel is internal only.
  const out = { input: DEFAULT_INPUT, output: DEFAULT_OUTPUT, limit: 0, frozenTime: null };

  const requireValue = (flag, i) => {
    if (i + 1 >= argv.length) {
      process.stderr.write(`missing value for ${flag}\n`);
      process.exit(2);
    }
    return argv[i + 1];
  };

  for (let i = 2; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--input")  { out.input  = requireValue(a, i); i++; continue; }
    if (a === "--output") { out.output = requireValue(a, i); i++; continue; }
    if (a === "--limit")  {
      const v = requireValue(a, i); i++;
      const n = Number(v);
      if (!Number.isFinite(n) || !Number.isInteger(n) || n <= 0) {
        process.stderr.write(`invalid --limit: ${v} (expected positive integer; use --all for no limit)\n`);
        process.exit(2);
      }
      out.limit = n;
      continue;
    }
    if (a === "--all") { out.limit = 0; continue; }
    if (a === "--frozen-time") { out.frozenTime = requireValue(a, i); i++; continue; }
    if (a === "--help" || a === "-h") {
      process.stdout.write([
        "course-to-tribal-tips.mjs — KNOWLEDGE-CONVERSION-MS0/U-KC-B1",
        "  --input <path>        course-content-candidates.jsonl  (default: " + DEFAULT_INPUT + ")",
        "  --output <path>       KnowledgeTip JSON                (default: " + DEFAULT_OUTPUT + ")",
        "  --limit N             cap converted records (positive integer; default: no limit)",
        "  --all                 process every record (default behavior)",
        "  --frozen-time <iso>   override now() for byte-stable test runs (UTC normalized)",
      ].join("\n") + "\n");
      process.exit(0);
    }
    process.stderr.write(`unknown arg: ${a}\n`);
    process.exit(2);
  }
  // PRISM_AUDIT_FROZEN_TIME / PRISM_FROZEN_TIME — match the pattern used by
  // audit-monolith-port-state.mjs so test runners can set one env for all
  // determinism-sensitive scripts.
  if (!out.frozenTime) {
    out.frozenTime = process.env.PRISM_AUDIT_FROZEN_TIME || process.env.PRISM_FROZEN_TIME || null;
  }
  return out;
}

function fail(code, msg) {
  process.stderr.write(`error: ${msg}\n`);
  process.exit(code);
}

async function main() {
  const opts = parseArgs(process.argv);
  const now = opts.frozenTime ? new Date(opts.frozenTime) : new Date();
  if (Number.isNaN(now.getTime())) fail(2, `invalid --frozen-time: ${opts.frozenTime}`);

  let records;
  try {
    records = loadCandidates(opts.input);
  } catch (err) {
    fail(2, err.message);
    return;
  }
  if (records.length === 0) fail(2, `no records in ${opts.input}`);

  const slice = opts.limit > 0 ? records.slice(0, opts.limit) : records;
  const tips = convertAll(slice, now);
  if (tips.length === 0) fail(3, "convertAll produced 0 tips — every record must have candidateAssets");

  const env = buildEnvelope(tips, {
    now,
    relativeSource: path.relative(REPO_ROOT, opts.input).replace(/\\/g, "/"),
    sourceRecords: slice.length,
  });

  const outDir = path.dirname(opts.output);
  try {
    fs.mkdirSync(outDir, { recursive: true });
    // Atomic write: tmp + rename. A crashed converter mid-write would otherwise
    // leave a partially-written JSON that the engine's `try{JSON.parse}catch`
    // (line 692-712) silently skips — every MIT-OCW tip would vanish from the
    // store with no error surfaced anywhere.
    const tmp = opts.output + ".tmp";
    fs.writeFileSync(tmp, JSON.stringify(env, null, 2) + "\n", "utf-8");
    fs.renameSync(tmp, opts.output);
  } catch (err) {
    fail(3, `write failed: ${err.message}`);
  }

  process.stdout.write(JSON.stringify({
    ok: true,
    records: slice.length,
    tips: tips.length,
    output: path.relative(REPO_ROOT, opts.output).replace(/\\/g, "/"),
    advisoryOnly: true,
    mustHumanVerify: true,
  }, null, 2) + "\n");
}

const isCLI = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));
if (isCLI) {
  void main().catch((err) => fail(3, err?.stack || String(err)));
}
