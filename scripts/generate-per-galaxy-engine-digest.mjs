#!/usr/bin/env node
// U-GALAXY-MS1-G1 (2026-05-27, slot:alpha): emit per-galaxy ENGINE_DIGEST.md.
//
// Reads mcp-server/src/engines/<galaxy>/ subdirs AND classifies flat-sibling
// engines via state/shared/memory-galaxy-routing.json (C1 output — present?
// best-effort fallback to filename-heuristic). For each galaxy emits a
// galaxy-local ENGINE_DIGEST.md with 1-line-per-engine: <Name> (<size>) — <purpose>.
// Purpose extracted from each engine's top JSDoc / // comment block.
//
// Writes: mcp-server/data/docs/galaxies/<galaxy>/ENGINE_DIGEST.md
//
// Per SCOPE-EXPANSION §Q3 #1 — saves ~3-5K tokens/SessionStart for chats not in
// that galaxy (vs the monolithic mcp-server/data/docs/ENGINE_DIGEST.md which loads
// 150+ engines for every chat regardless).
//
// Run: node scripts/generate-per-galaxy-engine-digest.mjs           # all 20 galaxies
//      node scripts/generate-per-galaxy-engine-digest.mjs --galaxy mill

import fs from "node:fs";
import path from "node:path";

const PRISM = process.env.PRISM_ROOT || "H:/prism";
const ENGINES = path.join(PRISM, "mcp-server/src/engines");
const OUTPUT_ROOT = path.join(PRISM, "mcp-server/data/docs/galaxies");
const ROUTING = path.join(PRISM, "state/shared/memory-galaxy-routing.json");

const GALAXIES = [
  "mill", "lathe", "wedm", "quoting", "business", "academy", "post-processor",
  "cad", "cam", "shop-floor", "mit-curriculum", "pdf-corpus", "pdf-corpus-mill",
  "quality", "cad-fusion-live", "speed-feed", "knowledge-conversion",
  "compliance-safety", "corpus-aggregation", "tribal-knowledge", "agent-orchestration",
];

// Filename-heuristic for flat-sibling engines (fallback when routing JSON missing)
const GALAXY_FILENAME_PREFIXES = {
  mill: /^(Mill|Hyper?Mill|HighFeed|Trochoidal|Helical|ChamferMill|BallEnd|BallMill|Counterfactual|Adaptive.*Mill|AdvancedMilling)/i,
  lathe: /^(Lathe|HardTurn|DiamondTurn|EccentricTurning|JMDieLathe|Fusion.*Turn|HyperMill.*Turn)/i,
  wedm: /^(WEDM|EDM)/i,
  quoting: /^(Quote|Cost|Pricing|Billing|InstantQuote|JobCosting|Estimat|Freight|Import|Material.*Price)/i,
  business: /^(Business|Customer|Employee|ERP|Vendor|Accounting|PayrollHR)/i,
  academy: /^(Course|Learning|Training)/i,
  "post-processor": /^(GCode|MasterPost|.*Post.*)/i,
  cad: /^CAD/i,
  cam: /^CAM/i,
  "shop-floor": /^(ShopFloor|MachineLive|Traveler)/i,
};

function classifyEngine(filename) {
  for (const [galaxy, re] of Object.entries(GALAXY_FILENAME_PREFIXES)) {
    if (re.test(filename)) return galaxy;
  }
  return null;
}

function extractPurpose(content) {
  const lines = content.split("\n").slice(0, 30);
  for (const l of lines) {
    const m = l.match(/^\s*\*\s*(.+?\.)/) || l.match(/^\s*\/\/\s*(.+?\.)/);
    if (m && m[1].length > 20 && m[1].length < 180) return m[1];
  }
  return "(no top JSDoc/comment purpose)";
}

function statSafe(p) {
  try { return fs.statSync(p); } catch { return null; }
}

function readSafe(p) {
  try { return fs.readFileSync(p, "utf8"); } catch { return null; }
}

function main() {
  const args = process.argv.slice(2);
  const galaxyFlagIdx = args.indexOf("--galaxy");
  const galaxyFilter = galaxyFlagIdx >= 0 ? args[galaxyFlagIdx + 1] : null;

  if (!fs.existsSync(OUTPUT_ROOT)) fs.mkdirSync(OUTPUT_ROOT, { recursive: true });

  // Scan all engine files
  const flatEngines = fs.readdirSync(ENGINES)
    .filter(f => f.endsWith("Engine.ts") || f.endsWith(".ts"))
    .filter(f => !f.includes("test"))
    .map(f => ({ name: f, path: path.join(ENGINES, f) }))
    .filter(e => statSafe(e.path)?.isFile());

  const byGalaxy = Object.fromEntries(GALAXIES.map(g => [g, []]));

  // 1. Subdir engines first (canonical location)
  for (const g of GALAXIES) {
    const dir = path.join(ENGINES, g);
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir)) {
      if (!f.endsWith(".ts")) continue;
      const p = path.join(dir, f);
      const s = statSafe(p);
      if (!s?.isFile()) continue;
      byGalaxy[g].push({ name: f, path: p, size: s.size, location: "subdir" });
    }
  }

  // 2. Flat-sibling engines via heuristic
  for (const e of flatEngines) {
    const g = classifyEngine(e.name);
    if (g && byGalaxy[g]) {
      const s = statSafe(e.path);
      byGalaxy[g].push({ name: e.name, path: e.path, size: s.size, location: "flat" });
    }
  }

  // 3. Emit per-galaxy ENGINE_DIGEST.md
  let totalEmitted = 0;
  for (const g of GALAXIES) {
    if (galaxyFilter && g !== galaxyFilter) continue;
    const engines = byGalaxy[g].sort((a, b) => b.size - a.size);
    if (engines.length === 0) continue;
    const outDir = path.join(OUTPUT_ROOT, g);
    if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });
    const outFile = path.join(outDir, "ENGINE_DIGEST.md");
    const lines = [
      `# ${g} Galaxy — ENGINE_DIGEST (auto-generated 2026-05-27)`,
      "",
      `Generated by \`scripts/generate-per-galaxy-engine-digest.mjs\`. Per SCOPE-EXPANSION §Q3 #1 — per-galaxy digest loads only when CWD-relevant (vs monolithic root ENGINE_DIGEST). Sorted by file size (largest = highest leverage).`,
      "",
      `**${engines.length} engines** (${engines.filter(e => e.location === "subdir").length} subdir + ${engines.filter(e => e.location === "flat").length} flat-classified)`,
      "",
      "| Engine | Size | Location | Purpose |",
      "|--------|------|----------|---------|",
    ];
    for (const e of engines) {
      const content = readSafe(e.path) || "";
      const purpose = extractPurpose(content);
      const kb = (e.size / 1024).toFixed(1) + "K";
      lines.push(`| \`${e.name}\` | ${kb} | ${e.location} | ${purpose.replace(/\|/g, "\\|")} |`);
    }
    lines.push("");
    lines.push(`_Cascade: this file loads under cwd-cascade when editing under \`mcp-server/src/engines/${g}/\` or any \`${g}\`-classified flat-sibling. Parent: \`engines/CLAUDE.md\` (baseline) → \`engines/${g}/CLAUDE.md\` (galactic center) → THIS DIGEST._`);

    fs.writeFileSync(outFile, lines.join("\n"));
    console.log(`  ${g}: ${engines.length} engines → ${outFile}`);
    totalEmitted++;
  }

  console.log(`\nGenerated ${totalEmitted} per-galaxy ENGINE_DIGEST.md files at ${OUTPUT_ROOT}/`);
}

try { main(); } catch (e) {
  console.error("generate-per-galaxy-engine-digest crashed:", e.message);
  process.exit(1);
}
