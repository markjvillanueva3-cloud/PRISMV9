/**
 * train-wedm-galaxy.ts — the runnable, in-galaxy training stage for the WEDM
 * knowledge corpus.
 *
 * A parametric LoRA fine-tune needs torch+unsloth+a 7B base (NOT installed in
 * this session). What the galaxy CAN run now, without a GPU, is the in-process
 * learning/validation pipeline + emitting the ready-to-run GPU bundle:
 *
 *   1. Score every corpus output through the EXISTING RLHF evaluators
 *      (reward shaping + S(x) safety + reasoning quality), broken down per kind
 *      so the scores are HONEST (advisory text scores high on reasoning, low on
 *      program-syntax reward — it is knowledge text, not raw G-code).
 *   2. Emit the parametric LoRA bundle (train_wedm_lora.py + requirements.txt)
 *      via WEDMLoRATrainingScriptEngine, pointed at the knowledge corpus, so the
 *      actual GPU fine-tune is one command away on a box with the stack.
 *
 *   cd mcp-server && npx tsx ../scripts/train-wedm-galaxy.ts
 *
 * Pure consumer of existing engines; standalone (tsx); fail-loud. No ${...}
 * template literals (scripts/ security hook).
 */

import * as fs from "node:fs";
import * as path from "node:path";
import { wedmLoRARewardShapingEngine } from "../mcp-server/src/engines/WEDMLoRARewardShapingEngine.js";
import { wedmLoRASafetyEvaluatorEngine } from "../mcp-server/src/engines/WEDMLoRASafetyEvaluatorEngine.js";
import { wedmLoRAReasoningEvaluatorEngine } from "../mcp-server/src/engines/WEDMLoRAReasoningEvaluatorEngine.js";
import { wedmLoRATrainingScriptEngine } from "../mcp-server/src/engines/WEDMLoRATrainingScriptEngine.js";

const CORPUS_DIR = path.resolve(process.cwd(), "data/training/wedm-knowledge");
const TRAIN = path.join(CORPUS_DIR, "wedm_knowledge_train.jsonl");
const BUNDLE_DIR = path.join(CORPUS_DIR, "lora-bundle");

type Pair = { instruction: string; input: string; output: string; meta: { kind: string } };
type Acc = { n: number; reward: number; sx: number; reason: number; safePass: number; reasonPass: number };

function newAcc(): Acc {
  return { n: 0, reward: 0, sx: 0, reason: 0, safePass: 0, reasonPass: 0 };
}
function mean(sum: number, n: number): number {
  return n === 0 ? 0 : Math.round((sum / n) * 1000) / 1000;
}

function main(): void {
  if (!fs.existsSync(TRAIN)) {
    console.error("[train-wedm] FATAL: corpus not found at " + TRAIN + " — run build-wedm-knowledge-corpus.ts first.");
    process.exit(2);
  }
  const pairs: Pair[] = fs
    .readFileSync(TRAIN, "utf8")
    .split(/\r?\n/)
    .filter((l) => l.trim().length > 0)
    .map((l) => JSON.parse(l) as Pair);

  if (pairs.length === 0) {
    console.error("[train-wedm] FATAL: 0 training pairs. Nothing to score.");
    process.exit(3);
  }

  // ── Stage 1: RLHF eval gauntlet (in-process, no GPU) ──
  const overall = newAcc();
  const byKind: Record<string, Acc> = {};
  for (const p of pairs) {
    const rew = wedmLoRARewardShapingEngine.calculateReward(p.output, {
      instruction: p.instruction,
      expected_type: p.meta.kind,
    });
    const saf = wedmLoRASafetyEvaluatorEngine.evaluate(p.output);
    const rea = wedmLoRAReasoningEvaluatorEngine.evaluate(p.output);

    const k = p.meta.kind;
    byKind[k] ??= newAcc();
    for (const a of [overall, byKind[k]]) {
      a.n += 1;
      a.reward += rew.total_reward;
      a.sx += saf.s_x_score;
      a.reason += rea.overall_score;
      a.safePass += saf.passed ? 1 : 0;
      a.reasonPass += rea.passed ? 1 : 0;
    }
  }

  const fmt = (a: Acc) => ({
    n: a.n,
    mean_reward: mean(a.reward, a.n), // -1..1 (program-syntax weighted — low for advisory text, expected)
    mean_s_x: mean(a.sx, a.n), // 0..1 safety
    mean_reasoning: mean(a.reason, a.n), // 0..100 coherence/domain/justification
    safety_pass_rate: mean(a.safePass, a.n),
    reasoning_pass_rate: mean(a.reasonPass, a.n),
  });

  // ── Stage 2: emit the parametric GPU LoRA bundle pointed at the corpus ──
  wedmLoRATrainingScriptEngine.setConfig({ dataset_path: TRAIN.replace(/\\/g, "/") });
  const bundle = wedmLoRATrainingScriptEngine.generateScript();
  fs.mkdirSync(BUNDLE_DIR, { recursive: true });
  fs.writeFileSync(path.join(BUNDLE_DIR, bundle.filename), bundle.script, "utf8");
  fs.writeFileSync(path.join(BUNDLE_DIR, "requirements.txt"), bundle.requirements, "utf8");
  fs.writeFileSync(path.join(BUNDLE_DIR, "config.json"), bundle.config_json, "utf8");
  const readme =
    "WEDM LoRA training bundle (generated by train-wedm-galaxy.ts).\n\n" +
    "In-process learning (RLHF eval gauntlet) already ran in-galaxy — see the report.\n" +
    "The PARAMETRIC fine-tune needs a GPU box with the stack (NOT installed in the\n" +
    "authoring session). To run it:\n\n" +
    "  cd " + BUNDLE_DIR.replace(/\\/g, "/") + "\n" +
    "  pip install -r requirements.txt\n" +
    "  python " + bundle.filename + "\n\n" +
    "Dataset: " + TRAIN.replace(/\\/g, "/") + " (" + pairs.length + " Alpaca pairs)\n" +
    "Owner: india hosts the GPU retrain/deploy gate per the closed-loop contract.\n";
  fs.writeFileSync(path.join(BUNDLE_DIR, "README.txt"), readme, "utf8");

  const report = {
    trained_examples: pairs.length,
    overall: fmt(overall),
    by_kind: Object.fromEntries(Object.entries(byKind).map(([k, a]) => [k, fmt(a)])),
    gpu_bundle: {
      dir: BUNDLE_DIR,
      script: bundle.filename,
      base_model: "unsloth/Qwen2.5-Coder-7B-bnb-4bit",
      estimated_vram_gb: bundle.estimated_vram_gb,
      estimated_time_hours: bundle.estimated_time_hours,
      status: "ready — needs GPU box + pip install (torch/unsloth not installed here)",
    },
  };
  console.log("=== WEDM IN-GALAXY TRAINING REPORT ===");
  console.log(JSON.stringify(report, null, 2));
  console.log(
    "[train-wedm] OK — scored " + pairs.length + " pairs through reward+safety+reasoning; GPU LoRA bundle emitted to " +
    BUNDLE_DIR.replace(/\\/g, "/") + ".",
  );
}

main();
