#!/usr/bin/env node
/**
 * bundle-base-post.mjs — produce a self-contained single-file Tier-1 post for shipping to a
 * Fusion posts library (where the convention is one .cps per post, no companion includes).
 *
 * The dev sources stay split (post + include("prism-paths-feed.cps")) for no-drift testing;
 * this concatenates the shared feed core ABOVE the post body and strips the include() line.
 * The feed core's IIFE attaches the factor fns to globalThis, so the post body below resolves
 * them exactly as include() would — verified by the bundle test in prism-base-hurco.test.mjs.
 *
 * Single-source preserved: never hand-edit the bundle — edit the two sources + re-run this.
 * Usage: node scripts/bundle-base-post.mjs [outPath]
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const POSTS = path.join(__dirname, "..", "mcp-server", "data", "posts", "prism-base");
const CORE = path.join(POSTS, "prism-paths-feed.cps");
const POST = path.join(POSTS, "PRISM-Base-Hurco-3Axis.cps");

export function buildBundle() {
  const core = readFileSync(CORE, "utf8");
  const post = readFileSync(POST, "utf8").replace(/^\s*include\(.*$/m, "// [bundled] shared feed core inlined above (single source: prism-paths-feed.cps)");
  const banner =
    "/**\n * PRISM-Base-Hurco-3Axis-Bundled.cps — SHIPPED single-file Tier-1 post (DO NOT HAND-EDIT)\n" +
    " * Generated by scripts/bundle-base-post.mjs from:\n" +
    " *   - prism-paths-feed.cps  (shared adaptive-feed core)\n" +
    " *   - PRISM-Base-Hurco-3Axis.cps  (the post)\n" +
    " * Edit those sources, then re-bundle. The split sources are the single source of truth;\n" +
    " * this bundle is byte-verified to emit identical NC by prism-base-hurco.test.mjs.\n */\n\n";
  return banner + core + "\n\n// ============================ POST BODY ============================\n\n" + post;
}

function main() {
  const out = process.argv[2] || path.join(POSTS, "PRISM-Base-Hurco-3Axis-Bundled.cps");
  writeFileSync(out, buildBundle());
  console.log("bundled -> " + out + " (" + buildBundle().length + " bytes)");
}
const invokedDirectly = process.argv[1] && /bundle-base-post\.mjs$/.test(process.argv[1].replace(/\\/g, "/"));
if (invokedDirectly) main();
