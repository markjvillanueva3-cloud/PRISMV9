#!/usr/bin/env node
/**
 * wire-vendor-corpus-to-galaxies.mjs
 *
 * /goal Phase 2 (2026-05-31, slot charlie): plot the paths to everything the
 * VENDOR-NETWORK-MS0 catalog-pull expanded (PDFs, vendors, SFC manifest, JM
 * purchases, S/F extraction targets) and WIRE the relevant subset into the
 * 6 named consumer galaxies so each has direct access:
 *   speed-feed (oscar) · database-expansion (juliett) · mill (foxtrot) ·
 *   business (hotel) · post-processor (echo) · cam (kilo).
 *
 * Sibling of scripts/wire-galaxies-to-resource-roots.mjs (juliett, 2026-05-30) —
 * same MARKED-idempotent-block mechanism, but per-galaxy TAILORED (each galaxy
 * gets only its relevant artifacts + a domain "why") and scoped to the named
 * consumers (NOT fleet-wide). The 3 critical roots stay the uniform pointer;
 * this adds the fine-grained, actionable vendor-corpus pointer.
 *
 *   1. Reads the canonical index (source of truth):
 *      state/shared/quoting/VENDOR-CATALOG-CORPUS-INDEX.json
 *   2. Splices a MARKED, idempotent "## 🧰 Vendor catalog corpus" section into
 *      each consumer galaxy's PATHS.md (mcp-server/src/engines/<galaxy>/PATHS.md).
 *
 * IDEMPOTENT: re-running replaces the marked block in place (no duplication).
 * Re-run after every catalog-pull round so the galaxies always see current paths.
 *
 * Usage:
 *   node scripts/wire-vendor-corpus-to-galaxies.mjs            # apply
 *   node scripts/wire-vendor-corpus-to-galaxies.mjs --check    # dry-run freshness gate (exit 2 if stale)
 *
 * Karpathy: CLASSIFY=transform+wire · EDGE CASES=missing index / target galaxy
 * with no PATHS.md (warn+skip, never fabricate a dir) / re-run / orphaned marker /
 * unknown artifact id in consumer list · FAIL MODES=index missing or invalid JSON,
 * zero targets resolved.
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const INDEX_REL = "state/shared/quoting/VENDOR-CATALOG-CORPUS-INDEX.json";
const INDEX = path.join(REPO, INDEX_REL);
const ENGINES_DIR = path.join(REPO, "mcp-server/src/engines");

export const BEGIN = "<!-- BEGIN:vendor-catalog-corpus (generated by scripts/wire-vendor-corpus-to-galaxies.mjs — do not hand-edit) -->";
export const END = "<!-- END:vendor-catalog-corpus -->";

function escapeRegex(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/** Resolve an artifact id to its registry record; null if unknown (caller skips, loudly). */
export function resolveArtifact(index, id) {
  return (index.artifacts || []).find((a) => a.id === id) || null;
}

/**
 * Build the marked, idempotent section for one consumer galaxy.
 * Pure: same (galaxyName, index) → byte-identical output.
 * Returns null if the galaxy is not a declared consumer (caller skips).
 */
export function buildGalaxyBlock(galaxyName, index) {
  const consumer = (index.galaxyConsumers || {})[galaxyName];
  if (!consumer) return null;
  const s = index.summary || {};
  const lines = [];
  lines.push(BEGIN);
  lines.push("## 🧰 Vendor catalog corpus (VENDOR-NETWORK-MS0 — wired by charlie 2026-05-31)");
  lines.push(
    `> Cutting-tool maker/vendor catalog corpus charlie's catalog-pull expanded. ` +
      `Source of truth: \`${INDEX_REL}\` · owner: ${index.owner} (acquisition+triage); oscar owns the \`.ts\` S/F extraction. ` +
      `Corpus: **${s.sfc_makers ?? "?"} makers** (${s.sfc_high_extract ?? "?"} HIGH/not-ingested → extract now, ${s.sfc_on_disk ?? "?"} on-disk) · ` +
      `**${s.pulled_dir_pdfs ?? "?"} pulled PDFs** · **${s.directory_vendors ?? "?"}-vendor** directory.`
  );
  lines.push(`- **Why ${galaxyName} (${consumer.label}):** ${consumer.why}`);
  for (const id of consumer.artifacts || []) {
    const a = resolveArtifact(index, id);
    if (!a) {
      lines.push(`- ⚠ _(unresolved artifact id \`${id}\` — fix ${INDEX_REL})_`);
      continue;
    }
    lines.push(`- \`${a.path}\` (${a.kind}) — ${a.role}`);
  }
  lines.push(END);
  return lines.join("\n");
}

/**
 * Idempotently wire `block` into `content` at file-end. Strips all prior complete
 * BEGIN..END spans + orphaned lone markers, then appends once. Converges in a single
 * pass from any prior state; never loses non-marker content. (Same contract as the
 * resource-roots sibling.)
 */
export function spliceSection(content, block) {
  const fullRe = new RegExp(escapeRegex(BEGIN) + "[\\s\\S]*?" + escapeRegex(END), "g");
  let stripped = content.replace(fullRe, "");
  stripped = stripped
    .split(/\r?\n/)
    .filter((l) => l.trim() !== BEGIN.trim() && l.trim() !== END.trim())
    .join("\n");
  return stripped.replace(/\s*$/, "") + "\n\n" + block + "\n";
}

/** The declared consumer galaxies (keys of galaxyConsumers), sorted for stable output. */
export function discoverTargets(index) {
  return Object.keys(index.galaxyConsumers || {}).sort();
}

function main() {
  const check = process.argv.includes("--check");
  if (!fs.existsSync(INDEX)) {
    console.error(`[wire-vendor-corpus] FATAL: index not found: ${INDEX}`);
    process.exit(1);
  }
  let index;
  try {
    index = JSON.parse(fs.readFileSync(INDEX, "utf-8"));
  } catch (e) {
    console.error(`[wire-vendor-corpus] FATAL: index is not valid JSON: ${e.message}`);
    process.exit(1);
  }
  const targets = discoverTargets(index);

  let changed = 0;
  let unchanged = 0;
  let skipped = 0;
  const report = [];
  for (const g of targets) {
    const p = path.join(ENGINES_DIR, g, "PATHS.md");
    if (!fs.existsSync(p)) {
      skipped++;
      report.push(`skip   ${g}  (no PATHS.md at ${path.relative(REPO, p)} — galaxy dir absent; not fabricating)`);
      continue;
    }
    const before = fs.readFileSync(p, "utf-8");
    const block = buildGalaxyBlock(g, index);
    if (block == null) {
      skipped++;
      report.push(`skip   ${g}  (not a declared consumer)`);
      continue;
    }
    const after = spliceSection(before, block);
    const hadSection = before.includes(BEGIN);
    if (after !== before) {
      if (!check) fs.writeFileSync(p, after);
      changed++;
      report.push(`${hadSection ? "updated" : "wired  "} ${g}`);
    } else {
      unchanged++;
      report.push(`ok     ${g}`);
    }
  }

  console.log(`[wire-vendor-corpus] ${check ? "CHECK (no writes)" : "APPLIED"}`);
  console.log(`  consumer galaxies : ${targets.length}`);
  console.log(`  PATHS.md changed  : ${changed}`);
  console.log(`  PATHS.md unchanged: ${unchanged}`);
  console.log(`  skipped           : ${skipped}`);
  for (const r of report) console.log(`    ${r}`);
  if (targets.length === 0) {
    console.error("[wire-vendor-corpus] WARN: zero consumer galaxies in index");
    process.exit(1);
  }
  if (check && changed > 0) {
    console.error("[wire-vendor-corpus] --check: wiring STALE (changes pending) — run without --check to apply.");
    process.exit(2);
  }
}

// Run only when invoked directly (not when imported by the test).
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
