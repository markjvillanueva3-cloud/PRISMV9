#!/usr/bin/env node
/**
 * generate-engine-wiki.mjs
 *
 * Generates one Obsidian wiki entry per atomic engine at
 *   H:/prism/knowledge/wiki/architecture/engines/<domain>/<EngineName>.md
 *
 * Atomic engines are L5 nodes with subgroup=atomic_engine and id pattern
 *   eng.<domain>.<lowercased_name>
 *
 * Each entry surfaces:
 *   - engine name, domain, status (built|stub|stub_heavy)
 *   - parent layer/domain cross-refs
 *   - source path guess (mcp-server/src/engines/<EngineName>.ts)
 *   - related dispatcher (best-match L4 in the same domain)
 *
 * Output count: ~1696 entries grouped under 36 domain subdirectories.
 * Total runtime: ~5s on current graph.
 *
 * Idempotent — AUTO-START/END markers preserve human content.
 * Updates wiki/index.md ### Engines (per-domain index) subsection.
 *
 * Flags:
 *   --dry-run   skip writes
 *   --domain=X  generate only entries for domain X (useful for testing)
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { readGraphStreaming } from "./lib/graph-io.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PRISM_ROOT = resolve(__dirname, "..");
const GRAPH_PATH = resolve(PRISM_ROOT, "state/shared/system-viz/system-graph.json");
const WIKI_ARCH_DIR = resolve(PRISM_ROOT, "knowledge/wiki/architecture");
const WIKI_ENGINES_DIR = join(WIKI_ARCH_DIR, "engines");
const WIKI_INDEX = resolve(PRISM_ROOT, "knowledge/wiki/index.md");
const ENGINES_SRC = resolve(PRISM_ROOT, "mcp-server/src/engines");

const args = process.argv.slice(2);
const FLAGS = {
  dryRun: args.includes("--dry-run"),
  domainFilter: (args.find((a) => a.startsWith("--domain=")) || "").split("=")[1] || null,
};

const AUTO_START = "<!-- AUTO-START — regenerated by generate-engine-wiki.mjs -->";
const AUTO_END = "<!-- AUTO-END -->";

function readJson(p) {
  return JSON.parse(readFileSync(p, "utf8"));
}

function ensureDir(d) {
  if (!existsSync(d)) mkdirSync(d, { recursive: true });
}

function slug(s) {
  return String(s || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function indexGraph(G) {
  const nodeById = new Map();
  for (const n of G.nodes) nodeById.set(n.id, n);
  // Edge index: from → [to ids], to → [from ids]
  const outEdges = new Map();
  const inEdges = new Map();
  for (const e of G.edges) {
    (outEdges.get(e.from) || outEdges.set(e.from, []).get(e.from)).push(e.to);
    (inEdges.get(e.to) || inEdges.set(e.to, []).get(e.to)).push(e.from);
  }
  // Dispatchers keyed by domain match (label or id contains domain)
  const dispatchersByDomain = new Map();
  for (const n of G.nodes) {
    if (n.layer !== "L4") continue;
    const labelLc = (n.label || "").toLowerCase();
    const idLc = (n.id || "").toLowerCase();
    for (const d of [labelLc, idLc.replace(/^disp\./, "").replace(/dispatcher$/, "")]) {
      const arr = dispatchersByDomain.get(d) || [];
      arr.push(n);
      dispatchersByDomain.set(d, arr);
    }
  }
  return { nodeById, outEdges, inEdges, dispatchersByDomain };
}

function parseEngineId(id) {
  const m = /^eng\.([a-z0-9_]+)\.(.+)$/.exec(id);
  if (!m) return null;
  return { domain: m[1], engineSlug: m[2] };
}

function bestDispatcherMatch(domain, idx) {
  // Try exact-domain dispatcher first, then any L4 whose label starts with domain
  const exact = idx.dispatchersByDomain.get(domain);
  if (exact && exact.length) return exact[0];
  for (const [k, arr] of idx.dispatchersByDomain) {
    if (k.startsWith(domain) || domain.startsWith(k)) {
      if (arr.length) return arr[0];
    }
  }
  return null;
}

function guessSourcePath(engineName) {
  // engine name in label is already PascalCase (e.g. "AbrasiveJetMachiningEngine")
  // primary location: mcp-server/src/engines/<EngineName>.ts
  const candidate = join(ENGINES_SRC, `${engineName}.ts`);
  if (existsSync(candidate)) {
    return `mcp-server/src/engines/${engineName}.ts`;
  }
  return null;
}

function render(node, parsed, dispatcher, sourcePath, generatedAt) {
  const engineName = node.label || parsed.engineSlug;
  const status = node.status || "?";
  const domain = parsed.domain;
  const dispatcherLine = dispatcher
    ? `[[dispatcher-${slug(dispatcher.label || dispatcher.id)}]] — \`${dispatcher.label || dispatcher.id}\` (${dispatcher.subgroup || "?"})`
    : "_(no L4 dispatcher match — may need wiring)_";
  const sourceLine = sourcePath
    ? `\`${sourcePath}\``
    : "_(source not found at expected path — may be in a subdirectory)_";
  return `---
title: ${engineName}
type: engine
engine_id: ${node.id}
domain: ${domain}
parent_layer: L5
status: ${status}
generated_by: scripts/generate-engine-wiki.mjs
last_verified: ${generatedAt}
tags: [engine, domain-${slug(domain)}, status-${slug(status)}, atomic]
related:
  - knowledge/wiki/architecture/domain-${slug(domain)}.md
  - knowledge/wiki/architecture/layer-l5.md
  - state/shared/system-viz/system-graph.json
---

# ${engineName}

> Atomic engine in domain \`${domain}\` · status: **${status}**

${AUTO_START}

## Status

| Field | Value |
|-------|-------|
| Engine name | \`${engineName}\` |
| Graph node | \`${node.id}\` |
| Domain | [[domain-${slug(domain)}]] |
| Parent layer | [[layer-l5]] |
| Status | ${status} |

## Source

${sourceLine}

## Primary dispatcher

${dispatcherLine}

## Doctrine

- Engines should be wired to ≥1 dispatcher (else they are orphans flagged in BUILD_STATE)
- Do not bypass dispatcher when calling from frontend or another engine
- Tests must invoke through the dispatcher round-trip, not the engine singleton

${AUTO_END}

## See also

- Domain index: [[domain-${slug(domain)}]]
- Engine layer: [[layer-l5]]
- Live graph node: \`${node.id}\` in \`state/shared/system-viz/system-graph.json\`
`;
}

function preserveHuman(existing, full) {
  if (!existing) return full;
  const sStart = existing.indexOf(AUTO_START);
  const sEnd = existing.indexOf(AUTO_END);
  const nStart = full.indexOf(AUTO_START);
  const nEnd = full.indexOf(AUTO_END);
  if (sStart === -1 || sEnd === -1) return full;
  const before = existing.slice(0, sStart);
  const after = existing.slice(sEnd + AUTO_END.length);
  const newAuto = full.slice(nStart, nEnd + AUTO_END.length);
  return before + newAuto + after;
}

function updateIndex(domainSummary) {
  if (!existsSync(WIKI_INDEX)) return null;
  const text = readFileSync(WIKI_INDEX, "utf8");
  const lines = Object.entries(domainSummary)
    .sort((a, b) => b[1] - a[1])
    .map(([d, c]) => `- engines under \`${d}\`: ${c} entries — see \`knowledge/wiki/architecture/engines/${d}/\``);
  const block = ["<!-- ARCH-ENGINES-START -->", ...lines, "<!-- ARCH-ENGINES-END -->"].join("\n");
  if (text.includes("<!-- ARCH-ENGINES-START -->")) {
    return text.replace(/<!-- ARCH-ENGINES-START -->[\s\S]*?<!-- ARCH-ENGINES-END -->/m, block);
  }
  if (text.includes("<!-- ARCH-DISPATCHERS-END -->")) {
    return text.replace(
      /<!-- ARCH-DISPATCHERS-END -->/,
      "<!-- ARCH-DISPATCHERS-END -->\n\n### Engines (per-domain counts)\n\n" + block
    );
  }
  return text.trimEnd() + "\n\n### Engines\n\n" + block + "\n";
}

function main() {
  if (!existsSync(GRAPH_PATH)) {
    console.error("graph missing");
    process.exit(2);
  }
  // Streaming reader — graph file may exceed V8's ~512MB max-string-length
  // ceiling, in which case `JSON.parse(readFileSync(p, "utf8"))` crashes with
  // ERR_STRING_TOO_LONG. See scripts/lib/graph-io.mjs.
  const G = readGraphStreaming(GRAPH_PATH);
  const idx = indexGraph(G);
  const generatedAt = new Date().toISOString().split("T")[0];

  ensureDir(WIKI_ENGINES_DIR);

  let written = 0;
  let skipped = 0;
  const domainCounts = {};
  const t0 = Date.now();

  for (const node of G.nodes) {
    if (node.layer !== "L5") continue;
    const tag = node.subgroup || node.kind || "";
    if (tag !== "atomic_engine") continue;
    const parsed = parseEngineId(node.id);
    if (!parsed) {
      skipped++;
      continue;
    }
    if (FLAGS.domainFilter && parsed.domain !== FLAGS.domainFilter) continue;

    const dispatcher = bestDispatcherMatch(parsed.domain, idx);
    const sourcePath = guessSourcePath(node.label || parsed.engineSlug);
    const full = render(node, parsed, dispatcher, sourcePath, generatedAt);

    const domainDir = join(WIKI_ENGINES_DIR, parsed.domain);
    ensureDir(domainDir);
    const fileName = `${slug(node.label || parsed.engineSlug)}.md`;
    const outPath = join(domainDir, fileName);
    const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
    const finalContent = preserveHuman(existing, full);

    if (!FLAGS.dryRun) writeFileSync(outPath, finalContent, "utf8");
    written++;
    domainCounts[parsed.domain] = (domainCounts[parsed.domain] || 0) + 1;
  }

  const indexUpdated = !FLAGS.dryRun && !FLAGS.domainFilter ? updateIndex(domainCounts) : null;
  if (indexUpdated && !FLAGS.dryRun) writeFileSync(WIKI_INDEX, indexUpdated, "utf8");

  console.log(
    `generated ${written} engine wiki entries in ${Date.now() - t0}ms (skipped ${skipped}, domains: ${Object.keys(domainCounts).length})`
  );
}

main();
