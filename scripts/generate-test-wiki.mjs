#!/usr/bin/env node
/**
 * generate-test-wiki.mjs
 *
 * One wiki entry per test file under mcp-server/src/__tests__/**.*.test.ts
 * (~3,400 files — the last big uncovered surface; engines/actions/hooks/skills/
 * modules all have entries, the test suite didn't). Each entry surfaces:
 *   - the file's leading docblock (most start "<NAME>.test.ts — <subject> tests")
 *   - target engine/dispatcher (heuristic from filename: FooEngine.test.ts → FooEngine)
 *   - test count (it(/test() and assertion count (expect()
 *   - @milestone tag if present
 *   - first few describe()/it() titles (so the entry says what it actually checks)
 *
 * Output: knowledge/wiki/architecture/tests/<group>/<slug>.md  +  .../tests-index.md
 * Grouped by a filename-prefix "domain" (wedm/hypermill/lathe/mill/cam/cad/ppg/…) so no
 * single dir holds thousands of files. Catalog links every entry → no orphans.
 *
 * Idempotent. preserveHuman() keeps anything outside the AUTO markers. Flags: --dry-run
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { resolve, dirname, join, relative, basename } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PRISM_ROOT = resolve(__dirname, "..");
const TESTS_ROOT = resolve(PRISM_ROOT, "mcp-server/src/__tests__");
const WIKI_ARCH_DIR = resolve(PRISM_ROOT, "knowledge/wiki/architecture");
const OUT_DIR = join(WIKI_ARCH_DIR, "tests");
const INDEX_OUT = join(WIKI_ARCH_DIR, "tests-index.md");
const WIKI_INDEX = resolve(PRISM_ROOT, "knowledge/wiki/index.md");

const args = new Set(process.argv.slice(2));
const FLAGS = { dryRun: args.has("--dry-run"), full: args.has("--full") };

function say(s) { process.stdout.write(s + "\n"); }

const AUTO_START = "<!-- AUTO-START — regenerated by generate-test-wiki.mjs -->";
const AUTO_END = "<!-- AUTO-END -->";

const DOCBLOCK_LINES = 20;
const TITLE_SAMPLE = 6;          // describe()/it() titles to surface
const DESC_MAX = 200;
const RENDER_VERSION = 2;        // v2: type:test (was architecture)        // bump to force a full re-render after a render-logic change
const MTIME_SIDECAR = resolve(PRISM_ROOT, "state/shared/system-viz/.test-wiki-mtimes.json");
// sidecar shape: { v, files: { relPath: { mtime, name, group, it, expect, target, outPath } } }
// unchanged files skip the (slow) content read + render but still feed the index from the sidecar.

function loadSidecar() {
  if (FLAGS.full) return { v: RENDER_VERSION, files: {} };
  try {
    const j = JSON.parse(readFileSync(MTIME_SIDECAR, "utf8"));
    if (j && j.v === RENDER_VERSION && j.files) return j;
  } catch {}
  return { v: RENDER_VERSION, files: {} };
}

function ensureDir(d) { if (!existsSync(d)) mkdirSync(d, { recursive: true }); }
function slug(s) { return String(s || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 90) || "x"; }

function walkTestFiles(dir) {
  const out = [];
  function rec(d) {
    let entries;
    try { entries = readdirSync(d, { withFileTypes: true }); } catch { return; }
    for (const e of entries) {
      const full = join(d, e.name);
      if (e.isDirectory()) rec(full);
      else if (e.isFile() && /\.test\.ts$/.test(e.name)) out.push(full);
    }
  }
  rec(dir);
  return out;
}

function leadingDocblock(text) {
  const lines = text.split(/\r?\n/).slice(0, DOCBLOCK_LINES);
  const buf = [];
  let inBlock = false;
  for (const ln of lines) {
    const t = ln.trim();
    if (t.startsWith("/*") || inBlock) { inBlock = true; const s = t.replace(/^\/?\*+\/?/, "").replace(/\*\/$/, "").replace(/^={3,}$/, "").trim(); if (s && !/^@/.test(s)) buf.push(s); if (t.endsWith("*/")) break; continue; }
    if (t.startsWith("//")) { buf.push(t.replace(/^\/+\s?/, "")); continue; }
    if (buf.length && t === "") continue;
    if (buf.length) break;
  }
  return buf.join(" · ").slice(0, 400);
}

// FooEngine.test.ts → FooEngine ; foo-bar.test.ts → (none)
function targetFromName(name) {
  const base = basename(name, ".test.ts");
  const m = base.match(/^([A-Za-z][A-Za-z0-9]*(?:Engine|Dispatcher|Manager|Pipeline|Orchestrator|Bridge|Service|Registry|Hook))$/);
  return m ? m[1] : null;
}

// Known high-volume domain prefixes get their own dir; everything else is bucketed
// by first-2-chars of the slug (≤~36 buckets, ~95 files each) so no dir has thousands
// and we don't end up with thousands of 1-file dirs either.
const KNOWN_GROUPS = new Set([
  "wedm", "cwedm", "hypermill", "lathe", "mill", "cam", "cad", "ppg", "tool", "machine",
  "turning", "forge", "okuma", "fanuc", "haas", "mazak", "siemens", "fusion", "mastercam",
  "inventor", "solidworks", "esprit", "edm", "grinder", "sinker", "welder", "swiss", "xproc",
  "neural", "physics", "safety", "ai", "agi", "post", "blueprint", "print", "quote", "erp",
]);
function groupOf(name) {
  const base = basename(name, ".test.ts").toLowerCase();
  const first = (base.match(/^[a-z0-9]+/) || ["misc"])[0];
  if (/dispatcher$/.test(first)) return "dispatchers";
  if (KNOWN_GROUPS.has(first)) return first;
  const slugd = slug(base);
  const b2 = (slugd.match(/^[a-z0-9]{1,2}/) || ["_x"])[0];
  return `_${b2}`;
}

function sampleTitles(text, n = TITLE_SAMPLE) {
  const out = [];
  const re = /\b(?:describe|it|test)\(\s*[`'"]([^`'"]{3,120})[`'"]/g;
  let m;
  while ((m = re.exec(text)) !== null && out.length < n) out.push(m[1].trim());
  return out;
}

function render(file, gen) {
  const rel = relative(PRISM_ROOT, file).replace(/\\/g, "/");
  const name = basename(file, ".test.ts");
  let text = "", lineCount = 0, size = 0;
  try { const st = statSync(file); size = st.size; } catch {}
  try { text = readFileSync(file, "utf8"); lineCount = text.split(/\r?\n/).length; } catch {}
  const doc = leadingDocblock(text);
  const target = targetFromName(file);
  const itCount = (text.match(/\b(?:it|test)\s*\(/g) || []).length;
  const expectCount = (text.match(/\bexpect\s*\(/g) || []).length;
  const milestone = (text.match(/@milestone\s+([^\n*]+)/) || [, null])[1];
  const ttl = sampleTitles(text);
  const desc = (doc || `${name}.test.ts — ${itCount} test(s), ${expectCount} assertion(s)${target ? ` for ${target}` : ""}`).slice(0, DESC_MAX);
  const group = groupOf(file);
  return `---
title: Test — ${name}.test.ts
type: test
kind: test
test_path: ${rel}
group: ${group}${target ? `\ntarget: ${target}` : ""}${milestone ? `\nmilestone: ${milestone.trim()}` : ""}
it_count: ${itCount}
expect_count: ${expectCount}
line_count: ${lineCount}
generated_by: scripts/generate-test-wiki.mjs
last_verified: ${gen}
tags: [architecture, system-viz, test, ${slug(group)}${target ? `, ${slug(target)}` : ""}]
related:
  - knowledge/wiki/architecture/tests-index.md${target ? `\n  - knowledge/wiki/architecture/${slug(target)}.md` : ""}
---

# Test — \`${name}.test.ts\`

> ${desc}

${AUTO_START}

| Field | Value |
|-------|-------|
| Path | \`${rel}\` |
| Group | ${group} |${target ? `\n| Target | [[${slug(target)}]] (\`${target}\`) |` : ""}
| Tests (\`it\`/\`test\`) | ${itCount} |
| Assertions (\`expect\`) | ${expectCount} |
| Lines | ${lineCount} |${milestone ? `\n| Milestone | \`${milestone.trim()}\` |` : ""}

## What it checks (sampled describe/it titles)

${ttl.length ? ttl.map((t) => `- ${t}`).join("\n") : "_(no describe/it titles parsed — may use a non-standard runner pattern)_"}

## How to run

\`\`\`bash
cd mcp-server && npx vitest run src/__tests__/${rel.replace(/^mcp-server\/src\/__tests__\//, "")}
\`\`\`

(Or \`rtk vitest run …\` for token-reduced output.) After an engine edit, the post-edit hook suggests the matching test; this entry is the wiki index of it.

${AUTO_END}

## See also

- Test catalog: [[tests-index]]${target ? `\n- Engine under test: [[${slug(target)}]]` : ""}
- Run all: \`cd mcp-server && npx vitest run\` · coverage: \`/test-coverage\`
`;
}

function renderIndex(byGroup, total, gen) {
  const groups = Object.entries(byGroup).sort((a, b) => b[1].entries.length - a[1].entries.length);
  const sections = groups.map(([g, info]) => {
    const list = info.entries.slice().sort((a, b) => a.name.localeCompare(b.name)).map((e) => `- [[${e.name}]]${e.itCount ? ` _(${e.itCount} it, ${e.expectCount} expect)_` : ""}${e.target ? ` → [[${slug(e.target)}]]` : ""}`).join("\n");
    return `### \`${g}\` — ${info.entries.length} tests · ${info.itCount} it · ${info.expectCount} assertions\n\n${list}`;
  }).join("\n\n");
  const totIt = groups.reduce((s, [, i]) => s + i.itCount, 0);
  const totExp = groups.reduce((s, [, i]) => s + i.expectCount, 0);
  return `---
title: Tests — catalog
type: architecture
kind: test-index
total_tests: ${total}
total_groups: ${groups.length}
total_it: ${totIt}
total_expect: ${totExp}
generated_by: scripts/generate-test-wiki.mjs
last_verified: ${gen}
tags: [architecture, system-viz, test, catalog, index, qa]
related:
  - mcp-server/src/__tests__
  - knowledge/wiki/architecture/_stats.md
---

# Tests — catalog

> Every test file under \`mcp-server/src/__tests__/\` gets its own wiki entry. **${total} test files** in **${groups.length} groups** — ${totIt} \`it\`/\`test\` cases, ${totExp} \`expect\` assertions. Answers "is there a test for X?" / "what does \`Foo.test.ts\` cover?".

${AUTO_START}

**Total:** ${total} test files · ${groups.length} groups · ${totIt} test cases · ${totExp} assertions. Per-test entries under \`knowledge/wiki/architecture/tests/<group>/\`.

| Group | Tests | \`it\` cases | \`expect\` |
|-------|-------|-----------|-----------|
${groups.map(([g, i]) => `| \`${g}\` | ${i.entries.length} | ${i.itCount} | ${i.expectCount} |`).join("\n")}

${sections}

## Doctrine

- Tests verify **intent, not behavior** — every test encodes *why* the behavior matters (CLAUDE.md R9). \`toBeDefined()\` stubs are hook-rejected; real reference values / algebraic invariants only.
- After an engine edit, run the matching test (the post-edit hook suggests which). Full sweep: \`cd mcp-server && npx vitest run\`. Coverage: \`/test-coverage\`.
- A new engine ships with: real tests + dispatcher wiring + round-trip E2E (comprehensive-build enforcement).

${AUTO_END}

## See also

- Wiki stats: [[_stats]]
- Test-runner agent: \`test-runner\` (Agent subagent_type) · \`/test-coverage\` skill
- Vitest config: \`mcp-server/vitest.config.ts\`
`;
}

function preserveHuman(existing, full) {
  if (!existing) return full;
  const sStart = existing.indexOf(AUTO_START);
  const sEnd = existing.indexOf(AUTO_END);
  const nStart = full.indexOf(AUTO_START);
  const nEnd = full.indexOf(AUTO_END);
  if (sStart === -1 || sEnd === -1) return full;
  return existing.slice(0, sStart) + full.slice(nStart, nEnd + AUTO_END.length) + existing.slice(sEnd + AUTO_END.length);
}

function updateWikiIndex(total, groups) {
  if (!existsSync(WIKI_INDEX)) return null;
  const text = readFileSync(WIKI_INDEX, "utf8");
  const block = ["<!-- ARCH-TESTS-START -->",
    `_Total: ${total} per-test wiki entries across ${groups} groups — see [[tests-index]]._`,
    "", "Dir: `architecture/tests/<group>/`. Answers \"is there a test for X?\" / \"what does Foo.test.ts cover?\".",
    "<!-- ARCH-TESTS-END -->"].join("\n");
  if (text.includes("<!-- ARCH-TESTS-START -->")) return text.replace(/<!-- ARCH-TESTS-START -->[\s\S]*?<!-- ARCH-TESTS-END -->/m, block);
  if (text.includes("<!-- ARCH-MONOLITH-MODULES-END -->")) return text.replace(/<!-- ARCH-MONOLITH-MODULES-END -->/, "<!-- ARCH-MONOLITH-MODULES-END -->\n\n### Tests (per-test entries)\n\n" + block);
  return text.trimEnd() + "\n\n### Tests\n\n" + block + "\n";
}

function main() {
  if (!existsSync(TESTS_ROOT)) { say("test wiki: mcp-server/src/__tests__ missing — nothing to do"); return; }
  const gen = new Date().toISOString().split("T")[0];
  const t0 = Date.now();
  const files = walkTestFiles(TESTS_ROOT);
  if (!files.length) { say("test wiki: no .test.ts files found"); return; }
  if (!FLAGS.dryRun) ensureDir(OUT_DIR);
  const sidecar = loadSidecar();
  const nextSidecar = { v: RENDER_VERSION, files: {} };

  const byGroup = {};
  const usedPaths = new Set();
  let rendered = 0, reused = 0;
  for (const f of files) {
    const rel = relative(PRISM_ROOT, f).replace(/\\/g, "/");
    let mtime = 0; try { mtime = Math.round(statSync(f).mtimeMs); } catch {}
    const prev = sidecar.files[rel];
    const g = groupOf(f);
    const dir = join(OUT_DIR, slug(g));
    let fname = `${slug(basename(f, ".test.ts"))}.md`;
    let outPath = join(dir, fname);
    let n = 2; while (usedPaths.has(outPath)) { outPath = join(dir, fname.replace(/\.md$/, `-${n++}.md`)); }
    usedPaths.add(outPath);

    let meta;
    if (prev && prev.mtime === mtime && prev.outPath === outPath && existsSync(outPath)) {
      // unchanged — keep the file, reuse the index metadata
      meta = { name: prev.name, group: g, it: prev.it || 0, expect: prev.expect || 0, target: prev.target || null };
      reused++;
    } else {
      if (!FLAGS.dryRun) ensureDir(dir);
      const full = render(f, gen);
      const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
      if (!FLAGS.dryRun) writeFileSync(outPath, preserveHuman(existing, full), "utf8");
      const it = Number((full.match(/^it_count:\s*(\d+)/m) || [, 0])[1]);
      const exp = Number((full.match(/^expect_count:\s*(\d+)/m) || [, 0])[1]);
      const target = (full.match(/^target:\s*(.+)$/m) || [, null])[1];
      meta = { name: basename(outPath, ".md"), group: g, it, expect: exp, target };
      rendered++;
    }
    nextSidecar.files[rel] = { mtime, name: meta.name, group: g, it: meta.it, expect: meta.expect, target: meta.target, outPath };
    (byGroup[g] ||= { entries: [], itCount: 0, expectCount: 0 });
    byGroup[g].entries.push({ name: meta.name, itCount: meta.it, expectCount: meta.expect, target: meta.target });
    byGroup[g].itCount += meta.it; byGroup[g].expectCount += meta.expect;
  }

  if (!FLAGS.dryRun) {
    const idxExisting = existsSync(INDEX_OUT) ? readFileSync(INDEX_OUT, "utf8") : null;
    writeFileSync(INDEX_OUT, preserveHuman(idxExisting, renderIndex(byGroup, files.length, gen)), "utf8");
    const wi = updateWikiIndex(files.length, Object.keys(byGroup).length);
    if (wi) writeFileSync(WIKI_INDEX, wi, "utf8");
    try { writeFileSync(MTIME_SIDECAR, JSON.stringify(nextSidecar), "utf8"); } catch {}
  }

  say(`test wiki: ${files.length} entries across ${Object.keys(byGroup).length} groups (${rendered} rendered, ${reused} reused), ${Date.now() - t0}ms`);
}

main();
