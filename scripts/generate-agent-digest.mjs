#!/usr/bin/env node
/**
 * generate-agent-digest.mjs — 1-line-per-agent index for .claude/agents/.
 *
 * MEMORY-WIKI-OPTIMIZATION-MS0 / U-MWO06 (slot:bravo 2026-05-26).
 * Closes the discoverability gap: 103 agent files in .claude/agents/ but no
 * AGENT_DIGEST.md (parallel to mcp-server/data/docs/ENGINE_DIGEST.md).  Without
 * an index, operators reach for subagent_type by memory or guess.
 *
 * Reads .claude/agents/<name>.md, extracts the `description:` frontmatter field,
 * emits 1 line per agent: "agentname — first-sentence-of-description".
 *
 * Usage:  node scripts/generate-agent-digest.mjs [--out PATH]
 * Exit:   0 ok · 1 agents dir missing · 2 runtime error
 *
 * @module scripts/generate-agent-digest
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const DEFAULT_AGENTS_DIR = path.join(ROOT, ".claude", "agents");
const DEFAULT_OUT = path.join(ROOT, ".claude", "agents", "AGENT_DIGEST.md");

const MAX_DESC_CHARS = 180;

/** Parse YAML frontmatter (simple — top-level scalar fields only).  Returns {} on miss. */
export function parseFrontmatter(text) {
  if (!text.startsWith("---")) return {};
  const end = text.indexOf("\n---", 3);
  if (end < 0) return {};
  const block = text.slice(3, end);
  const out = {};
  for (const line of block.split(/\r?\n/)) {
    const m = line.match(/^([A-Za-z_][A-Za-z0-9_-]*)\s*:\s*(.+?)\s*$/);
    if (!m) continue;
    let val = m[2];
    // Strip wrapping quotes.
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    out[m[1]] = val;
  }
  return out;
}

/** Reduce a description to one tight line. */
export function tighten(desc) {
  if (!desc) return "(no description)";
  // First sentence: split on `. ` or newline, take first non-empty fragment.
  const firstSentence = desc.split(/\.\s|\n/)[0].trim();
  const flat = firstSentence.replace(/\s+/g, " ");
  return flat.length > MAX_DESC_CHARS ? `${flat.slice(0, MAX_DESC_CHARS - 1)}…` : flat;
}

/** Pure: build digest content from a list of {name, desc, model?} entries. */
export function render(entries) {
  const sorted = [...entries].sort((a, b) => a.name.localeCompare(b.name));
  const lines = [
    "# .claude/agents/ — AGENT_DIGEST.md",
    "",
    `_Auto-generated by \`scripts/generate-agent-digest.mjs\`. Closes discoverability gap (U-MWO06, slot:bravo 2026-05-26)._`,
    "",
    `**${sorted.length} agents** available via the Task tool's \`subagent_type\` parameter.`,
    "",
    "| Agent | Description |",
    "|-------|-------------|",
  ];
  for (const e of sorted) {
    const safeDesc = e.desc.replace(/\|/g, "\\|");
    lines.push(`| \`${e.name}\` | ${safeDesc} |`);
  }
  lines.push("");
  return lines.join("\n");
}

/** I/O wrapper. */
export function run({ agentsDir = DEFAULT_AGENTS_DIR, outPath = DEFAULT_OUT, fsImpl = fs } = {}) {
  if (!fsImpl.existsSync(agentsDir)) {
    return { ok: false, reason: "agents-dir-missing", path: agentsDir };
  }
  const entries = [];
  let names;
  try { names = fsImpl.readdirSync(agentsDir); }
  catch (e) { return { ok: false, reason: "readdir-failed", error: e instanceof Error ? e.message : String(e) }; }

  for (const name of names) {
    if (!name.endsWith(".md")) continue;
    if (name === "AGENT_DIGEST.md") continue; // don't index ourselves
    const file = path.join(agentsDir, name);
    let raw;
    try { raw = fsImpl.readFileSync(file, "utf8"); }
    catch { continue; }
    const fm = parseFrontmatter(raw);
    entries.push({
      name: name.replace(/\.md$/, ""),
      desc: tighten(fm.description || ""),
    });
  }

  const content = render(entries);
  fsImpl.writeFileSync(outPath, content, "utf8");
  return { ok: true, count: entries.length, outPath, bytes: content.length };
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith("generate-agent-digest.mjs")) {
  try {
    const result = run();
    process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
    process.exit(result.ok ? 0 : 1);
  } catch (e) {
    process.stderr.write(`generate-agent-digest: ${e instanceof Error ? e.message : String(e)}\n`);
    process.exit(2);
  }
}
