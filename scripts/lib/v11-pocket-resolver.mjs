/**
 * v11-pocket-resolver.mjs — pure functions that resolve PRISM's
 * UserToolLibrary state into a JS object literal the Hurco v11 .cps
 * can consume at emit time when Fusion's tool descriptors lack pocket /
 * length-offset / dia-offset / sister-tool / remaining-life data.
 *
 * Closes the iter12-confirmed v10/v11 tool-pocket tedium: operator
 * skips Fusion's tool-palette pocket fields, post falls back to
 * defaults. With this DB inlined as `var PRISM_TOOL_POCKET_DB = {…};`
 * the .cps does an automatic lookup by tool number → magazine pocket,
 * length offset (H#), dia offset (D#), sister-tool T-number, and
 * remaining tool-life (minutes).
 *
 * Pure-only — caller owns IO + .cps embedding.
 *
 * @milestone POST-BRIDGE-SYNERGY-MS0/U-V11-AUTO-POCKET-FROM-LIBRARY
 * @slot echo · @iter 23 · @date 2026-05-26
 */

/** Pure: derive Hurco H-offset register from magazine_position (1:1 by default). */
export function defaultLengthOffsetFromPocket(pocket) {
  const p = Number(pocket);
  if (!Number.isFinite(p) || p <= 0) return 0;
  return Math.floor(p);
}

/** Pure: derive Hurco D-offset register from magazine_position (1:1 by default). */
export function defaultDiaOffsetFromPocket(pocket) {
  const p = Number(pocket);
  if (!Number.isFinite(p) || p <= 0) return 0;
  return Math.floor(p);
}

/** Pure: clamp + classify a remaining-life ratio (0 = exhausted, 1 = fresh). */
export function lifeFraction(usedMin, avgLifeMin) {
  const u = Number(usedMin) || 0;
  const a = Number(avgLifeMin);
  if (!Number.isFinite(a) || a <= 0) return 1;
  const f = 1 - u / a;
  if (f < 0) return 0;
  if (f > 1) return 1;
  return f;
}

/** Pure: build a single pocket-record from a UserTool + optional crib usage. */
export function toolToPocketRecord(tool, crib = {}) {
  if (tool == null || typeof tool !== "object") return null;
  const pocket = Number(tool.magazine_position);
  if (!Number.isFinite(pocket) || pocket <= 0) return null;
  const h = Number.isFinite(Number(tool.length_offset)) ? Number(tool.length_offset) : defaultLengthOffsetFromPocket(pocket);
  const d = Number.isFinite(Number(tool.dia_offset)) ? Number(tool.dia_offset) : defaultDiaOffsetFromPocket(pocket);
  const used = Number(crib.total_usage_min) || 0;
  const life = Number(crib.avg_life_min) || Number(tool.avg_life_min) || 0;
  return {
    pocket,
    h_offset: h,
    d_offset: d,
    sister_pocket: Number.isFinite(Number(tool.sister_pocket)) ? Number(tool.sister_pocket) : null,
    life_remaining_min: life > 0 ? Math.max(0, life - used) : null,
    life_fraction: lifeFraction(used, life),
    diameter_mm: Number(tool.diameter_mm) || null,
    flutes: Number(tool.flutes) || null,
    machine_name: tool.machine_name || null,
  };
}

/** Pure: build the full pocket-DB keyed by tool number (T#). Filters by machine_name if supplied. */
export function buildPocketDb(tools, options = {}) {
  const machineName = options.machine_name || null;
  const cribByToolId = options.cribByToolId instanceof Map ? options.cribByToolId : new Map();
  const out = {};
  let included = 0;
  let skippedNoMachine = 0;
  let skippedNoPocket = 0;
  for (const tool of tools || []) {
    if (tool == null) continue;
    if (machineName && tool.machine_name && tool.machine_name !== machineName) { skippedNoMachine++; continue; }
    if (machineName && !tool.machine_name) { skippedNoMachine++; continue; }
    const crib = cribByToolId.get(tool.id) || {};
    const rec = toolToPocketRecord(tool, crib);
    if (rec == null) { skippedNoPocket++; continue; }
    out["T" + rec.pocket] = rec;
    included++;
  }
  return { db: out, stats: { included, skippedNoMachine, skippedNoPocket, machineFilter: machineName } };
}

/** Pure: render the pocket DB as a Fusion-postable JS var-declaration string. */
export function renderPocketDbAsJs(db, options = {}) {
  const varName = options.varName || "PRISM_TOOL_POCKET_DB";
  const generatedAt = options.generatedAt || new Date().toISOString();
  const machine = options.machine_name || "(any)";
  const lines = [];
  lines.push("// AUTO-GENERATED by scripts/generate-v11-pocket-db.mjs");
  lines.push("// Source: PRISM UserToolLibrary + ToolCrib usage");
  lines.push("// Consumer: HURCO_VM30i_PRISM_v*.cps — fallback when Fusion lacks pocket data");
  lines.push("// Machine filter: " + machine + " · Generated: " + generatedAt);
  lines.push("var " + varName + " = {");
  for (const key of Object.keys(db || {}).sort((a, b) => {
    const na = Number(String(a).replace(/^T/, ""));
    const nb = Number(String(b).replace(/^T/, ""));
    return na - nb;
  })) {
    const r = db[key];
    const sister = r.sister_pocket == null ? "null" : ("T" + r.sister_pocket);
    const sisterStr = sister === "null" ? "null" : "\"" + sister + "\"";
    const life = r.life_remaining_min == null ? "null" : r.life_remaining_min.toFixed(1);
    lines.push("  \"" + key + "\": { pocket: " + r.pocket + ", H: " + r.h_offset + ", D: " + r.d_offset + ", sister: " + sisterStr + ", life_min: " + life + ", D_mm: " + (r.diameter_mm == null ? "null" : r.diameter_mm) + ", flutes: " + (r.flutes == null ? "null" : r.flutes) + " },");
  }
  lines.push("};");
  return lines.join("\n");
}

/** Pure: lookup helper used at emit time — returns pocket record or null. */
export function lookupPocket(db, toolNumber) {
  if (db == null || typeof db !== "object") return null;
  const n = Number(toolNumber);
  if (!Number.isFinite(n) || n <= 0) return null;
  return db["T" + n] || null;
}
