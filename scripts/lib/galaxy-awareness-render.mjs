/**
 * galaxy-awareness-render.mjs -- PURE renderer for a galaxy's AWARENESS.md
 * (AI-SYNERGY-AUDIT-MS0/U-AISYN-AWARENESS-MD, slot:charlie).
 *
 * Turns ONE per-galaxy record from state/shared/specs/AI-SYNERGY-AUDIT.json into a
 * compact, grounded AWARENESS.md doctrine file -- the dedicated per-galaxy AI-synergy
 * awareness surface. It is auto-loaded (Bibryam context cascade) when a chat works in
 * mcp-server/src/engines/<galaxy>/, so every galaxy carries a DURABLE, version-
 * controlled statement of (a) how it uses AI, (b) the exact invocation to reason over
 * its own context via the local-Ollama reasoning bridge, and (c) its vault / cross-
 * substrate synergy facts -- richer than the ephemeral fleet-hook auto-inject.
 *
 * PURE: no fs, no clock, no randomness. The galaxy record + an audit timestamp in =>
 * byte-identical markdown out, so it is fully unit-testable (R9). The composite score
 * is deliberately NOT printed (it would be stale the instant this file is credited as
 * an awareness surface); the 4 STABLE sub-dimensions + qualitative capability facts ARE
 * printed, with a pointer to the full live audit for the composite (R12 honesty).
 */

/** ASCII-only guard: the repo blocks em-dash / smart quotes in code+doc files. */
function asciiClean(s) {
  return String(s == null ? "" : s);
}

/** Human description of HOW this galaxy owns-or-wires AI, from its signals. */
export function describeOwnsOrWires(signals) {
  const s = signals || {};
  const parts = [];
  if (Number(s.aiEngineCount) > 0) {
    const bd = s.typeBreakdown && Object.keys(s.typeBreakdown).length
      ? ` (${Object.entries(s.typeBreakdown).map(([k, v]) => `${v} ${k}`).join(", ")})`
      : "";
    parts.push(`owns ${s.aiEngineCount} name-attributed AI engine(s)${bd}`);
  }
  if (Number(s.bridgeCount) > 0) parts.push(`${s.bridgeCount} reasoning/neural bridge engine(s)`);
  if (Number(s.aiDispatcherActions) > 0) parts.push(`${s.aiDispatcherActions} per-galaxy AI dispatcher action(s)`);
  if (s.servedByReasoningBridge) parts.push("served by the live-validated generic reasoning bridge (leg #10)");
  if (!parts.length) return "no name-attributed AI assets (reasons via the fleet AI substrate)";
  return parts.join("; ");
}

/**
 * Render the AWARENESS.md body for one galaxy. PURE.
 * @param {object} record one element of AI-SYNERGY-AUDIT.json.galaxies
 * @param {object} opts { auditDate?, auditPath? }
 * @returns {string} markdown (ASCII-only, trailing newline)
 */
export function renderAwarenessMd(record, opts = {}) {
  if (!record || typeof record.galaxy !== "string" || !record.galaxy.trim()) {
    throw new Error("renderAwarenessMd: record.galaxy (non-empty string) required");
  }
  const g = record.galaxy.trim();
  const s = record.subScores || {};
  const sig = record.signals || {};
  const auditDate = asciiClean(opts.auditDate || "unknown");
  const auditPath = asciiClean(opts.auditPath || "state/shared/specs/AI-SYNERGY-AUDIT.md");

  const edges = sig.edges || {};
  const edgeList = Object.entries({
    "owned-by-slot": edges.ownedBySlot,
    "documented-by": edges.documentedBy,
    "consensus-of": edges.consensusOf,
    embeds: edges.embeds,
  })
    .filter(([, v]) => v)
    .map(([k]) => k);

  const examples = Array.isArray(sig.aiEngineExamples) ? sig.aiEngineExamples.slice(0, 5) : [];
  const dispEx = Array.isArray(sig.aiDispatcherActionExamples) ? sig.aiDispatcherActionExamples.slice(0, 5) : [];

  const L = [];
  L.push(`# ${g} -- AI-synergy awareness`);
  L.push("");
  L.push(`> Auto-generated by \`scripts/generate-galaxy-awareness.mjs\` from \`state/shared/specs/AI-SYNERGY-AUDIT.json\` (audit ${auditDate}).`);
  L.push("> Bibryam context-cascade surface: auto-loaded when a chat works in this galaxy dir. Do NOT hand-edit -- re-run the generator.");
  L.push("> Dedicated per-galaxy AI awareness surface (AI-SYNERGY-AUDIT-MS0/U-AISYN-AWARENESS-MD).");
  L.push("");
  L.push("## How this galaxy uses AI");
  L.push(`- ${describeOwnsOrWires(sig)}`);
  L.push("- Reason over THIS galaxy's own context (CLAUDE + synthesis + posture) via local Ollama, free:");
  L.push("  ```bash");
  L.push(`  node scripts/lib/galaxy-reasoning-bridge.mjs ${g} "<your question about this galaxy>"`);
  L.push("  ```");
  L.push("");
  L.push("## AI assets (name-heuristic, advisory)");
  L.push(`- AI engines attributed: **${Number(sig.aiEngineCount) || 0}**${examples.length ? ` e.g. ${examples.join(", ")}` : ""}`);
  L.push(`- AI dispatcher actions: **${Number(sig.aiDispatcherActions) || 0}**${dispEx.length ? ` e.g. ${dispEx.join(", ")}` : ""}`);
  L.push(`- reasoning/neural bridges: **${Number(sig.bridgeCount) || 0}**`);
  L.push("");
  L.push("## Vault + cross-substrate synergy");
  L.push(`- Obsidian synthesis brain: \`knowledge/memories/patterns/${g}_synthesis.md\` -- ${sig.hasSynthesis ? "present" : "ABSENT (gap)"}`);
  L.push(`- LoRA training-dataset feed: ${sig.inLoraDataset ? "yes (galaxy in vault->LoRA dataset)" : "NO (gap)"}`);
  L.push(`- typed cross-substrate edges: ${edgeList.length ? edgeList.join(", ") : "none yet"}`);
  L.push("");
  L.push("## PSN legs this galaxy touches");
  L.push("- #1 Obsidian brain (synthesis + memories) | #3 Wiki | #6 system-viz (cross-substrate edges)");
  L.push(`- #10 NN/GNN reasoning -- via ${sig.servedByReasoningBridge || Number(sig.bridgeCount) > 0 ? "the reasoning bridge" : "the fleet AI router"}`);
  L.push("");
  L.push("## Stable sub-posture (as of the audit above)");
  L.push("| dim | score |");
  L.push("|-----|-------|");
  L.push(`| discoverability (CLAUDE+MEMORY name AI) | ${s.discoverability != null ? s.discoverability : "n/a"} |`);
  L.push(`| ownsOrWiresAi | ${s.ownsOrWiresAi != null ? s.ownsOrWiresAi : "n/a"} |`);
  L.push(`| vaultSynergy | ${s.vaultSynergy != null ? s.vaultSynergy : "n/a"} |`);
  L.push(`| crossSubstrate | ${s.crossSubstrate != null ? s.crossSubstrate : "n/a"} |`);
  L.push("");
  L.push(`_Composite score is live (drifts as the fleet evolves) -- see \`${auditPath}\` row \`${g}\`. This file IS this galaxy's awarenessSurface dimension._`);
  L.push("");
  return L.join("\n");
}
