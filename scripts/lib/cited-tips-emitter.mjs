/**
 * cited-tips-emitter.mjs — pure functions that convert curriculum
 * tribal-tip candidates into typed TypeScript CitedTip entries for
 * `mcp-server/src/data/tribal-tips/{controller}-cited-tips.ts`.
 *
 * Mirrors the iter6 CitedPostTip shape; one file per controller. Auto-
 * emission is the operator-curation step (manual review optional). Each
 * tip carries id + sourceId + citation + body + signals + score so the
 * post-processor + classifier engines can rank tips by provenance and
 * difficulty.
 *
 * @milestone POST-PDF-NODE-MS0/U-CITED-TIPS-EMIT
 * @slot echo · @iter 13 · @date 2026-05-26
 */

const TS_HEADER = `/**
 * AUTO-GENERATED by scripts/generate-cited-tips-from-candidates.mjs.
 * Source: mcp-server/data/ingestion_cache/curriculum-tribal-candidates/jm-die-curriculum-tribal-candidates.jsonl
 * Do not edit by hand — re-run the generator instead. Manual curation:
 * mark accepted tips with status:"approved" via a sibling overlay.
 */
`;

const TS_INTERFACE = `export interface CitedTip {
  readonly id: string;
  readonly sourceId: string;
  readonly sourceTitle: string;
  readonly citation: string;
  readonly page: number;
  readonly domain: string;
  readonly controller: string | null;
  readonly vendor: string | null;
  readonly difficulty: "easy" | "intermediate" | "advanced" | "complex";
  readonly score: number;
  readonly bodyLength: number;
  readonly body: string;
}
`;

/** Pure: cap body text to N chars (default 2000) for the TS file to keep diffs reviewable. */
export function truncateBody(body, max) {
  const limit = Number.isInteger(max) && max > 0 ? max : 2000;
  const s = String(body || "");
  if (s.length <= limit) return s;
  return s.slice(0, limit) + "\n…[truncated " + (s.length - limit) + " chars]";
}

/** Pure: escape a string for embedding inside a TS double-quoted template literal-safe block. */
export function escapeForTemplate(s) {
  return String(s || "")
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");
}

/** Pure: render a single candidate as a TS object literal entry. */
export function renderTipEntry(cand, opts = {}) {
  const body = truncateBody(cand.body, opts.maxBodyChars);
  const escapedBody = escapeForTemplate(body);
  const ctl = cand.controller ? `"${cand.controller}"` : "null";
  const ven = cand.vendor ? `"${cand.vendor}"` : "null";
  const sourceTitle = String(cand.sourceTitle || "").replace(/"/g, '\\"');
  const sourceId = String(cand.sourceId || "").replace(/"/g, '\\"');
  const citation = String(cand.citation || "").replace(/"/g, '\\"');
  const domain = String(cand.domain || "reference").replace(/"/g, '\\"');
  const diff = String(cand.difficulty || "easy").replace(/"/g, '\\"');
  return `  {
    id: "${cand.id}",
    sourceId: "${sourceId}",
    sourceTitle: "${sourceTitle}",
    citation: "${citation}",
    page: ${cand.page || 0},
    domain: "${domain}",
    controller: ${ctl},
    vendor: ${ven},
    difficulty: "${diff}",
    score: ${typeof cand.score === "number" ? cand.score : 0},
    bodyLength: ${cand.body ? cand.body.length : 0},
    body: \`${escapedBody}\`,
  },`;
}

/** Pure: full TS file body for a controller's tips array. */
export function renderTipsFile(controller, tips, opts = {}) {
  const controllerSafe = String(controller || "unknown").toLowerCase().replace(/[^a-z0-9]/g, "_");
  const constName = `${controllerSafe.toUpperCase()}_CITED_TIPS`;
  const entries = (tips || []).map((t) => renderTipEntry(t, opts)).join("\n");
  return [
    TS_HEADER,
    TS_INTERFACE,
    `export const ${constName}: readonly CitedTip[] = [`,
    entries,
    `] as const;`,
    ``,
    `export const ${constName}_STATS = {`,
    `  controller: "${controllerSafe}",`,
    `  count: ${tips.length},`,
    `  generatedAt: "${new Date().toISOString()}",`,
    `} as const;`,
    ``,
  ].join("\n");
}

/** Pure: bucket candidates by controller; null/unspecified bucketed separately. */
export function bucketByController(candidates) {
  const out = new Map();
  for (const c of candidates || []) {
    const k = c?.controller || "unspecified";
    if (!out.has(k)) out.set(k, []);
    out.get(k).push(c);
  }
  return out;
}

/** Pure: deterministic ranking — score desc, then id asc — for stable diffs. */
export function rankCandidatesForEmit(candidates) {
  if (!Array.isArray(candidates)) return [];
  return candidates.slice().sort((a, b) => {
    const sb = typeof b?.score === "number" ? b.score : 0;
    const sa = typeof a?.score === "number" ? a.score : 0;
    if (sb !== sa) return sb - sa;
    return String(a?.id || "").localeCompare(String(b?.id || ""));
  });
}
