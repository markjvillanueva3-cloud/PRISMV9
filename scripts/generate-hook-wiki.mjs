#!/usr/bin/env node
/**
 * generate-hook-wiki.mjs
 *
 * Generates one Obsidian wiki entry per Claude Code hook at
 *   H:/prism/knowledge/wiki/architecture/hooks/<source>/<name>.md
 *
 * Reads:
 *   - H:/prism/.claude/hooks/*.mjs         (project, runtime)
 *   - H:/prism/mcp-server/src/hooks/*.ts   (engine source-of-truth)
 *
 * Each entry surfaces hook name, source path, header description, and
 * the typical event surface (SessionStart, PreToolUse, etc.) inferred from
 * the file body.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync } from "node:fs";
import { resolve, dirname, join, basename } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PRISM_ROOT = resolve(__dirname, "..");
const WIKI_ARCH_DIR = resolve(PRISM_ROOT, "knowledge/wiki/architecture");
const HOOKS_DIR = join(WIKI_ARCH_DIR, "hooks");
const WIKI_INDEX = resolve(PRISM_ROOT, "knowledge/wiki/index.md");

const SOURCES = {
  runtime: { dir: resolve(PRISM_ROOT, ".claude/hooks"), ext: ".mjs" },
  engine: { dir: resolve(PRISM_ROOT, "mcp-server/src/hooks"), ext: ".ts" },
};

const AUTO_START = "<!-- AUTO-START — regenerated by generate-hook-wiki.mjs -->";
const AUTO_END = "<!-- AUTO-END -->";

const EVENT_TYPES = ["SessionStart", "UserPromptSubmit", "PreToolUse", "PostToolUse", "Stop", "PreCompact", "SessionEnd", "Notification"];

function ensureDir(d) { if (!existsSync(d)) mkdirSync(d, { recursive: true }); }
function slug(s) { return String(s || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""); }

function listHooks(dir, ext) {
  if (!existsSync(dir)) return [];
  try {
    return readdirSync(dir, { withFileTypes: true })
      .filter((e) => e.isFile() && e.name.endsWith(ext))
      .map((e) => join(dir, e.name));
  } catch {
    return [];
  }
}

function extractHeaderDoc(content) {
  // Look for top-of-file JSDoc/block comment
  const m = content.match(/^\/\*\*?([\s\S]*?)\*\//);
  if (!m) return "";
  return m[1].replace(/^\s*\*?\s?/gm, "").trim();
}

function inferEvents(content, name) {
  const found = new Set();
  for (const ev of EVENT_TYPES) {
    if (content.includes(ev)) found.add(ev);
  }
  // Filename pattern fallback
  if (name.includes("sessionstart") || name.includes("session-start")) found.add("SessionStart");
  if (name.includes("precompact") || name.includes("pre-compact")) found.add("PreCompact");
  if (name.includes("stop")) found.add("Stop");
  if (name.includes("pretool") || name.includes("pre-tool")) found.add("PreToolUse");
  if (name.includes("posttool") || name.includes("post-tool")) found.add("PostToolUse");
  return [...found];
}

function render(source, hookPath, header, events, generatedAt) {
  const name = basename(hookPath).replace(/\.(mjs|ts)$/, "");
  const desc = header.slice(0, 500) || "_(no header docblock — read source for behavior)_";
  return `---
title: Hook — ${name}
type: hook
hook_name: ${name}
hook_source: ${source}
source_path: ${hookPath.replace(/\\/g, "/")}
events: [${events.join(", ")}]
generated_by: scripts/generate-hook-wiki.mjs
last_verified: ${generatedAt}
tags: [hook, source-${source}, ${events.map((e) => `event-${e.toLowerCase()}`).join(", ")}]
related:
  - knowledge/wiki/architecture/layer-l6.md
---

# Hook — \`${name}\`

**Source:** ${source}  ·  **File:** \`${hookPath.replace(/\\/g, "/")}\`
**Triggers on:** ${events.length ? events.join(", ") : "_(events not inferable from source)_"}

${AUTO_START}

## Description (from file header)

${desc}

## Events

${events.length ? events.map((e) => `- \`${e}\``).join("\n") : "_(no event signatures found — may be a helper or imported by another hook)_"}

## Doctrine

- Hooks are enforced by the Claude Code harness on every applicable event
- Source-of-truth lives in \`H:/.claude/settings.json\` (project + user merged)
- Source files in \`.claude/hooks/\` (runtime) and \`mcp-server/src/hooks/\` (engine)
- Hook output convention: print to stdout, return JSON \`{ continue: true }\` to proceed

${AUTO_END}

## See also

- Engine layer: [[layer-l6]]
- Hook bus settings: \`H:/.claude/settings.json\`
- Verify hook refs: \`node H:/prism/.claude/helpers/verify-hook-refs.mjs\`
`;
}

function preserveHuman(existing, full) {
  if (!existing) return full;
  const sStart = existing.indexOf(AUTO_START);
  const sEnd = existing.indexOf(AUTO_END);
  const nStart = full.indexOf(AUTO_START);
  const nEnd = full.indexOf(AUTO_END);
  if (sStart === -1 || sEnd === -1) return full;
  return existing.slice(0, sStart) + full.slice(nStart, nEnd + AUTO_END.length) + existing.slice(sEnd + AUTO_END.length);
}

function updateIndex(counts) {
  if (!existsSync(WIKI_INDEX)) return null;
  const text = readFileSync(WIKI_INDEX, "utf8");
  const lines = Object.entries(counts).map(([s, c]) => `- ${s}: ${c} hooks`);
  const block = ["<!-- ARCH-HOOKS-START -->", `_Total: ${Object.values(counts).reduce((a, b) => a + b, 0)} hook entries_`, "", ...lines, "<!-- ARCH-HOOKS-END -->"].join("\n");
  if (text.includes("<!-- ARCH-HOOKS-START -->")) {
    return text.replace(/<!-- ARCH-HOOKS-START -->[\s\S]*?<!-- ARCH-HOOKS-END -->/m, block);
  }
  if (text.includes("<!-- ARCH-SKILLS-END -->")) {
    return text.replace(/<!-- ARCH-SKILLS-END -->/, "<!-- ARCH-SKILLS-END -->\n\n### Hooks\n\n" + block);
  }
  return text.trimEnd() + "\n\n### Hooks\n\n" + block + "\n";
}

function main() {
  ensureDir(HOOKS_DIR);
  const generatedAt = new Date().toISOString().split("T")[0];
  const counts = {};
  let total = 0;
  const t0 = Date.now();

  for (const [source, { dir, ext }] of Object.entries(SOURCES)) {
    const hooks = listHooks(dir, ext);
    counts[source] = hooks.length;
    const sourceDir = join(HOOKS_DIR, source);
    ensureDir(sourceDir);
    for (const path of hooks) {
      let content = "";
      try { content = readFileSync(path, "utf8"); } catch { continue; }
      const header = extractHeaderDoc(content);
      const name = basename(path).replace(/\.(mjs|ts)$/, "");
      const events = inferEvents(content, name.toLowerCase());
      const outPath = join(sourceDir, `${slug(name)}.md`);
      const full = render(source, path, header, events, generatedAt);
      const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
      writeFileSync(outPath, preserveHuman(existing, full), "utf8");
      total++;
    }
  }

  const indexUpdated = updateIndex(counts);
  if (indexUpdated) writeFileSync(WIKI_INDEX, indexUpdated, "utf8");
  console.log(`generated ${total} hook wiki entries in ${Date.now() - t0}ms (sources: ${JSON.stringify(counts)})`);
}

main();
