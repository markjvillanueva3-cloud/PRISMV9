/**
 * migrate-hooks-to-rpc.test.mjs — U-DOCKER-HOOK-BROKER-P5
 *
 * Hermetic tests for the migration orchestrator. Build a temp dir with
 * synthetic hook files, drive `planMigration` / `applyMigrate` / `planUndo`
 * / `run` against it, assert the on-disk shape after each phase.
 */

import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, writeFileSync, readFileSync, existsSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import {
  shimContent,
  planMigration,
  planUndo,
  applyMigrate,
  applyUndo,
  renderStep,
  run,
} from "./migrate-hooks-to-rpc.mjs";

describe("shimContent", () => {
  it("includes the hook name + runShim call", () => {
    const s = shimContent("foo-hook");
    assert.match(s, /import \{ runShim \} from "\.\/_rpc-shim\.mjs"/);
    assert.match(s, /await runShim\("foo-hook", import\.meta\.url\)/);
  });

  it("escapes names with special characters via JSON.stringify", () => {
    const s = shimContent('quotes"in name');
    assert.match(s, /runShim\("quotes\\"in name"/);
  });

  it("includes the AUTO-GENERATED banner", () => {
    assert.match(shimContent("x"), /AUTO-GENERATED by scripts\/migrate-hooks-to-rpc\.mjs/);
  });
});

describe("planMigration", () => {
  it("classifies as 'migrate' for existing un-migrated files", () => {
    const dir = mkdtempSync(join(tmpdir(), "mhr-plan-"));
    try {
      const p = join(dir, "a.mjs");
      writeFileSync(p, "// original\n");
      const plan = planMigration([p]);
      assert.equal(plan.length, 1);
      assert.equal(plan[0].action, "migrate");
      assert.equal(plan[0].name, "a");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("classifies as 'skip-migrated' when .original.mjs already exists", () => {
    const dir = mkdtempSync(join(tmpdir(), "mhr-plan-skip-"));
    try {
      const p = join(dir, "b.mjs");
      writeFileSync(p, "// shim\n");
      writeFileSync(join(dir, "b.original.mjs"), "// real\n");
      const plan = planMigration([p]);
      assert.equal(plan[0].action, "skip-migrated");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("classifies as 'skip-missing' when source no longer exists", () => {
    const dir = mkdtempSync(join(tmpdir(), "mhr-plan-missing-"));
    try {
      const plan = planMigration([join(dir, "ghost.mjs")]);
      assert.equal(plan[0].action, "skip-missing");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});

describe("planUndo", () => {
  it("classifies as 'undo' when .original.mjs peer exists", () => {
    const dir = mkdtempSync(join(tmpdir(), "mhr-undo-"));
    try {
      const p = join(dir, "c.mjs");
      writeFileSync(p, shimContent("c"));
      writeFileSync(join(dir, "c.original.mjs"), "// original\n");
      const plan = planUndo([p]);
      assert.equal(plan[0].action, "undo");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("classifies as 'skip-pristine' when no .original.mjs peer", () => {
    const dir = mkdtempSync(join(tmpdir(), "mhr-undo-pristine-"));
    try {
      const p = join(dir, "d.mjs");
      writeFileSync(p, "// never migrated\n");
      const plan = planUndo([p]);
      assert.equal(plan[0].action, "skip-pristine");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});

describe("applyMigrate + applyUndo (round-trip)", () => {
  it("migrate: renames original → .original.mjs, writes shim to <name>.mjs", () => {
    const dir = mkdtempSync(join(tmpdir(), "mhr-rt-"));
    try {
      const p = join(dir, "rt.mjs");
      const originalBody = "// real hook logic\nexport default (s) => s.length;\n";
      writeFileSync(p, originalBody);
      applyMigrate({ filePath: p, name: "rt" });
      assert.equal(existsSync(p), true);
      assert.equal(existsSync(join(dir, "rt.original.mjs")), true);
      assert.equal(readFileSync(join(dir, "rt.original.mjs"), "utf8"), originalBody);
      assert.match(readFileSync(p, "utf8"), /runShim\("rt", import\.meta\.url\)/);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("undo: restores .original.mjs over the shim file", () => {
    const dir = mkdtempSync(join(tmpdir(), "mhr-undo-rt-"));
    try {
      const p = join(dir, "back.mjs");
      const originalBody = "// real logic v2\n";
      // Start in migrated state.
      writeFileSync(p, shimContent("back"));
      writeFileSync(join(dir, "back.original.mjs"), originalBody);
      // Undo.
      applyUndo({ filePath: p, name: "back" });
      // Current file should be the original content again.
      assert.equal(readFileSync(p, "utf8"), originalBody);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});

describe("run end-to-end (dry-run + apply + undo)", () => {
  it("dry-run reports planned actions without mutating disk", () => {
    const dir = mkdtempSync(join(tmpdir(), "mhr-dry-"));
    try {
      const a = join(dir, "a.mjs");
      const b = join(dir, "b.mjs");
      writeFileSync(a, "// hook a\n");
      writeFileSync(b, "// hook b\n");
      const summary = run({ files: [a, b], apply: false });
      assert.equal(summary.planned, 2);
      assert.equal(summary.applied, 0);
      assert.equal(summary.failed, 0);
      assert.equal(summary.steps.every((s) => s.status === "planned"), true);
      // Disk untouched
      assert.equal(existsSync(join(dir, "a.original.mjs")), false);
      assert.equal(existsSync(join(dir, "b.original.mjs")), false);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("--apply migrates all files end-to-end", () => {
    const dir = mkdtempSync(join(tmpdir(), "mhr-apply-"));
    try {
      const a = join(dir, "a.mjs");
      const b = join(dir, "b.mjs");
      writeFileSync(a, "// hook a body\n");
      writeFileSync(b, "// hook b body\n");
      const summary = run({ files: [a, b], apply: true });
      assert.equal(summary.applied, 2);
      assert.equal(summary.failed, 0);
      assert.equal(existsSync(join(dir, "a.original.mjs")), true);
      assert.equal(existsSync(join(dir, "b.original.mjs")), true);
      assert.match(readFileSync(a, "utf8"), /runShim/);
      assert.match(readFileSync(b, "utf8"), /runShim/);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("re-running --apply is idempotent (skips already-migrated)", () => {
    const dir = mkdtempSync(join(tmpdir(), "mhr-idem-"));
    try {
      const a = join(dir, "a.mjs");
      writeFileSync(a, "// hook a\n");
      run({ files: [a], apply: true });
      const second = run({ files: [a], apply: true });
      assert.equal(second.applied, 0);
      assert.equal(second.skipped, 1);
      assert.equal(second.steps[0].action, "skip-migrated");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("--undo restores pre-migration state", () => {
    const dir = mkdtempSync(join(tmpdir(), "mhr-undo-e2e-"));
    try {
      const a = join(dir, "a.mjs");
      const originalBody = "// before migration\n";
      writeFileSync(a, originalBody);
      run({ files: [a], apply: true });
      const undoSummary = run({ files: [a], apply: true, undo: true });
      assert.equal(undoSummary.applied, 1);
      assert.equal(readFileSync(a, "utf8"), originalBody);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("--max caps the number of steps acted on", () => {
    const dir = mkdtempSync(join(tmpdir(), "mhr-max-"));
    try {
      const files = [];
      for (let i = 0; i < 5; i++) {
        const p = join(dir, `h${i}.mjs`);
        writeFileSync(p, `// hook ${i}\n`);
        files.push(p);
      }
      const summary = run({ files, apply: true, max: 3 });
      assert.equal(summary.applied, 3);
      // Verify only the first 3 were migrated.
      for (let i = 0; i < 5; i++) {
        const migrated = existsSync(join(dir, `h${i}.original.mjs`));
        if (i < 3) assert.equal(migrated, true, `h${i} should be migrated`);
        else assert.equal(migrated, false, `h${i} should NOT be migrated`);
      }
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("--filter narrows files by substring", () => {
    const dir = mkdtempSync(join(tmpdir(), "mhr-filter-"));
    try {
      const a = join(dir, "alpha.mjs");
      const b = join(dir, "bravo.mjs");
      writeFileSync(a, "// alpha\n");
      writeFileSync(b, "// bravo\n");
      const summary = run({ files: [a, b], apply: true, filter: "alpha" });
      assert.equal(summary.applied, 1);
      assert.equal(existsSync(join(dir, "alpha.original.mjs")), true);
      assert.equal(existsSync(join(dir, "bravo.original.mjs")), false);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("renderStep produces a tagged single-line representation", () => {
    const line = renderStep({ action: "migrate", name: "foo", filePath: "/a/foo.mjs" });
    assert.match(line, /\[migrate\]/);
    assert.match(line, /foo/);
  });
});
