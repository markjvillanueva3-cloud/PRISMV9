#!/usr/bin/env node
// U-GALAXY-MS1-B3 (2026-05-27, slot:alpha): weekly-memory-synthesis populater.
// Per SCOPE-EXPANSION §Q6 #3 (HMEMV06). Reads last-7-day memories from
// knowledge/memories/{feedback,reference,project}/, groups by galaxy + slot via
// the C1 routing classifier output, emits weekly-synthesis MD at
// knowledge/memories/weekly-synthesis/<YYYY-WW>.md. The `prism_memory:weekly_synthesis_get`
// MCP action consumes these — currently NOTHING populates them. This closes that gap.
//
// Run: node scripts/weekly-memory-synthesis.mjs              # current week
//      node scripts/weekly-memory-synthesis.mjs --weeks 4    # last 4 weeks
//
// Pure-ish: I/O at read+write boundaries, classification + grouping pure.

import fs from "node:fs";
import path from "node:path";

const PRISM = process.env.PRISM_ROOT || "H:/prism";
const MEMORY_ROOTS = ["feedback", "reference", "project"].map(t =>
  path.join(PRISM, "knowledge/memories", t),
);
const OUT_DIR = path.join(PRISM, "knowledge/memories/weekly-synthesis");
const WEEK_MS = 7 * 24 * 60 * 60 * 1000;

function isoWeek(d) {
  // ISO-8601 week-of-year (YYYY-WW format)
  const tmp = new Date(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()));
  const dayNum = tmp.getUTCDay() || 7;
  tmp.setUTCDate(tmp.getUTCDate() + 4 - dayNum);
  const yearStart = new Date(Date.UTC(tmp.getUTCFullYear(), 0, 1));
  const week = Math.ceil(((tmp - yearStart) / 86400000 + 1) / 7);
  return `${tmp.getUTCFullYear()}-W${String(week).padStart(2, "0")}`;
}

function safeStat(p) { try { return fs.statSync(p); } catch { return null; } }
function safeRead(p) { try { return fs.readFileSync(p, "utf8"); } catch { return null; } }

function scanMemoriesInWindow(windowStart) {
  const out = [];
  for (const root of MEMORY_ROOTS) {
    if (!fs.existsSync(root)) continue;
    const kind = path.basename(root);
    for (const f of fs.readdirSync(root)) {
      if (!f.endsWith(".md")) continue;
      const p = path.join(root, f);
      const s = safeStat(p);
      if (!s) continue;
      if (s.mtimeMs < windowStart) continue;
      out.push({ path: p, name: f, kind, mtimeMs: s.mtimeMs, size: s.size });
    }
  }
  return out;
}

function classifyEntries(entries) {
  // Reuse alpha's C1 classifier heuristic — load routing JSON if present, else
  // best-effort filename-keyword bucket.
  const ROUTING = path.join(PRISM, "state/shared/memory-galaxy-routing.json");
  const routingByPath = new Map();
  try {
    const raw = JSON.parse(fs.readFileSync(ROUTING, "utf8"));
    for (const [galaxy, paths] of Object.entries(raw.byGalaxy || {})) {
      for (const p of paths) routingByPath.set(p.replace(/\\/g, "/"), galaxy);
    }
  } catch { /* fall back to none */ }
  return entries.map(e => ({
    ...e,
    galaxy: routingByPath.get(e.path.replace(/\\/g, "/")) || "universal",
  }));
}

function groupByGalaxy(classified) {
  const groups = {};
  for (const e of classified) {
    if (!groups[e.galaxy]) groups[e.galaxy] = [];
    groups[e.galaxy].push(e);
  }
  // Sort each galaxy's entries by mtime descending (newest first)
  for (const g of Object.values(groups)) g.sort((a, b) => b.mtimeMs - a.mtimeMs);
  return groups;
}

function renderSynthesis(week, groups, windowDays, themes = new Map()) {
  const lines = [];
  lines.push(`# Weekly memory synthesis — ${week}`);
  lines.push("");
  lines.push(`Auto-generated by \`scripts/weekly-memory-synthesis.mjs\`. Scans memories with mtime in the trailing ${windowDays}-day window, groups by Domain-Galaxy classification (via C1 routing if present, else \`universal\` bucket).`);
  lines.push("");
  const totalEntries = Object.values(groups).reduce((a, g) => a + g.length, 0);
  lines.push(`**Total entries in window:** ${totalEntries} across ${Object.keys(groups).length} galaxy buckets.`);
  lines.push("");
  // Sorted galaxy list — universal last, otherwise alphabetical
  const galaxiesSorted = Object.keys(groups).sort((a, b) => {
    if (a === "universal") return 1;
    if (b === "universal") return -1;
    return a.localeCompare(b);
  });
  for (const g of galaxiesSorted) {
    const items = groups[g];
    lines.push(`## ${g} (${items.length})`);
    lines.push("");
    // Optional local-LLM week's-theme (U-OBS-WEEKLY-LLM-SYNTH); present only when
    // PRISM_WEEKLY_LLM_SYNTH ran → absent = byte-identical to before. Escape
    // interior underscores so a theme can't unbalance the italic blockquote.
    const theme = typeof themes.get === "function" ? themes.get(g) : undefined;
    if (theme) { lines.push(`> _${String(theme).replace(/_/g, "\\_")}_`); lines.push(""); }
    for (const e of items.slice(0, 20)) {
      const ageDays = Math.floor((Date.now() - e.mtimeMs) / 86400000);
      const head = safeRead(e.path)?.split("\n").find(l => l.startsWith("# "))?.replace(/^# /, "") || e.name;
      lines.push(`- [${ageDays}d ago · ${e.kind}] **${e.name}** — ${head.slice(0, 100)}`);
    }
    if (items.length > 20) lines.push(`- _(...+${items.length - 20} more)_`);
    lines.push("");
  }
  lines.push("---");
  lines.push("");
  // Honest footer note (R12): only when the optional local-LLM theme pass ran.
  const llmNote = (typeof themes.size === "number" && themes.size > 0)
    ? ` Per-galaxy themes synthesized by a local LLM (\`PRISM_WEEKLY_LLM_SYNTH\`, $0 Claude tokens).`
    : "";
  lines.push(`_Consumed by \`prism_memory:weekly_synthesis_get\` MCP action. Regenerated weekly via cron (registration: scripted-task, not yet auto-enabled — operator wires manually).${llmNote} Cross-ref: SCOPE-EXPANSION §Q6 #3 + HERMES-MEMORY-VAULT-MS0 U-HMEMV06._`);
  return lines.join("\n");
}

async function main() {
  const args = process.argv.slice(2);
  const weeksFlagIdx = args.indexOf("--weeks");
  const weeksBack = weeksFlagIdx >= 0 ? parseInt(args[weeksFlagIdx + 1], 10) || 1 : 1;

  if (!fs.existsSync(OUT_DIR)) fs.mkdirSync(OUT_DIR, { recursive: true });
  const now = Date.now();
  const windowStart = now - (weeksBack * WEEK_MS);
  const windowDays = weeksBack * 7;
  const week = isoWeek(new Date(now));

  const entries = scanMemoriesInWindow(windowStart);
  if (entries.length === 0) {
    console.log(`No memories with mtime in trailing ${windowDays}d window. Skipping.`);
    return;
  }
  const classified = classifyEntries(entries);
  const groups = groupByGalaxy(classified);

  // U-OBS-WEEKLY-LLM-SYNTH: optional local-LLM per-galaxy "week's theme" pass
  // (default-OFF). $0 Claude tokens — synthesis offloaded to the resident
  // Blackwell coder. Lazy-imported so the default path stays dependency-light.
  // Fail-open: model down / NONE → empty themes → byte-identical list-only output.
  let themes = new Map();
  const llmSynth = process.env.PRISM_WEEKLY_LLM_SYNTH === "1" || args.includes("--llm-synth");
  if (llmSynth) {
    const { synthesizeGroups } = await import("./lib/weekly-synth-llm.mjs");
    const { callOllama } = await import("./ask-ollama.mjs");
    // Coder model directly (NOT the reasoning-model resolver — it returns empty at
    // low num_predict). Knob: PRISM_WEEKLY_LLM_MODEL / PRISM_WEEKLY_LLM_TIMEOUT_MS.
    const model = process.env.PRISM_WEEKLY_LLM_MODEL || "qwen2.5-coder:32b";
    const timeoutMs = Number(process.env.PRISM_WEEKLY_LLM_TIMEOUT_MS) || 30000;
    const callFn = async (prompt) => {
      const r = await callOllama(model, prompt, { numPredict: 160, timeoutMs });
      return r?.ok ? r.text : null;
    };
    themes = await synthesizeGroups(groups, { callFn });
  }

  const synthesis = renderSynthesis(week, groups, windowDays, themes);

  const outFile = path.join(OUT_DIR, `${week}.md`);
  fs.writeFileSync(outFile, synthesis);
  console.log(`Generated weekly synthesis: ${outFile}`);
  console.log(`Entries: ${entries.length} across ${Object.keys(groups).length} galaxies${llmSynth ? ` · themed ${themes.size}` : ""}`);
  console.log(`Window: trailing ${windowDays} days`);
}

try { await main(); } catch (e) {
  console.error("weekly-memory-synthesis crashed:", e.message);
  process.exit(1);
}
