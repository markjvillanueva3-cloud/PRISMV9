#!/usr/bin/env node
/**
 * generate-formula-algo-wiki.mjs
 *
 * Generates Obsidian wiki entries for L6/L8 formula + algorithm nodes:
 *   - knowledge/wiki/architecture/formulas/<slug>.md   (80 nodes)
 *   - knowledge/wiki/architecture/algorithms/<slug>.md (53 nodes)
 *
 * Formula nodes (from graph):
 *   - L8 kind=novel_formula  — ensemble formulas awaiting an aggregator engine
 *   - L6 kind=constant       — physics constant tables (CANONICAL_KIENZLE, etc.)
 *   - L6 kind=type           — formula-related TypeScript types (ISOGroup, etc.)
 * Algorithm nodes:
 *   - L6 — id pattern alg.<name> (AntColonyTSP, KalmanFilter, etc.)
 *
 * Each entry cross-refs its parent layer and (for algorithms) the algorithm
 * registry. Idempotent with AUTO-START/END markers.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PRISM_ROOT = resolve(__dirname, "..");
const GRAPH_PATH = resolve(PRISM_ROOT, "state/shared/system-viz/system-graph.json");
const ARCH_DIR = resolve(PRISM_ROOT, "knowledge/wiki/architecture");
const FORMULAS_DIR = join(ARCH_DIR, "formulas");
const ALGOS_DIR = join(ARCH_DIR, "algorithms");
const WIKI_INDEX = resolve(PRISM_ROOT, "knowledge/wiki/index.md");

const args = new Set(process.argv.slice(2));
const FLAGS = { dryRun: args.has("--dry-run") };

const AUTO_START = "<!-- AUTO-START — regenerated by generate-formula-algo-wiki.mjs -->";
const AUTO_END = "<!-- AUTO-END -->";

function readJson(p) { return JSON.parse(readFileSync(p, "utf8")); }
function ensureDir(d) { if (!existsSync(d)) mkdirSync(d, { recursive: true }); }
function slug(s) { return String(s || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""); }

function preserveHuman(existing, full) {
  if (!existing) return full;
  const sStart = existing.indexOf(AUTO_START);
  const sEnd = existing.indexOf(AUTO_END);
  const nStart = full.indexOf(AUTO_START);
  const nEnd = full.indexOf(AUTO_END);
  if (sStart === -1 || sEnd === -1) return full;
  return existing.slice(0, sStart) + full.slice(nStart, nEnd + AUTO_END.length) + existing.slice(sEnd + AUTO_END.length);
}

const FORMULA_KIND_DESC = {
  novel_formula: "Ensemble formula — multiple engines compute a related quantity but no canonical aggregator exists yet. Candidate for an aggregator engine.",
  constant: "Physics constant table — canonical values (Kienzle kc1.1, Taylor C/n, material props). NEVER inline; import from src/physics/constants.ts.",
  type: "Formula-related TypeScript type — shared shape used across physics engines.",
};

function renderFormula(node, generatedAt) {
  const name = node.label || node.id;
  const kind = node.kind || node.subgroup || "formula";
  const cleanName = name.replace(/\n.*/s, "").trim();
  const desc = FORMULA_KIND_DESC[kind] || `Formula-layer node of kind \`${kind}\`.`;
  return `---
title: Formula — ${cleanName}
type: formula
formula_id: ${node.id}
kind: ${kind}
parent_layer: ${node.layer}
generated_by: scripts/generate-formula-algo-wiki.mjs
last_verified: ${generatedAt}
tags: [architecture, system-viz, formula, ${kind}]
related:
  - knowledge/wiki/architecture/layer-${node.layer.toLowerCase()}.md
  - mcp-server/src/physics/constants.ts
---

# Formula — \`${cleanName}\`

> ${desc}

${AUTO_START}

| Field | Value |
|-------|-------|
| Name | \`${cleanName}\` |
| Graph node | \`${node.id}\` |
| Kind | ${kind} |
| Parent layer | [[layer-${node.layer.toLowerCase()}]] |
${name.includes("\n") ? `| Note | ${name.split("\n").slice(1).join(" ").trim()} |\n` : ""}

## Doctrine

- Physics constants live ONLY in \`mcp-server/src/physics/constants.ts\` — never inline
- Canonical kc1.1 per ISO group: P=1800, M=2100, K=1100, N=700, S=2800, H=3200
- novel_formula ensembles flag where an aggregator engine would consolidate scattered logic

${AUTO_END}

## See also

- Parent layer: [[layer-${node.layer.toLowerCase()}]]
- Constants source: \`mcp-server/src/physics/constants.ts\`
- Live graph: \`state/shared/system-viz/system-graph.json\`
`;
}

function renderAlgo(node, generatedAt) {
  const name = node.label || node.id;
  return `---
title: Algorithm — ${name}
type: algorithm
algorithm_id: ${node.id}
parent_layer: L6
generated_by: scripts/generate-formula-algo-wiki.mjs
last_verified: ${generatedAt}
tags: [architecture, system-viz, algorithm, core-primitive]
related:
  - knowledge/wiki/architecture/layer-l6.md
  - knowledge/wiki/architecture/registry-reg-algorithmregistry.md
---

# Algorithm — \`${name}\`

> Core algorithmic primitive (L6). Composed by engines for optimization, filtering, search, and control.

${AUTO_START}

| Field | Value |
|-------|-------|
| Name | \`${name}\` |
| Graph node | \`${node.id}\` |
| Parent layer | [[layer-l6]] |
| Registry | [[registry-reg-algorithmregistry]] |

## Doctrine

- Algorithms are Tier-0 atomic primitives — building one cascades to 5–20 engines
- Source: \`mcp-server/src/algorithms/${name}.ts\` (verify path)
- Registered in \`AlgorithmRegistry\`; query via \`prism_calc:algorithm_*\` actions

${AUTO_END}

## See also

- Parent layer: [[layer-l6]]
- Algorithm registry: [[registry-reg-algorithmregistry]]
- Inspect via \`/algorithm-inspect ${name}\`
`;
}

function updateIndex(formulaCount, algoCount) {
  if (!existsSync(WIKI_INDEX)) return null;
  const text = readFileSync(WIKI_INDEX, "utf8");
  const block = [
    "<!-- ARCH-FORMULAS-START -->",
    `_${formulaCount} formula entries (knowledge/wiki/architecture/formulas/) · ${algoCount} algorithm entries (knowledge/wiki/architecture/algorithms/)_`,
    "<!-- ARCH-FORMULAS-END -->",
  ].join("\n");
  if (text.includes("<!-- ARCH-FORMULAS-START -->")) {
    return text.replace(/<!-- ARCH-FORMULAS-START -->[\s\S]*?<!-- ARCH-FORMULAS-END -->/m, block);
  }
  if (text.includes("<!-- ARCH-HOOKS-END -->")) {
    return text.replace(/<!-- ARCH-HOOKS-END -->/, "<!-- ARCH-HOOKS-END -->\n\n### Formulas & algorithms\n\n" + block);
  }
  return text.trimEnd() + "\n\n### Formulas & algorithms\n\n" + block + "\n";
}

function main() {
  if (!existsSync(GRAPH_PATH)) { console.error("graph missing"); process.exit(2); }
  const G = readJson(GRAPH_PATH);
  const generatedAt = new Date().toISOString().split("T")[0];
  ensureDir(FORMULAS_DIR);
  ensureDir(ALGOS_DIR);

  let formulaCount = 0, algoCount = 0;
  const t0 = Date.now();

  for (const n of G.nodes) {
    const isFormula = (n.id || "").startsWith("formula.") || (n.kind || n.subgroup || "").includes("formula");
    const isAlgo = (n.id || "").startsWith("alg.") || (n.kind || n.subgroup || "") === "algorithm";
    if (isFormula) {
      const outPath = join(FORMULAS_DIR, `${slug(n.id)}.md`);
      const full = renderFormula(n, generatedAt);
      const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
      if (!FLAGS.dryRun) writeFileSync(outPath, preserveHuman(existing, full), "utf8");
      formulaCount++;
    } else if (isAlgo) {
      const outPath = join(ALGOS_DIR, `${slug(n.id)}.md`);
      const full = renderAlgo(n, generatedAt);
      const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
      if (!FLAGS.dryRun) writeFileSync(outPath, preserveHuman(existing, full), "utf8");
      algoCount++;
    }
  }

  const indexUpdated = !FLAGS.dryRun ? updateIndex(formulaCount, algoCount) : null;
  if (indexUpdated && !FLAGS.dryRun) writeFileSync(WIKI_INDEX, indexUpdated, "utf8");

  console.log(`generated ${formulaCount} formula + ${algoCount} algorithm wiki entries in ${Date.now() - t0}ms`);
}

main();
