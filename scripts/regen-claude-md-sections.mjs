#!/usr/bin/env node
/**
 * regen-claude-md-sections.mjs — Phase D.4 of DEV-VELOCITY-AUTOTRIGGER-MS0.
 *
 * Marker-based splicer for `H:/prism/CLAUDE.md`. Auto-regenerates specific
 * sections delimited by HTML-comment markers so post-commit can refresh
 * them without rewriting the whole document.
 *
 * Marker format:
 *   <!-- AUTO-GEN: <section-key> START -->
 *   ... regenerable content ...
 *   <!-- AUTO-GEN: <section-key> END -->
 *
 * Generators registered below produce content for each known section-key.
 * Each generator is pure (reads filesystem state, returns markdown string).
 * Splice is atomic (temp + rename) and idempotent (skip if content unchanged).
 *
 * Built-in sections (initial roster):
 *   dev-velocity-autotrigger        — DEV-VELOCITY-AUTOTRIGGER-MS0 status & artifact map
 *   skill-auto-trigger-status       — current _skill-triggers.jsonl count + last regen
 *
 * Adding a section:
 *   1. Insert marker pair in CLAUDE.md where you want content spliced.
 *   2. Add a generator function below + register in GENERATORS.
 *   3. Run this script (post-commit hook will pick it up).
 *
 * Flags:
 *   --section=<key>         only regenerate one section (default: all)
 *   --dry-run               print would-be content; don't write
 *   --verbose               per-section logging
 *   --target=<path>         override CLAUDE.md path (default: H:/prism/CLAUDE.md)
 *
 * Exit: 0 = success (no-op or regen), 1 = error, 2 = marker mismatch
 */
import { readFileSync, writeFileSync, renameSync, existsSync, statSync } from "node:fs";
import { resolve, join } from "node:path";

const PRISM_ROOT = "H:/prism";
const CLAUDE_MD_DEFAULT = join(PRISM_ROOT, "CLAUDE.md");
const SKILL_TRIGGERS_JSONL = join(PRISM_ROOT, "knowledge/wiki/architecture/_skill-triggers.jsonl");

const args = process.argv.slice(2);
const FLAGS = {
  dryRun: args.includes("--dry-run"),
  verbose: args.includes("--verbose"),
};
let onlySection = null;
let targetPath = CLAUDE_MD_DEFAULT;
for (const a of args) {
  if (a.startsWith("--section=")) onlySection = a.slice("--section=".length);
  else if (a.startsWith("--target=")) targetPath = a.slice("--target=".length);
}

function log(msg) {
  if (FLAGS.verbose) process.stderr.write(`[regen-claude-md] ${msg}\n`);
}

// ────────────────────────────────────────────────────────────────────────────
// Generators
// ────────────────────────────────────────────────────────────────────────────

function gen_dev_velocity_autotrigger() {
  // List the 11 skills + 2 hooks + 2 scripts shipped under this milestone.
  const skills = [
    "/scrutiny-batch",        "/quick-archive",      "/encoding-guard (hook+skill)",
    "/big-blob-hunt",         "/skill-recall-tune",  "/dispatcher-coverage",
    "/peer-file-isolation",   "/staged-sanity",      "/scrutiny-replay",
    "/envelope-drift-fix",    "/wire-unwired",
  ];
  const hooks = [
    "skill-auto-trigger.mjs (UserPromptSubmit T2 — Phase D.2)",
    "git-lock-sweeper.mjs PreToolUse arm (Phase C.2 extension)",
    "mcp-route-suggest.mjs smarter classifier (Phase C.1)",
  ];
  const scripts = [
    "extract-skill-triggers.mjs (Phase D.3 — feeds D.2 hook)",
    "regen-claude-md-sections.mjs (Phase D.4 — this script)",
  ];
  return [
    "**Milestone:** `DEV-VELOCITY-AUTOTRIGGER-MS0` (13 units shipped 2026-05-12..13)",
    "",
    "**11 new skills** (all in `.claude/commands/*.md`):",
    ...skills.map(s => `- ${s}`),
    "",
    "**Hook changes:**",
    ...hooks.map(s => `- ${s}`),
    "",
    "**Scripts:**",
    ...scripts.map(s => `- ${s}`),
    "",
    "**Auto-trigger orchestrator:** `skill-auto-trigger.mjs` reads `knowledge/wiki/architecture/_skill-triggers.jsonl` (regenerated by `extract-skill-triggers.mjs`) and surfaces top-K (default 3) skill suggestions per UserPromptSubmit. Pure suggest-only. Knob: `PRISM_SKILL_AUTO_TRIGGER_DISABLE=1`.",
    "",
    "**Pipeline integrations** (per-skill `pipeline_integrations:` frontmatter): forge/forge-audit/rgs/roadmap/close-out — see each skill's manifest for trigger phase.",
    "",
    "**Plan:** `state/shared/SKILL-AUTO-TRIGGER-PLAN.md` (full P0-P13 detail).",
  ].join("\n");
}

function gen_skill_auto_trigger_status() {
  let count = 0, lastMtime = "(missing)";
  if (existsSync(SKILL_TRIGGERS_JSONL)) {
    try {
      const txt = readFileSync(SKILL_TRIGGERS_JSONL, "utf8");
      count = txt.split("\n").filter(Boolean).length;
      lastMtime = statSync(SKILL_TRIGGERS_JSONL).mtime.toISOString();
    } catch { /* skip */ }
  }
  return [
    `**Trigger ledger:** \`knowledge/wiki/architecture/_skill-triggers.jsonl\``,
    `**Triggers registered:** ${count}     **Last regen:** ${lastMtime}`,
    `**Regenerate:** \`node scripts/extract-skill-triggers.mjs\``,
    `**Consumed by:** \`.claude/hooks/skill-auto-trigger.mjs\` (UserPromptSubmit T2)`,
  ].join("\n");
}

const GENERATORS = {
  "dev-velocity-autotrigger": gen_dev_velocity_autotrigger,
  "skill-auto-trigger-status": gen_skill_auto_trigger_status,
};

// ────────────────────────────────────────────────────────────────────────────
// Splice
// ────────────────────────────────────────────────────────────────────────────

const MARKER_PREFIX = "<!-- AUTO-GEN:";
const MARKER_SUFFIX_START = "START -->";
const MARKER_SUFFIX_END = "END -->";

function findMarkers(doc, sectionKey) {
  const startMarker = `${MARKER_PREFIX} ${sectionKey} ${MARKER_SUFFIX_START}`;
  const endMarker = `${MARKER_PREFIX} ${sectionKey} ${MARKER_SUFFIX_END}`;
  const startIdx = doc.indexOf(startMarker);
  const endIdx = doc.indexOf(endMarker, startIdx >= 0 ? startIdx + startMarker.length : 0);
  if (startIdx < 0 || endIdx < 0 || endIdx <= startIdx) return null;
  return { startIdx, endIdx, startMarker, endMarker, startMarkerLen: startMarker.length };
}

function spliceSection(doc, sectionKey, newContent) {
  const m = findMarkers(doc, sectionKey);
  if (!m) return { doc, changed: false, missing: true };
  // Replace content between markers (preserve markers themselves)
  const before = doc.slice(0, m.startIdx + m.startMarkerLen);
  const after = doc.slice(m.endIdx);
  const block = `\n${newContent}\n`;
  const next = before + block + after;
  return { doc: next, changed: next !== doc, missing: false };
}

function atomicWrite(path, content) {
  const tmp = `${path}.${process.pid}.${Date.now()}.tmp`;
  writeFileSync(tmp, content);
  renameSync(tmp, path);
}

function main() {
  if (!existsSync(targetPath)) {
    process.stderr.write(`regen-claude-md-sections: target missing: ${targetPath}\n`);
    return 1;
  }
  let doc = readFileSync(targetPath, "utf8");
  const original = doc;
  let regenerated = 0, missing = [];

  const keys = onlySection ? [onlySection] : Object.keys(GENERATORS);
  for (const k of keys) {
    const gen = GENERATORS[k];
    if (!gen) {
      process.stderr.write(`regen-claude-md-sections: unknown section: ${k}\n`);
      return 1;
    }
    const content = gen();
    const result = spliceSection(doc, k, content);
    if (result.missing) {
      log(`section "${k}" markers not found in target — skipping (operator must add markers first)`);
      missing.push(k);
      continue;
    }
    doc = result.doc;
    if (result.changed) {
      regenerated++;
      log(`section "${k}" regenerated`);
    } else {
      log(`section "${k}" up to date`);
    }
  }

  if (FLAGS.dryRun) {
    process.stderr.write(`DRY-RUN — would regenerate ${regenerated} section(s)${missing.length ? `, ${missing.length} marker(s) missing: ${missing.join(", ")}` : ""}\n`);
    if (FLAGS.verbose && regenerated > 0) process.stdout.write(doc);
    return 0;
  }

  if (doc !== original) {
    atomicWrite(targetPath, doc);
    process.stderr.write(`regen-claude-md-sections: regenerated ${regenerated} section(s) in ${targetPath}\n`);
  } else {
    process.stderr.write(`regen-claude-md-sections: no changes (${regenerated} section(s) up to date)${missing.length ? `, ${missing.length} marker(s) missing: ${missing.join(", ")}` : ""}\n`);
  }
  return 0;
}

try {
  process.exit(main());
} catch (e) {
  process.stderr.write(`regen-claude-md-sections fatal: ${e.message}\n${e.stack}\n`);
  process.exit(1);
}
