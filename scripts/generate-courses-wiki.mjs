function preserveHuman(existing, full) {
  if (!existing) return full;
  const sStart = existing.indexOf(AUTO_START);
  const sEnd = existing.indexOf(AUTO_END);
  const nStart = full.indexOf(AUTO_START);
  const nEnd = full.indexOf(AUTO_END);
  if (sStart === -1 || sEnd === -1) return full;
  return existing.slice(0, sStart) + full.slice(nStart, nEnd + AUTO_END.length) + existing.slice(sEnd + AUTO_END.length);
}

function updateWikiIndex(academyN, mitN, has220) {
  if (!existsSync(WIKI_INDEX)) return null;
  const text = readFileSync(WIKI_INDEX, "utf8");
  const total = academyN + mitN + (has220 ? 1 : 0) + 1;
  const block = ["<!-- ARCH-COURSES-START -->",
    `_Total: ${total} course entries — ${academyN} PRISM Academy + ${mitN} MIT OCW${has220 ? " + 1 (220-course KB)" : ""} + index. See [[courses-index]]._`,
    "", "Dir: `architecture/courses/`. Served by CurriculumEngine / CourseBuilderEngine / the MITCourse* engine family.",
    "<!-- ARCH-COURSES-END -->"].join("\n");
  if (text.includes("<!-- ARCH-COURSES-START -->")) return text.replace(/<!-- ARCH-COURSES-START -->[\s\S]*?<!-- ARCH-COURSES-END -->/m, block);
  if (text.includes("<!-- ARCH-MISC-L8-END -->")) return text.replace(/<!-- ARCH-MISC-L8-END -->/, "<!-- ARCH-MISC-L8-END -->\n\n### Courses (Academy + MIT OCW)\n\n" + block);
  return text.trimEnd() + "\n\n### Courses\n\n" + block + "\n";
}

function main() {
  const gen = new Date().toISOString().split("T")[0];
  const t0 = Date.now();
  if (!FLAGS.dryRun) ensureDir(COURSES_DIR);

  // 1. Academy courses
  const academyEntries = [];
  let academyFiles = [];
  try { academyFiles = readdirSync(ACADEMY_DIR).filter((f) => /^course-.*\.ts$/.test(f)); } catch {}
  for (const f of academyFiles) {
    const c = parseAcademyCourse(join(ACADEMY_DIR, f));
    if (!c) continue;
    const name = `academy-${slug(c.courseId)}-${slug(c.title)}`.slice(0, 90);
    const outPath = join(COURSES_DIR, `${name}.md`);
    const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
    if (!FLAGS.dryRun) writeFileSync(outPath, preserveHuman(existing, renderAcademy(c, gen)), "utf8");
    academyEntries.push({ name, title: c.title, level: c.level, modules: c.modules, hours: c.hours });
  }

  // 2. MIT courses
  const mitEntries = [];
  for (const c of MIT_COURSES) {
    const name = `mit-${slug(c.code)}-${slug(c.name)}`.slice(0, 90);
    const outPath = join(COURSES_DIR, `${name}.md`);
    const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
    if (!FLAGS.dryRun) writeFileSync(outPath, preserveHuman(existing, renderMIT(c, gen)), "utf8");
    mitEntries.push({ name, code: c.code, title: c.name, dept: c.dept });
  }

  // 3. 220-course KB
  const has220 = existsSync(resolve(PRISM_ROOT, "extracted/knowledge_bases")) || existsSync(resolve(PRISM_ROOT, "extracted_modules/complete_extraction"));
  if (has220 && !FLAGS.dryRun) {
    const outPath = join(COURSES_DIR, "220-course-knowledge-base-extracted.md");
    const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
    writeFileSync(outPath, preserveHuman(existing, render220(gen)), "utf8");
  }

  // index
  if (!FLAGS.dryRun) {
    const idxExisting = existsSync(INDEX_OUT) ? readFileSync(INDEX_OUT, "utf8") : null;
    writeFileSync(INDEX_OUT, preserveHuman(idxExisting, renderIndex(academyEntries, mitEntries, has220, gen)), "utf8");
    const wi = updateWikiIndex(academyEntries.length, mitEntries.length, has220);
    if (wi) writeFileSync(WIKI_INDEX, wi, "utf8");
  }

  const total = academyEntries.length + mitEntries.length + (has220 ? 1 : 0) + 1;
  console.log(`courses wiki: ${total} entries (${academyEntries.length} academy + ${mitEntries.length} MIT${has220 ? " + 220-KB index" : ""} + catalog), ${Date.now() - t0}ms`);
}

main();
