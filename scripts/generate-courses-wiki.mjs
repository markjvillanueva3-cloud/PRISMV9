function ensureDir(d) { if (!existsSync(d)) mkdirSync(d, { recursive: true }); }
function slug(s) { return String(s || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 90) || "x"; }

// ── 1. PRISM Academy courses ──────────────────────────────────────────────────
function parseAcademyCourse(file) {
  let text = "";
  try { text = readFileSync(file, "utf8"); } catch { return null; }
  const head = text.slice(0, 2000);
  const title = (head.match(/Course[^:]*:\s*([^\n*]+)/i) || [, basename(file, ".ts")])[1].trim();
  const level = (head.match(/Level:\s*([A-Za-z ]+)/i) || [, null])[1];
  const modules = (head.match(/(\d+)\s*Modules?/i) || [, null])[1];
  const hours = (head.match(/~?\s*([\d.]+)\s*hours?/i) || [, null])[1];
  // first non-header sentence of the docblock
  const docBody = (head.match(/\*\/\s*$/m) ? "" : "");
  const blurb = (head.match(/\*\s+([A-Z][^\n*]{20,200})/m) || [, ""])[1].trim();
  // count exported modules / lessons heuristically
  const moduleCount = (text.match(/moduleId:/g) || []).length;
  const lessonCount = (text.match(/\bid:\s*`?\$\{COURSE_ID\}-mod-\d+-les-/g) || text.match(/-les-\d+/g) || []).length;
  const courseId = (text.match(/COURSE_ID\s*=\s*["']([^"']+)["']/) || [, basename(file, ".ts")])[1];
  return { file, courseId, title, level: level ? level.trim() : null, modules, hours, blurb, moduleCount, lessonCount };
}

