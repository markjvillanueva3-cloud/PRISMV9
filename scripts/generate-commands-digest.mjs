#!/usr/bin/env node
/**
 * generate-commands-digest.mjs — 1-line-per-skill index for .claude/commands/.
 *
 * MEMORY-WIKI-OPTIMIZATION-MS0 / U-MWO16 (slot:bravo 2026-05-26).  Parallel to
 * U-MWO06 (AGENT_DIGEST) + U-MWO12 (HOOK_DIGEST) — closes the LAST major
 * discoverability gap.  ~316 .md skills under .claude/commands/ are auto-injected
 * every SessionStart turn (per CLAUDE.md "~440 skills auto-injected") with NO
 * index, forcing per-prompt regex search.  This emits a tiny markdown index that
 * lives alongside HOOK_DIGEST + AGENT_DIGEST for one-glance lookup.
 *
 * Strategy: scan every .md file (top-level + 1 subdir) in .claude/commands/.
 * Parse YAML frontmatter for `name:` + `description:`; fall back to first H1 +
 * blockquote line if frontmatter absent.  Group by category (top-level vs
 * subdir name) so domain studios (wedm/, lathe/, etc.) cluster.
 *
 * Usage:  node scripts/generate-commands-digest.mjs [--out PATH]
 * Exit:   0 ok · 1 commands dir missing · 2 runtime error
 *
 * @module scripts/generate-commands-digest
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const DEFAULT_COMMANDS_DIR = path.join(ROOT, ".claude", "commands");
const DEFAULT_OUT = path.join(ROOT, ".claude", "commands", "COMMANDS_DIGEST.md");

const MAX_DESC_CHARS = 120;
const HEAD_BYTES = 2048;

/** Parse YAML frontmatter.  Returns {name, description} or null.  Pure. */
export function parseFrontmatter(src) {
  if (!src.startsWith("---")) return null;
  const end = src.indexOf("\n---", 4);
  if (end < 0) return null;
  const block = src.slice(4, end);
  const out = {};
  for (const line of block.split(/\r?\n/)) {
    const m = line.match(/^([a-zA-Z_]+):\s*(.+)$/);
    if (!m) continue;
    out[m[1]] = m[2].trim().replace(/^["']|["']$/g, "");
  }
  return out;
}

/** Fallback: first H1 + first non-empty body sentence. */
export function extractFallback(src) {
  const lines = src.split(/\r?\n/);
  let name = null;
  let desc = null;
  for (const raw of lines) {
    const line = raw.trim();
    if (!name && line.startsWith("# ")) {
      name = line.slice(2).trim().split(/\s+—\s+/)[0];
      continue;
    }
    if (name && !desc && line && !line.startsWith("#") && !line.startsWith("---")) {
      desc = line.replace(/^>\s*/, "").replace(/^\*\*|\*\*$/g, "").trim();
      break;
    }
  }
  return { name, description: desc };
}

/** Pure tighten — clip to MAX_DESC_CHARS. */
export function tighten(text) {
  if (!text) return "(no description)";
  const collapsed = text.replace(/\s+/g, " ").trim();
  return collapsed.length > MAX_DESC_CHARS
    ? `${collapsed.slice(0, MAX_DESC_CHARS - 1)}…`
    : collapsed;
}

/** Render grouped markdown table.  Pure. */
export function render(entries) {
  const groups = new Map();
  for (const e of entries) {
    if (!groups.has(e.category)) groups.set(e.category, []);
    groups.get(e.category).push(e);
  }
  const sortedCategories = [...groups.keys()].sort();
  const lines = [
    "# .claude/commands/ — COMMANDS_DIGEST.md",
    "",
    "_Auto-generated by `scripts/generate-commands-digest.mjs` (U-MWO16, slot:bravo 2026-05-26)._",
    "",
    `**${entries.length} skills** indexed across ${sortedCategories.length} categories.  Invoke any via \`/<name>\` in chat or via Skill tool.`,
    "",
  ];
  for (const cat of sortedCategories) {
    const group = groups.get(cat).sort((a, b) => a.name.localeCompare(b.name));
    lines.push(`## ${cat} (${group.length})`);
    lines.push("");
    lines.push("| Skill | Description |");
    lines.push("|-------|-------------|");
    for (const e of group) {
      const safeDesc = tighten(e.description).replace(/\|/g, "\\|");
      lines.push(`| \`/${e.name}\` | ${safeDesc} |`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

/** Walk top-level + 1 subdir depth.  Pure given fsImpl. */
export function walkSkills({ commandsDir, fsImpl = fs }) {
  const entries = [];
  let names;
  try { names = fsImpl.readdirSync(commandsDir, { withFileTypes: true }); }
  catch { return entries; }
  for (const entry of names) {
    if (entry.isFile() && entry.name.endsWith(".md") && entry.name !== "COMMANDS_DIGEST.md") {
      entries.push({ file: path.join(commandsDir, entry.name), category: "(top-level)" });
    } else if (entry.isDirectory()) {
      const subdir = path.join(commandsDir, entry.name);
      let subnames;
      try { subnames = fsImpl.readdirSync(subdir); } catch { continue; }
      for (const sub of subnames) {
        if (!sub.endsWith(".md")) continue;
        entries.push({ file: path.join(subdir, sub), category: entry.name });
      }
    }
  }
  return entries;
}

/** I/O wrapper. */
export function run({ commandsDir = DEFAULT_COMMANDS_DIR, outPath = DEFAULT_OUT, fsImpl = fs } = {}) {
  if (!fsImpl.existsSync(commandsDir)) {
    return { ok: false, reason: "commands-dir-missing", path: commandsDir };
  }
  const fileList = walkSkills({ commandsDir, fsImpl });
  const entries = [];
  for (const { file, category } of fileList) {
    let head = "";
    try {
      const fd = fsImpl.openSync(file, "r");
      const buf = Buffer.alloc(HEAD_BYTES);
      const bytesRead = fsImpl.readSync(fd, buf, 0, HEAD_BYTES, 0);
      fsImpl.closeSync(fd);
      head = buf.subarray(0, bytesRead).toString("utf8");
    } catch { continue; }
    const fm = parseFrontmatter(head);
    const fallback = extractFallback(head);
    const name = (fm?.name) || fallback.name || path.basename(file, ".md");
    const description = (fm?.description) || fallback.description || "";
    entries.push({ name, description, category });
  }
  const content = render(entries);
  fsImpl.writeFileSync(outPath, content, "utf8");
  return { ok: true, count: entries.length, outPath, bytes: content.length };
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith("generate-commands-digest.mjs")) {
  try {
    const result = run();
    process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
    process.exit(result.ok ? 0 : 1);
  } catch (e) {
    process.stderr.write(`generate-commands-digest: ${e instanceof Error ? e.message : String(e)}\n`);
    process.exit(2);
  }
}
