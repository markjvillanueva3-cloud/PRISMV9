#!/usr/bin/env node
/**
 * code-vault-moc.mjs -- build the Obsidian "2nd brain" NAVIGATION layer (Maps of Content)
 * over the per-file code notes emitted by code-to-vault.mjs.
 *
 * Per-file notes make every source file a brain node (coverage); MOCs make the ~7,800-node
 * pile BROWSABLE (the "2nd brain / OS functionality" the operator asked for). A MOC is an
 * index note that links to a set of per-file notes -- so a chat / the frontend / a human can
 * navigate "show me every dispatcher", "everything in the mill galaxy", from one entry point
 * instead of grepping 7,800 files. Each MOC is itself a vault node (graphed + recall-indexed),
 * and its outbound `[[wikilinks]]` densify the Obsidian graph (kind-hub + galaxy-hub edges).
 *
 * Emits (idempotent, atomic, ASCII-only):
 *   - knowledge/memories/reference/reference_code_moc_kind_<kind>.md    (one per KIND)
 *   - knowledge/memories/reference/reference_code_moc_galaxy_<galaxy>.md (one per galaxy w/ notes)
 *   - knowledge/memories/reference/reference_code_moc_master.md          (graphed entry hub)
 *   - knowledge/CODE-VAULT-MOC.md                                        (human entry point)
 *
 *   node scripts/code-vault-moc.mjs            # build all MOCs
 *   node scripts/code-vault-moc.mjs --json     # report grouping, no writes
 *   node scripts/code-vault-moc.mjs --dry-run  # scan + group, no writes
 *
 * Env: PRISM_CODE_VAULT_FROZEN_TIME=<iso> pins generatedAt for diff-stable test output.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = "H:/prism";
const VAULT_DIR = path.join(REPO_ROOT, "knowledge", "memories", "reference");
const MASTER_HUMAN = path.join(REPO_ROOT, "knowledge", "CODE-VAULT-MOC.md");

function nowIso() {
  return process.env.PRISM_CODE_VAULT_FROZEN_TIME || new Date().toISOString();
}

/** Parse the fields a MOC needs from one note's frontmatter (pure, fail-soft). */
export function parseNoteMeta(content, filename) {
  const get = (key) => {
    const m = String(content || "").match(new RegExp(`^\\s*${key}:\\s*(.+?)\\s*$`, "m"));
    return m ? m[1].replace(/^["']|["']$/g, "").trim() : "";
  };
  const kindRaw = get("kind"); // "code-<kind>"
  const kind = kindRaw.replace(/^code-/, "") || (String(filename).match(/^reference_code_([a-z]+)_/) || [])[1] || "other";
  return {
    name: get("name") || String(filename).replace(/\.md$/, ""),
    kind,
    galaxy: get("galaxy") || "unassigned",
    alias: get("aliases") || "",
    desc: get("description").replace(/[|\r\n]+/g, " ").slice(0, 90),
  };
}

/** A display line for one note in a MOC. */
function noteLine(m) {
  const label = m.alias || m.name;
  return `- [[${m.name}|${label}]]${m.desc ? ` -- ${m.desc}` : ""}`;
}

/** Build a per-kind MOC note (pure). Alpha-bucketed when large so it stays navigable. */
export function buildKindMoc(kind, metas, generatedAt) {
  const sorted = [...metas].sort((a, b) => (a.alias || a.name).localeCompare(b.alias || b.name));
  let body;
  if (sorted.length > 60) {
    const buckets = new Map();
    for (const m of sorted) {
      const c = ((m.alias || m.name).replace(/^reference_code_[a-z]+_/, "")[0] || "#").toUpperCase();
      const key = /[A-Z]/.test(c) ? c : "#";
      if (!buckets.has(key)) buckets.set(key, []);
      buckets.get(key).push(m);
    }
    body = [...buckets.keys()].sort().map((k) => `\n### ${k}\n${buckets.get(k).map(noteLine).join("\n")}`).join("\n");
  } else {
    body = sorted.map(noteLine).join("\n");
  }
  return `---
name: reference_code_moc_kind_${kind}
description: "Map of Content -- all ${sorted.length} ${kind} code notes (navigation hub)"
metadata:
  type: reference
  kind: code-moc
  moc: kind
---

# Code MOC -- ${kind} (${sorted.length} notes)

> Navigation hub for every \`${kind}\` per-file note. Auto-generated by \`scripts/code-vault-moc.mjs\`.
> generatedAt: ${generatedAt}  |  Master: [[reference_code_moc_master]]
${body}
`;
}

/** Build a per-galaxy MOC note (pure). */
export function buildGalaxyMoc(galaxy, metas, generatedAt) {
  const byKind = new Map();
  for (const m of metas) { if (!byKind.has(m.kind)) byKind.set(m.kind, []); byKind.get(m.kind).push(m); }
  const body = [...byKind.keys()].sort().map((k) => {
    const list = byKind.get(k).sort((a, b) => (a.alias || a.name).localeCompare(b.alias || b.name));
    return `\n## ${k} (${list.length})\n${list.map(noteLine).join("\n")}`;
  }).join("\n");
  return `---
name: reference_code_moc_galaxy_${galaxy}
description: "Map of Content -- all ${metas.length} code notes in the ${galaxy} galaxy"
metadata:
  type: reference
  kind: code-moc
  moc: galaxy
  galaxy: ${galaxy}
---

# Code MOC -- ${galaxy} galaxy (${metas.length} notes)

> Every code note whose source lives in the ${galaxy} galaxy. Auto-generated by \`scripts/code-vault-moc.mjs\`.
> generatedAt: ${generatedAt}  |  Master: [[reference_code_moc_master]]
${body}
`;
}

/** Build the master MOC body shared by the graphed node + the human entry file (pure). */
export function buildMasterBody(byKind, byGalaxy, generatedAt) {
  const total = [...byKind.values()].reduce((n, a) => n + a.length, 0);
  const kindRows = [...byKind.keys()].sort()
    .map((k) => `| ${k} | ${byKind.get(k).length} | [[reference_code_moc_kind_${k}]] |`).join("\n");
  const galaxyRows = [...byGalaxy.keys()].filter((g) => g !== "unassigned").sort()
    .map((g) => `| ${g} | ${byGalaxy.get(g).length} | [[reference_code_moc_galaxy_${g}]] |`).join("\n");
  const unassigned = byGalaxy.get("unassigned") ? byGalaxy.get("unassigned").length : 0;
  return `# CODE VAULT -- Map of Content (2nd-brain navigation)

> Entry point to the ${total} per-file code brain nodes. Auto-generated by \`scripts/code-vault-moc.mjs\`.
> generatedAt: ${generatedAt}. Per-file notes by \`scripts/code-to-vault.mjs\`; inventory \`state/shared/CODE-VAULT-INVENTORY.md\`.

## By kind
| kind | notes | map |
|------|-------|-----|
${kindRows}

## By galaxy (source-located)
| galaxy | notes | map |
|--------|-------|-----|
${galaxyRows}

_(${unassigned} notes are cross-cutting / not under a galaxy subdir.)_

## How to use
Open a kind map ("every dispatcher") or a galaxy map ("everything mill") to browse; each entry
links to a per-file note (what-it-is + exports + methods + dependency wikilinks + source path).
Recall by meaning: \`/system-viz find <name>\` or \`prism_session:master_index_query\`. This MOC and
every per-file note is an Obsidian brain node on H:. Related: [[code-vault-bridge]].
`;
}

function scanNotes() {
  const byKind = new Map();
  const byGalaxy = new Map();
  let files;
  try { files = fs.readdirSync(VAULT_DIR); } catch { return { byKind, byGalaxy }; }
  for (const f of files) {
    if (!/^reference_code_.+\.md$/.test(f)) continue;
    if (/^reference_code_moc_/.test(f)) continue;               // don't index MOCs into MOCs
    let content;
    try { content = fs.readFileSync(path.join(VAULT_DIR, f), "utf8"); } catch { continue; }
    // Identity guard: only notes code-to-vault GENERATED (they carry `kind: code-<X>`).
    // Excludes hand-authored reference_code_* memory notes (e.g. graph_projection, vault_bridge).
    if (!/^\s*kind:\s*code-/m.test(content)) continue;
    const m = parseNoteMeta(content, f);
    if (m.kind === "moc") continue;
    if (!byKind.has(m.kind)) byKind.set(m.kind, []);
    byKind.get(m.kind).push(m);
    if (!byGalaxy.has(m.galaxy)) byGalaxy.set(m.galaxy, []);
    byGalaxy.get(m.galaxy).push(m);
  }
  return { byKind, byGalaxy };
}

function writeAtomic(absPath, content) {
  const tmp = `${absPath}.tmp-${process.pid}`;
  try { fs.writeFileSync(tmp, content, "utf8"); fs.renameSync(tmp, absPath); return true; }
  catch (err) { try { fs.unlinkSync(tmp); } catch { /* gone */ } process.stderr.write(`[code-moc] WRITE FAIL ${path.basename(absPath)}: ${err.message}\n`); return false; }
}

function main() {
  const argv = process.argv.slice(2);
  const jsonOnly = argv.includes("--json");
  const dryRun = argv.includes("--dry-run");
  const generatedAt = nowIso();
  const { byKind, byGalaxy } = scanNotes();
  const total = [...byKind.values()].reduce((n, a) => n + a.length, 0);

  if (jsonOnly) {
    const kinds = Object.fromEntries([...byKind].map(([k, v]) => [k, v.length]));
    const galaxies = Object.fromEntries([...byGalaxy].map(([g, v]) => [g, v.length]));
    process.stdout.write(JSON.stringify({ generatedAt, total, kinds, galaxies }, null, 2) + "\n");
    return;
  }

  let wrote = 0;
  if (!dryRun) {
    fs.mkdirSync(VAULT_DIR, { recursive: true });
    for (const [k, metas] of byKind) if (writeAtomic(path.join(VAULT_DIR, `reference_code_moc_kind_${k}.md`), buildKindMoc(k, metas, generatedAt))) wrote++;
    for (const [g, metas] of byGalaxy) {
      if (g === "unassigned") continue; // too broad to be a useful hub
      if (writeAtomic(path.join(VAULT_DIR, `reference_code_moc_galaxy_${g}.md`), buildGalaxyMoc(g, metas, generatedAt))) wrote++;
    }
    const masterBody = buildMasterBody(byKind, byGalaxy, generatedAt);
    const masterNote = `---
name: reference_code_moc_master
description: "Master Map of Content -- entry hub to all ${total} per-file code brain nodes"
metadata:
  type: reference
  kind: code-moc
  moc: master
---

${masterBody}`;
    if (writeAtomic(path.join(VAULT_DIR, "reference_code_moc_master.md"), masterNote)) wrote++;
    if (writeAtomic(MASTER_HUMAN, masterBody)) wrote++;
  }

  process.stdout.write(
    `[code-moc] ${dryRun ? "(dry-run) " : ""}scanned ${total} notes | kinds=${byKind.size} galaxies=${[...byGalaxy.keys()].filter((g) => g !== "unassigned").length} | wrote ${wrote} MOC(s)\n`,
  );
}

// Entrypoint guard: importing the build* fns (the test does) never writes the live vault.
const __isCli = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (__isCli) main();
