#!/usr/bin/env node
/**
 * generate-skill-wiki.mjs
 *
 * Generates one Obsidian wiki entry per Claude Code skill at
 *   H:/prism/knowledge/wiki/architecture/skills/<scope>/<name>.md
 *
 * Reads markdown files from:
 *   - H:/prism/.claude/commands/         (project scope)
 *   - C:/Users/wompu/.claude/commands/   (user scope)
 *
 * Each skill file is itself a markdown spec. This wiki entry surfaces:
 *   - skill name, description (from frontmatter)
 *   - scope (project|user)
 *   - source path
 *   - tags from frontmatter
 *
 * Idempotent — AUTO-START/END markers preserve human notes.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync } from "node:fs";
import { resolve, dirname, join, basename } from "node:path";
import { fileURLToPath } from "node:url";
import { homedir } from "node:os";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PRISM_ROOT = resolve(__dirname, "..");
const WIKI_ARCH_DIR = resolve(PRISM_ROOT, "knowledge/wiki/architecture");
const SKILLS_DIR = join(WIKI_ARCH_DIR, "skills");
const WIKI_INDEX = resolve(PRISM_ROOT, "knowledge/wiki/index.md");

// User-skill path is per-machine: ~/.claude/commands. The old hardcoded
// C:/Users/wompu path only resolved on one workstation — on others it silently
// produced 0 user-skill entries. homedir() is correct everywhere.
const SCOPES = {
  project: resolve(PRISM_ROOT, ".claude/commands"),
  user: join(homedir(), ".claude", "commands"),
};

const AUTO_START = "<!-- AUTO-START — regenerated by generate-skill-wiki.mjs -->";
const AUTO_END = "<!-- AUTO-END -->";
const DESC_MAX = 200;

function ensureDir(d) { if (!existsSync(d)) mkdirSync(d, { recursive: true }); }
function slug(s) { return String(s || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""); }

function parseFrontmatter(content) {
  const m = content.match(/^---\s*\n([\s\S]*?)\n---/);
  if (!m) return { fm: {}, body: content };
  const body = content.slice(m[0].length);
  const fm = {};
  for (const line of m[1].split("\n")) {
    const kv = line.match(/^([a-z_-]+)\s*:\s*(.*)$/i);
    if (!kv) continue;
    const k = kv[1].trim();
    let v = kv[2].trim();
    if (v.startsWith("'") || v.startsWith('"')) v = v.slice(1, -1);
    fm[k] = v;
  }
  return { fm, body };
}

function listSkills(dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  function walk(d, prefix = "") {
    let entries;
    try { entries = readdirSync(d, { withFileTypes: true }); } catch { return; }
    for (const e of entries) {
      const full = join(d, e.name);
      if (e.isDirectory()) walk(full, prefix + e.name + "/");
      else if (e.isFile() && e.name.endsWith(".md")) {
        out.push({ path: full, relative: prefix + e.name });
      }
    }
  }
  walk(dir);
  return out;
}

function render(scope, skill, fm, body, generatedAt) {
  const name = basename(skill.relative, ".md");
  const desc = fm.description ? String(fm.description).slice(0, DESC_MAX) : "_(no description in frontmatter)_";
  const tags = fm.tags || "";
  const model = fm.model || "";
  const allowedTools = fm["allowed-tools"] || "";
  const firstParagraph = body
    .split("\n\n")
    .find((p) => p.trim().length > 0 && !p.startsWith("#"))
    ?.slice(0, 400) || "";
  return `---
title: Skill — ${name}
type: skill
skill_name: ${name}
scope: ${scope}
source_path: ${skill.path.replace(/\\/g, "/")}
generated_by: scripts/generate-skill-wiki.mjs
last_verified: ${generatedAt}
tags: [skill, scope-${scope}${tags ? ", " + tags : ""}]
related:
  - knowledge/wiki/architecture/layer-l8.md
---

# Skill — \`${name}\`

> ${desc}

**Scope:** ${scope}${model ? `  ·  **Model:** \`${model}\`` : ""}${allowedTools ? `  ·  **Allowed tools:** \`${allowedTools}\`` : ""}

${AUTO_START}

| Field | Value |
|-------|-------|
| Name | \`${name}\` |
| Scope | ${scope} |
| Source | \`${skill.path.replace(/\\/g, "/")}\` |
| Model | ${model || "default"} |
| Tags | ${tags || "_(none)_"} |

## Description (first paragraph)

${firstParagraph || "_(no body content)_"}

${AUTO_END}

## See also

- Skills root: \`${SCOPES[scope]}\`
- Invoke via Skill tool with name \`${name}\` (no leading slash)
`;
}

function preserveHuman(existing, full) {
  if (!existing) return full;
  const sStart = existing.indexOf(AUTO_START);
  const sEnd = existing.indexOf(AUTO_END);
  const nStart = full.indexOf(AUTO_START);
  const nEnd = full.indexOf(AUTO_END);
  if (sStart === -1 || sEnd === -1) return full;
  return existing.slice(0, sStart) + full.slice(nStart, nEnd + AUTO_END.length) + existing.slice(sEnd + AUTO_END.length);
}

function updateIndex(counts) {
  if (!existsSync(WIKI_INDEX)) return null;
  const text = readFileSync(WIKI_INDEX, "utf8");
  const lines = Object.entries(counts).map(([s, c]) => `- ${s}: ${c} skills`);
  const block = ["<!-- ARCH-SKILLS-START -->", `_Total: ${Object.values(counts).reduce((a, b) => a + b, 0)} skill entries_`, "", ...lines, "<!-- ARCH-SKILLS-END -->"].join("\n");
  if (text.includes("<!-- ARCH-SKILLS-START -->")) {
    return text.replace(/<!-- ARCH-SKILLS-START -->[\s\S]*?<!-- ARCH-SKILLS-END -->/m, block);
  }
  if (text.includes("<!-- ARCH-MILESTONES-END -->")) {
    return text.replace(/<!-- ARCH-MILESTONES-END -->/, "<!-- ARCH-MILESTONES-END -->\n\n### Skills\n\n" + block);
  }
  return text.trimEnd() + "\n\n### Skills\n\n" + block + "\n";
}

function main() {
  ensureDir(SKILLS_DIR);
  const generatedAt = new Date().toISOString().split("T")[0];
  const counts = {};
  let total = 0;
  const t0 = Date.now();

  for (const [scope, dir] of Object.entries(SCOPES)) {
    const skills = listSkills(dir);
    counts[scope] = skills.length;
    const scopeDir = join(SKILLS_DIR, scope);
    ensureDir(scopeDir);
    for (const s of skills) {
      let content = "";
      try { content = readFileSync(s.path, "utf8"); } catch { continue; }
      const { fm, body } = parseFrontmatter(content);
      const fileName = slug(s.relative.replace(/\//g, "-").replace(/\.md$/, "")) + ".md";
      const outPath = join(scopeDir, fileName);
      const full = render(scope, s, fm, body, generatedAt);
      const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
      writeFileSync(outPath, preserveHuman(existing, full), "utf8");
      total++;
    }
  }

  const indexUpdated = updateIndex(counts);
  if (indexUpdated) writeFileSync(WIKI_INDEX, indexUpdated, "utf8");
  console.log(`generated ${total} skill wiki entries in ${Date.now() - t0}ms (scopes: ${JSON.stringify(counts)})`);
}

main();
