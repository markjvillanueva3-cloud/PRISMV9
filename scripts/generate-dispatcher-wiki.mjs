#!/usr/bin/env node
/**
 * generate-dispatcher-wiki.mjs
 *
 * Generates one Obsidian wiki entry per L4 dispatcher at
 *   H:/prism/knowledge/wiki/architecture/dispatcher-<name>.md
 *
 * Each entry surfaces:
 *   - dispatcher id, canonical label, category (manufacturing|system|ai_intel|business)
 *   - status (built|stub|etc)
 *   - action count + sample actions (from L4a children connected by edge)
 *   - engines consumed (L4 → L5 outbound edges)
 *   - cross-refs to [[layer-l4]] + [[layer-l4a]]
 *
 * Idempotent — AUTO-START/END markers preserve human content.
 * Updates wiki/index.md ### Dispatchers subsection (ARCH-DISPATCHERS markers).
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PRISM_ROOT = resolve(__dirname, "..");
const GRAPH_PATH = resolve(PRISM_ROOT, "state/shared/system-viz/system-graph.json");
const WIKI_ARCH_DIR = resolve(PRISM_ROOT, "knowledge/wiki/architecture");
const WIKI_INDEX = resolve(PRISM_ROOT, "knowledge/wiki/index.md");

const args = new Set(process.argv.slice(2));
const FLAGS = { dryRun: args.has("--dry-run") };

const AUTO_START = "<!-- AUTO-START — regenerated by generate-dispatcher-wiki.mjs -->";
const AUTO_END = "<!-- AUTO-END -->";

const SAMPLE_ACTIONS_PER = 12;

function readJson(p) {
  return JSON.parse(readFileSync(p, "utf8"));
}

function ensureDir(d) {
  if (!existsSync(d)) mkdirSync(d, { recursive: true });
}

function slug(label) {
  return String(label || "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function indexGraph(G) {
  const nodeById = new Map();
  for (const n of G.nodes) nodeById.set(n.id, n);
  // Edges grouped by source dispatcher → action / engine
  const outEdges = new Map();
  for (const e of G.edges) {
    const arr = outEdges.get(e.from) || [];
    arr.push(e);
    outEdges.set(e.from, arr);
  }
  return { nodeById, outEdges };
}

function analyzeDispatcher(disp, { nodeById, outEdges }) {
  const out = outEdges.get(disp.id) || [];
  const actions = [];
  const engineEdges = [];
  for (const e of out) {
    const t = nodeById.get(e.to);
    if (!t) continue;
    if (t.layer === "L4a") actions.push(t);
    else if (t.layer === "L5") engineEdges.push(t);
  }
  return {
    actionCount: actions.length,
    actionsSample: actions.slice(0, SAMPLE_ACTIONS_PER).map((a) => a.label || a.id),
    engineEdges: engineEdges.slice(0, 8).map((n) => ({ id: n.id, label: n.label || n.id })),
  };
}

const CATEGORY_PURPOSE = {
  manufacturing: "Manufacturing-domain dispatcher — milling/turning/EDM/CAD/CAM/multi-axis routing.",
  system: "System-level dispatcher — session, context, dev, memory, orchestration, telemetry.",
  ai_intel: "AI/Intelligence dispatcher — reasoning, knowledge graph, neural, deep learning routes.",
  business: "Business dispatcher — billing, quoting, ERP, ROI, sales, customer-facing routes.",
};

function render(disp, analysis, generatedAt, headline) {
  const purpose = CATEGORY_PURPOSE[disp.subgroup] || `Dispatcher in category \`${disp.subgroup || "?"}\`.`;
  const actionLines = analysis.actionsSample.length
    ? analysis.actionsSample.map((a) => `- \`${String(a).replace(/\n/g, " ")}\``).join("\n")
    : "_(no actions wired)_";
  const engineLines = analysis.engineEdges.length
    ? analysis.engineEdges.map((e) => `- \`${e.id}\` — ${e.label.replace(/\n/g, " ")}`).join("\n")
    : "_(no L5 engine edges in graph — may indicate scaffold-only dispatcher)_";
  return `---
title: Dispatcher — ${disp.label || disp.id}
type: architecture
dispatcher_id: ${disp.id}
category: ${disp.subgroup || "?"}
parent_layer: L4
generated_by: scripts/generate-dispatcher-wiki.mjs
last_verified: ${generatedAt}
tags: [architecture, system-viz, dispatcher, dispatcher-${slug(disp.label || disp.id)}, ${disp.subgroup || "uncategorized"}]
related:
  - knowledge/wiki/architecture/layer-l4.md
  - knowledge/wiki/architecture/layer-l4a.md
  - state/shared/system-viz/system-graph.json
---

# Dispatcher — \`${disp.label || disp.id}\`

> ${purpose}

**Status:** ${disp.status || "?"}  ·  **Category:** ${disp.subgroup || "?"}  ·  **Action count:** ${analysis.actionCount}
**System headline:** ${headline.built ?? "?"} engines wired across all dispatchers

${AUTO_START}

## Sample actions (first ${SAMPLE_ACTIONS_PER})

${actionLines}

${analysis.actionCount > SAMPLE_ACTIONS_PER ? `_…and ${analysis.actionCount - SAMPLE_ACTIONS_PER} more. See full enum in dispatcher source._` : ""}

## Engine consumers (L5 edges)

${engineLines}

## Doctrine

- Prefer this dispatcher's actions over inlining engine logic
- Action enum, Zod schema, and lazy import must all match (see \`comprehensive-build-enforce\` hook)
- New action: add to enum + schema + handler in same commit (atomic build)

${AUTO_END}

## See also

- Parent layer: [[layer-l4]]
- Actions layer: [[layer-l4a]]
- Dispatcher source: \`mcp-server/src/tools/dispatchers/${disp.label || disp.id}Dispatcher.ts\`
- Live graph: \`state/shared/system-viz/system-graph.json\`
`;
}

function preserveHuman(existing, full) {
  if (!existing) return full;
  const sStart = existing.indexOf(AUTO_START);
  const sEnd = existing.indexOf(AUTO_END);
  const nStart = full.indexOf(AUTO_START);
  const nEnd = full.indexOf(AUTO_END);
  if (sStart === -1 || sEnd === -1) return full;
  const before = existing.slice(0, sStart);
  const after = existing.slice(sEnd + AUTO_END.length);
  const newAuto = full.slice(nStart, nEnd + AUTO_END.length);
  return before + newAuto + after;
}

function updateIndex(entries) {
  if (!existsSync(WIKI_INDEX)) return null;
  const text = readFileSync(WIKI_INDEX, "utf8");
  const lines = entries
    .sort((a, b) => b.actionCount - a.actionCount)
    .map(
      (e) => `- [[dispatcher-${slug(e.label)}]] — \`${e.label}\` (${e.actionCount} actions, ${e.category})`
    );
  const block = [
    "<!-- ARCH-DISPATCHERS-START -->",
    ...lines,
    "<!-- ARCH-DISPATCHERS-END -->",
  ].join("\n");

  if (text.includes("<!-- ARCH-DISPATCHERS-START -->")) {
    return text.replace(
      /<!-- ARCH-DISPATCHERS-START -->[\s\S]*?<!-- ARCH-DISPATCHERS-END -->/m,
      block
    );
  }
  if (text.includes("<!-- ARCH-DOMAINS-END -->")) {
    return text.replace(
      /<!-- ARCH-DOMAINS-END -->/,
      "<!-- ARCH-DOMAINS-END -->\n\n### Dispatchers (sorted by action count)\n\n" + block
    );
  }
  return text.trimEnd() + "\n\n### Dispatchers\n\n" + block + "\n";
}

function main() {
  if (!existsSync(GRAPH_PATH)) {
    process.stderr.write("graph missing\n");
    process.exit(2);
  }
  const G = readJson(GRAPH_PATH);
  const idx = indexGraph(G);
  const headline = (G.meta && G.meta.headline) || {};
  const generatedAt = new Date().toISOString().split("T")[0];

  ensureDir(WIKI_ARCH_DIR);
  const entries = [];

  for (const n of G.nodes) {
    if (n.layer !== "L4") continue;
    const analysis = analyzeDispatcher(n, idx);
    const outPath = join(WIKI_ARCH_DIR, `dispatcher-${slug(n.label || n.id)}.md`);
    const full = render(n, analysis, generatedAt, headline);
    const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
    const final = preserveHuman(existing, full);
    if (FLAGS.dryRun) {
      process.stdout.write(`would write ${outPath} (${final.length}b, ${analysis.actionCount} actions)\n`);
    } else {
      writeFileSync(outPath, final, "utf8");
    }
    entries.push({
      id: n.id,
      label: n.label || n.id,
      actionCount: analysis.actionCount,
      category: n.subgroup || "?",
    });
  }

  const indexUpdated = updateIndex(entries);
  if (indexUpdated && !FLAGS.dryRun) writeFileSync(WIKI_INDEX, indexUpdated, "utf8");

  process.stdout.write(
    `generated ${entries.length} dispatcher wiki entries · index ${indexUpdated ? "updated" : "skipped"}\n`
  );
}

main();
