#!/usr/bin/env node
/**
 * generate-extracted-modules-wiki.mjs
 *
 * One wiki entry per *module file* of the decomposed PRISM v8.89 monolith.
 * `generate-monolith-wiki.mjs` already does the folder-level rollup (~37 entries);
 * this goes a level deeper — every `.js`/`.ts`/`.json` module under:
 *   - extracted/<category>/        (categorized decomposition, ~330 files)
 *   - extracted_modules/<bucket>/   (flat dumps incl. complete_extraction/ ~830, ~1047 total)
 *
 * Each entry surfaces: module name, source folder + category, ext, byte size,
 * line count, the leading docblock (the monolith chunks all start with a header
 * docblock — "Extracted from PRISM v8.89.002 monolith · References: N · Category: X")
 * and the doctrine note: this is decomposed v8.89 source — survey it before
 * re-implementing (it's the source material for SFC / Master-Post / MS1 /
 * CADCAM-AI / LEARN; full map in wiki "prism-v8-89-monolith-extraction.md").
 *
 * Output: knowledge/wiki/architecture/monolith-modules/<category>/<slug>.md
 * Plus:   knowledge/wiki/architecture/monolith-modules-index.md  (catalog, links every entry by category)
 *
 * Idempotent. preserveHuman() keeps anything outside the AUTO markers.
 * Flags: --dry-run
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { resolve, dirname, join, relative, basename, extname } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PRISM_ROOT = resolve(__dirname, "..");
const SRC_ROOTS = [
  { root: resolve(PRISM_ROOT, "extracted"), tag: "extracted", categorized: true },
  { root: resolve(PRISM_ROOT, "extracted_modules"), tag: "extracted_modules", categorized: false },
];
const WIKI_ARCH_DIR = resolve(PRISM_ROOT, "knowledge/wiki/architecture");
const OUT_DIR = join(WIKI_ARCH_DIR, "monolith-modules");
const INDEX_OUT = join(WIKI_ARCH_DIR, "monolith-modules-index.md");
const WIKI_INDEX = resolve(PRISM_ROOT, "knowledge/wiki/index.md");

const args = new Set(process.argv.slice(2));
const FLAGS = { dryRun: args.has("--dry-run") };

const AUTO_START = "<!-- AUTO-START — regenerated by generate-extracted-modules-wiki.mjs -->";
const AUTO_END = "<!-- AUTO-END -->";

const MODULE_EXTS = new Set([".js", ".ts", ".mjs", ".cjs", ".json"]);
const DOCBLOCK_LINES = 18;          // how many leading lines to scan for the monolith header
const DESC_MAX = 200;
// Link EVERY module from the catalog so per-module entries aren't orphans. The
// catalog page (monolith-modules-index.md) is allowed to be large — it's a
// catalog, not index.md. (Categories print a summary table + a full link list.)
const INDEX_SAMPLE_PER_CAT = 100000;

function ensureDir(d) { if (!existsSync(d)) mkdirSync(d, { recursive: true }); }
function slug(s) { return String(s || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 90) || "x"; }
function isBackupDir(name) { return /backup|_old|_ARCHIVE|materials_v9|materials_complete|materials_enhanced/i.test(name); }

function walkModules(srcRoot, categorized) {
  // depth 1 (categorized: extracted/<cat>/<file>) or depth 1 (extracted_modules/<bucket>/<file>) — both 1 level
  const out = [];
  let cats;
  try { cats = readdirSync(srcRoot, { withFileTypes: true }); } catch { return out; }
  for (const c of cats) {
    if (!c.isDirectory()) {
      // top-level loose files (rare) — bucket them as "_root"
      if (c.isFile() && MODULE_EXTS.has(extname(c.name).toLowerCase())) out.push({ category: "_root", file: join(srcRoot, c.name) });
      continue;
    }
    if (isBackupDir(c.name)) continue;
    const catDir = join(srcRoot, c.name);
    let files;
    try { files = readdirSync(catDir, { withFileTypes: true }); } catch { continue; }
    for (const f of files) {
      if (f.isDirectory()) {
        // one more level (complete_extraction sometimes nests) — flatten with a "<cat>/<sub>" category label
        let sub;
        try { sub = readdirSync(join(catDir, f.name), { withFileTypes: true }); } catch { continue; }
        for (const sf of sub) {
          if (sf.isFile() && MODULE_EXTS.has(extname(sf.name).toLowerCase())) out.push({ category: `${c.name}/${f.name}`, file: join(catDir, f.name, sf.name) });
        }
        continue;
      }
      if (f.isFile() && MODULE_EXTS.has(extname(f.name).toLowerCase())) out.push({ category: c.name, file: join(catDir, f.name) });
    }
  }
  return out;
}

function leadingDocblock(text) {
  // first /* … */ or run of // lines within the first DOCBLOCK_LINES lines
  const lines = text.split(/\r?\n/).slice(0, DOCBLOCK_LINES);
  const buf = [];
  let inBlock = false;
  for (const ln of lines) {
    const t = ln.trim();
    if (t.startsWith("/*") || inBlock) { inBlock = true; const s = t.replace(/^\/?\*+\/?/, "").replace(/\*\/$/, "").trim(); if (s) buf.push(s); if (t.endsWith("*/")) break; continue; }
    if (t.startsWith("//")) { buf.push(t.replace(/^\/+\s?/, "")); continue; }
    if (buf.length && t === "") continue;
    if (buf.length) break;
  }
  return buf.join(" · ").slice(0, 400);
}

function parseMonolithHeader(docblock) {
  // "Extracted from PRISM v8.89.002 monolith · References: 34 · Category: general · Lines: 2205 · Session: R2.3.3 …"
  const refs = (docblock.match(/References?:\s*(\d+)/i) || [, null])[1];
  const cat = (docblock.match(/Category:\s*([^\s·]+)/i) || [, null])[1];
  const sess = (docblock.match(/Session:\s*([^·]+)/i) || [, null])[1];
  const fromMonolith = /v8\.89|monolith/i.test(docblock);
  return { refs: refs ? Number(refs) : null, declaredCategory: cat || null, session: sess ? sess.trim() : null, fromMonolith };
}

function render(m, gen) {
  const rel = relative(PRISM_ROOT, m.file).replace(/\\/g, "/");
  const name = basename(m.file);
  let text = "", lineCount = 0, size = 0;
  try { const st = statSync(m.file); size = st.size; } catch {}
  try { text = readFileSync(m.file, "utf8"); lineCount = text.split(/\r?\n/).length; } catch {}
  const doc = leadingDocblock(text);
  const hdr = parseMonolithHeader(doc);
  const desc = (doc || `${name} — monolith module (${m.category})`).slice(0, DESC_MAX);
  const bucket = rel.startsWith("extracted_modules/") ? "extracted_modules" : "extracted";
  return `---
title: Monolith module — ${name}
type: architecture
kind: monolith-module
module_path: ${rel}
bucket: ${bucket}
category: ${m.category}${hdr.declaredCategory ? `\ndeclared_category: ${hdr.declaredCategory}` : ""}${hdr.refs != null ? `\nmonolith_references: ${hdr.refs}` : ""}
ext: ${extname(name).replace(/^\./, "") || "?"}
line_count: ${lineCount}
size_bytes: ${size}
from_monolith: ${hdr.fromMonolith}
generated_by: scripts/generate-extracted-modules-wiki.mjs
last_verified: ${gen}
tags: [architecture, system-viz, monolith, extracted-module, ${slug(m.category)}]
related:
  - knowledge/wiki/architecture/monolith-modules-index.md
  - knowledge/wiki/architecture/prism-v8-89-monolith-extraction.md
  - knowledge/wiki/architecture/monolith-extraction/index.md
---

# Monolith module — \`${name}\`

> ${desc}

${AUTO_START}

| Field | Value |
|-------|-------|
| Path | \`${rel}\` |
| Bucket | ${bucket} |
| Category | ${m.category}${hdr.declaredCategory && hdr.declaredCategory !== m.category ? ` (declared: ${hdr.declaredCategory})` : ""} |
| Extension | \`${extname(name) || "?"}\` |
| Lines | ${lineCount} |
| Size | ${(size / 1024).toFixed(1)} KB |
${hdr.refs != null ? `| Monolith references | ${hdr.refs} |\n` : ""}${hdr.session ? `| Extraction session | ${hdr.session} |\n` : ""}| From v8.89 monolith | ${hdr.fromMonolith ? "yes" : "unknown"} |

## Leading docblock

\`\`\`
${doc || "(no leading docblock)"}
\`\`\`

## Doctrine

- This is **decomposed PRISM v8.89 source** — survey it BEFORE re-implementing. It's the source material for SFC / Master-Post / MS1 / CADCAM-AI / LEARN (tracked in \`REVENUE-ROADMAP §R6\`).
- The \`extracted/\` tree is the categorized decomposition; \`extracted_modules/\` (esp. \`complete_extraction/\`) is the flat dump pool — these are a **separate pool** from BUILD_STATE's unwired-engines list.
- Before lifting this into \`mcp-server/src/\`, run \`duplicationGuardEngine.checkBeforeCreating()\` — much of this is already re-implemented; the anti-re-extract guard throws on duplicates.

${AUTO_END}

## See also

- Monolith module catalog: [[monolith-modules-index]]
- v8.89 extraction overview: [[prism-v8-89-monolith-extraction]]
- Folder-level rollup: [[index]] (under \`architecture/monolith-extraction/\`)
`;
}

function renderIndex(byCategory, total, gen) {
  const cats = Object.entries(byCategory).sort((a, b) => b[1].count - a[1].count);
  const sections = cats.map(([cat, info]) => {
    const sample = info.entries.slice(0, INDEX_SAMPLE_PER_CAT).map((e) => `- [[${e.name}]]${e.refs != null ? ` _(refs: ${e.refs})_` : ""}`).join("\n");
    const more = info.count > INDEX_SAMPLE_PER_CAT ? `\n- … +${info.count - INDEX_SAMPLE_PER_CAT} more in \`monolith-modules/${slug(cat)}/\`` : "";
    return `### \`${cat}\` — ${info.count} modules\n\n${sample}${more}`;
  }).join("\n\n");
  return `---
title: Monolith modules — catalog
type: architecture
kind: monolith-module-index
total_modules: ${total}
total_categories: ${cats.length}
generated_by: scripts/generate-extracted-modules-wiki.mjs
last_verified: ${gen}
tags: [architecture, system-viz, monolith, extracted-module, catalog, index]
related:
  - knowledge/wiki/architecture/prism-v8-89-monolith-extraction.md
  - knowledge/wiki/architecture/monolith-extraction/index.md
  - REVENUE-ROADMAP-v7.5.md
---

# Monolith modules — catalog

> Every decomposed-monolith module file under \`extracted/\` and \`extracted_modules/\` gets its own wiki entry (one level deeper than the folder rollup). **${total} modules** across **${cats.length} categories**. Source material for SFC / Master-Post / MS1 / CADCAM-AI / LEARN — survey before re-implementing.

${AUTO_START}

**Total:** ${total} modules · ${cats.length} categories. Per-module entries live under \`knowledge/wiki/architecture/monolith-modules/<category>/\`.

| Category | Modules |
|----------|---------|
${cats.map(([c, i]) => `| \`${c}\` | ${i.count} |`).join("\n")}

${sections}

## Doctrine

- These are **already-extracted artifacts** — do NOT re-extract (CLAUDE.md anti-re-extract guard throws on duplicates). Provenance: \`mcp-server/data/state/extraction-log.json\` + \`extracted_modules/FINAL_EXTRACTION_SUMMARY.json\` + \`extracted/EXTRACTION_REGISTRY.json\`.
- The "missing 10 modules" in \`FINAL_EXTRACTION_SUMMARY.json\` was a stale flag — all present (verified; cleared to \`[]\` with \`missing_legacy\` audit note).
- Before lifting any module into \`mcp-server/src/\`: \`duplicationGuardEngine.checkBeforeCreating()\` first.

${AUTO_END}

## See also

- v8.89 extraction overview: [[prism-v8-89-monolith-extraction]]
- Folder rollup: [[index]] (\`architecture/monolith-extraction/\`)
- Revenue roadmap §R6 (monolith-harvest): \`REVENUE-ROADMAP-v7.5.md\`
`;
}

function preserveHuman(existing, full) {
  if (!existing) return full;
  const sStart = existing.indexOf(AUTO_START);
  const sEnd = existing.indexOf(AUTO_END);
  const nStart = full.indexOf(AUTO_START);
  const nEnd = full.indexOf(AUTO_END);
  if (sStart === -1 || sEnd === -1) return full;
  return existing.slice(0, sStart) + full.slice(nStart, nEnd + AUTO_END.length) + existing.slice(sEnd + AUTO_END.length);
}

function updateWikiIndex(total, cats) {
  if (!existsSync(WIKI_INDEX)) return null;
  const text = readFileSync(WIKI_INDEX, "utf8");
  const block = ["<!-- ARCH-MONOLITH-MODULES-START -->",
    `_Total: ${total} per-module wiki entries across ${cats} categories — see [[monolith-modules-index]]._`,
    "", "Dir: `architecture/monolith-modules/<category>/`. These are the decomposed v8.89 monolith source files (source material for SFC / Master-Post / MS1 / CADCAM-AI / LEARN).",
    "<!-- ARCH-MONOLITH-MODULES-END -->"].join("\n");
  if (text.includes("<!-- ARCH-MONOLITH-MODULES-START -->")) return text.replace(/<!-- ARCH-MONOLITH-MODULES-START -->[\s\S]*?<!-- ARCH-MONOLITH-MODULES-END -->/m, block);
  if (text.includes("<!-- ARCH-MISC-L8-END -->")) return text.replace(/<!-- ARCH-MISC-L8-END -->/, "<!-- ARCH-MISC-L8-END -->\n\n### Monolith modules (per-module, v8.89 decomposition)\n\n" + block);
  return text.trimEnd() + "\n\n### Monolith modules\n\n" + block + "\n";
}

function main() {
  const gen = new Date().toISOString().split("T")[0];
  const t0 = Date.now();
  const modules = [];
  for (const { root, categorized } of SRC_ROOTS) {
    if (!existsSync(root)) continue;
    for (const m of walkModules(root, categorized)) modules.push(m);
  }
  if (!modules.length) { console.log("monolith-modules wiki: no extracted modules found — nothing to do"); return; }

  const byCategory = {};
  const usedPaths = new Set();
  let written = 0;
  for (const m of modules) {
    const catSlug = slug(m.category);
    const dir = join(OUT_DIR, catSlug);
    if (!FLAGS.dryRun) ensureDir(dir);
    let fname = `${slug(basename(m.file, extname(m.file)))}.md`;
    let outPath = join(dir, fname);
    let n = 2;
    while (usedPaths.has(outPath)) { outPath = join(dir, fname.replace(/\.md$/, `-${n++}.md`)); }
    usedPaths.add(outPath);
    const full = render(m, gen);
    const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
    if (!FLAGS.dryRun) writeFileSync(outPath, preserveHuman(existing, full), "utf8");
    written++;
    const entryName = basename(outPath, ".md");
    const refs = (full.match(/^monolith_references:\s*(\d+)/m) || [, null])[1];
    (byCategory[m.category] ||= { count: 0, entries: [] }).count++;
    byCategory[m.category].entries.push({ name: entryName, refs: refs != null ? Number(refs) : null });
  }

  if (!FLAGS.dryRun) {
    ensureDir(OUT_DIR);
    const idxExisting = existsSync(INDEX_OUT) ? readFileSync(INDEX_OUT, "utf8") : null;
    writeFileSync(INDEX_OUT, preserveHuman(idxExisting, renderIndex(byCategory, written, gen)), "utf8");
    const wi = updateWikiIndex(written, Object.keys(byCategory).length);
    if (wi) writeFileSync(WIKI_INDEX, wi, "utf8");
  }

  console.log(`monolith-modules wiki: ${written} per-module entries across ${Object.keys(byCategory).length} categories, ${Date.now() - t0}ms`);
}

main();
