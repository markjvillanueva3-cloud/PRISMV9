#!/usr/bin/env node
/**
 * databases-to-vault.mjs -- connect EVERY PRISM database to the Obsidian vault.
 *
 * Operator goal (2026-06-14, slot:papa): "ensure ALL databases are connected to the
 * Obsidian vault. Machines, tools, materials, tooling, vendors, potential customers,
 * jm die data, fixtures."
 *
 * For each database in scripts/lib/database-registry.mjs this bridge resolves the live
 * record count from the store's manifest/file and writes a DATA-CONTENTS-INVENTORY note
 * to knowledge/memories/reference/reference_db_<id>.md -- the same vault location the
 * existing per-store bridges use (jm-shop-knowledge-to-vault, vendor-catalog-db). Those
 * notes become first-class brain nodes: generate-memories-atomic graphs them, the
 * memory-relevance / master-index hooks recall them, and the Stop obsidian-memory-feed
 * mirrors them -- so any chat / feature / the frontend can answer "where is the machine
 * database, how big is it, how do I query it" by MEANING, not by re-grepping the tree.
 *
 * Re-runnable + fail-soft (a missing store -> the note records it as a GAP, R12 -- never
 * faked). Also writes a consolidated state/shared/DATABASE-VAULT-INVENTORY.md index.
 *
 *   node scripts/databases-to-vault.mjs            # write all notes + the index
 *   node scripts/databases-to-vault.mjs --json     # report only, no writes
 *   node scripts/databases-to-vault.mjs --dry-run  # resolve counts, no writes
 *
 * Env: PRISM_DB_VAULT_FROZEN_TIME=<iso> pins the generatedAt for diff-stable output.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DATABASES, REPO_ROOT, resolveCount, validateRegistry } from "./lib/database-registry.mjs";

const VAULT_DIR = path.join(REPO_ROOT, "knowledge", "memories", "reference");
const INDEX_PATH = path.join(REPO_ROOT, "state", "shared", "DATABASE-VAULT-INVENTORY.md");

function nowIso() {
  return process.env.PRISM_DB_VAULT_FROZEN_TIME || new Date().toISOString();
}

/** Resolve the byte size of the primary source (file or dir), fail-soft. */
function sourceSizeBytes(rel) {
  if (!rel) return null;
  const abs = path.isAbsolute(rel) ? rel : path.join(REPO_ROOT, rel);
  try {
    const st = fs.statSync(abs);
    if (st.isFile()) return st.size;
    if (st.isDirectory()) {
      let total = 0;
      for (const e of fs.readdirSync(abs, { withFileTypes: true })) {
        if (e.isFile()) { try { total += fs.statSync(path.join(abs, e.name)).size; } catch { /* skip */ } }
      }
      return total;
    }
  } catch { /* absent */ }
  return null;
}

/** Build the markdown DATA-CONTENTS-INVENTORY note for one database (pure). */
export function buildNote(db, resolved, generatedAt) {
  const countLine =
    resolved.count !== null
      ? `**${resolved.count.toLocaleString()}** records (${resolved.detail})`
      : `**count unavailable** (${resolved.detail})`;
  const status = db.gap ? "GAP -- store not yet built" : resolved.count !== null ? "connected" : "degraded (count unresolved)";
  const desc = `${db.displayName} -- ${resolved.count !== null ? resolved.count.toLocaleString() + " records" : (db.gap ? "GAP/unbuilt" : "count n/a")}; primary at ${db.primarySource || "(no on-disk store)"}`;
  const sourceLines = db.sources.map((s) => `- \`${s.path}\` -- ${s.role}`).join("\n");
  const galaxies = (db.galaxies || []).join(", ") || "(unassigned)";
  const existing = db.existingVaultNote ? `\n> Companion note (pre-existing): [[${db.existingVaultNote.replace(/\.md$/, "")}]]\n` : "";

  return `---
name: reference_db_${db.id}
description: ${desc.replace(/\n/g, " ")}
metadata:
  type: reference
---

# ${db.displayName} -- DATA-CONTENTS INVENTORY

> Auto-generated by \`scripts/databases-to-vault.mjs\` (DATABASE-VAULT-BRIDGE, slot:papa). Re-run to refresh.
> generatedAt: ${generatedAt}  ·  status: **${status}**
${existing}
## What it is
${db.description}

## Records
${countLine}

## Where it lives
- **Primary source:** \`${db.primarySource || "(none -- see status)"}\`
- **Galaxies served:** ${galaxies}
- **Category:** ${db.category}

## Sources
${sourceLines}

## Schema (shape)
${db.schemaHint}

## How to query it
${db.queryHint}

## Connection to the brain
This note IS the connection: it is a vault memory node under \`knowledge/memories/reference/\`, graphed by \`generate-memories-atomic\` into the system-viz graph and indexed by the master-index, so any chat / feature recalls "${db.id} database" by MEANING via \`/system-viz find\` or \`prism_session:master_index_query\` (the recall path that applies to H:-authored vault notes). Related: [[feedback_never_assume_data_file_contents]].
`;
}

function main() {
  const argv = process.argv.slice(2);
  const jsonOnly = argv.includes("--json");
  const dryRun = argv.includes("--dry-run");
  const generatedAt = nowIso();

  const problems = validateRegistry();
  if (problems.length > 0) {
    process.stderr.write(`[db-vault] registry INVALID:\n  ${problems.join("\n  ")}\n`);
    process.exit(2);
  }

  const results = [];
  for (const db of DATABASES) {
    const resolved = resolveCount(db.count);
    const bytes = sourceSizeBytes(db.primarySource);
    results.push({ id: db.id, displayName: db.displayName, count: resolved.count, detail: resolved.detail, gap: !!db.gap, bytes });
    if (!jsonOnly && !dryRun) {
      const note = buildNote(db, resolved, generatedAt);
      fs.mkdirSync(VAULT_DIR, { recursive: true });
      fs.writeFileSync(path.join(VAULT_DIR, `reference_db_${db.id}.md`), note, "utf8");
    }
  }

  const connected = results.filter((r) => r.count !== null).length;
  const gaps = results.filter((r) => r.gap).length;

  if (jsonOnly) {
    process.stdout.write(JSON.stringify({ generatedAt, total: results.length, connected, gaps, databases: results }, null, 2) + "\n");
    return;
  }

  if (!dryRun) {
    // Consolidated index.
    const rows = results
      .map((r) => `| ${r.id} | ${r.displayName} | ${r.gap ? "GAP" : r.count !== null ? r.count.toLocaleString() : "n/a"} | ${r.gap ? "unbuilt" : r.count !== null ? "connected" : "degraded"} | reference_db_${r.id}.md |`)
      .join("\n");
    const index = `# DATABASE -> OBSIDIAN VAULT INVENTORY

> Auto-generated by \`scripts/databases-to-vault.mjs\`. generatedAt: ${generatedAt}
> ${connected}/${results.length} databases connected (count resolved); ${gaps} GAP(s). Each row has a DATA-CONTENTS-INVENTORY vault note under knowledge/memories/reference/.

| id | database | records | status | vault note |
|----|----------|---------|--------|-----------|
${rows}

## Doctrine
Every PRISM database is connected to the Obsidian brain via a \`reference_db_<id>.md\` note (location + count + schema + sample + query-hint). Refresh: \`node scripts/databases-to-vault.mjs\`. Registry: \`scripts/lib/database-registry.mjs\`. Pattern: [[feedback_never_assume_data_file_contents]].
`;
    fs.mkdirSync(path.dirname(INDEX_PATH), { recursive: true });
    fs.writeFileSync(INDEX_PATH, index, "utf8");
  }

  process.stdout.write(
    `[db-vault] ${dryRun ? "(dry-run) " : ""}${results.length} databases | ${connected} connected | ${gaps} gap(s)\n` +
    results.map((r) => `  ${r.gap ? "[GAP]" : r.count !== null ? "[OK] " : "[!!] "} ${r.id.padEnd(20)} ${r.count !== null ? String(r.count).padStart(8) : "     n/a"}  ${r.detail}`).join("\n") + "\n" +
    (dryRun ? "" : `[db-vault] wrote ${results.length} notes -> ${path.relative(REPO_ROOT, VAULT_DIR)}/ + index -> ${path.relative(REPO_ROOT, INDEX_PATH)}\n`),
  );
}

// Entrypoint guard: only run the live vault write when invoked as a CLI, so
// importing buildNote (the test does) never mutates the real vault.
const __isCli = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (__isCli) main();
