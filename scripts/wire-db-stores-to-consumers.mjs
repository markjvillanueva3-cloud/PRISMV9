#!/usr/bin/env node
/**
 * wire-db-stores-to-consumers.mjs
 *
 * GOAL (juliett, 2026-06-01): "all databases properly wired and bridged to all domains,
 * nodes and galaxies that will intake them. strategically wire based off necessity and logic."
 *
 * The canonical DatabaseRegistry bridge (data/databases/DB_MANIFEST.json) makes the 3
 * juliett-owned directory stores DISCOVERABLE at runtime (prism_data:database_list /
 * globalSearch). This script closes the AWARENESS layer: it splices a marked, idempotent
 * "## 📥 Registered DB intake" section into the PATHS.md of every galaxy declared as a
 * `consumer` of a store in the manifest — so a chat working in that galaxy knows the store
 * exists, what it holds, and how to query it. The consumer lists ARE the necessity+logic
 * wiring (declared once in the manifest, applied here).
 *
 * Source of truth: data/databases/DB_MANIFEST.json `consumers` fields.
 * IDEMPOTENT: re-running replaces the marked block in place; a galaxy no longer listed as a
 * consumer has its stale block stripped. Re-run when the manifest's consumer lists change.
 *
 * Usage:
 *   node scripts/wire-db-stores-to-consumers.mjs            # apply
 *   node scripts/wire-db-stores-to-consumers.mjs --check    # dry-run freshness gate (exit 2 if stale)
 *
 * Karpathy: CLASSIFY=transform+wire · EDGE CASES=galaxy consumes 0/1/many stores · galaxy
 * removed from consumers (strip stale) · re-run (idempotent) · CRLF · missing PATHS.md (skip) ·
 * manifest missing/malformed. FAIL MODES=manifest absent → exit 1; zero galaxies → exit 1.
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { discoverGalaxies } from "./wire-galaxies-to-resource-roots.mjs";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST_REL = "data/databases/DB_MANIFEST.json";
const MANIFEST = path.join(REPO, MANIFEST_REL);
const ENGINES_DIR = path.join(REPO, "mcp-server/src/engines");

export const BEGIN = "<!-- BEGIN:registered-db-intake (generated by scripts/wire-db-stores-to-consumers.mjs — do not hand-edit) -->";
export const END = "<!-- END:registered-db-intake -->";

function escapeRegex(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/** Stores (from the manifest) that name `galaxy` in their `consumers` list, sorted by id. */
export function storesForGalaxy(manifest, galaxy) {
  const dbs = (manifest && Array.isArray(manifest.databases)) ? manifest.databases : [];
  return dbs
    .filter((d) => Array.isArray(d.consumers) && d.consumers.includes(galaxy))
    .sort((a, b) => String(a.id).localeCompare(String(b.id)));
}

/** Pure: same (galaxy, stores) → byte-identical block. */
export function buildGalaxyBlock(galaxy, stores) {
  const lines = [BEGIN];
  lines.push(`## 📥 Registered DB intake (juliett-owned stores the ${galaxy} galaxy consumes — DB-EXPANSION-BRIDGE-MS0)`);
  lines.push(`> Discoverable at runtime via \`prism_data:database_list\` / \`globalSearch\` (registered in \`${MANIFEST_REL}\`). Re-wire after manifest consumer-list changes: \`node scripts/wire-db-stores-to-consumers.mjs\`.`);
  for (const s of stores) {
    const n = Number.isFinite(s.entry_count) ? s.entry_count.toLocaleString() : "?";
    const man = s.manifest_file ? ` · manifest \`${s.manifest_file}\`` : "";
    // file-backed stores carry source_file (not source_dir); fall back so the path is never "undefined" — the fleet needs a real pathway to each DB file
    const path = s.source_dir || s.source_file || "(path n/a)";
    lines.push(`- **${s.id}** (${s.name}) — \`${path}\` · ${n} entries${man} · query: \`prism_data:database_search\` or \`node scripts/db-toolbelt.mjs --status\``);
  }
  lines.push(END);
  return lines.join("\n");
}

/**
 * Idempotently wire `block` into `content` at file-end (block=null → strip-only).
 * Strips ALL prior complete BEGIN..END spans + orphaned lone marker lines, then appends
 * the canonical block once (if provided). Converges in one pass from any prior state;
 * never loses non-marker content.
 */
export function spliceSection(content, block) {
  const fullRe = new RegExp(escapeRegex(BEGIN) + "[\\s\\S]*?" + escapeRegex(END), "g");
  const existing = content.match(fullRe) || [];
  const norm = (s) => s.replace(/\r/g, "");
  // CHURN-FREE FAST-PATH: if my block already exists verbatim (exactly one copy, no
  // duplicate/orphan markers), leave it IN PLACE — do NOT move it to file-end. Without this,
  // a sibling append-at-end wirer (e.g. charlie's wire-vendor-corpus) that runs after us puts
  // its block below ours; our next run would then drag ours back to the end, and the two
  // wirers would reorder each other forever. No-op-when-unchanged breaks that loop.
  if (block && existing.length === 1 && norm(existing[0]) === norm(block)) {
    const afterStrip = content.replace(fullRe, "");
    const hasOrphan = afterStrip
      .split(/\r?\n/)
      .some((l) => l.trim() === BEGIN.trim() || l.trim() === END.trim());
    if (!hasOrphan) return content;
  }
  // Otherwise (absent / changed / duplicated / orphaned): strip all complete spans + lone
  // marker lines, then append the canonical block once at file-end.
  let stripped = content.replace(fullRe, "");
  stripped = stripped
    .split(/\r?\n/)
    .filter((l) => l.trim() !== BEGIN.trim() && l.trim() !== END.trim())
    .join("\n");
  const base = stripped.replace(/\s*$/, "");
  if (!block) return base + "\n";
  return base + "\n\n" + block + "\n";
}

function main() {
  const check = process.argv.includes("--check");
  if (!fs.existsSync(MANIFEST)) {
    console.error(`[wire-db-stores] FATAL: manifest not found: ${MANIFEST}`);
    process.exit(1);
  }
  let manifest;
  try {
    manifest = JSON.parse(fs.readFileSync(MANIFEST, "utf-8"));
  } catch (e) {
    console.error(`[wire-db-stores] FATAL: manifest malformed: ${e.message}`);
    process.exit(1);
  }
  const galaxies = discoverGalaxies(ENGINES_DIR);

  let changed = 0;
  let unchanged = 0;
  let wiredGalaxies = 0;
  const report = [];
  for (const g of galaxies) {
    const p = path.join(ENGINES_DIR, g, "PATHS.md");
    const before = fs.readFileSync(p, "utf-8");
    const stores = storesForGalaxy(manifest, g);
    const block = stores.length ? buildGalaxyBlock(g, stores) : null;
    const after = spliceSection(before, block);
    if (stores.length) wiredGalaxies++;
    if (after !== before) {
      if (!check) fs.writeFileSync(p, after);
      changed++;
      report.push(`${block ? "wire " : "strip"} ${g.padEnd(20)} ${stores.map((s) => s.id).join(", ")}`);
    } else {
      unchanged++;
    }
  }

  console.log(`[wire-db-stores] ${check ? "CHECK (no writes)" : "APPLIED"}`);
  console.log(`  galaxies discovered     : ${galaxies.length}`);
  console.log(`  galaxies consuming a DB  : ${wiredGalaxies}`);
  console.log(`  PATHS.md changed        : ${changed}`);
  console.log(`  PATHS.md unchanged      : ${unchanged}`);
  for (const r of report) console.log(`    ${r}`);
  if (galaxies.length === 0) {
    console.error("[wire-db-stores] WARN: zero galaxies discovered — check ENGINES_DIR");
    process.exit(1);
  }
  if (check && changed > 0) {
    console.error("[wire-db-stores] --check: wiring STALE (changes pending) — run without --check to apply.");
    process.exit(2);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
