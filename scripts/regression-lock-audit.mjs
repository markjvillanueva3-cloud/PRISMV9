#!/usr/bin/env node
// scripts/regression-lock-audit.mjs
// U-REGRESSION-LOCK-AUDIT (2026-06-09, slot:alpha): CLI shell over
// scripts/lib/regression-lock-audit.mjs. Audits the `## Recent regressions`
// ledger (CLAUDE.md + optionally every galaxy CLAUDE.md) for the Opik-L3 lock
// property: does each documented fix ship a recurrence-catching test?
//
// Advisory-only: it AUDITS, it never writes tests or edits CLAUDE.md. Emits a
// markdown punch list + a roost-shaped JSON that a system-viz ghost-roost
// generator can consume (sierra wires the roost; this only emits the data).
//
// Usage:
//   node scripts/regression-lock-audit.mjs            # write report + json
//   node scripts/regression-lock-audit.mjs --json     # machine output to stdout
//   node scripts/regression-lock-audit.mjs --galaxies # also scan galaxy CLAUDE.mds
// Knobs: PRISM_REGRESSION_LOCK_AUDIT_DISABLE=1
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { glob } from "node:fs/promises";

import { parseRegressionEntries, classifyLock, LOCK } from "./lib/regression-lock-audit.mjs";

const REPO = "H:/prism";
const OUT_MD = join(REPO, "state", "shared", "REGRESSION-LOCK-AUDIT.md");
const OUT_JSON = join(REPO, "state", "shared", "REGRESSION-LOCK-AUDIT.json");

// Real commit->files reader. Fail-soft to null on a bad/stale sha so the entry
// degrades to UNVERIFIABLE rather than crashing the audit (R12 keep-running).
function gitCommitFiles(sha) {
  if (!sha) return null;
  try {
    const out = execFileSync("git", ["-C", REPO, "show", "--name-only", "--format=", sha], {
      encoding: "utf8",
      timeout: 8000,
      stdio: ["ignore", "pipe", "ignore"],
    });
    const files = out.split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
    return files.length ? files : null;
  } catch {
    return null; // unknown sha / git error -> UNVERIFIABLE
  }
}

async function main() {
  if (process.env.PRISM_REGRESSION_LOCK_AUDIT_DISABLE === "1") {
    process.stdout.write("regression-lock-audit: disabled via knob\n");
    return 0;
  }
  const asJson = process.argv.includes("--json");
  const withGalaxies = process.argv.includes("--galaxies");

  // Primary source: root CLAUDE.md. Fleet-wide: optionally every galaxy CLAUDE.md.
  const sources = [{ file: join(REPO, "CLAUDE.md"), galaxy: "root" }];
  if (withGalaxies) {
    try {
      for await (const p of glob(join(REPO, "mcp-server/src/engines/*/CLAUDE.md"))) {
        const galaxy = dirname(p).split(/[\\/]/).pop();
        sources.push({ file: p, galaxy });
      }
    } catch { /* glob unsupported -> root only, fail-soft */ }
  }

  // Aggregate entries across sources, tagging each with its galaxy.
  const tagged = [];
  for (const { file, galaxy } of sources) {
    if (!existsSync(file)) continue;
    let md;
    try { md = readFileSync(file, "utf8"); } catch { continue; }
    for (const e of parseRegressionEntries(md)) {
      tagged.push(classifyLock({ ...e, galaxy }, gitCommitFiles));
    }
  }

  // Summarize (reuse the lib's counting semantics by re-deriving over tagged).
  const locked = tagged.filter((e) => e.status === LOCK.LOCKED).length;
  const unlocked = tagged.filter((e) => e.status === LOCK.UNLOCKED).length;
  const unverifiable = tagged.filter((e) => e.status === LOCK.UNVERIFIABLE).length;
  const judgeable = locked + unlocked;
  const order = { [LOCK.UNLOCKED]: 0, [LOCK.LOCKED]: 1, [LOCK.UNVERIFIABLE]: 2 };
  tagged.sort((a, b) => (order[a.status] - order[b.status]) || String(b.date).localeCompare(String(a.date)));
  const summary = {
    advisoryOnly: true,
    mustHumanVerify: true,
    generatedFromSources: sources.map((s) => s.galaxy),
    total: tagged.length,
    locked,
    unlocked,
    unverifiable,
    lockRate: judgeable > 0 ? Number((locked / judgeable).toFixed(4)) : null,
  };

  // Roost-shaped flat array for a future system-viz ghost-roost (sierra wires it).
  const roost = tagged.map((e, i) => ({
    id: `ghost.regression_unlocked.${e.sha || "nosha"}.${i}`,
    label: `[${e.status}] ${e.description}`.slice(0, 120),
    status: e.status,
    galaxy: e.galaxy || "root",
    sha: e.sha || null,
    date: e.date,
  }));

  if (asJson) {
    process.stdout.write(JSON.stringify({ summary, roost }, null, 2) + "\n");
    return 0;
  }

  // Markdown report -- UNLOCKED first (the punch list).
  const pct = summary.lockRate === null ? "n/a" : `${(summary.lockRate * 100).toFixed(1)}%`;
  const lines = [
    "# Regression-Lock Audit (advisory)",
    "",
    "_Opik-L3 self-repairing-harness applied to PRISM: does each documented regression ship a recurrence-catching test? Generated by scripts/regression-lock-audit.mjs ._",
    "",
    `- **total** documented regressions: ${summary.total}`,
    `- **LOCKED** (fix shipped a test): ${locked}`,
    `- **UNLOCKED** (source fix, NO test -- recurrence risk): ${unlocked}`,
    `- **UNVERIFIABLE** (no sha / stale sha / doc-only fix): ${unverifiable}`,
    `- **lock rate** (locked / judgeable): ${pct}`,
    "",
    "## UNLOCKED -- recurrence-risk punch list (write a test that fails without the fix)",
    "",
  ];
  const unlockedRows = tagged.filter((e) => e.status === LOCK.UNLOCKED);
  if (!unlockedRows.length) lines.push("_(none -- every judgeable regression is locked)_");
  for (const e of unlockedRows) {
    lines.push(`- [${e.galaxy}] ${e.date} \`${e.sha}\` -- ${e.description}`);
  }
  lines.push("", "## How to roost this in /system-viz (sierra)", "",
    "`REGRESSION-LOCK-AUDIT.json` `.roost[]` is a flat `{id,label,status,galaxy,sha}` array.",
    "A `ghost.regression_unlocked` roost generator can splice it into the graph the same",
    "way other ghost roosts do (FAST[] + merge). This CLI only emits the data.", "");

  writeFileSync(OUT_MD, lines.join("\n"));
  writeFileSync(OUT_JSON, JSON.stringify({ summary, roost }, null, 2));
  process.stdout.write(
    `regression-lock-audit: ${summary.total} regressions | LOCKED ${locked} | UNLOCKED ${unlocked} | UNVERIFIABLE ${unverifiable} | lockRate ${pct}\n` +
    `  report: ${OUT_MD}\n  json:   ${OUT_JSON}\n`,
  );
  return 0;
}

const invokedDirectly = (() => {
  try { return fileURLToPath(import.meta.url) === process.argv[1]; } catch { return false; }
})();
if (invokedDirectly) main().then((c) => process.exit(c || 0)).catch((e) => {
  try { process.stderr.write(`regression-lock-audit fatal: ${e.message}\n`); } catch {}
  process.exit(1);
});

export { gitCommitFiles };
