#!/usr/bin/env node
/**
 * generate-monolith-wiki.mjs
 *
 * Surfaces the original PRISM v8.89 monolith extraction corpus in the Obsidian
 * 2nd brain. The monolith was a 986,622-line HTML app; it was extracted into
 * two trees on disk:
 *
 *   H:/prism/extracted/          — categorized (25 category dirs: engines,
 *     algorithms, formulas, constants, controllers, core, business, catalogs,
 *     infrastructure, integration, knowledge_bases, learning, machines,
 *     materials*, mit, systems, tools, units). Tracked by EXTRACTION_REGISTRY.json
 *     (wave-based) + MASTER_EXTRACTION_INDEX.json (per-engine-file line counts).
 *
 *   H:/prism/extracted_modules/  — flat-by-folder (11 folders: ai_ml_engines,
 *     COMPLETE, complete_extraction, MEGA, ULTRA, GIANT, databases,
 *     geometry_engines, physics_engines, priority_extraction, system).
 *     950 modules / 154 MB / 99.9% extraction rate per FINAL_EXTRACTION_SUMMARY.json.
 *
 * Output: knowledge/wiki/architecture/monolith-extraction/
 *   index.md                — master overview (source size, both trees, totals, status)
 *   category-<name>.md       — one per extracted/<dir>/ (file list + line counts)
 *   modules-<folder>.md      — one per extracted_modules/<folder>/ (module .js list)
 *   missing.md               — the still-missing modules
 *
 * Idempotent — AUTO-START/END markers preserve human notes. Cross-links from
 * layer-l9 (filesystem) handled by inject-wiki-crosslinks.mjs.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PRISM_ROOT = resolve(__dirname, "..");
const EXTRACTED_DIR = resolve(PRISM_ROOT, "extracted");
const MODULES_DIR = resolve(PRISM_ROOT, "extracted_modules");
const WIKI_ARCH_DIR = resolve(PRISM_ROOT, "knowledge/wiki/architecture");
const OUT_DIR = join(WIKI_ARCH_DIR, "monolith-extraction");
const WIKI_INDEX = resolve(PRISM_ROOT, "knowledge/wiki/index.md");

const args = new Set(process.argv.slice(2));
const FLAGS = { dryRun: args.has("--dry-run") };

const AUTO_START = "<!-- AUTO-START — regenerated by generate-monolith-wiki.mjs -->";
const AUTO_END = "<!-- AUTO-END -->";
const MAX_FILES_LISTED = 100;

function readJsonSafe(p) {
  try { return JSON.parse(readFileSync(p, "utf8")); } catch { return null; }
}
function ensureDir(d) { if (!existsSync(d)) mkdirSync(d, { recursive: true }); }
function slug(s) { return String(s || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""); }

function listDirs(root) {
  if (!existsSync(root)) return [];
  try {
    return readdirSync(root, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name);
  } catch { return []; }
}

function listFiles(dir, exts) {
  if (!existsSync(dir)) return [];
  try {
    return readdirSync(dir, { withFileTypes: true })
      .filter((e) => e.isFile() && (!exts || exts.some((x) => e.name.toLowerCase().endsWith(x))))
      .map((e) => {
        let size = 0;
        try { size = statSync(join(dir, e.name)).size; } catch {}
        return { name: e.name, size };
      });
  } catch { return []; }
}

function preserveHuman(existing, full) {
  if (!existing) return full;
  const sStart = existing.indexOf(AUTO_START);
  const sEnd = existing.indexOf(AUTO_END);
  const nStart = full.indexOf(AUTO_START);
  const nEnd = full.indexOf(AUTO_END);
  if (sStart === -1 || sEnd === -1) return full;
  return existing.slice(0, sStart) + full.slice(nStart, nEnd + AUTO_END.length) + existing.slice(sEnd + AUTO_END.length);
}

function write(path, content) {
  if (FLAGS.dryRun) { process.stdout.write(`would write ${path} (${content.length}b)\n`); return; }
  writeFileSync(path, content, "utf8");
}

function fmtMB(bytes) { return (bytes / (1024 * 1024)).toFixed(2); }

function renderIndex(reg, master, finalSummary, categoryDirs, moduleDirs, generatedAt) {
  const sourceLines = reg?.sourceLines ?? master?.summary?.total_lines ?? "?";
  const sourceFile = reg?.sourceFile ?? "PRISM v8.89 monolith HTML";
  const modTotal = finalSummary?.total_modules ?? "?";
  const modRate = finalSummary?.extraction_rate ? finalSummary.extraction_rate.toFixed(1) + "%" : "?";
  const modChars = finalSummary?.total_chars ? fmtMB(finalSummary.total_chars) + " MB" : "?";
  const folderRows = finalSummary?.by_folder
    ? Object.entries(finalSummary.by_folder).map(([f, info]) => `| [[modules-${slug(f)}]] | \`${f}\` | ${info.count} | ${fmtMB(info.size)} |`).join("\n")
    : "_(FINAL_EXTRACTION_SUMMARY.json not found)_";
  const catRows = categoryDirs.map((d) => `| [[category-${slug(d)}]] | \`${d}\` |`).join("\n");
  const missingRows = (finalSummary?.missing || []).map((m) => `- \`${m}\``).join("\n") || "_(none — 100% extracted)_";
  return `---
title: Monolith Extraction — index
type: architecture
generated_by: scripts/generate-monolith-wiki.mjs
last_verified: ${generatedAt}
tags: [architecture, monolith, extraction, prism-v8-89, legacy]
related:
  - knowledge/wiki/architecture/layer-l9.md
  - knowledge/wiki/architecture/layer-l6.md
---

# PRISM v8.89 Monolith Extraction — index

> The original PRISM was a single ${typeof sourceLines === "number" ? sourceLines.toLocaleString() : sourceLines}-line HTML monolith.
> It was extracted into two on-disk trees so its engines, algorithms, formulas, and
> datasets could be ported into the current modular MCP architecture. This index
> maps that extraction corpus into the Obsidian brain.

**Source:** \`${sourceFile}\`
**Extracted modules:** ${modTotal} modules · ${modChars} · ${modRate} extraction rate

${AUTO_START}

## Tree 1 — \`extracted/\` (categorized)

Tracked by \`extracted/EXTRACTION_REGISTRY.json\` (wave-based) + \`extracted/MASTER_EXTRACTION_INDEX.json\` (per-engine-file line counts).
${reg?.progress ? `\nProgress: ${reg.progress.modulesExtracted}/${reg.progress.totalModulesTarget} modules · ${reg.progress.linesExtracted?.toLocaleString()}/${reg.progress.totalLinesTarget?.toLocaleString()} lines · ${reg.progress.percentComplete?.toFixed(1)}%\n` : ""}
${master?.summary ? `Engine subset: ${master.summary.total_files} files · ${master.summary.total_lines?.toLocaleString()} lines · ${master.summary.total_size_mb} MB · ${master.summary.extraction_status}\n` : ""}

| Wiki entry | Category dir |
|------------|--------------|
${catRows}

## Tree 2 — \`extracted_modules/\` (flat by folder)

Tracked by \`extracted_modules/FINAL_EXTRACTION_SUMMARY.json\`. This is the more complete extraction (99.9%).

| Wiki entry | Folder | Modules | Size (MB) |
|------------|--------|---------|-----------|
${folderRows}

## Still missing

${missingRows}

> See [[missing]] for the full list with notes.

## Integration status

These extracted modules are reference material for the current MCP build. When
porting one, run \`duplicationGuardEngine.checkBeforeCreating\` first — many have
already been re-implemented as modern engines (see \`mcp-server/data/state/extraction-log.json\`).

${AUTO_END}

## See also

- Filesystem layer: [[layer-l9]]  ·  Core layer: [[layer-l6]]
- Extraction log: \`mcp-server/data/state/extraction-log.json\`
- Source trees: \`H:/prism/extracted/\` · \`H:/prism/extracted_modules/\`
`;
}

function renderCategory(catName, files, masterCategory, generatedAt) {
  const fileRows = (() => {
    if (masterCategory && Array.isArray(masterCategory.files)) {
      return masterCategory.files.slice(0, MAX_FILES_LISTED).map((f) => `| \`${f.name}\` | ${f.lines ?? "?"} | ${f.size_kb ?? "?"} |`).join("\n");
    }
    return files.slice(0, MAX_FILES_LISTED).map((f) => `| \`${f.name}\` | — | ${(f.size / 1024).toFixed(1)} |`).join("\n");
  })();
  const total = masterCategory?.files?.length ?? files.length;
  return `---
title: Monolith Extraction — ${catName}
type: architecture
extraction_tree: extracted
category: ${catName}
generated_by: scripts/generate-monolith-wiki.mjs
last_verified: ${generatedAt}
tags: [architecture, monolith, extraction, extracted-${slug(catName)}]
related:
  - knowledge/wiki/architecture/monolith-extraction/index.md
  - knowledge/wiki/architecture/layer-l9.md
---

# Monolith Extraction — \`extracted/${catName}/\`

> ${masterCategory?.description || `Extracted ${catName} modules from the PRISM v8.89 monolith.`}

**Files:** ${total}${total > MAX_FILES_LISTED ? ` (showing first ${MAX_FILES_LISTED})` : ""}

${AUTO_START}

| File | Lines | Size (KB) |
|------|-------|-----------|
${fileRows}

${AUTO_END}

## See also

- Extraction index: [[index]]
- Filesystem layer: [[layer-l9]]
- Source dir: \`H:/prism/extracted/${catName}/\`
`;
}

function renderModuleFolder(folderName, files, summaryEntry, generatedAt) {
  const fileRows = files.slice(0, MAX_FILES_LISTED).map((f) => `| \`${f.name}\` | ${(f.size / 1024).toFixed(1)} |`).join("\n") || "_(no .js files)_";
  return `---
title: Monolith Extraction — ${folderName}
type: architecture
extraction_tree: extracted_modules
folder: ${folderName}
generated_by: scripts/generate-monolith-wiki.mjs
last_verified: ${generatedAt}
tags: [architecture, monolith, extraction, modules-${slug(folderName)}]
related:
  - knowledge/wiki/architecture/monolith-extraction/index.md
  - knowledge/wiki/architecture/layer-l9.md
---

# Monolith Extraction — \`extracted_modules/${folderName}/\`

> ${summaryEntry ? `${summaryEntry.count} modules · ${fmtMB(summaryEntry.size)} MB` : "Extracted module folder"} from the PRISM v8.89 monolith.

**Modules:** ${files.length}${files.length > MAX_FILES_LISTED ? ` (showing first ${MAX_FILES_LISTED})` : ""}

${AUTO_START}

| Module | Size (KB) |
|--------|-----------|
${fileRows}

${AUTO_END}

## See also

- Extraction index: [[index]]
- Filesystem layer: [[layer-l9]]
- Source dir: \`H:/prism/extracted_modules/${folderName}/\`
`;
}

function renderMissing(finalSummary, generatedAt) {
  const missing = finalSummary?.missing || [];
  const rows = missing.map((m) => `- \`${m}\` — not yet extracted from the v8.89 source`).join("\n") || "_(none — 100% extracted)_";
  return `---
title: Monolith Extraction — missing modules
type: architecture
generated_by: scripts/generate-monolith-wiki.mjs
last_verified: ${generatedAt}
tags: [architecture, monolith, extraction, gap]
related:
  - knowledge/wiki/architecture/monolith-extraction/index.md
---

# Monolith Extraction — still-missing modules

> Modules present in the v8.89 monolith inventory but not yet pulled into either extraction tree.

${AUTO_START}

${rows}

${AUTO_END}

## See also

- Extraction index: [[index]]
- Source inventory: \`extracted_modules/FINAL_EXTRACTION_SUMMARY.json\`
`;
}

function updateWikiIndex(catCount, folderCount) {
  if (!existsSync(WIKI_INDEX)) return null;
  const text = readFileSync(WIKI_INDEX, "utf8");
  const block = [
    "<!-- ARCH-MONOLITH-START -->",
    `_PRISM v8.89 monolith extraction: [[index]] overview + ${catCount} category entries + ${folderCount} module-folder entries + [[missing]] — see knowledge/wiki/architecture/monolith-extraction/_`,
    "<!-- ARCH-MONOLITH-END -->",
  ].join("\n");
  if (text.includes("<!-- ARCH-MONOLITH-START -->")) {
    return text.replace(/<!-- ARCH-MONOLITH-START -->[\s\S]*?<!-- ARCH-MONOLITH-END -->/m, block);
  }
  if (text.includes("<!-- ARCH-FORMULAS-END -->")) {
    return text.replace(/<!-- ARCH-FORMULAS-END -->/, "<!-- ARCH-FORMULAS-END -->\n\n### Monolith extraction\n\n" + block);
  }
  return text.trimEnd() + "\n\n### Monolith extraction\n\n" + block + "\n";
}

function main() {
  if (!existsSync(EXTRACTED_DIR) && !existsSync(MODULES_DIR)) {
    console.error("neither extracted/ nor extracted_modules/ found — nothing to do");
    process.exit(0);
  }
  const reg = readJsonSafe(join(EXTRACTED_DIR, "EXTRACTION_REGISTRY.json"));
  const master = readJsonSafe(join(EXTRACTED_DIR, "MASTER_EXTRACTION_INDEX.json"));
  const finalSummary = readJsonSafe(join(MODULES_DIR, "FINAL_EXTRACTION_SUMMARY.json"));
  const generatedAt = new Date().toISOString().split("T")[0];

  ensureDir(OUT_DIR);
  const t0 = Date.now();

  // Skip backup/archive variant dirs — they're snapshots, not extraction targets
  const SKIP_DIR_RE = /backup|_archive|_old/i;
  const categoryDirs = listDirs(EXTRACTED_DIR).filter((d) => !SKIP_DIR_RE.test(d));
  const moduleDirs = listDirs(MODULES_DIR);

  // index
  {
    const p = join(OUT_DIR, "index.md");
    const existing = existsSync(p) ? readFileSync(p, "utf8") : null;
    write(p, preserveHuman(existing, renderIndex(reg, master, finalSummary, categoryDirs, moduleDirs, generatedAt)));
  }
  // missing
  {
    const p = join(OUT_DIR, "missing.md");
    const existing = existsSync(p) ? readFileSync(p, "utf8") : null;
    write(p, preserveHuman(existing, renderMissing(finalSummary, generatedAt)));
  }
  // per category dir (extracted/)
  let catCount = 0;
  const masterCategories = master?.categories || {};
  for (const catName of categoryDirs) {
    const files = listFiles(join(EXTRACTED_DIR, catName), [".js", ".json", ".ts"]);
    // Match a MASTER_EXTRACTION_INDEX category by description heuristic — engines dir maps to all physics/* etc.
    const masterCat = masterCategories[catName] || null;
    const p = join(OUT_DIR, `category-${slug(catName)}.md`);
    const existing = existsSync(p) ? readFileSync(p, "utf8") : null;
    write(p, preserveHuman(existing, renderCategory(catName, files, masterCat, generatedAt)));
    catCount++;
  }
  // per module folder (extracted_modules/)
  let folderCount = 0;
  const byFolder = finalSummary?.by_folder || {};
  for (const folderName of moduleDirs) {
    const files = listFiles(join(MODULES_DIR, folderName), [".js"]);
    const p = join(OUT_DIR, `modules-${slug(folderName)}.md`);
    const existing = existsSync(p) ? readFileSync(p, "utf8") : null;
    write(p, preserveHuman(existing, renderModuleFolder(folderName, files, byFolder[folderName], generatedAt)));
    folderCount++;
  }

  const indexUpdated = !FLAGS.dryRun ? updateWikiIndex(catCount, folderCount) : null;
  if (indexUpdated && !FLAGS.dryRun) writeFileSync(WIKI_INDEX, indexUpdated, "utf8");

  console.log(`monolith-wiki: index + missing + ${catCount} category + ${folderCount} module-folder entries in ${Date.now() - t0}ms`);
}

main();
