#!/usr/bin/env node
/**
 * generate-action-wiki.mjs
 *
 * Generates one Obsidian wiki entry per L4a dispatcher action at
 *   H:/prism/knowledge/wiki/architecture/actions/<dispatcher>/<action>.md
 *
 * L4a nodes have id pattern `disp.<dispatcherName>.action.<actionName>` and
 * are connected by edge from their parent L4 dispatcher node.
 *
 * Each entry is intentionally small (~600 bytes): frontmatter + action name
 * + parent dispatcher cross-ref + position-in-enum. Bulk volume comes from
 * coverage (9,228 actions across 97 dispatchers), not per-entry depth — for
 * deeper context follow the [[dispatcher-...]] cross-link.
 *
 * Idempotent. Updates wiki/index.md ### Actions subsection w/ counts.
 *
 * Flags:
 *   --dry-run         skip writes
 *   --dispatcher=X    generate only X's actions (testing)
 *   --limit=N         cap total entries (safety throttle)
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PRISM_ROOT = resolve(__dirname, "..");
const GRAPH_PATH = resolve(PRISM_ROOT, "state/shared/system-viz/system-graph.json");
const WIKI_ARCH_DIR = resolve(PRISM_ROOT, "knowledge/wiki/architecture");
const ACTIONS_DIR = join(WIKI_ARCH_DIR, "actions");
const WIKI_INDEX = resolve(PRISM_ROOT, "knowledge/wiki/index.md");

const args = process.argv.slice(2);
const FLAGS = {
  dryRun: args.includes("--dry-run"),
  dispatcherFilter: (args.find((a) => a.startsWith("--dispatcher=")) || "").split("=")[1] || null,
  limit: parseInt((args.find((a) => a.startsWith("--limit=")) || "").split("=")[1] || "0", 10) || 0,
};

const AUTO_START = "<!-- AUTO-START — regenerated by generate-action-wiki.mjs -->";
const AUTO_END = "<!-- AUTO-END -->";

function readJson(p) {
  return JSON.parse(readFileSync(p, "utf8"));
}

function ensureDir(d) {
  if (!existsSync(d)) mkdirSync(d, { recursive: true });
}

function slug(s) {
  return String(s || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function indexGraph(G) {
  const nodeById = new Map();
  for (const n of G.nodes) nodeById.set(n.id, n);
  return nodeById;
}

function parseActionId(id) {
  // Expected: disp.<dispName>.action.<actionName>
  const m = /^disp\.([a-z0-9_]+)\.action\.(.+)$/i.exec(id);
  if (!m) return null;
  return { dispatcherKey: m[1], actionName: m[2] };
}

function render(actionNode, parsed, dispatcherNode, positionIndex, generatedAt) {
  const actionName = actionNode.label || parsed.actionName;
  const dispLabel = dispatcherNode ? dispatcherNode.label || parsed.dispatcherKey : parsed.dispatcherKey;
  const dispCategory = dispatcherNode?.subgroup || "?";
  return `---
title: ${dispLabel}:${actionName}
type: action
action_id: ${actionNode.id}
dispatcher: ${dispLabel}
action_name: ${actionName}
parent_layer: L4a
generated_by: scripts/generate-action-wiki.mjs
last_verified: ${generatedAt}
tags: [action, dispatcher-${slug(dispLabel)}, ${dispCategory}]
related:
  - knowledge/wiki/architecture/dispatcher-${slug(dispLabel)}.md
  - knowledge/wiki/architecture/layer-l4a.md
---

# ${dispLabel}:\`${actionName}\`

> Dispatcher action — invoke via \`${dispLabel}({ action: "${actionName}", ... })\`

${AUTO_START}

| Field | Value |
|-------|-------|
| Action | \`${actionName}\` |
| Dispatcher | [[dispatcher-${slug(dispLabel)}]] |
| Category | ${dispCategory} |
| Graph node | \`${actionNode.id}\` |
| Position in dispatcher | ${positionIndex} |

${AUTO_END}

## See also

- Parent dispatcher: [[dispatcher-${slug(dispLabel)}]]
- Actions layer: [[layer-l4a]]
- Live graph: \`state/shared/system-viz/system-graph.json\`
`;
}

function preserveHuman(existing, full) {
  if (!existing) return full;
  const sStart = existing.indexOf(AUTO_START);
  const sEnd = existing.indexOf(AUTO_END);
  const nStart = full.indexOf(AUTO_START);
  const nEnd = full.indexOf(AUTO_END);
  if (sStart === -1 || sEnd === -1) return full;
  const before = existing.slice(0, sStart);
  const after = existing.slice(sEnd + AUTO_END.length);
  const newAuto = full.slice(nStart, nEnd + AUTO_END.length);
  return before + newAuto + after;
}

function updateIndex(perDispatcherCounts, totalWritten) {
  if (!existsSync(WIKI_INDEX)) return null;
  const text = readFileSync(WIKI_INDEX, "utf8");
  const top = Object.entries(perDispatcherCounts)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 12);
  const block = [
    "<!-- ARCH-ACTIONS-START -->",
    `_Total: ${totalWritten} action entries across ${Object.keys(perDispatcherCounts).length} dispatchers — see \`knowledge/wiki/architecture/actions/<dispatcher>/\`._`,
    "",
    "Top dispatchers by action count:",
    ...top.map(([d, c]) => `- \`${d}\`: ${c} actions`),
    "<!-- ARCH-ACTIONS-END -->",
  ].join("\n");
  if (text.includes("<!-- ARCH-ACTIONS-START -->")) {
    return text.replace(/<!-- ARCH-ACTIONS-START -->[\s\S]*?<!-- ARCH-ACTIONS-END -->/m, block);
  }
  if (text.includes("<!-- ARCH-ENGINES-END -->")) {
    return text.replace(
      /<!-- ARCH-ENGINES-END -->/,
      "<!-- ARCH-ENGINES-END -->\n\n### Actions (per-dispatcher counts)\n\n" + block
    );
  }
  return text.trimEnd() + "\n\n### Actions\n\n" + block + "\n";
}

function main() {
  if (!existsSync(GRAPH_PATH)) {
    console.error("graph missing");
    process.exit(2);
  }
  const G = readJson(GRAPH_PATH);
  const nodeById = indexGraph(G);
  const generatedAt = new Date().toISOString().split("T")[0];

  ensureDir(ACTIONS_DIR);

  // Per-dispatcher action enumeration position tracking
  const positionCounter = new Map();
  const perDispatcherCounts = {};
  let written = 0;
  let skipped = 0;
  const t0 = Date.now();

  for (const node of G.nodes) {
    if (node.layer !== "L4a") continue;
    const parsed = parseActionId(node.id);
    if (!parsed) {
      skipped++;
      continue;
    }
    const dispId = `disp.${parsed.dispatcherKey}`;
    const dispatcherNode = nodeById.get(dispId);
    const dispLabel = dispatcherNode?.label || parsed.dispatcherKey;
    if (FLAGS.dispatcherFilter && dispLabel !== FLAGS.dispatcherFilter) continue;
    if (FLAGS.limit && written >= FLAGS.limit) break;

    const pos = (positionCounter.get(parsed.dispatcherKey) || 0) + 1;
    positionCounter.set(parsed.dispatcherKey, pos);

    const dispDir = join(ACTIONS_DIR, slug(dispLabel));
    ensureDir(dispDir);
    const fileName = `${slug(parsed.actionName)}.md`;
    const outPath = join(dispDir, fileName);
    const full = render(node, parsed, dispatcherNode, pos, generatedAt);
    const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
    const finalContent = preserveHuman(existing, full);

    if (!FLAGS.dryRun) writeFileSync(outPath, finalContent, "utf8");
    written++;
    perDispatcherCounts[dispLabel] = (perDispatcherCounts[dispLabel] || 0) + 1;
  }

  if (!FLAGS.dispatcherFilter && !FLAGS.limit) {
    const indexUpdated = !FLAGS.dryRun ? updateIndex(perDispatcherCounts, written) : null;
    if (indexUpdated && !FLAGS.dryRun) writeFileSync(WIKI_INDEX, indexUpdated, "utf8");
  }

  console.log(
    `generated ${written} action wiki entries in ${Date.now() - t0}ms ` +
      `(skipped ${skipped}, dispatchers: ${Object.keys(perDispatcherCounts).length})`
  );
}

main();
