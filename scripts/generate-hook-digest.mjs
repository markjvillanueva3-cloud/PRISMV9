#!/usr/bin/env node
/**
 * generate-hook-digest.mjs — 1-line-per-hook index for .claude/hooks/.
 *
 * MEMORY-WIKI-OPTIMIZATION-MS0 / U-MWO12 (slot:bravo 2026-05-26).  Parallel to
 * U-MWO06 (AGENT_DIGEST.md) — closes discoverability gap for the 916-hook
 * directory.  Per session-start brief 391 of 916 hooks are orphan-on-disk
 * (42.7%), making an index useful for orphan-detection too.
 *
 * Strategy: scan top-level .mjs hook files in .claude/hooks/.  For each:
 *   1. First JSDoc-style summary line from the @module header (first sentence)
 *   2. Tier marker `// tier: T#` if present (T0=blocker, T1=soft-gate, T2=injector, T3=observer, T4=async)
 *   3. Trigger event inferred from filename prefix (session-start-*, pre-tool-*, stop-*, user-prompt-*)
 *
 * Usage:  node scripts/generate-hook-digest.mjs [--out PATH]
 * Exit:   0 ok · 1 hooks dir missing · 2 runtime error
 *
 * @module scripts/generate-hook-digest
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const DEFAULT_HOOKS_DIR = path.join(ROOT, ".claude", "hooks");
const DEFAULT_OUT = path.join(ROOT, ".claude", "hooks", "HOOK_DIGEST.md");

const MAX_SUMMARY_CHARS = 140;
const HEAD_BYTES = 4096;  // First 4 KB is enough to find the JSDoc header + tier marker

/** Extract first descriptive line from a hook source.  Pure. */
export function extractSummary(src) {
  // Find first `* <text>` line inside the leading JSDoc block; skip @tags + empty/decorative-only lines.
  const jsdocMatch = src.match(/\/\*\*([\s\S]*?)\*\//);
  if (!jsdocMatch) return "(no description)";
  for (const raw of jsdocMatch[1].split(/\r?\n/)) {
    const cleaned = raw.replace(/^\s*\*\s?/, "").trim();
    if (!cleaned) continue;
    if (cleaned.startsWith("@")) continue;
    if (/^[-=*]+$/.test(cleaned)) continue;
    // Take first sentence.
    const firstSentence = cleaned.split(/\.\s|\s—\s/)[0].trim();
    return firstSentence.length > MAX_SUMMARY_CHARS
      ? `${firstSentence.slice(0, MAX_SUMMARY_CHARS - 1)}…`
      : firstSentence;
  }
  return "(no description)";
}

/** Extract `// tier: T#` marker.  Returns null if absent. */
export function extractTier(src) {
  const m = src.match(/\/\/\s*tier:\s*(T\d)/i);
  return m ? m[1].toUpperCase() : null;
}

/** Infer trigger event from filename prefix.  Pure. */
export function inferTrigger(filename) {
  const stem = filename.replace(/\.mjs$/, "");
  if (stem.startsWith("session-start-")) return "SessionStart";
  if (stem.startsWith("user-prompt-") || stem.includes("user-prompt")) return "UserPromptSubmit";
  if (stem.startsWith("pre-tool-") || stem.startsWith("pretool")) return "PreToolUse";
  if (stem.startsWith("post-tool-") || stem.startsWith("posttool")) return "PostToolUse";
  if (stem.startsWith("stop-")) return "Stop";
  if (stem.startsWith("precompact-")) return "PreCompact";
  if (stem.startsWith("subagent-")) return "SubagentStart";
  return "?";
}

/** Pure render — sorted by trigger then name. */
export function render(entries) {
  const sorted = [...entries].sort((a, b) => {
    if (a.trigger !== b.trigger) return a.trigger.localeCompare(b.trigger);
    return a.name.localeCompare(b.name);
  });
  const lines = [
    "# .claude/hooks/ — HOOK_DIGEST.md",
    "",
    "_Auto-generated by `scripts/generate-hook-digest.mjs` (U-MWO12, slot:bravo 2026-05-26)._",
    "",
    `**${sorted.length} hooks** indexed.  Tier: T0=blocker · T1=soft-gate · T2=injector · T3=observer · T4=async.`,
    "",
    "| Trigger | Hook | Tier | Summary |",
    "|---------|------|------|---------|",
  ];
  for (const e of sorted) {
    const safeSummary = e.summary.replace(/\|/g, "\\|");
    lines.push(`| ${e.trigger} | \`${e.name}\` | ${e.tier || "?"} | ${safeSummary} |`);
  }
  lines.push("");
  return lines.join("\n");
}

/** I/O wrapper. */
export function run({ hooksDir = DEFAULT_HOOKS_DIR, outPath = DEFAULT_OUT, fsImpl = fs } = {}) {
  if (!fsImpl.existsSync(hooksDir)) {
    return { ok: false, reason: "hooks-dir-missing", path: hooksDir };
  }
  let names;
  try { names = fsImpl.readdirSync(hooksDir); }
  catch (e) { return { ok: false, reason: "readdir-failed", error: e instanceof Error ? e.message : String(e) }; }

  const entries = [];
  for (const name of names) {
    if (!name.endsWith(".mjs")) continue;
    if (name.endsWith(".test.mjs")) continue;
    const file = path.join(hooksDir, name);
    let head = "";
    try {
      const fd = fsImpl.openSync(file, "r");
      const buf = Buffer.alloc(HEAD_BYTES);
      const bytesRead = fsImpl.readSync(fd, buf, 0, HEAD_BYTES, 0);
      fsImpl.closeSync(fd);
      head = buf.subarray(0, bytesRead).toString("utf8");
    } catch { continue; }
    entries.push({
      name: name.replace(/\.mjs$/, ""),
      trigger: inferTrigger(name),
      tier: extractTier(head),
      summary: extractSummary(head),
    });
  }

  const content = render(entries);
  fsImpl.writeFileSync(outPath, content, "utf8");
  return { ok: true, count: entries.length, outPath, bytes: content.length };
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith("generate-hook-digest.mjs")) {
  try {
    const result = run();
    process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
    process.exit(result.ok ? 0 : 1);
  } catch (e) {
    process.stderr.write(`generate-hook-digest: ${e instanceof Error ? e.message : String(e)}\n`);
    process.exit(2);
  }
}
