#!/usr/bin/env node
/**
 * generate-tribal-wiki.mjs
 *
 * Per-CATEGORY index entries for the tribal-knowledge corpus. `knowledge/tribal/`
 * holds ~4,245 atomic tip files (each with `id/title/source/confidence/category/tags`
 * frontmatter) — replicating each as a wiki entry would 4x the architecture tree
 * for marginal value (the tip IS the markdown, and `build-wiki-leaf-index.mjs` now
 * indexes `knowledge/tribal/` directly so every tip is recall-searchable). Instead
 * this generator emits one index per *category* (file-name prefix), e.g.:
 *
 *   tribal/cam-tips-mastercam.md   — 261 Mastercam CAM tips, sampled + linked, dominant `category` values
 *   tribal/cam-tips-edgecam.md     — 221 EdgeCAM tips …  (one per ~18 CAM systems)
 *   tribal/controller-knowledge.md — 121 controller-knowledge tips
 *   tribal/auto-ingested.md        — 326 auto-ingested tips
 *   tribal/wedm-knowledge.md       — WEDM-KB + JM-Die WEDM tips (incl. MIT-derived)
 *   …
 * Plus tribal/tribal-corpus-index.md — the master catalog of all categories.
 *
 * Output: knowledge/wiki/architecture/tribal/<slug>.md  +  .../tribal-corpus-index.md
 * (Distinct from the legacy single `tribal-knowledge-index.md` that generate-tribal-index.mjs emits — that stays.)
 *
 * Idempotent. preserveHuman() keeps anything outside the AUTO markers. Flags: --dry-run
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { resolve, dirname, join, basename } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PRISM_ROOT = resolve(__dirname, "..");
const TRIBAL_DIR = resolve(PRISM_ROOT, "knowledge/tribal");
const WIKI_ARCH_DIR = resolve(PRISM_ROOT, "knowledge/wiki/architecture");
const OUT_DIR = join(WIKI_ARCH_DIR, "tribal");
const INDEX_OUT = join(WIKI_ARCH_DIR, "tribal-corpus-index.md");
const WIKI_INDEX = resolve(PRISM_ROOT, "knowledge/wiki/index.md");

const args = new Set(process.argv.slice(2));
const FLAGS = { dryRun: args.has("--dry-run") };

const AUTO_START = "<!-- AUTO-START — regenerated by generate-tribal-wiki.mjs -->";
const AUTO_END = "<!-- AUTO-END -->";

const SAMPLE_PER_CATEGORY = 25;     // tip deep-links per category index page
const SCAN_FOR_META = 12;           // how many leading lines to read per tip for frontmatter

function ensureDir(d) { if (!existsSync(d)) mkdirSync(d, { recursive: true }); }
function slug(s) { return String(s || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 90) || "x"; }

// Strip the trailing numeric/id segment to get the category prefix.
//   auto-ingested-tips-auto-5042.md          -> auto-ingested-tips-auto
//   mastercam-cam-tips-mc-117.md             -> mastercam-cam-tips-mc
//   controller-knowledge-tips-ctrl-067.md    -> controller-knowledge-tips-ctrl
function categoryOf(fname) {
  const base = basename(fname, ".md");
  return base.replace(/-[A-Za-z0-9]*\d[A-Za-z0-9]*$/, "").replace(/-+$/, "") || base;
}

// Human label + cross-refs from a category prefix.
function categoryMeta(cat) {
  const m = cat.match(/^([a-z0-9]+)-cam-tips/);
  if (m) {
    const sysMap = { mastercam: "Mastercam", edgecam: "EdgeCAM", surfcam: "SurfCAM", bobcad: "BobCAD-CAM", catia: "CATIA Machining", esprit: "ESPRIT", worknc: "WorkNC", topsolid: "TopSolid", camworks: "CAMWorks", tebis: "Tebis", sprutcam: "SprutCAM", powermill: "PowerMILL", gibbscam: "GibbsCAM", cimatron: "Cimatron", solidcam: "SolidCAM", fusion360: "Fusion 360", nx: "Siemens NX", hypermill: "hyperMILL" };
    const sys = sysMap[m[1]] || m[1];
    return { label: `${sys} CAM tips`, kind: "cam-tips", system: sys, refs: [`dispatcher-cam`, slug(`${m[1]}functionindexengine`)] };
  }
  if (/^controller-knowledge/.test(cat)) return { label: "Controller knowledge tips", kind: "controller", refs: ["dispatcher-cam", "registry-controllerregistry"] };
  if (/^auto-ingested/.test(cat)) return { label: "Auto-ingested tips", kind: "auto", refs: ["tribal-knowledge-index"] };
  if (/^wedm-knowledge/.test(cat)) return { label: "WEDM knowledge tips" + (/jm-die/.test(cat) ? " (JM Die)" : " (KB)"), kind: "wedm", refs: ["dispatcher-cam", "layer-l8"] };
  if (/extracted/.test(cat)) return { label: cat.replace(/-/g, " ") + " (extracted)", kind: "extracted", refs: ["monolith-modules-index"] };
  return { label: cat.replace(/-/g, " "), kind: "general", refs: ["tribal-knowledge-index"] };
}

function parseTipFrontmatter(file) {
  let text = "";
  try { text = readFileSync(file, "utf8"); } catch { return {}; }
  const head = text.split(/\r?\n/).slice(0, SCAN_FOR_META).join("\n");
  const get = (k) => { const r = head.match(new RegExp(`^${k}:\\s*["']?([^"'\\n]+)["']?`, "mi")); return r ? r[1].trim() : null; };
  return { id: get("id"), title: get("title"), source: get("source") || get("_source"), confidence: get("confidence"), category: get("category") };
}

function renderCategory(cat, files, gen) {
  const meta = categoryMeta(cat);
  // sample N tips spread across the list (first, last, and evenly between)
  const sorted = [...files].sort();
  const step = Math.max(1, Math.floor(sorted.length / SAMPLE_PER_CATEGORY));
  const sampled = [];
  for (let i = 0; i < sorted.length && sampled.length < SAMPLE_PER_CATEGORY; i += step) sampled.push(sorted[i]);
  const tipRows = sampled.map((f) => {
    const fm = parseTipFrontmatter(join(TRIBAL_DIR, f));
    const rel = `knowledge/tribal/${f}`;
    return `- [${fm.title || basename(f, ".md")}](${rel})${fm.category ? ` _(${fm.category}${fm.confidence ? `, conf ${fm.confidence}` : ""})_` : ""}`;
  }).join("\n");
  // dominant `category` field values across the sample
  const catCounts = {};
  for (const f of sampled) { const c = parseTipFrontmatter(join(TRIBAL_DIR, f)).category; if (c) catCounts[c] = (catCounts[c] || 0) + 1; }
  const topCats = Object.entries(catCounts).sort((a, b) => b[1] - a[1]).slice(0, 6).map(([c]) => `\`${c}\``).join(", ") || "—";
  return `---
title: Tribal tips — ${meta.label}
type: architecture
kind: tribal-category
tribal_category: ${cat}
tip_count: ${files.length}${meta.system ? `\ncam_system: ${meta.system}` : ""}
generated_by: scripts/generate-tribal-wiki.mjs
last_verified: ${gen}
tags: [architecture, system-viz, tribal, tribal-knowledge, ${meta.kind}, ${slug(meta.label)}]
related:
${meta.refs.map((r) => `  - knowledge/wiki/architecture/${r}.md`).join("\n")}
  - knowledge/wiki/architecture/tribal-corpus-index.md
---

# Tribal tips — ${meta.label}

> ${files.length} tribal-knowledge tips in this category${meta.system ? ` (CAM system: ${meta.system})` : ""}. Atomic markdown files under \`knowledge/tribal/${cat}-*.md\` — each indexed in \`_leaf-index.jsonl\` so the recall hooks surface them on keyword match.

${AUTO_START}

| Field | Value |
|-------|-------|
| Category prefix | \`${cat}\` |
| Tip count | ${files.length} |
| Storage | \`knowledge/tribal/${cat}-*.md\` |${meta.system ? `\n| CAM system | ${meta.system} |` : ""}
| Dominant \`category\` tags (sampled) | ${topCats} |
| Recall | indexed in \`knowledge/wiki/architecture/_leaf-index.jsonl\` (type \`tribal-tip\`) → \`wiki-precheck-inject.mjs\` |
| Dispatcher search | \`prism_knowledge:tribal_search\` / \`prism_shop_practice:tribal_search\` (full corpus) |

## Sample tips (${sampled.length} of ${files.length})

${tipRows || "_(no tips parsed)_"}

## How it's consumed

- Full-corpus search: \`prismSelfAwarenessEngine.searchTribalKnowledge(q)\` / \`prism_knowledge:tribal_search\` / \`prism_shop_practice:tribal_search\`.
- Recall: every tip file is in \`_leaf-index.jsonl\` (built by \`build-wiki-leaf-index.mjs\`), so \`wiki-precheck-inject.mjs\` (BM25 + cosine) surfaces matching tips on prompt; \`wiki-recall-on-read.mjs\` surfaces the tip when you open one.
- Capture/extend: \`/shop-knowledge\`, \`/distill-tribal\`, \`TribalKnowledgeEngine.addTip()\`.

${AUTO_END}

## See also

- Tribal corpus catalog: [[tribal-corpus-index]]
- Legacy single index: [[tribal-knowledge-index]]
${meta.refs.map((r) => `- [[${r}]]`).join("\n")}
`;
}

function renderIndex(byCat, totalFiles, gen) {
  const cats = Object.entries(byCat).sort((a, b) => b[1].length - a[1].length);
  return `---
title: Tribal corpus — catalog
type: architecture
kind: tribal-index
total_tips: ${totalFiles}
total_categories: ${cats.length}
generated_by: scripts/generate-tribal-wiki.mjs
last_verified: ${gen}
tags: [architecture, system-viz, tribal, tribal-knowledge, catalog, index]
related:
  - knowledge/wiki/architecture/tribal-knowledge-index.md
  - knowledge/tribal
---

# Tribal corpus — catalog

> ${totalFiles} tribal-knowledge tips across ${cats.length} categories (mostly per-CAM-system tip libraries + controller knowledge + auto-ingested + WEDM). Each tip is an atomic markdown file under \`knowledge/tribal/\`, indexed in \`_leaf-index.jsonl\` for recall.

${AUTO_START}

**Total:** ${totalFiles} tips · ${cats.length} categories. Per-category index entries under \`knowledge/wiki/architecture/tribal/\`.

| Category | Tips | Index entry |
|----------|------|-------------|
${cats.map(([c, files]) => { const m = categoryMeta(c); const name = `tribal-${slug(m.system ? `${m.system}-cam-tips` : m.label)}`; return `| \`${c}\` | ${files.length} | [[${name}]] |`; }).join("\n")}

## Recall path

All ${totalFiles} tips are in \`knowledge/wiki/architecture/_leaf-index.jsonl\` (type \`tribal-tip\`, built by \`build-wiki-leaf-index.mjs\`) — so \`wiki-precheck-inject.mjs\` (BM25 + cosine fallback) surfaces matching tips on any prompt, and \`wiki-recall-on-read.mjs\` surfaces a tip when you open it. Full-corpus programmatic search: \`prism_knowledge:tribal_search\` / \`prismSelfAwarenessEngine.searchTribalKnowledge(q)\`.

## Doctrine

- Tribal tips are **noisy** by construction (auto-ingested, vendor-doc-derived, shop-floor) — carry the \`confidence\` field through; don't treat a 60-confidence tip as gospel.
- The 26 MIT-derived WEDM tips + 14 MIT-cited WEDM formulas trace back to the 5 MIT OCW courses ([[courses-index]]).
- Capture new tips via \`/shop-knowledge\` / \`TribalKnowledgeEngine.addTip()\` — they land in \`knowledge/tribal/\` and get indexed on the next \`build-wiki-leaf-index\` run.

${AUTO_END}

## See also

- Legacy single index: [[tribal-knowledge-index]]
- Courses (MIT-derived tip lineage): [[courses-index]]
- Tribal-knowledge guide skill: \`/tribal-knowledge-guide\`, \`/shop-knowledge\`
`;
}

function preserveHuman(existing, full) {
  if (!existing) return full;
  const sStart = existing.indexOf(AUTO_START);
  const sEnd = existing.indexOf(AUTO_END);
  const nStart = full.indexOf(AUTO_START);
  const nEnd = full.indexOf(AUTO_END);
  if (sStart === -1 || sEnd === -1) return full;
  return existing.slice(0, sStart) + full.slice(nStart, nEnd + AUTO_END.length) + existing.slice(sEnd + AUTO_END.length);
}

function updateWikiIndex(totalFiles, catCount) {
  if (!existsSync(WIKI_INDEX)) return null;
  const text = readFileSync(WIKI_INDEX, "utf8");
  const block = ["<!-- ARCH-TRIBAL-CORPUS-START -->",
    `_Total: ${totalFiles} tribal tips across ${catCount} categories — per-category index entries under \`architecture/tribal/\`; master catalog [[tribal-corpus-index]]. Every tip is in \`_leaf-index.jsonl\` for recall._`,
    "<!-- ARCH-TRIBAL-CORPUS-END -->"].join("\n");
  if (text.includes("<!-- ARCH-TRIBAL-CORPUS-START -->")) return text.replace(/<!-- ARCH-TRIBAL-CORPUS-START -->[\s\S]*?<!-- ARCH-TRIBAL-CORPUS-END -->/m, block);
  if (text.includes("<!-- ARCH-COURSES-END -->")) return text.replace(/<!-- ARCH-COURSES-END -->/, "<!-- ARCH-COURSES-END -->\n\n### Tribal corpus (per-category)\n\n" + block);
  return text.trimEnd() + "\n\n### Tribal corpus\n\n" + block + "\n";
}

function main() {
  if (!existsSync(TRIBAL_DIR)) { console.log("tribal wiki: knowledge/tribal/ missing — nothing to do"); return; }
  const gen = new Date().toISOString().split("T")[0];
  const t0 = Date.now();
  let files = [];
  try { files = readdirSync(TRIBAL_DIR).filter((f) => f.endsWith(".md")); } catch {}
  const byCat = {};
  for (const f of files) (byCat[categoryOf(f)] ||= []).push(f);

  if (!FLAGS.dryRun) ensureDir(OUT_DIR);
  let written = 0;
  const usedNames = new Set();
  for (const [cat, catFiles] of Object.entries(byCat)) {
    const m = categoryMeta(cat);
    let name = `tribal-${slug(m.system ? `${m.system}-cam-tips` : m.label)}`;
    let n = 2; while (usedNames.has(name)) name = `tribal-${slug(m.system ? `${m.system}-cam-tips` : m.label)}-${n++}`;
    usedNames.add(name);
    const outPath = join(OUT_DIR, `${name}.md`);
    const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
    if (!FLAGS.dryRun) writeFileSync(outPath, preserveHuman(existing, renderCategory(cat, catFiles, gen)), "utf8");
    written++;
  }
  if (!FLAGS.dryRun) {
    const idxExisting = existsSync(INDEX_OUT) ? readFileSync(INDEX_OUT, "utf8") : null;
    writeFileSync(INDEX_OUT, preserveHuman(idxExisting, renderIndex(byCat, files.length, gen)), "utf8");
    const wi = updateWikiIndex(files.length, Object.keys(byCat).length);
    if (wi) writeFileSync(WIKI_INDEX, wi, "utf8");
  }
  console.log(`tribal wiki: ${written} per-category index entries + catalog (${files.length} tips, ${Object.keys(byCat).length} categories), ${Date.now() - t0}ms`);
}

main();
