// Upsert the block into a PATHS.md body. Idempotent: replaces an existing block
// (between markers) or appends with a leading blank line. Returns the new body.
export function upsertBlock(body, block) {
  const src = typeof body === "string" ? body : "";
  const re = new RegExp(escapeRe(BEGIN) + "[\\s\\S]*?" + escapeRe(END));
  if (re.test(src)) return src.replace(re, block);
  const trimmed = src.replace(/\s+$/, "");
  return trimmed + "\n\n" + block + "\n";
}

function escapeRe(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"); }

// Enumerate galaxy dirs that own a PATHS.md.
export function listGalaxies() {
  let entries;
  try { entries = fs.readdirSync(ENG, { withFileTypes: true }); } catch { return []; }
  return entries
    .filter((d) => d.isDirectory() && d.name !== ".claude")
    .map((d) => d.name)
    .filter((g) => fs.existsSync(path.join(ENG, g, "PATHS.md")))
    .sort();
}

export function enrichAll({ dryRun = false } = {}) {
  const galaxies = listGalaxies();
  const results = [];
  for (const g of galaxies) {
    const pathsFile = path.join(ENG, g, "PATHS.md");
    let body;
    try { body = fs.readFileSync(pathsFile, "utf8"); } catch { results.push({ galaxy: g, ok: false, reason: "unreadable" }); continue; }
    const block = buildAtlasBlock(g);
    const next = upsertBlock(body, block);
    const changed = next !== body;
    if (changed && !dryRun) {
      const tmp = pathsFile + `.tmp-${process.pid}`;
      fs.writeFileSync(tmp, next);
      fs.renameSync(tmp, pathsFile);
    }
    results.push({ galaxy: g, ok: true, changed, hadBlock: body.includes(BEGIN) });
  }
  return { total: galaxies.length, changed: results.filter((r) => r.changed).length, results };
}

function main() {
  const dryRun = process.argv.includes("--dry");
  const r = enrichAll({ dryRun });
  process.stdout.write(`knowledge-atlas: ${r.changed}/${r.total} PATHS.md ${dryRun ? "would change" : "enriched"}\n`);
  const fresh = r.results.filter((x) => x.changed && !x.hadBlock).length;
  const updated = r.results.filter((x) => x.changed && x.hadBlock).length;
  process.stdout.write(`  new block: ${fresh} · updated existing: ${updated} · unchanged: ${r.total - r.changed}\n`);
  process.exit(0);
}

