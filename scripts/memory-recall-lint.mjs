#!/usr/bin/env node
// memory-recall-lint.mjs — MEMORY-GEN-COVERAGE (2026-06-01 slot:golf)
//
// The GENERATION-side companion to the invocation units U-MRS-EXCLUDE (supersession
// exclusion) + U-MRDB-WIRE (per-galaxy domain boost): a per-galaxy recall-READINESS
// scorecard. It answers "does each galaxy keep its primary domain context?" by
// scoring every galaxy's brain record (the domain hub the domain-boost elevates) and
// the corpus's recall hygiene, then GENERATES a dashboard artifact that directs where
// memory generation is still needed.
//
// Reads:  the BM25 memory-index sidecar (state/shared/memory-index-sidecar.json) — it
//         already carries the per-galaxy brain records (namespace 'galaxies') and is
//         already supersession-filtered at build (U-MRS-EXCLUDE).
// Writes: state/shared/dashboards/memory-recall-readiness.{md,json} (golf-allowlisted).
//
// Pure `analyzeRecallReadiness` is hermetically testable; I/O is in main().
// Advisory: exits 0 always; never mutates a memory file.

import { readFileSync, writeFileSync, renameSync, mkdirSync, existsSync } from "node:fs";
import { dirname } from "node:path";

import { SLOT_GALAXY_MAP } from "./lib/slot-galaxy-map.mjs";
import { isSupersededMemory } from "./lib/memory-index-search-lib.mjs";

const DEFAULT_SIDECAR = "H:/prism/state/shared/memory-index-sidecar.json";
const DEFAULT_OUT_MD = "H:/prism/state/shared/dashboards/memory-recall-readiness.md";
const DEFAULT_OUT_JSON = "H:/prism/state/shared/dashboards/memory-recall-readiness.json";

// A galaxy brain is "thin" when its indexed signal (description + domain opening) is
// too small to win a domain query — i.e. the domain-boost has little to elevate, so
// that galaxy is NOT keeping its primary domain context. 80 chars ≈ a bare H1 + a
// few words; rich brains run to the 700-char GALAXY_OPENING_MAX.
export const THIN_BRAIN_CHARS = 80;
// A memory is recall-blind when it has neither a description NOR a usable opening —
// BM25/dense have almost nothing to match, so it is effectively unreachable.
export const RECALL_BLIND_OPENING = 20;

/**
 * PURE. records = sidecar records [{name, namespace, description, opening}].
 * galaxies = array of galaxy slugs to score. Returns a structured report.
 */
export function analyzeRecallReadiness(records, galaxies) {
  const recs = Array.isArray(records) ? records : [];
  const byNamespace = {};
  let total = 0, missingDescription = 0, recallBlind = 0, supersededLeaked = 0;

  for (const r of recs) {
    if (!r || typeof r !== "object") continue;
    total++;
    const ns = r.namespace || "uncategorized";
    const slot = (byNamespace[ns] ||= { total: 0, missingDescription: 0, recallBlind: 0 });
    slot.total++;
    const desc = String(r.description || "").trim();
    const opening = String(r.opening || "").trim();
    if (!desc) {
      missingDescription++; slot.missingDescription++;
      if (opening.length < RECALL_BLIND_OPENING) { recallBlind++; slot.recallBlind++; }
    }
    // U-MRS-EXCLUDE filters superseded at sidecar BUILD; a description-form marker
    // leaking through means a stale rebuild — surface it (best-effort, sidecar has
    // no full body, only the description carries the [SUPERSEDED token).
    if (isSupersededMemory(desc)) supersededLeaked++;
  }

  const brainByName = new Map(
    recs.filter((r) => r && r.namespace === "galaxies").map((r) => [r.name, r]),
  );
  const uniqGalaxies = [...new Set(galaxies || [])];
  const galaxyScores = uniqGalaxies.map((g) => {
    const b = brainByName.get(g);
    const descLen = b ? String(b.description || "").length : 0;
    const openLen = b ? String(b.opening || "").length : 0;
    const signal = descLen + openLen;
    return {
      galaxy: g,
      present: !!b,
      descLen,
      openLen,
      signal,
      thin: !b || signal < THIN_BRAIN_CHARS,
    };
  });

  const missingBrains = galaxyScores.filter((g) => !g.present).map((g) => g.galaxy);
  const thinBrains = galaxyScores.filter((g) => g.present && g.thin).map((g) => g.galaxy);

  return {
    total,
    missingDescription,
    recallBlind,
    supersededLeaked,
    byNamespace,
    galaxyCount: uniqGalaxies.length,
    galaxyScores,
    missingBrains,
    thinBrains,
  };
}

export function renderMarkdown(report, { builtAt } = {}) {
  const L = [];
  L.push("# Memory recall-readiness scorecard");
  L.push("");
  L.push(`_Generated by \`scripts/memory-recall-lint.mjs\` (MEMORY-GEN-COVERAGE). ${builtAt || ""}_`);
  L.push("");
  L.push(`- **Corpus:** ${report.total} recall records`);
  L.push(`- **Missing description:** ${report.missingDescription}  ·  **recall-blind (no desc + tiny body):** ${report.recallBlind}`);
  L.push(`- **Superseded leaked into sidecar:** ${report.supersededLeaked} (should be 0 — U-MRS-EXCLUDE filters at build; >0 ⇒ rebuild)`);
  L.push("");
  L.push("## Per-galaxy domain-context coverage");
  L.push("");
  L.push("Galaxies whose brain is the recall hub the per-galaxy domain-boost (U-MRDB-WIRE) elevates. A **missing** or **thin** brain = that galaxy does NOT keep its primary domain context → memory generation needed there.");
  L.push("");
  if (report.missingBrains.length) {
    L.push(`- ⛔ **Missing brains (${report.missingBrains.length}):** ${report.missingBrains.join(", ")}`);
  } else {
    L.push("- ✅ Every mapped galaxy has a brain record.");
  }
  if (report.thinBrains.length) {
    L.push(`- ⚠️ **Thin brains (${report.thinBrains.length}, signal < ${THIN_BRAIN_CHARS} chars):** ${report.thinBrains.join(", ")}`);
  } else {
    L.push("- ✅ No thin brains.");
  }
  L.push("");
  L.push("| galaxy | brain | signal chars |");
  L.push("|--------|-------|--------------|");
  for (const g of [...report.galaxyScores].sort((a, b) => a.signal - b.signal)) {
    const status = !g.present ? "⛔ missing" : g.thin ? "⚠️ thin" : "✅";
    L.push(`| ${g.galaxy} | ${status} | ${g.signal} |`);
  }
  L.push("");
  L.push("## Recall hygiene by namespace");
  L.push("");
  L.push("| namespace | total | missing-desc | recall-blind |");
  L.push("|-----------|-------|--------------|--------------|");
  for (const [ns, v] of Object.entries(report.byNamespace).sort((a, b) => b[1].total - a[1].total)) {
    L.push(`| ${ns} | ${v.total} | ${v.missingDescription} | ${v.recallBlind} |`);
  }
  L.push("");
  return L.join("\n");
}

function writeAtomic(path, content) {
  const dir = dirname(path);
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
  const tmp = `${path}.tmp.${process.pid}`;
  writeFileSync(tmp, content, "utf8");
  renameSync(tmp, path);
}

function main() {
  const args = process.argv.slice(2);
  const wantsJson = args.includes("--json");
  const sidecarPath = DEFAULT_SIDECAR;

  let sidecar;
  try { sidecar = JSON.parse(readFileSync(sidecarPath, "utf8")); }
  catch {
    process.stderr.write(`[memory-recall-lint] cannot read sidecar ${sidecarPath} — run build-memory-index-sidecar.mjs first.\n`);
    process.exit(0);
  }

  const galaxies = Object.values(SLOT_GALAXY_MAP);
  const report = analyzeRecallReadiness(sidecar.records || [], galaxies);
  const builtAt = new Date().toISOString();

  writeAtomic(DEFAULT_OUT_JSON, JSON.stringify({ builtAt, ...report }, null, 2));
  writeAtomic(DEFAULT_OUT_MD, renderMarkdown(report, { builtAt }));

  if (wantsJson) {
    process.stdout.write(JSON.stringify({
      ok: true, builtAt, total: report.total,
      missingBrains: report.missingBrains, thinBrains: report.thinBrains,
      recallBlind: report.recallBlind, supersededLeaked: report.supersededLeaked,
    }, null, 2) + "\n");
  } else {
    process.stdout.write(
      `[memory-recall-lint] ${report.total} records · galaxies: ${report.galaxyCount} `
      + `(${report.missingBrains.length} missing, ${report.thinBrains.length} thin brains) `
      + `· recall-blind ${report.recallBlind} · superseded-leak ${report.supersededLeaked}\n`
      + `  → ${DEFAULT_OUT_MD}\n`,
    );
  }
}

const invokedDirect = (() => {
  try {
    const here = new URL(import.meta.url).pathname.replace(/^\/+([A-Za-z]:)/, "$1");
    const argv = process.argv[1] || "";
    const norm = (s) => s.replace(/\\/g, "/").toLowerCase();
    return norm(here) === norm(argv);
  } catch { return false; }
})();

if (invokedDirect) main();
