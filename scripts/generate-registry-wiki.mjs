#!/usr/bin/env node
/**
 * generate-registry-wiki.mjs
 *
 * Generates one Obsidian wiki entry per L7 registry/catalog node at
 *   H:/prism/knowledge/wiki/architecture/registries/<id>.md
 *
 * L7 contains (as of 2026-05-11):
 *   - 23 base registries (kind=registry) — agents, alarms, algorithms, etc.
 *   - 4 catalogs (kind=catalog) — CAM function catalog, etc.
 *   - 3 catalog roots (kind=catalog_root) — top-level catalog containers
 *   - 34 vendor catalogs (kind=catalog_vendor) — per-CAM-vendor function lists
 *
 * Each entry surfaces:
 *   - node id, kind, status, parent layer L7
 *   - sample drilled entries (L8 registry_entry / catalog_function children)
 *   - cross-refs to [[layer-l7]] + related domain pages
 *
 * Idempotent — AUTO-START/END markers preserve human notes.
 * Updates wiki/index.md ### Registries & catalogs subsection.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PRISM_ROOT = resolve(__dirname, "..");
const GRAPH_PATH = resolve(PRISM_ROOT, "state/shared/system-viz/system-graph.json");
const WIKI_ARCH_DIR = resolve(PRISM_ROOT, "knowledge/wiki/architecture");
const REGISTRIES_DIR = join(WIKI_ARCH_DIR, "registries");
const WIKI_INDEX = resolve(PRISM_ROOT, "knowledge/wiki/index.md");

const args = new Set(process.argv.slice(2));
const FLAGS = { dryRun: args.has("--dry-run") };

const AUTO_START = "<!-- AUTO-START — regenerated by generate-registry-wiki.mjs -->";
const AUTO_END = "<!-- AUTO-END -->";

const SAMPLE_CHILDREN = 15;

const KIND_PURPOSE = {
  registry: "Base registry — read-mostly knowledge table consumed by engines for lookup or validation.",
  catalog: "Catalog — structured reference data (e.g. CAM function catalog, materials catalog).",
  catalog_root: "Top-level catalog container — groups vendor-specific or category-specific sub-catalogs.",
  catalog_vendor: "Per-vendor catalog — function/operation list for a specific CAM system or tooling vendor.",
};

function readJson(p) {
  return JSON.parse(readFileSync(p, "utf8"));
}

function ensureDir(d) {
  if (!existsSync(d)) mkdirSync(d, { recursive: true });
}

function slug(s) {
  return String(s || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function buildChildIndex(G) {
  // For each L7 node, find L8 children connected by edge: from L7 → L8
  const children = new Map();
  const nodeById = new Map();
  for (const n of G.nodes) nodeById.set(n.id, n);
  for (const e of G.edges) {
    const from = nodeById.get(e.from);
    const to = nodeById.get(e.to);
    if (!from || !to) continue;
    if (from.layer === "L7" && to.layer === "L8") {
      const arr = children.get(from.id) || [];
      arr.push(to);
      children.set(from.id, arr);
    }
  }
  // Fallback: L8 nodes whose id encodes a parent registry (e.g. reg.materialregistry.entry.X)
  for (const n of G.nodes) {
    if (n.layer !== "L8") continue;
    const m = /^(reg\.[a-z0-9_]+)\./.exec(n.id);
    if (!m) continue;
    const parentId = m[1];
    if (!nodeById.has(parentId)) continue;
    const arr = children.get(parentId) || [];
    if (!arr.includes(n)) arr.push(n);
    children.set(parentId, arr);
  }
  return children;
}

function render(node, kids, generatedAt, headline) {
  const kind = node.kind || node.subgroup || "registry";
  const purpose = KIND_PURPOSE[kind] || `Node of kind \`${kind}\` in the L7 layer.`;
  const kidsSample = kids.slice(0, SAMPLE_CHILDREN);
  const childRows = kidsSample.length
    ? kidsSample.map((c) => `- \`${c.id}\` — ${(c.label || "(unnamed)").replace(/\n/g, " ")}`).join("\n")
    : "_(no drilled L8 children indexed — registry may be opaque)_";
  return `---
title: Registry — ${node.label || node.id}
type: architecture
registry_id: ${node.id}
kind: ${kind}
parent_layer: L7
status: ${node.status || "?"}
generated_by: scripts/generate-registry-wiki.mjs
last_verified: ${generatedAt}
tags: [architecture, system-viz, registry, ${kind}]
related:
  - knowledge/wiki/architecture/layer-l7.md
  - knowledge/wiki/architecture/layer-l8.md
  - state/shared/system-viz/system-graph.json
---

# Registry — \`${node.label || node.id}\`

> ${purpose}

**Kind:** ${kind}  ·  **Status:** ${node.status || "?"}  ·  **Drilled children:** ${kids.length}
**System headline:** ${headline.wikiEntries ?? "?"} wiki entries · ${headline.built ?? "?"} engines wired

${AUTO_START}

## Drilled entries (sample of ${SAMPLE_CHILDREN})

${childRows}

${kids.length > SAMPLE_CHILDREN ? `_…and ${kids.length - SAMPLE_CHILDREN} more drilled entries. See full list in source._` : ""}

## Doctrine

- Registries are read-mostly — engines query them by key
- Updates should go through the registry-rebuild scripts, not hand-edits
- New entry: validate against the registry's Zod schema (\`mcp-server/src/schemas/\`)

${AUTO_END}

## See also

- Parent layer: [[layer-l7]]
- Drilled-children layer: [[layer-l8]]
- Live graph: \`state/shared/system-viz/system-graph.json\`
`;
}

function preserveHuman(existing, full) {
  if (!existing) return full;
  const sStart = existing.indexOf(AUTO_START);
  const sEnd = existing.indexOf(AUTO_END);
  const nStart = full.indexOf(AUTO_START);
  const nEnd = full.indexOf(AUTO_END);
  if (sStart === -1 || sEnd === -1) return full;
  const before = existing.slice(0, sStart);
  const after = existing.slice(sEnd + AUTO_END.length);
  const newAuto = full.slice(nStart, nEnd + AUTO_END.length);
  return before + newAuto + after;
}

function updateIndex(byKind) {
  if (!existsSync(WIKI_INDEX)) return null;
  const text = readFileSync(WIKI_INDEX, "utf8");
  const lines = Object.entries(byKind)
    .sort((a, b) => b[1].length - a[1].length)
    .flatMap(([kind, entries]) => [
      `**${kind}** (${entries.length}):`,
      ...entries.map((e) => `- [[registry-${slug(e.id)}]] — \`${e.label}\``),
      "",
    ]);
  const block = ["<!-- ARCH-REGISTRIES-START -->", ...lines, "<!-- ARCH-REGISTRIES-END -->"].join("\n");
  if (text.includes("<!-- ARCH-REGISTRIES-START -->")) {
    return text.replace(/<!-- ARCH-REGISTRIES-START -->[\s\S]*?<!-- ARCH-REGISTRIES-END -->/m, block);
  }
  if (text.includes("<!-- ARCH-ACTIONS-END -->")) {
    return text.replace(
      /<!-- ARCH-ACTIONS-END -->/,
      "<!-- ARCH-ACTIONS-END -->\n\n### Registries & catalogs\n\n" + block
    );
  }
  return text.trimEnd() + "\n\n### Registries & catalogs\n\n" + block + "\n";
}

function main() {
  if (!existsSync(GRAPH_PATH)) {
    console.error("graph missing");
    process.exit(2);
  }
  const G = readJson(GRAPH_PATH);
  const children = buildChildIndex(G);
  const headline = (G.meta && G.meta.headline) || {};
  const generatedAt = new Date().toISOString().split("T")[0];

  ensureDir(REGISTRIES_DIR);

  const byKind = {};
  let written = 0;
  const t0 = Date.now();

  for (const node of G.nodes) {
    if (node.layer !== "L7") continue;
    const kids = children.get(node.id) || [];
    const fileName = `registry-${slug(node.id)}.md`;
    const outPath = join(REGISTRIES_DIR, fileName);
    const full = render(node, kids, generatedAt, headline);
    const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
    const finalContent = preserveHuman(existing, full);
    if (!FLAGS.dryRun) writeFileSync(outPath, finalContent, "utf8");
    written++;
    const kind = node.kind || node.subgroup || "registry";
    (byKind[kind] = byKind[kind] || []).push({
      id: node.id,
      label: node.label || node.id,
    });
  }

  const indexUpdated = !FLAGS.dryRun ? updateIndex(byKind) : null;
  if (indexUpdated && !FLAGS.dryRun) writeFileSync(WIKI_INDEX, indexUpdated, "utf8");

  console.log(
    `generated ${written} registry wiki entries in ${Date.now() - t0}ms (kinds: ${Object.keys(byKind).join(", ")})`
  );
}

main();
