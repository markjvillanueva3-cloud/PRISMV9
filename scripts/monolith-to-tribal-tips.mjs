#!/usr/bin/env node
/**
 * monolith-to-tribal-tips — Lane A direct-wire converter
 * KNOWLEDGE-CONVERSION-MS0 / U-KC-B2
 *
 * Reads state/shared/specs/monolith-port-ledger.json, filters to the data-lane
 * subset (laneHint starts with "A/B2"), and emits a KnowledgeTip[] envelope
 * into DOC_KNOWLEDGE_DIR (cad-engine/knowledge_store/) that
 * TribalKnowledgeEngine.loadDocumentLearnedTips() auto-loads on init.
 *
 * Scope (load-bearing per state/shared/specs/KNOWLEDGE-CONVERSION-PLAN.md):
 *   - Lane A direct-wire ONLY. No /forge calls, no LLM distillation, no engine
 *     creation. Each tip is a search-aware NAVIGATION/PROVENANCE pointer —
 *     "this legacy monolith module X is [ported|unported|ambiguous] under
 *     PRISM path Y" — surfaced through prism_knowledge:tribal_search.
 *   - Source is the audit-ledger emitted by U-KC-A1; the 133 data-lane items
 *     (vs 815 code-lane items) are the Lane A subset. Code-lane items go to
 *     Lane B/C and stay out of this converter's scope.
 *
 * Engine override notes (TribalKnowledgeEngine.ts:685-718):
 *   - `id` is generated by array index: TK-DL-<docId>-NNN. Not stable across
 *     re-runs that add/remove records.
 *   - `source` is OVERRIDDEN to `document:<docId>` on auto-load. Per-tip
 *     provenance survives in tags ("monolith:<name>" tag) + body, not source.
 *   - `confidence: item.confidence || 70` falsy-promotes 0 → 70.
 *     computeConfidence FLOORS at 1 to defeat this on score=0 items.
 *   - JSON.parse is wrapped in try/catch and silently skipped on malformed
 *     input. Atomic write via .tmp + renameSync is load-bearing.
 *
 * CLI:
 *   --input <path>      (default: state/shared/specs/monolith-port-ledger.json)
 *   --output <path>     (default: cad-engine/knowledge_store/monolith-data-lane-tips.json)
 *   --limit N           positive integer, caps tip count
 *   --frozen-time ISO   determinism — clamps generatedAt + created_at
 *   --help
 *
 * Exit codes: 0=ok, 2=arg-validation failure, 3=I/O / parse failure.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, "..");

// ---- Canonical category set (mirrors TribalKnowledgeEngine.ts CORE_CATEGORIES + KnowledgeCategory union)
// Kept in source-of-truth sync with course-to-tribal-tips.mjs to avoid drift.
export const VALID_KNOWLEDGE_CATEGORIES = Object.freeze([
  "setup", "tooling", "speeds_feeds", "fixturing", "surface_finish", "thread", "safety",
  "maintenance", "material_handling", "quality", "troubleshooting", "programming",
  "electronics", "automation", "metrology", "design", "materials_science",
  "process_engineering", "lean_manufacturing", "additive", "inspection", "cam_strategy",
  "optimization", "post_processor", "roughing", "workflow", "multi_axis", "verification",
  "simulation", "mold_die", "probing", "general",
]);

// ---- Category mapping for the 5 monolith data-lane categories.
// Every VALUE is a member of VALID_KNOWLEDGE_CATEGORIES (drift test enforces this).
export const CATEGORY_TO_KNOWLEDGE = Object.freeze({
  materials: "materials_science",
  databases: "general",
  machines: "setup",
  tools: "tooling",
  knowledge_bases: "general",
});

// ---- Name-pattern overrides for the 80 "databases" + 14 "knowledge_bases" buckets.
// Pattern → KnowledgeCategory. Evaluated in declaration order; first match wins.
// Patterns are word-boundary anchored against the UPPERCASE monolith name.
// NOTE: `\b` does NOT break on `_` (underscore is a regex word char), so a
// naive /\bPOST\b/ never matches inside FUSION_POST_DATABASE. Monolith names
// are underscore-delimited UPPERCASE — use explicit (?:^|_) … (?:_|$) token
// boundaries. Prefix rules (FIXTURE → FIXTURING/FIXTURES) intentionally omit
// the trailing boundary.
const NAME_PATTERN_OVERRIDES = Object.freeze([
  { pattern: /(?:^|_)POST(?:_|$)/,                          category: "post_processor" },
  { pattern: /(?:^|_)FIXTURE/,                              category: "fixturing" },
  { pattern: /(?:^|_)(WORKHOLDING|VISE|CHUCK)(?:_|$)/,      category: "fixturing" },
  { pattern: /(?:^|_)(TOOL|HOLDER|ENDMILL|CUTTER|DRILL|INSERT|TAP|REAMER)(?:_|$)/, category: "tooling" },
  { pattern: /(?:^|_)MATERIAL/,                             category: "materials_science" },
  { pattern: /(?:^|_)MACHINE/,                              category: "setup" },
  { pattern: /(?:^|_)(MEASURE|METROLOGY|GAGE|CMM|PROBE)(?:_|$)/, category: "metrology" },
  { pattern: /(?:^|_)(PROGRAM|GCODE|NC)(?:_|$)/,            category: "programming" },
  { pattern: /(?:^|_)CAM(?:_|$)/,                           category: "cam_strategy" },
  { pattern: /(?:^|_)(QUALITY|QC|SPC)(?:_|$)/,              category: "quality" },
  { pattern: /(?:^|_)SAFETY/,                               category: "safety" },
]);

const MAX_TAG_LEN = 80;
const MAX_TITLE_LEN = 200;

// ---- Pure transforms ------------------------------------------------------

/** True iff this ledger item is a data-lane (Lane A) target. */
export function isDataLaneItem(item) {
  if (!item || typeof item !== "object") return false;
  const hint = typeof item.laneHint === "string" ? item.laneHint : "";
  return hint.startsWith("A/B2");
}

/** Map a raw monolith item to a KnowledgeCategory. */
export function categorizeMonolithItem(item) {
  if (!item || typeof item !== "object") return "general";
  const name = typeof item.name === "string" ? item.name : "";
  // Name-pattern overrides win over category default — they encode more signal
  // (PRISM_FUSION_POST_DATABASE under category=databases is really post_processor).
  for (const rule of NAME_PATTERN_OVERRIDES) {
    if (rule.pattern.test(name)) return rule.category;
  }
  const cat = typeof item.category === "string" ? item.category.toLowerCase() : "";
  const mapped = CATEGORY_TO_KNOWLEDGE[cat];
  return mapped || "general";
}

/**
 * Compute confidence from the audit-ledger score. score ∈ [0,1] → [1,100].
 * FLOOR at 1: engine's `item.confidence || 70` would falsy-promote 0 → 70,
 * silently masking unmatched modules. score>1 / NaN / non-finite → 1.
 */
export function computeConfidence(score) {
  if (typeof score !== "number" || !Number.isFinite(score)) return 1;
  const raw = Math.round(score * 100);
  if (!Number.isFinite(raw) || raw < 1) return 1;
  if (raw > 100) return 100;
  return raw;
}

/** Humanize PRISM_FUSION_POST_DATABASE → "Fusion Post Database". */
export function humanizeName(name) {
  if (typeof name !== "string") return "";
  let s = name.replace(/^PRISM_/, "");
  // Split on _, lowercase, title-case each non-empty word
  s = s.split("_")
    .filter(Boolean)
    .map((w) => w.charAt(0) + w.slice(1).toLowerCase())
    .join(" ");
  return s;
}

/**
 * Build the per-tip tag list. Deterministic order; deduplicated.
 *
 * The `monolith:<name>` PROVENANCE tag is exempt from the MAX_TAG_LEN clamp:
 * the engine OVERRIDES `source` to `document:<docId>` on auto-load
 * (TribalKnowledgeEngine.ts:707), so this tag is the ONLY surviving link back
 * to the originating monolith module. Silently dropping it for a long name
 * would make the tip unattributable — a Karpathy-R12 silent lie. The engine
 * stores tags as a plain string[] with no length limit, so an over-long
 * provenance tag is safe; only cosmetic tags (category/state/type/ported) are
 * length-clamped.
 */
export function buildTags(item) {
  const cosmetic = [];
  cosmetic.push("monolith");
  cosmetic.push("data-lane");
  if (item && typeof item.category === "string" && item.category) {
    cosmetic.push(`monolith-category:${item.category.toLowerCase()}`);
  }
  if (item && typeof item.state === "string" && item.state) {
    cosmetic.push(`state:${item.state.toLowerCase()}`);
  }
  if (item && typeof item.type === "string" && item.type) {
    cosmetic.push(`type:${item.type.toLowerCase()}`);
  }
  let portedTag = null;
  if (item && typeof item.match === "string" && item.match) {
    // Surface the ported PRISM home as a navigable tag (without path separators
    // that would tokenize oddly; keep the basename + parent dir as one token).
    const segments = item.match.split(/[\/\\]+/).filter(Boolean);
    const tail = segments.slice(-2).join("/");
    if (tail) portedTag = `ported:${tail}`;
  }
  // The provenance tag is NEVER length-dropped (see docstring).
  let provenanceTag = null;
  if (item && typeof item.name === "string" && item.name) {
    provenanceTag = `monolith:${item.name}`;
  }
  const seen = new Set();
  const out = [];
  const pushUnique = (t) => {
    if (typeof t !== "string" || !t) return;
    if (seen.has(t)) return;
    seen.add(t);
    out.push(t);
  };
  for (const t of cosmetic) {
    if (t.length > MAX_TAG_LEN) continue; // cosmetic tags: silently drop if oversized
    pushUnique(t);
  }
  if (portedTag && portedTag.length <= MAX_TAG_LEN) pushUnique(portedTag);
  if (provenanceTag) pushUnique(provenanceTag); // exempt from MAX_TAG_LEN
  return out;
}

/** Build the human-readable body. NEVER blank — fallback to name + category. */
export function buildBody(item) {
  if (!item || typeof item !== "object") return "Monolith module (unknown).";
  const name = typeof item.name === "string" ? item.name : "(unknown)";
  const category = typeof item.category === "string" ? item.category : "uncategorized";
  const type = typeof item.type === "string" ? item.type : "unknown";
  const state = typeof item.state === "string" ? item.state : "unknown";
  const lines = [
    `Legacy monolith data-lane module **${name}** (category: ${category}, type: ${type}).`,
    `Port state: ${state}.`,
  ];
  if (typeof item.match === "string" && item.match) {
    lines.push(`Current PRISM home: \`${item.match}\`.`);
  } else {
    lines.push(`No matching PRISM file resolved by the audit.`);
  }
  if (typeof item.note === "string" && item.note) {
    lines.push(`Audit note: ${item.note}`);
  }
  if (Array.isArray(item.alternatives) && item.alternatives.length > 0) {
    const alts = item.alternatives
      .filter((a) => a && typeof a.file === "string")
      .map((a) => `\`${a.file}\``);
    if (alts.length > 0) lines.push(`Alternatives: ${alts.join(", ")}.`);
  }
  return lines.join(" ");
}

/** Build the title; clamp to MAX_TITLE_LEN. */
export function buildTitle(item) {
  if (!item || typeof item.name !== "string") return "Monolith module";
  const human = humanizeName(item.name);
  const title = `Monolith: ${human || item.name}`;
  return title.length > MAX_TITLE_LEN ? title.slice(0, MAX_TITLE_LEN) : title;
}

/** Convert one data-lane ledger item to a KnowledgeTip. */
export function itemToTip(item, now) {
  if (!item || typeof item !== "object") return null;
  if (!isDataLaneItem(item)) return null;
  if (typeof item.name !== "string" || !item.name) return null;
  const created_at = new Date(now).toISOString().slice(0, 10);
  return {
    title: buildTitle(item),
    body: buildBody(item),
    category: categorizeMonolithItem(item),
    tags: buildTags(item),
    confidence: computeConfidence(item.score),
    source: `monolith:${item.name}`,
    created_at,
  };
}

/** Sort key for byte-stable output. Pure ASCII to avoid locale variance. */
function sortKey(item) {
  // (name) is the natural identity. The U+001F separator is unused here (no
  // multi-field secondary sort needed) but the source-of-truth pattern from
  // course-to-tribal-tips.mjs is preserved for any future composite key.
  return String((item && item.name) || "");
}

/** Convert a list of ledger items to tips. Sorted, deterministic, filtered. */
export function convertAll(items, now) {
  if (!Array.isArray(items)) return [];
  const sorted = items.slice().sort((a, b) => {
    const ka = sortKey(a);
    const kb = sortKey(b);
    return ka < kb ? -1 : ka > kb ? 1 : 0;
  });
  const out = [];
  for (const it of sorted) {
    const tip = itemToTip(it, now);
    if (tip) out.push(tip);
  }
  return out;
}

/** Wrap the tip array in the canonical envelope. */
export function buildEnvelope(tips, ctx) {
  const sourceRecords = (ctx && typeof ctx.sourceRecords === "number") ? ctx.sourceRecords : 0;
  const sourceFile = (ctx && typeof ctx.relativeSource === "string") ? ctx.relativeSource : "";
  const now = (ctx && ctx.now) || new Date();
  return {
    schemaVersion: "1.0.0",
    kind: "monolith-data-lane-tips",
    advisoryOnly: true,
    mustHumanVerify: true,
    caveat:
      "ADVISORY navigation/provenance index distilled from monolith-port-ledger.json data-lane subset (133 items). " +
      "These are NOT vetted machinist tribal knowledge — they are pointer cards mapping legacy monolith module identifiers " +
      "to their ported PRISM homes (when resolved by the audit). Use for code-archaeology / cross-reference; do NOT treat " +
      "as authoritative shop-floor guidance. Best entries become real PRISM assets only via the human-gated /forge + scrutiny pipeline.",
    generatedAt: new Date(now).toISOString(),
    sourceFile,
    sourceRecords,
    generator: "scripts/monolith-to-tribal-tips.mjs",
    milestone: "KNOWLEDGE-CONVERSION-MS0",
    unit: "U-KC-B2",
    tips,
  };
}

// ---- I/O ------------------------------------------------------------------

/**
 * Load the ledger and return the data-lane items.
 * Throws on parse failure; returns [] on missing file (caller decides).
 */
export function loadLedger(absPath) {
  const raw = fs.readFileSync(absPath, "utf8");
  const ledger = JSON.parse(raw);
  const ix = ledger && typeof ledger.indexedModules === "object" ? ledger.indexedModules : {};
  // indexedModules is stored as a numeric-string-keyed object (was JSON.stringify'd from an array).
  const items = Object.keys(ix)
    .filter((k) => /^\d+$/.test(k))
    .sort((a, b) => Number(a) - Number(b))
    .map((k) => ix[k])
    .filter((v) => v && typeof v === "object");
  return items.filter(isDataLaneItem);
}

/** Atomic write: <out>.tmp + renameSync. The engine's JSON.parse try/catch
 *  silently skips malformed files, so atomicity is load-bearing. */
export function atomicWriteJson(absPath, payload) {
  const tmp = absPath + ".tmp";
  fs.mkdirSync(path.dirname(absPath), { recursive: true });
  fs.writeFileSync(tmp, JSON.stringify(payload, null, 2) + "\n", "utf8");
  fs.renameSync(tmp, absPath);
}

// ---- CLI ------------------------------------------------------------------

const HELP = `Usage: node scripts/monolith-to-tribal-tips.mjs [options]

Reads the monolith port-ledger (state/shared/specs/monolith-port-ledger.json
by default), filters to the 133-item data-lane subset, and emits a
KnowledgeTip[] envelope to cad-engine/knowledge_store/monolith-data-lane-tips.json.

Options:
  --input <path>       ledger path (default: state/shared/specs/monolith-port-ledger.json)
  --output <path>      tip envelope path (default: cad-engine/knowledge_store/monolith-data-lane-tips.json)
  --limit N            cap tip count (positive integer; useful for testing)
  --frozen-time ISO    pin generatedAt + created_at to this UTC ISO date
                       (also reads env PRISM_AUDIT_FROZEN_TIME / PRISM_FROZEN_TIME)
  --help               show this message
`;

function parseArgs(argv) {
  const args = { input: null, output: null, limit: null, frozenTime: null, help: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--help" || a === "-h") { args.help = true; continue; }
    if (a === "--input" || a === "--output" || a === "--limit" || a === "--frozen-time") {
      const v = argv[i + 1];
      if (typeof v === "undefined" || v.startsWith("--")) {
        const err = new Error(`flag ${a} requires a value`);
        err.code = "EUSAGE";
        throw err;
      }
      if (a === "--input") args.input = v;
      else if (a === "--output") args.output = v;
      else if (a === "--limit") {
        if (!/^\d+$/.test(v)) {
          const err = new Error(`invalid --limit: expected positive integer, got ${JSON.stringify(v)}`);
          err.code = "EUSAGE";
          throw err;
        }
        const n = Number(v);
        if (!Number.isFinite(n) || n < 1) {
          const err = new Error(`invalid --limit: expected positive integer, got ${JSON.stringify(v)}`);
          err.code = "EUSAGE";
          throw err;
        }
        args.limit = n;
      }
      else if (a === "--frozen-time") args.frozenTime = v;
      i++;
      continue;
    }
    const err = new Error(`unknown flag: ${a}`);
    err.code = "EUSAGE";
    throw err;
  }
  return args;
}

function main() {
  let args;
  try {
    args = parseArgs(process.argv.slice(2));
  } catch (e) {
    process.stderr.write(String(e && e.message ? e.message : e) + "\n");
    process.exit(2);
  }
  if (args.help) {
    process.stdout.write(HELP);
    process.exit(0);
  }
  const frozen = args.frozenTime || process.env.PRISM_AUDIT_FROZEN_TIME || process.env.PRISM_FROZEN_TIME || null;
  const now = frozen ? new Date(frozen) : new Date();
  if (frozen && (isNaN(now.getTime()) || !Number.isFinite(now.getTime()))) {
    process.stderr.write(`invalid --frozen-time: ${frozen}\n`);
    process.exit(2);
  }
  const inputAbs = path.resolve(REPO_ROOT, args.input || "state/shared/specs/monolith-port-ledger.json");
  const outputAbs = path.resolve(REPO_ROOT, args.output || "cad-engine/knowledge_store/monolith-data-lane-tips.json");
  let items;
  try {
    items = loadLedger(inputAbs);
  } catch (e) {
    process.stderr.write(`failed to load ledger ${inputAbs}: ${e && e.message ? e.message : e}\n`);
    process.exit(3);
  }
  const sourceRecords = items.length;
  let tips = convertAll(items, now);
  if (args.limit && tips.length > args.limit) tips = tips.slice(0, args.limit);
  const relativeSource = path.relative(REPO_ROOT, inputAbs).replace(/\\/g, "/");
  const envelope = buildEnvelope(tips, { now, relativeSource, sourceRecords });
  try {
    atomicWriteJson(outputAbs, envelope);
  } catch (e) {
    process.stderr.write(`failed to write ${outputAbs}: ${e && e.message ? e.message : e}\n`);
    process.exit(3);
  }
  const relOut = path.relative(REPO_ROOT, outputAbs).replace(/\\/g, "/");
  process.stdout.write(`monolith-to-tribal-tips: wrote ${tips.length} tips to ${relOut} (source ${sourceRecords} data-lane items)\n`);
}

// Only run main() when invoked directly (not on import for tests).
if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  main();
}
