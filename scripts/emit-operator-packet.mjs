#!/usr/bin/env node
/**
 * emit-operator-packet.mjs — generate a plain-language OPERATOR SETUP CARD (a "shop traveler")
 * from the canonical job, written for an INEXPERIENCED machinist. The goal (PRISM's mission): a
 * new operator should be able to set up + run the part safely WITHOUT knowing speeds/feeds, WCS
 * math, or how to build a tool list — the card spells out every step.
 *
 * Pure function `buildPacket(program)` returns the markdown (testable); the CLI writes it.
 * Single source of truth = scripts/lib/prism-base-job.mjs (shared with the tool library).
 *
 * Usage: node scripts/emit-operator-packet.mjs [rich|basic] [outPath]
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { TOOLS, STOCK, WCS, UNITS, MATERIAL, PROGRAMS, VISE, toolByNum } from "./lib/prism-base-job.mjs";

const inch = (v) => (v % 1 === 0 ? String(v) : String(Number(v.toFixed(4)))) + '"';

export function buildPacket(programKey = "rich") {
  const prog = PROGRAMS[programKey];
  if (!prog) throw new Error(`unknown program '${programKey}' (have: ${Object.keys(PROGRAMS).join(", ")})`);
  const tools = prog.toolNums.map(toolByNum).filter(Boolean);

  const toolRows = tools.map((t) =>
    `| **T${t.num}** | ${t.desc} | ${inch(t.dia)} | ${t.flutes} | offset **H${t.num}** | ${t.rpm} RPM |`).join("\n");

  const loadSteps = tools.map((t, i) =>
    `${i + 1}. **Pocket/Tool ${t.num}** — ${t.pocket} In the control's Tool Setup, set tool **${t.num}** type **${t.type}**, diameter **${inch(t.dia)}**${t.sig ? `, point angle **${t.sig}°**` : ""}. Touch it off and store its length in offset **H${t.num}**.`).join("\n");

  const opSteps = prog.ops.map((o, i) => {
    const t = toolByNum(o.tool);
    return `${i + 1}. **${o.name}** (T${o.tool}, ${t ? t.desc : "?"}) — ${o.plain}`;
  }).join("\n");

  return `# OPERATOR SETUP CARD — ${prog.title}

> For PRISM. Written for a new operator. Do the steps in order. If anything looks wrong, **stop and ask**.
> PRISM already calculated the speeds and feeds — do **not** change them on the first run.

**Program file:** \`${prog.file}\`
**Material:** ${MATERIAL.name}  ·  **Units:** ${UNITS} (set the control to ${UNITS})  ·  **Work offset:** ${WCS}

---

## 1. Vise, stock + work zero (the most important step)
**Vise: ${VISE.model} (${VISE.kind}).** It's an inch vise — the part is inch too, so everything matches.
- Grip the block by its **${VISE.clampWidth}" face** (open the jaws to about ${VISE.clampWidth}"); the **${VISE.alongJaw}" length** lies along the jaw.
- Set the block on **parallels** so its **top sticks up ~${VISE.stickoutAboveJaw}" above the jaw tops**. The program cuts a 0.6" deep pocket and a 0.5" drill from the top, so the cut **and the tool holder** must clear the jaws — don't grip it down low.
- Tap the block down onto the parallels, then tighten firmly.

**Stock + zero:**
- The block is a **${STOCK.x} × ${STOCK.y} × ${STOCK.z} ${STOCK.units}** plate, long side left-to-right.
- Set your part zero (**${WCS}**) at the **${STOCK.wcsCornerPlain}**:
  - **X0, Y0** = the ${STOCK.wcsCorner} of the block.
  - **Z0** = the **top** of the block.
- Double-check: jog to X0 Y0 — the spindle should be over that corner. Jog to Z0 — the tool tip should just touch the top.

## 2. Tools — load these and set the offsets
The program calls each tool by number and reads its length from the matching **H** offset. Get these exact.

| Tool | What it is | Dia | Flutes | Length offset | Speed |
|------|-----------|-----|--------|---------------|-------|
${toolRows}

${loadSteps}

> A ready-made tool library (\`prism-base-tools.tools\`) is in your Fusion CAM Local Libraries if you post from Fusion.

## 3. What the program does (so you know what to expect)
${opSteps}

## 4. Before you hit cycle-start (safety checklist)
- [ ] Right material in the vise, clamped tight, zero set (step 1).
- [ ] Every tool loaded in the right pocket with its **H** offset stored (step 2).
- [ ] Coolant on (the program turns it on with **M08**) and aimed at the cut.
- [ ] **Feed override to ~50%** and a hand on the feed-hold for the FIRST run.
- [ ] Watch the first tool change + first plunge. If the tool is anywhere unexpected — **feed hold, then stop**.
- [ ] Once it looks right, walk the override back up to 100%.

## 5. If something goes wrong
- Loud/chattering cut → feed hold, lower the override, let it finish that pass, then stop and ask.
- Tool rubbing / not cutting → check you loaded the right tool in that pocket and the H offset is correct.
- Alarm → write the alarm number down, stop, and ask. Don't clear-and-continue blindly.

_Generated by PRISM from the program's tools — every number here matches \`${prog.file}\`._
`;
}

// ── CLI ──
const isMain = process.argv[1] && /emit-operator-packet\.mjs$/.test(process.argv[1].replace(/\\/g, "/"));
if (isMain) {
  const key = (process.argv[2] && PROGRAMS[process.argv[2]]) ? process.argv[2] : "rich";
  const out = process.argv[3] || path.join("C:/Users/wompu/OneDrive/Desktop", `OPERATOR-SETUP-CARD-${key}.md`);
  writeFileSync(out, buildPacket(key));
  console.log(`operator setup card (${key}) -> ${out} (${TOOLS.length} tools known, ${PROGRAMS[key].ops.length} ops)`);
}
