#!/usr/bin/env node
/**
 * generate-frontend-wiki.mjs
 *
 * Generates wiki entries for L1 frontend nodes at
 *   H:/prism/knowledge/wiki/architecture/frontends/<kind>/<slug>.md
 *
 * L1 contains:
 *   - 5 variants  (frontend hosts: mcp-server/web, cqask, mcp-cadquery, ...)
 *   - 14 page rollups (category groupings like "Specialty Pages (38 pages)")
 *   - 146 individual pages
 *
 * Each entry surfaces:
 *   - node id, label, status, parent variant
 *   - flags "dead pixel" risk if status indicates the page exists but no L4
 *     dispatcher edge connects to it
 *   - cross-refs to [[layer-l1]] + [[layer-l2]] + variant page
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PRISM_ROOT = resolve(__dirname, "..");
const GRAPH_PATH = resolve(PRISM_ROOT, "state/shared/system-viz/system-graph.json");
const WIKI_ARCH_DIR = resolve(PRISM_ROOT, "knowledge/wiki/architecture");
const FE_DIR = join(WIKI_ARCH_DIR, "frontends");
const WIKI_INDEX = resolve(PRISM_ROOT, "knowledge/wiki/index.md");

const args = new Set(process.argv.slice(2));
const FLAGS = { dryRun: args.has("--dry-run") };

const AUTO_START = "<!-- AUTO-START — regenerated by generate-frontend-wiki.mjs -->";
const AUTO_END = "<!-- AUTO-END -->";

const KIND_PURPOSE = {
  variants: "Frontend host — a top-level UI variant (Next.js app, CAD viewer, slash-command HTML).",
  pages: "Page-group rollup — bundles related individual pages under a single category.",
  page: "Individual page — a frontend route. May be a 'dead pixel' if no L4 dispatcher edge connects.",
};

function readJson(p) { return JSON.parse(readFileSync(p, "utf8")); }
function ensureDir(d) { if (!existsSync(d)) mkdirSync(d, { recursive: true }); }
function slug(s) { return String(s || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""); }

function indexEdges(G) {
  const inByTarget = new Map();
  for (const e of G.edges) {
    const arr = inByTarget.get(e.to) || [];
    arr.push(e.from);
    inByTarget.set(e.to, arr);
  }
  return inByTarget;
}

function render(node, isDeadPixel, generatedAt, headline) {
  const kind = node.kind || node.subgroup || "page";
  const purpose = KIND_PURPOSE[kind] || `Frontend node of kind \`${kind}\`.`;
  const label = (node.label || node.id).replace(/\n/g, " · ");
  const deadFlag = isDeadPixel ? "⚠️ **DEAD PIXEL CANDIDATE** — no inbound edges in graph; verify backend wiring." : "";
  return `---
title: Frontend — ${label}
type: architecture
frontend_id: ${node.id}
kind: ${kind}
parent_layer: L1
status: ${node.status || "?"}
generated_by: scripts/generate-frontend-wiki.mjs
last_verified: ${generatedAt}
tags: [architecture, system-viz, frontend, ${kind}${isDeadPixel ? ", dead-pixel-risk" : ""}]
related:
  - knowledge/wiki/architecture/layer-l1.md
  - knowledge/wiki/architecture/layer-l2.md
  - state/shared/system-viz/system-graph.json
---

# Frontend — \`${label}\`

> ${purpose}

**Kind:** ${kind}  ·  **Status:** ${node.status || "?"}
**System headline:** ${headline.pendingFE ?? 0} frontend merges pending across all variants

${deadFlag}

${AUTO_START}

| Field | Value |
|-------|-------|
| Node id | \`${node.id}\` |
| Kind | ${kind} |
| Parent layer | [[layer-l1]] |
| Status | ${node.status || "?"} |
| Dead-pixel risk | ${isDeadPixel ? "yes — no inbound edges" : "no — has dispatcher/transport edges"} |

## Doctrine

- A page is a 'dead pixel' if its Tier-1 engine is unwired or missing
- Verify by tracing: L1 page → L2 transport → L3/L4 dispatcher → L5 engine
- New pages must ship with backend wiring in the same commit

${AUTO_END}

## See also

- Layer L1: [[layer-l1]]
- Transport L2: [[layer-l2]]
- Live graph: \`state/shared/system-viz/system-graph.json\`
`;
}

function preserveHuman(existing, full) {
  if (!existing) return full;
  const sStart = existing.indexOf(AUTO_START);
  const sEnd = existing.indexOf(AUTO_END);
  const nStart = full.indexOf(AUTO_START);
  const nEnd = full.indexOf(AUTO_END);
  if (sStart === -1 || sEnd === -1) return full;
  return existing.slice(0, sStart) + full.slice(nStart, nEnd + AUTO_END.length) + existing.slice(sEnd + AUTO_END.length);
}

function updateIndex(byKind, deadPixelCount) {
  if (!existsSync(WIKI_INDEX)) return null;
  const text = readFileSync(WIKI_INDEX, "utf8");
  const lines = [
    `_Total: ${Object.values(byKind).flat().length} frontend entries_ · ${deadPixelCount} flagged as dead-pixel risk`,
    "",
    ...Object.entries(byKind)
      .sort((a, b) => b[1].length - a[1].length)
      .map(([k, arr]) => `- **${k}**: ${arr.length} entries — see \`knowledge/wiki/architecture/frontends/${k}/\``),
  ];
  const block = ["<!-- ARCH-FRONTENDS-START -->", ...lines, "<!-- ARCH-FRONTENDS-END -->"].join("\n");
  if (text.includes("<!-- ARCH-FRONTENDS-START -->")) {
    return text.replace(/<!-- ARCH-FRONTENDS-START -->[\s\S]*?<!-- ARCH-FRONTENDS-END -->/m, block);
  }
  if (text.includes("<!-- ARCH-REGISTRIES-END -->")) {
    return text.replace(
      /<!-- ARCH-REGISTRIES-END -->/,
      "<!-- ARCH-REGISTRIES-END -->\n\n### Frontend pages\n\n" + block
    );
  }
  return text.trimEnd() + "\n\n### Frontend pages\n\n" + block + "\n";
}

function main() {
  if (!existsSync(GRAPH_PATH)) { console.error("graph missing"); process.exit(2); }
  const G = readJson(GRAPH_PATH);
  const inByTarget = indexEdges(G);
  const headline = (G.meta && G.meta.headline) || {};
  const generatedAt = new Date().toISOString().split("T")[0];
  ensureDir(FE_DIR);

  const byKind = {};
  let written = 0, deadPixelCount = 0;
  const t0 = Date.now();

  for (const node of G.nodes) {
    if (node.layer !== "L1") continue;
    const kind = node.kind || node.subgroup || "page";
    const isDeadPixel = kind === "page" && !(inByTarget.get(node.id) || []).length;
    if (isDeadPixel) deadPixelCount++;
    const subDir = join(FE_DIR, kind);
    ensureDir(subDir);
    const outPath = join(subDir, `${slug(node.id)}.md`);
    const full = render(node, isDeadPixel, generatedAt, headline);
    const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
    const finalContent = preserveHuman(existing, full);
    if (!FLAGS.dryRun) writeFileSync(outPath, finalContent, "utf8");
    written++;
    (byKind[kind] = byKind[kind] || []).push(node);
  }

  const indexUpdated = !FLAGS.dryRun ? updateIndex(byKind, deadPixelCount) : null;
  if (indexUpdated && !FLAGS.dryRun) writeFileSync(WIKI_INDEX, indexUpdated, "utf8");

  console.log(`generated ${written} frontend wiki entries in ${Date.now() - t0}ms · ${deadPixelCount} dead-pixel candidates`);
}

main();
