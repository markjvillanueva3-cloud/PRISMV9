#!/usr/bin/env node
/**
 * migrate-hooks-to-rpc.mjs — U-DOCKER-HOOK-BROKER-P5
 *
 * Rewrites the 78 module-safe `.claude/hooks/<name>.mjs` files to call the
 * broker via `_rpc-shim.mjs`, preserving the original at `<name>.original.mjs`.
 *
 * DRY RUN BY DEFAULT — emits a per-file diff plan; passes `--apply` to
 * actually mutate the filesystem. Reads HOOK-BROKER-COMPAT-REPORT.json
 * to pick the target set (only `module-safe` hooks); skips any hook
 * already migrated (has a `<name>.original.mjs` peer).
 *
 * Reversible: every original is preserved as `<name>.original.mjs`. A
 * single git revert OR re-running with `--undo` restores the
 * pre-migration state. The shim has a broker-down fallback that
 * dynamic-imports `<name>.original.mjs` automatically, so the system
 * keeps working even if the broker container is down.
 *
 * Usage:
 *   node scripts/migrate-hooks-to-rpc.mjs                 # dry-run (default)
 *   node scripts/migrate-hooks-to-rpc.mjs --apply         # actually mutate
 *   node scripts/migrate-hooks-to-rpc.mjs --apply --max 10  # cap to N hooks
 *   node scripts/migrate-hooks-to-rpc.mjs --undo --apply  # revert migration
 *   node scripts/migrate-hooks-to-rpc.mjs --filter foo    # only hooks matching substring
 *
 * Output:
 *   state/shared/HOOK-MIGRATION-LOG.json (per-run audit trail)
 *
 * @milestone U-DOCKER-HOOK-BROKER-P5
 */

import { readFileSync, writeFileSync, renameSync, existsSync, mkdirSync } from "node:fs";
import { join, resolve, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const REPO = resolve(__dirname, "..");
const REPORT_PATH = join(REPO, "state", "shared", "HOOK-BROKER-COMPAT-REPORT.json");
const HOOKS_DIR = join(REPO, ".claude", "hooks");
const LOG_PATH = join(REPO, "state", "shared", "HOOK-MIGRATION-LOG.json");

/**
 * Shim template — the new content of every migrated `<name>.mjs`. Tiny
 * by design so 78+ files are auditable at a glance.
 *
 * @param {string} name
 * @returns {string}
 */
export function shimContent(name) {
  return `#!/usr/bin/env node
// tier: T3
// AUTO-GENERATED by scripts/migrate-hooks-to-rpc.mjs (U-DHB-P5).
// Original logic preserved at \`${name}.original.mjs\`. The broker daemon
// (docker/hook-broker/server.mjs) holds it warm; on broker-down the
// shim dynamic-imports the .original.mjs peer (zero-rollback fallback).
import { runShim } from "./_rpc-shim.mjs";
await runShim(${JSON.stringify(name)}, import.meta.url);
`;
}

/**
 * Read HOOK-BROKER-COMPAT-REPORT.json and return paths classified as
 * `module-safe`. Throws if the report is missing — the broker survey
 * must be re-run first (`node scripts/classify-hooks-for-broker.mjs`).
 *
 * @returns {string[]}
 */
export function readModuleSafeHookPaths() {
  let report;
  try { report = JSON.parse(readFileSync(REPORT_PATH, "utf8")); }
  catch (e) {
    throw new Error(
      `cannot read ${REPORT_PATH}: ${e?.message}. Run ` +
      `\`node scripts/classify-hooks-for-broker.mjs\` first.`,
    );
  }
  if (!Array.isArray(report.perFile)) {
    throw new Error(`compat report has no perFile[]; regenerate it`);
  }
  return report.perFile
    .filter((e) => e && e.category === "module-safe" && typeof e.filePath === "string")
    .map((e) => e.filePath);
}

/**
 * Plan the per-file migration. Pure — returns an array of action records
 * without touching the filesystem. Each action is one of:
 *   - "migrate":         current file → .original.mjs + new shim file
 *   - "skip-migrated":   .original.mjs already exists (idempotent)
 *   - "skip-missing":    source file vanished after the survey
 *
 * @param {string[]} files
 * @param {(p: string) => boolean} [exists]  — io-injectable for tests
 * @returns {Array<{filePath: string, name: string, action: "migrate"|"skip-migrated"|"skip-missing"}>}
 */
export function planMigration(files, exists = existsSync) {
  const out = [];
  for (const filePath of files) {
    const name = basename(filePath).replace(/\.mjs$/, "");
    if (!exists(filePath)) {
      out.push({ filePath, name, action: "skip-missing" });
      continue;
    }
    const originalPeer = filePath.replace(/\.mjs$/, ".original.mjs");
    if (exists(originalPeer)) {
      out.push({ filePath, name, action: "skip-migrated" });
      continue;
    }
    out.push({ filePath, name, action: "migrate" });
  }
  return out;
}

/**
 * Plan the inverse operation — restore migrated hooks from their
 * `<name>.original.mjs` peers. Each action is:
 *   - "undo":          .original.mjs exists → rename back over current
 *   - "skip-pristine": no .original.mjs peer (already pristine)
 *
 * @param {string[]} files
 * @param {(p: string) => boolean} [exists]
 * @returns {Array<{filePath: string, name: string, action: "undo"|"skip-pristine"}>}
 */
export function planUndo(files, exists = existsSync) {
  const out = [];
  for (const filePath of files) {
    const name = basename(filePath).replace(/\.mjs$/, "");
    const originalPeer = filePath.replace(/\.mjs$/, ".original.mjs");
    if (!exists(originalPeer)) {
      out.push({ filePath, name, action: "skip-pristine" });
      continue;
    }
    out.push({ filePath, name, action: "undo" });
  }
  return out;
}

/**
 * Apply a single migration step on disk. Atomic per file:
 *   1. rename `<name>.mjs` → `<name>.original.mjs`
 *   2. write the shim content to `<name>.mjs`
 * If step 2 fails after step 1, the original is restored.
 *
 * @param {{filePath: string, name: string}} step
 */
export function applyMigrate(step) {
  const originalPeer = step.filePath.replace(/\.mjs$/, ".original.mjs");
  renameSync(step.filePath, originalPeer);
  try {
    writeFileSync(step.filePath, shimContent(step.name), "utf8");
  } catch (e) {
    // Restore on write failure.
    try { renameSync(originalPeer, step.filePath); } catch { /* best effort */ }
    throw e;
  }
}

/**
 * Apply a single undo step on disk: rename `<name>.original.mjs` over
 * the current `<name>.mjs`.
 *
 * @param {{filePath: string, name: string}} step
 */
export function applyUndo(step) {
  const originalPeer = step.filePath.replace(/\.mjs$/, ".original.mjs");
  // renameSync replaces the destination atomically on POSIX; on Windows
  // the destination must NOT exist, so unlink current first.
  if (existsSync(step.filePath)) {
    // Read-then-overwrite via renameSync; on Windows we need to delete
    // the target first. Use a try/import-style write here for clarity.
    writeFileSync(step.filePath, readFileSync(originalPeer, "utf8"), "utf8");
    // Remove the .original.mjs to leave the tree pristine.
    // Use fs.unlinkSync via dynamic import to keep top-level imports light.
    // (Inline import avoids a CJS-vs-ESM `unlinkSync` lookup at top scope.)
    // eslint-disable-next-line global-require
    import("node:fs").then((fs) => fs.unlinkSync(originalPeer)).catch(() => {});
  } else {
    renameSync(originalPeer, step.filePath);
  }
}

/**
 * Render a per-file plan as a compact log line.
 * @param {{filePath: string, name: string, action: string}} step
 * @returns {string}
 */
export function renderStep(step) {
  const tag = ({
    "migrate": "[migrate]      ",
    "skip-migrated": "[skip:migrated]",
    "skip-missing": "[skip:missing] ",
    "undo": "[undo]         ",
    "skip-pristine": "[skip:pristine]",
  })[step.action] || `[${step.action}]`;
  return `${tag} ${step.name}`;
}

/**
 * Main entry — orchestrates plan + (optionally) apply. Returns a structured
 * summary suitable for serialization to the migration log.
 *
 * @param {{ apply?: boolean, undo?: boolean, max?: number, filter?: string, files?: string[] }} [opts]
 * @returns {{ planned: number, applied: number, skipped: number, failed: number, steps: any[] }}
 */
export function run(opts = {}) {
  const apply = opts.apply === true;
  const undo = opts.undo === true;
  const max = typeof opts.max === "number" && opts.max > 0 ? opts.max : Infinity;
  const filter = opts.filter || null;

  let files = opts.files ?? readModuleSafeHookPaths();
  if (filter) files = files.filter((p) => p.includes(filter));

  const plan = undo ? planUndo(files) : planMigration(files);
  const steps = [];
  let applied = 0;
  let skipped = 0;
  let failed = 0;

  for (const step of plan) {
    if (steps.length >= max) break;
    if (step.action === "migrate") {
      if (apply) {
        try { applyMigrate(step); applied++; steps.push({ ...step, status: "applied" }); }
        catch (e) { failed++; steps.push({ ...step, status: "failed", error: e?.message || String(e) }); }
      } else {
        steps.push({ ...step, status: "planned" });
      }
    } else if (step.action === "undo") {
      if (apply) {
        try { applyUndo(step); applied++; steps.push({ ...step, status: "applied" }); }
        catch (e) { failed++; steps.push({ ...step, status: "failed", error: e?.message || String(e) }); }
      } else {
        steps.push({ ...step, status: "planned" });
      }
    } else {
      skipped++;
      steps.push({ ...step, status: "skipped" });
    }
  }

  return {
    planned: plan.length,
    applied,
    skipped,
    failed,
    steps,
  };
}

/**
 * Write the migration log to disk (idempotent — overwrites). Includes a
 * timestamp so downstream tools can detect stale logs.
 * @param {ReturnType<typeof run>} summary
 * @param {{ apply: boolean, undo: boolean }} mode
 */
export function writeLog(summary, mode) {
  try { mkdirSync(dirname(LOG_PATH), { recursive: true }); } catch { /* exists */ }
  const payload = {
    schemaVersion: "1.0.0",
    generated: new Date().toISOString(),
    mode,
    ...summary,
  };
  writeFileSync(LOG_PATH, JSON.stringify(payload, null, 2), "utf8");
}

const invokedAsCli = (() => {
  try { return process.argv[1] && resolve(process.argv[1]) === __filename; }
  catch { return false; }
})();
if (invokedAsCli) {
  const args = process.argv.slice(2);
  const apply = args.includes("--apply");
  const undo = args.includes("--undo");
  const maxIdx = args.indexOf("--max");
  const max = maxIdx >= 0 && args[maxIdx + 1] ? Number(args[maxIdx + 1]) : undefined;
  const filterIdx = args.indexOf("--filter");
  const filter = filterIdx >= 0 ? args[filterIdx + 1] : undefined;

  const summary = run({ apply, undo, max, filter });
  for (const s of summary.steps) console.log(renderStep(s));
  console.log("");
  console.log(`[${undo ? "undo" : "migrate"}] planned=${summary.planned} applied=${summary.applied} skipped=${summary.skipped} failed=${summary.failed} dry_run=${!apply}`);
  if (!apply) console.log("→ re-run with --apply to actually mutate the filesystem");
  writeLog(summary, { apply, undo });
}
