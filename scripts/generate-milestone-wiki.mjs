#!/usr/bin/env node
/**
 * generate-milestone-wiki.mjs
 *
 * Generates one Obsidian wiki entry per L8 milestone node at
 *   H:/prism/knowledge/wiki/architecture/milestones/<slug>.md
 *
 * L8 milestone nodes have:
 *   - kind === "milestone"
 *   - id like "ghost.ms.<scope>-ms<N>"
 *   - label with optional emoji prefix + scope code + description
 *   - status in {ghost, planned, in_progress, complete}
 *
 * Each entry surfaces:
 *   - scope code, milestone number, status
 *   - cross-refs to [[layer-l8]] + roadmap reference
 *   - drilled L9 planned-unit children if present in graph
 *
 * Pure-function summary — milestone status drift detection lives elsewhere
 * (state/shared/MILESTONE_PROGRESS.md). This wiki just exposes the planned
 * surface for chat/agent search.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PRISM_ROOT = resolve(__dirname, "..");
const GRAPH_PATH = resolve(PRISM_ROOT, "state/shared/system-viz/system-graph.json");
const WIKI_ARCH_DIR = resolve(PRISM_ROOT, "knowledge/wiki/architecture");
const MS_DIR = join(WIKI_ARCH_DIR, "milestones");
const WIKI_INDEX = resolve(PRISM_ROOT, "knowledge/wiki/index.md");

const args = new Set(process.argv.slice(2));
const FLAGS = { dryRun: args.has("--dry-run") };

const AUTO_START = "<!-- AUTO-START — regenerated by generate-milestone-wiki.mjs -->";
const AUTO_END = "<!-- AUTO-END -->";

function readJson(p) { return JSON.parse(readFileSync(p, "utf8")); }
function ensureDir(d) { if (!existsSync(d)) mkdirSync(d, { recursive: true }); }
function slug(s) { return String(s || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""); }

function parseMilestone(node) {
  // Try to extract scope + number from label "🔻 CAMK-MS0 · Feature-to-Toolpath..." or id "ghost.ms.camk-ms0"
  const label = node.label || "";
  const scopeMatch = label.match(/([A-Z][A-Z0-9-]+)-MS(\d+)/) || node.id.match(/\.([a-z0-9-]+)-ms(\d+)$/i);
  if (scopeMatch) return { scope: scopeMatch[1].toUpperCase(), num: scopeMatch[2] };
  return { scope: "UNKNOWN", num: "?" };
}

function indexEdges(G) {
  const outByFrom = new Map();
  for (const e of G.edges) {
    const arr = outByFrom.get(e.from) || [];
    arr.push(e.to);
    outByFrom.set(e.from, arr);
  }
  return outByFrom;
}

function indexByParent(G) {
  // parentId → [node, …] — for L9 leaf records attached via `parent` not edges
  const m = new Map();
  for (const n of G.nodes) {
    if (!n.parent) continue;
    const arr = m.get(n.parent) || [];
    arr.push(n);
    m.set(n.parent, arr);
  }
  return m;
}

function findUnits(G, msId, outByFrom, byParent) {
  // L9 planned-units are attached either by an explicit edge OR (more commonly,
  // since generate-system-viz emits them with a `parent` field and no edge) by
  // `parent === msId`. Union both so the milestone entry surfaces its units even
  // when the graph has zero edges into them (the ~2,256 degree-0 planned-unit case).
  const nodeById = new Map(G.nodes.map((n) => [n.id, n]));
  const seen = new Set();
  const out = [];
  for (const id of outByFrom.get(msId) || []) {
    const n = nodeById.get(id);
    if (n && n.layer === "L9" && !seen.has(n.id)) { seen.add(n.id); out.push(n); }
  }
  for (const n of byParent.get(msId) || []) {
    if (n && n.layer === "L9" && !seen.has(n.id)) { seen.add(n.id); out.push(n); }
  }
  return out.slice(0, 12);
}

function render(node, parsed, units, generatedAt) {
  const cleanLabel = (node.label || node.id).replace(/^[^\w]+/, "").replace(/\n/g, " · ");
  const unitRows = units.length
    ? units.map((u) => `- \`${u.id}\` — ${(u.label || "(unnamed)").replace(/\n/g, " ")}`).join("\n")
    : "_(no planned-unit children in graph — milestone may be high-level only)_";
  return `---
title: Milestone — ${parsed.scope}-MS${parsed.num}
type: architecture
milestone_id: ${node.id}
scope: ${parsed.scope}
milestone_num: ${parsed.num}
parent_layer: L8
status: ${node.status || "?"}
generated_by: scripts/generate-milestone-wiki.mjs
last_verified: ${generatedAt}
tags: [architecture, system-viz, milestone, scope-${slug(parsed.scope)}, status-${slug(node.status || "ghost")}]
related:
  - knowledge/wiki/architecture/layer-l8.md
  - state/shared/MILESTONE_PROGRESS.md
  - PRISM-UNIFIED-ROADMAP-v2.md
---

# Milestone — \`${parsed.scope}-MS${parsed.num}\`

> ${cleanLabel}

**Scope:** ${parsed.scope}  ·  **MS#:** ${parsed.num}  ·  **Status:** ${node.status || "ghost"}

${AUTO_START}

| Field | Value |
|-------|-------|
| Milestone ID | \`${node.id}\` |
| Scope | ${parsed.scope} |
| Number | MS${parsed.num} |
| Status | ${node.status || "ghost"} |
| Planned units (L9 children) | ${units.length} |
| Parent layer | [[layer-l8]] |

## Planned units (sample of 10)

${unitRows}

## Doctrine

- Milestone status drift between envelope and git lives in \`state/shared/MILESTONE_PROGRESS.md\`
- Before claiming this milestone, fork to a sibling worktree per CLAUDE.md conflict-fork rule
- Commit format: \`[${parsed.scope}-MS${parsed.num}]/U-<unit-id>: <title>\`

${AUTO_END}

## See also

- L8 layer (memory/milestones): [[layer-l8]]
- Live drift snapshot: \`state/shared/MILESTONE_PROGRESS.md\`
- Roadmap source: \`PRISM-UNIFIED-ROADMAP-v2.md\`
`;
}

function preserveHuman(existing, full) {
  if (!existing) return full;
  const sStart = existing.indexOf(AUTO_START);
  const sEnd = existing.indexOf(AUTO_END);
  const nStart = full.indexOf(AUTO_START);
  const nEnd = full.indexOf(AUTO_END);
  if (sStart === -1 || sEnd === -1) return full;
  return existing.slice(0, sStart) + full.slice(nStart, nEnd + AUTO_END.length) + existing.slice(sEnd + AUTO_END.length);
}

function updateIndex(byScope, total) {
  if (!existsSync(WIKI_INDEX)) return null;
  const text = readFileSync(WIKI_INDEX, "utf8");
  const lines = [
    `_Total: ${total} milestone entries across ${Object.keys(byScope).length} scopes._`,
    "",
    "Top scopes by milestone count:",
    ...Object.entries(byScope)
      .sort((a, b) => b[1] - a[1])
      .slice(0, 15)
      .map(([s, c]) => `- \`${s}\`: ${c} milestones`),
  ];
  const block = ["<!-- ARCH-MILESTONES-START -->", ...lines, "<!-- ARCH-MILESTONES-END -->"].join("\n");
  if (text.includes("<!-- ARCH-MILESTONES-START -->")) {
    return text.replace(/<!-- ARCH-MILESTONES-START -->[\s\S]*?<!-- ARCH-MILESTONES-END -->/m, block);
  }
  if (text.includes("<!-- ARCH-FRONTENDS-END -->")) {
    return text.replace(
      /<!-- ARCH-FRONTENDS-END -->/,
      "<!-- ARCH-FRONTENDS-END -->\n\n### Milestones (per-scope counts)\n\n" + block
    );
  }
  return text.trimEnd() + "\n\n### Milestones\n\n" + block + "\n";
}

function main() {
  if (!existsSync(GRAPH_PATH)) { console.error("graph missing"); process.exit(2); }
  const G = readJson(GRAPH_PATH);
  const outByFrom = indexEdges(G);
  const byParent = indexByParent(G);
  const generatedAt = new Date().toISOString().split("T")[0];
  ensureDir(MS_DIR);

  const byScope = {};
  let written = 0;
  const t0 = Date.now();

  for (const node of G.nodes) {
    if (node.layer !== "L8") continue;
    const tag = node.kind || node.subgroup || "";
    if (tag !== "milestone") continue;
    const parsed = parseMilestone(node);
    const units = findUnits(G, node.id, outByFrom, byParent);
    const outPath = join(MS_DIR, `milestone-${slug(node.id)}.md`);
    const full = render(node, parsed, units, generatedAt);
    const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
    const finalContent = preserveHuman(existing, full);
    if (!FLAGS.dryRun) writeFileSync(outPath, finalContent, "utf8");
    written++;
    byScope[parsed.scope] = (byScope[parsed.scope] || 0) + 1;
  }

  const indexUpdated = !FLAGS.dryRun ? updateIndex(byScope, written) : null;
  if (indexUpdated && !FLAGS.dryRun) writeFileSync(WIKI_INDEX, indexUpdated, "utf8");

  console.log(`generated ${written} milestone wiki entries in ${Date.now() - t0}ms (scopes: ${Object.keys(byScope).length})`);
}

main();
