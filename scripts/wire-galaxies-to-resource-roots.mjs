#!/usr/bin/env node
/**
 * wire-galaxies-to-resource-roots.mjs
 *
 * Operator directive (2026-05-30, slot juliett): the 3 most important folders in
 * PRISM — H:/PRISM/resources, H:/PRISM/JM DIE, H:/PRISM/Docustrata — must be reachable
 * from EVERY galaxy. This script is the single wiring mechanism:
 *
 *   1. Reads the canonical registry (source of truth):
 *      mcp-server/src/engines/database-expansion/CRITICAL-RESOURCE-ROOTS.json
 *   2. Regenerates the human atlas CRITICAL-RESOURCE-ROOTS.md next to it.
 *   3. Splices a MARKED, idempotent "## 🌐 Critical resource roots" section into
 *      every galaxy PATHS.md (dirs under mcp-server/src/engines/ that contain PATHS.md).
 *      - Uniform 3-root pointer for all galaxies.
 *      - A "Domain-relevant" line for galaxies with non-empty galaxyHints.
 *
 * IDEMPOTENT: re-running replaces the existing marked block in place (no duplication).
 * Re-run whenever a new galaxy is added or the registry changes.
 *
 * Usage:
 *   node scripts/wire-galaxies-to-resource-roots.mjs            # apply
 *   node scripts/wire-galaxies-to-resource-roots.mjs --check    # dry-run (report, no writes)
 *
 * Karpathy: CLASSIFY=transform+wire · EDGE CASES=missing markers / new galaxy / re-run /
 * hint for unknown galaxy / CRLF / trailing-newline drift · FAIL MODES=registry missing,
 * galaxy with no PATHS.md (skipped), partial marker.
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REGISTRY_REL = "mcp-server/src/engines/database-expansion/CRITICAL-RESOURCE-ROOTS.json";
const REGISTRY = path.join(REPO, REGISTRY_REL);
const ATLAS = path.join(path.dirname(REGISTRY), "CRITICAL-RESOURCE-ROOTS.md");
const ENGINES_DIR = path.join(REPO, "mcp-server/src/engines");

export const BEGIN = "<!-- BEGIN:critical-resource-roots (generated by scripts/wire-galaxies-to-resource-roots.mjs — do not hand-edit) -->";
export const END = "<!-- END:critical-resource-roots -->";

function escapeRegex(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/** One-line root summary used inside galaxy PATHS.md (compact — full map lives in the atlas). */
function rootLine(root) {
  const idx = root.ownIndex ? ` | index: ${root.ownIndex}` : "";
  const cons = root.consolidatedInto ? ` | consolidated: ${root.consolidatedInto}` : "";
  return `- \`${root.path}\` | ${root.role}${idx}${cons}`;
}

/**
 * Build the marked, idempotent section for one galaxy.
 * Pure: same (galaxyName, registry) → byte-identical output.
 */
export function buildGalaxyBlock(galaxyName, registry) {
  const lines = [];
  lines.push(BEGIN);
  lines.push("## 🌐 Critical resource roots (fleet-wide — operator-canonical 2026-05-30)");
  lines.push(`> The 3 most important data/resource roots in PRISM — EVERY galaxy is wired to these. Source of truth: \`${REGISTRY_REL}\` · human atlas: \`mcp-server/src/engines/database-expansion/CRITICAL-RESOURCE-ROOTS.md\` · owner: ${registry.owner}.`);
  for (const root of registry.roots) lines.push(rootLine(root));
  const hints = (registry.galaxyHints && registry.galaxyHints[galaxyName]) || [];
  if (Array.isArray(hints) && hints.length > 0) {
    const pretty = hints.map((h) => `\`${h}\``).join(" · ");
    lines.push(`- **Domain-relevant for ${galaxyName}:** ${pretty}`);
  }
  lines.push(END);
  return lines.join("\n");
}

/**
 * Wire the canonical block into `content`, idempotently, at file-end.
 * Strategy: strip ALL complete prior blocks (handles accidental duplicates) AND any
 * orphaned lone marker lines (torn-write residue — a BEGIN without its END, or vice-versa),
 * then append the canonical block once. This converges in a SINGLE pass from any prior
 * state (clean, duplicated, or half-written) and never loses non-marker content — only the
 * marker-bracketed block (our own generated text) and stray marker lines are removed.
 * Idempotent: a wired file (block already at end) re-emits byte-identical output.
 */
export function spliceSection(content, block) {
  // 1. Remove every complete BEGIN..END span (global, non-greedy). No `$`-interpretation:
  //    the replacement is the empty string.
  const fullRe = new RegExp(escapeRegex(BEGIN) + "[\\s\\S]*?" + escapeRegex(END), "g");
  let stripped = content.replace(fullRe, "");
  // 2. Drop orphaned lone marker lines left by a torn write. Surrounding prose is preserved.
  stripped = stripped
    .split(/\r?\n/)
    .filter((l) => l.trim() !== BEGIN.trim() && l.trim() !== END.trim())
    .join("\n");
  // 3. Append the canonical block once, normalized to exactly one blank line before it.
  return stripped.replace(/\s*$/, "") + "\n\n" + block + "\n";
}

/** Render the full human atlas markdown from the registry. */
export function renderAtlasMarkdown(registry) {
  const out = [];
  out.push("# Critical Resource Roots — fleet atlas");
  out.push("");
  out.push(`> GENERATED from \`${REGISTRY_REL}\` by \`scripts/wire-galaxies-to-resource-roots.mjs\` — do not hand-edit.`);
  out.push(`> Owner: ${registry.owner} · consumers: ${registry.consumers} · verified-on-disk ${registry.verifiedOnDisk}.`);
  out.push("");
  out.push("The 3 operator-designated most-important folders in PRISM. Every galaxy's PATHS.md carries a marked pointer to these (re-run the script to re-wire). The pathway is the **root + its own index** — deep file enumeration lives in each root's index (e.g. Docustrata `manifest.json` + `.index/`), never copied per-galaxy.");
  out.push("");
  for (const root of registry.roots) {
    out.push(`## ${root.path}`);
    out.push("");
    out.push(`**Role:** ${root.role}`);
    out.push("");
    if (root.fileCount != null) out.push(`- **Files:** ${root.fileCount.toLocaleString()}`);
    if (root.ownIndex) out.push(`- **Own index:** ${root.ownIndex}`);
    if (root.consolidatedInto) out.push(`- **Consolidated into:** ${root.consolidatedInto}`);
    out.push("");
    out.push("| Top-level folder | Purpose |");
    out.push("|---|---|");
    const cellSafe = (x) => String(x).replace(/\r?\n/g, " ").replace(/\|/g, "\\|");
    for (const [name, purpose] of Object.entries(root.topLevel)) {
      out.push(`| \`${cellSafe(name)}\` | ${cellSafe(purpose)} |`);
    }
    out.push("");
    if (Array.isArray(root.notableFiles) && root.notableFiles.length) {
      out.push("**Notable files:** " + root.notableFiles.map((f) => `\`${f}\``).join(" · "));
      out.push("");
    }
  }
  out.push("## Per-galaxy domain-relevant subfolders");
  out.push("");
  out.push("| Galaxy | Domain-relevant roots/subfolders (empty = uniform 3-root pointer only) |");
  out.push("|---|---|");
  for (const [g, hints] of Object.entries(registry.galaxyHints)) {
    if (g === "_comment") continue;
    const cell = Array.isArray(hints) && hints.length ? hints.map((h) => `\`${h}\``).join(" · ") : "_(infra/meta — uniform 3-root pointer)_";
    out.push(`| **${g}** | ${cell} |`);
  }
  out.push("");
  return out.join("\n");
}

/** Discover galaxy dirs (those containing a PATHS.md) under mcp-server/src/engines/. */
export function discoverGalaxies(enginesDir) {
  if (!fs.existsSync(enginesDir)) return [];
  return fs
    .readdirSync(enginesDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .filter((name) => fs.existsSync(path.join(enginesDir, name, "PATHS.md")))
    .sort();
}

function main() {
  const check = process.argv.includes("--check");
  if (!fs.existsSync(REGISTRY)) {
    console.error(`[wire-resource-roots] FATAL: registry not found: ${REGISTRY}`);
    process.exit(1);
  }
  const registry = JSON.parse(fs.readFileSync(REGISTRY, "utf-8"));
  const galaxies = discoverGalaxies(ENGINES_DIR);

  let changed = 0;
  let unchanged = 0;
  const wired = [];
  for (const g of galaxies) {
    const p = path.join(ENGINES_DIR, g, "PATHS.md");
    const before = fs.readFileSync(p, "utf-8");
    const block = buildGalaxyBlock(g, registry);
    const after = spliceSection(before, block);
    const hadSection = before.includes(BEGIN);
    if (after !== before) {
      if (!check) fs.writeFileSync(p, after);
      changed++;
      wired.push(`${hadSection ? "updated" : "wired  "} ${g}`);
    } else {
      unchanged++;
      wired.push(`ok     ${g}`);
    }
  }

  // Atlas
  const atlasMd = renderAtlasMarkdown(registry);
  const atlasBefore = fs.existsSync(ATLAS) ? fs.readFileSync(ATLAS, "utf-8") : "";
  const atlasChanged = atlasBefore !== atlasMd;
  if (atlasChanged && !check) fs.writeFileSync(ATLAS, atlasMd);

  console.log(`[wire-resource-roots] ${check ? "CHECK (no writes)" : "APPLIED"}`);
  console.log(`  galaxies discovered : ${galaxies.length}`);
  console.log(`  PATHS.md changed    : ${changed}`);
  console.log(`  PATHS.md unchanged  : ${unchanged}`);
  console.log(`  atlas .md           : ${atlasChanged ? (check ? "would update" : "updated") : "unchanged"}`);
  for (const w of wired) console.log(`    ${w}`);
  if (galaxies.length === 0) {
    console.error("[wire-resource-roots] WARN: zero galaxies discovered — check ENGINES_DIR");
    process.exit(1);
  }
  // --check is a freshness gate: non-zero exit when wiring is stale (usable in CI / pre-commit).
  if (check && (changed > 0 || atlasChanged)) {
    console.error("[wire-resource-roots] --check: wiring STALE (changes pending) — run without --check to apply.");
    process.exit(2);
  }
}

// Run only when invoked directly (not when imported by the test).
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
