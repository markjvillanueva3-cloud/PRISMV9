/**
 * HyperCADSAutomationEngine — hyperCAD-S CAD API Automation via AC Python Scripts (E1160)
 *
 * Generates hyperMILL Automation Center (AC) Python scripts for CAD operations:
 *   - import: STEP/IGES/DXF file import with coordinate system setup
 *   - heal: Geometry healing, normal alignment, stitch open edges
 *   - analyze: Draft angle, undercut, and wall thickness analysis
 *
 * All output is AC Python script strings executable by hyperMILL Automation Center.
 * No USB key required for script generation (mock layer handles execution in CI).
 *
 * Pattern: same AC Python generation pattern as HyperMillCodeGeneratorEngine (E1120).
 *
 * @engine HyperCADSAutomationEngine
 * @shortcode E1160
 * @dispatcher camDispatcher
 * @actions cam_hyperCADS_import, cam_hyperCADS_heal, cam_hyperCADS_analyze, cam_hyperCADS_automate
 * @milestone HM-REV-MS0 / U-HMR01
 */

// ─── Types ────────────────────────────────────────────────────────────────────

/** Supported CAD file formats for import */
export type CADFileFormat = "STEP" | "IGES" | "DXF" | "STL" | "PARASOLID";

/** Coordinate system orientation for import */
export interface CoordinateSystemSetup {
  /** X-axis vector [x, y, z] */
  x_axis?: [number, number, number];
  /** Y-axis vector [x, y, z] */
  y_axis?: [number, number, number];
  /** Origin offset [x, y, z] in mm */
  origin_offset?: [number, number, number];
}

/** Import operation parameters */
export interface CADSImportParams {
  /** Absolute path to the CAD file */
  file_path: string;
  /** File format (auto-detected from extension if omitted) */
  format?: CADFileFormat;
  /** Import tolerance in mm (default 0.01) */
  tolerance_mm?: number;
  /** Coordinate system setup */
  coordinate_system?: CoordinateSystemSetup;
  /** Assign imported body as workpiece in hyperCAD-S */
  set_as_workpiece?: boolean;
  /** Part name for the imported body */
  part_name?: string;
}

/** Heal operation parameters */
export interface CADSHealParams {
  /** Part body name to heal (defaults to active body) */
  body_name?: string;
  /** Stitching tolerance in mm (default 0.01) */
  stitch_tolerance_mm?: number;
  /** Healing tolerance in mm (default 0.05) */
  heal_tolerance_mm?: number;
  /** Align normals outward */
  align_normals?: boolean;
  /** Remove duplicate surfaces */
  remove_duplicates?: boolean;
  /** Fill small holes (diameter < fill_holes_diameter_mm) */
  fill_holes_diameter_mm?: number;
}

/** Analyze operation parameters */
export interface CADSAnalyzeParams {
  /** Part body name to analyze (defaults to active body) */
  body_name?: string;
  /** Draft analysis: minimum draft angle threshold in degrees */
  draft_angle_deg?: number;
  /** Undercut detection enabled */
  detect_undercuts?: boolean;
  /** Wall thickness analysis: minimum acceptable thickness in mm */
  min_wall_thickness_mm?: number;
  /** Analysis tool direction vector [x, y, z] */
  tool_direction?: [number, number, number];
}

/** Full automation sequence parameters */
export interface CADSAutomateParams {
  /** Import parameters */
  import_params: CADSImportParams;
  /** Heal after import */
  heal?: boolean;
  /** Heal parameters (used if heal=true) */
  heal_params?: CADSHealParams;
  /** Analyze after heal */
  analyze?: boolean;
  /** Analyze parameters (used if analyze=true) */
  analyze_params?: CADSAnalyzeParams;
}

/** Result for any CAD script generation */
export interface CADSScriptResult {
  /** Generated AC Python script text */
  script: string;
  /** Number of lines in the script */
  line_count: number;
  /** Operations performed */
  operations: string[];
  /** Warnings */
  warnings: string[];
  /** Mock mode flag */
  mock_mode: boolean;
}

// ─── File Format Detection ───────────────────────────────────────────────────

const FORMAT_MAP: Record<string, CADFileFormat> = {
  ".stp": "STEP",
  ".step": "STEP",
  ".igs": "IGES",
  ".iges": "IGES",
  ".dxf": "DXF",
  ".stl": "STL",
  ".x_t": "PARASOLID",
  ".x_b": "PARASOLID",
};

function detectFormat(filePath: string): CADFileFormat {
  const ext = filePath.toLowerCase().match(/\.[^.]+$/)?.[0] ?? "";
  return FORMAT_MAP[ext] ?? "STEP";
}

// ─── AC Python Script Builders ────────────────────────────────────────────────

/**
 * Build AC Python script header.
 * Matches pattern from HyperMillCodeGeneratorEngine.
 */
function buildScriptHeader(description: string): string[] {
  return [
    "# hyperCAD-S Automation Center Script",
    `# Generated by PRISM HyperCADSAutomationEngine (E1160)`,
    `# Operation: ${description}`,
    "# hyperMILL v33.0 / hyperCAD-S 2024",
    "",
    "import hm",
    "import os",
    "",
  ];
}

/**
 * Build AC Python import block for STEP/IGES/DXF.
 * Reference: hyperMILL Automation Center API v33 — hm.ImportCadFile()
 */
function buildImportBlock(p: CADSImportParams): string[] {
  const format = p.format ?? detectFormat(p.file_path);
  const tolerance = p.tolerance_mm ?? 0.01;
  const partName = p.part_name ?? "imported_part";
  const lines: string[] = [
    `# --- STEP 1: Import CAD file ---`,
    `cad_file = r"${p.file_path}"`,
    `if not os.path.isfile(cad_file):`,
    `    raise FileNotFoundError(f"CAD file not found: {cad_file}")`,
    "",
    `# Format: ${format}, Tolerance: ${tolerance}mm`,
    `import_result = hm.ImportCadFile(`,
    `    FileName=cad_file,`,
    `    Format="${format}",`,
    `    Tolerance=${tolerance},`,
    `    PartName="${partName}",`,
    `)`,
    `if import_result is None:`,
    `    raise RuntimeError("ImportCadFile returned None — check file format and path")`,
    "",
  ];

  if (p.coordinate_system) {
    const cs = p.coordinate_system;
    if (cs.origin_offset) {
      lines.push(
        `# Coordinate system offset`,
        `hm.SetCoordinateSystemOffset(`,
        `    X=${cs.origin_offset[0]},`,
        `    Y=${cs.origin_offset[1]},`,
        `    Z=${cs.origin_offset[2]},`,
        `)`,
        "",
      );
    }
    if (cs.x_axis && cs.y_axis) {
      lines.push(
        `# Coordinate system orientation`,
        `hm.SetCoordinateSystemAxes(`,
        `    XAxis=(${cs.x_axis.join(", ")}),`,
        `    YAxis=(${cs.y_axis.join(", ")}),`,
        `)`,
        "",
      );
    }
  }

  if (p.set_as_workpiece) {
    lines.push(
      `# Set imported body as hyperCAD-S workpiece`,
      `hm.SetWorkpiece(PartName="${partName}")`,
      `print(f"[PRISM] Workpiece set to: ${partName}")`,
      "",
    );
  }

  lines.push(`print(f"[PRISM] Import complete: ${partName} ({format})")`);
  return lines;
}

/**
 * Build AC Python heal block.
 * Reference: hyperMILL AC API v33 — hm.HealGeometry(), hm.StitchSurfaces()
 */
function buildHealBlock(p: CADSHealParams): string[] {
  const bodyName = p.body_name ?? "imported_part";
  const stitchTol = p.stitch_tolerance_mm ?? 0.01;
  const healTol = p.heal_tolerance_mm ?? 0.05;
  const alignNormals = p.align_normals ?? true;
  const removeDupes = p.remove_duplicates ?? true;

  const lines: string[] = [
    `# --- STEP 2: Heal geometry ---`,
    `hm.SelectBody(Name="${bodyName}")`,
    "",
    `# Stitch open edges (tolerance: ${stitchTol}mm)`,
    `stitch_result = hm.StitchSurfaces(`,
    `    BodyName="${bodyName}",`,
    `    Tolerance=${stitchTol},`,
    `)`,
    `print(f"[PRISM] Stitched edges: {stitch_result.get('edges_stitched', 0)}")`,
    "",
    `# Full geometry healing (tolerance: ${healTol}mm)`,
    `heal_result = hm.HealGeometry(`,
    `    BodyName="${bodyName}",`,
    `    Tolerance=${healTol},`,
    `    AlignNormals=${alignNormals ? "True" : "False"},`,
    `    RemoveDuplicates=${removeDupes ? "True" : "False"},`,
    `)`,
    `print(f"[PRISM] Heal status: {heal_result.get('status', 'unknown')}")`,
    `print(f"[PRISM] Faces healed: {heal_result.get('faces_healed', 0)}")`,
    "",
  ];

  if (p.fill_holes_diameter_mm && p.fill_holes_diameter_mm > 0) {
    lines.push(
      `# Fill small holes (max diameter: ${p.fill_holes_diameter_mm}mm)`,
      `hm.FillSmallHoles(`,
      `    BodyName="${bodyName}",`,
      `    MaxDiameter=${p.fill_holes_diameter_mm},`,
      `)`,
      "",
    );
  }

  lines.push(`print("[PRISM] Geometry healing complete")`);
  return lines;
}

/**
 * Build AC Python analyze block.
 * Reference: hyperMILL AC API v33 — hm.AnalyzeDraftAngle(), hm.AnalyzeWallThickness()
 */
function buildAnalyzeBlock(p: CADSAnalyzeParams): string[] {
  const bodyName = p.body_name ?? "imported_part";
  const draftAngle = p.draft_angle_deg ?? 3.0;
  const minWall = p.min_wall_thickness_mm ?? 1.0;
  const toolDir = p.tool_direction ?? [0, 0, 1];

  const lines: string[] = [
    `# --- STEP 3: Feature analysis ---`,
    `hm.SelectBody(Name="${bodyName}")`,
    "",
    `# Draft angle analysis (threshold: ${draftAngle}°)`,
    `draft_result = hm.AnalyzeDraftAngle(`,
    `    BodyName="${bodyName}",`,
    `    ToolDirection=(${toolDir.join(", ")}),`,
    `    MinDraftAngle=${draftAngle},`,
    `)`,
    `print(f"[PRISM] Faces with draft >= ${draftAngle}°: {draft_result.get('ok_faces', 0)}")`,
    `print(f"[PRISM] Faces with insufficient draft: {draft_result.get('problem_faces', 0)}")`,
    "",
  ];

  if (p.detect_undercuts) {
    lines.push(
      `# Undercut detection`,
      `undercut_result = hm.AnalyzeUndercuts(`,
      `    BodyName="${bodyName}",`,
      `    ToolDirection=(${toolDir.join(", ")}),`,
      `)`,
      `print(f"[PRISM] Undercut regions found: {undercut_result.get('undercut_count', 0)}")`,
      "",
    );
  }

  lines.push(
    `# Wall thickness analysis (min: ${minWall}mm)`,
    `thickness_result = hm.AnalyzeWallThickness(`,
    `    BodyName="${bodyName}",`,
    `    MinThickness=${minWall},`,
    `)`,
    `print(f"[PRISM] Thin-wall regions: {thickness_result.get('thin_wall_count', 0)}")`,
    `print(f"[PRISM] Min thickness found: {thickness_result.get('min_thickness_mm', 0):.3f}mm")`,
    "",
    `print("[PRISM] Feature analysis complete")`,
  );

  return lines;
}

// ─── Engine Class ──────────────────────────────────────────────────────────────

/**
 * HyperCADSAutomationEngine — generates AC Python scripts for CAD API operations.
 *
 * Works WITHOUT a hyperCAD-S USB key (script generation only).
 * Use HyperCADSMockLayer for simulated execution results in CI.
 */
export class HyperCADSAutomationEngine {
  private scriptCount = 0;

  /**
   * Generate an AC Python import script for a STEP/IGES/DXF file.
   *
   * @param params - Import parameters (file path, format, tolerance, WCS)
   * @returns CADSScriptResult with complete Python script string
   */
  generateImportScript(params: CADSImportParams): CADSScriptResult {
    this.scriptCount++;
    const warnings: string[] = [];
    const format = params.format ?? detectFormat(params.file_path);

    if (!params.file_path || params.file_path.trim() === "") {
      warnings.push("file_path is empty — script will fail at runtime");
    }
    if (!params.file_path.toLowerCase().endsWith(".stp") &&
        !params.file_path.toLowerCase().endsWith(".step") &&
        !params.file_path.toLowerCase().endsWith(".igs") &&
        !params.file_path.toLowerCase().endsWith(".iges") &&
        !params.file_path.toLowerCase().endsWith(".dxf")) {
      warnings.push(`Unusual file extension for format ${format} — verify manually`);
    }

    const lines = [
      ...buildScriptHeader(`Import ${format} file`),
      ...buildImportBlock(params),
    ];

    const script = lines.join("\n");
    return {
      script,
      line_count: lines.length,
      operations: ["hyperCADS_import"],
      warnings,
      mock_mode: process.env["HYPERMILL_MOCK"] === "true",
    };
  }

  /**
   * Generate an AC Python geometry healing script.
   *
   * @param params - Heal parameters (tolerances, normal alignment, hole fill)
   * @returns CADSScriptResult with complete Python script string
   */
  generateHealScript(params: CADSHealParams): CADSScriptResult {
    this.scriptCount++;
    const warnings: string[] = [];

    if ((params.stitch_tolerance_mm ?? 0.01) > 0.5) {
      warnings.push("stitch_tolerance_mm > 0.5mm may merge distinct edges — verify");
    }

    const lines = [
      ...buildScriptHeader("Geometry Healing"),
      ...buildHealBlock(params),
    ];

    const script = lines.join("\n");
    return {
      script,
      line_count: lines.length,
      operations: ["hyperCADS_heal"],
      warnings,
      mock_mode: process.env["HYPERMILL_MOCK"] === "true",
    };
  }

  /**
   * Generate an AC Python feature analysis script (draft, undercut, wall thickness).
   *
   * @param params - Analysis parameters (thresholds, tool direction)
   * @returns CADSScriptResult with complete Python script string
   */
  generateAnalyzeScript(params: CADSAnalyzeParams): CADSScriptResult {
    this.scriptCount++;
    const warnings: string[] = [];

    if ((params.draft_angle_deg ?? 3.0) < 0.5) {
      warnings.push("draft_angle_deg < 0.5° is very tight — most machined features require >= 1°");
    }

    const lines = [
      ...buildScriptHeader("Feature Analysis"),
      ...buildAnalyzeBlock(params),
    ];

    const script = lines.join("\n");
    return {
      script,
      line_count: lines.length,
      operations: ["hyperCADS_analyze"],
      warnings,
      mock_mode: process.env["HYPERMILL_MOCK"] === "true",
    };
  }

  /**
   * Generate a complete automation sequence: import → heal → analyze.
   *
   * @param params - Full automation parameters
   * @returns CADSScriptResult combining all operations
   */
  generateAutomationScript(params: CADSAutomateParams): CADSScriptResult {
    this.scriptCount++;
    const warnings: string[] = [];
    const operations: string[] = ["hyperCADS_import"];

    const lines: string[] = [
      ...buildScriptHeader("Full CAD Automation Sequence: Import → Heal → Analyze"),
      ...buildImportBlock(params.import_params),
    ];

    if (params.heal ?? true) {
      const healParams = params.heal_params ?? {};
      if (!healParams.body_name) {
        healParams.body_name = params.import_params.part_name ?? "imported_part";
      }
      lines.push(...buildHealBlock(healParams));
      operations.push("hyperCADS_heal");
    }

    if (params.analyze) {
      const analyzeParams = params.analyze_params ?? {};
      if (!analyzeParams.body_name) {
        analyzeParams.body_name = params.import_params.part_name ?? "imported_part";
      }
      lines.push(...buildAnalyzeBlock(analyzeParams));
      operations.push("hyperCADS_analyze");
    }

    lines.push(
      "",
      `print("[PRISM] CAD automation sequence complete")`,
      `print(f"[PRISM] Operations: ${operations.join(', ')}")`,
    );

    const script = lines.join("\n");
    return {
      script,
      line_count: lines.length,
      operations,
      warnings,
      mock_mode: process.env["HYPERMILL_MOCK"] === "true",
    };
  }

  /** Return script generation count (for diagnostics) */
  getScriptCount(): number {
    return this.scriptCount;
  }
}

/** Singleton export — use this in the dispatcher */
export const hyperCADSAutomationEngine = new HyperCADSAutomationEngine();
