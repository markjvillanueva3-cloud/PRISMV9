/**
 * Fusion360CodeGeneratorEngine — U-CADC13 (CAD-COMPLETE-MS0)
 *
 * Fusion 360 Python code generator extending UnifiedCADCodeGeneratorBase.
 * Emits Python code targeting Autodesk Fusion 360's Python API (adsk.*).
 *
 * Design:
 *   - Full ICADCodeGenerator contract with fusion360 CADSystemId
 *   - Emits Python using adsk.core, adsk.fusion, adsk.cam modules
 *   - Geometry via adsk.fusion.Sketch (SketchLines, SketchCircles, etc.)
 *   - Operations via adsk.fusion.Features (ExtrudeFeature, RevolveFeature, etc.)
 *   - Injectable execution path (Fusion 360 add-in HTTP bridge or mock for CI)
 *
 * Unit conversion:
 *   Fusion 360 internal units are cm. When user specifies mm, we multiply by 0.1.
 *   When user specifies inches, we multiply by 2.54.
 *
 * Fusion 360 API references:
 *   - Autodesk Fusion 360 API Reference (https://help.autodesk.com/view/fusion360/ENU/)
 *   - adsk.core, adsk.fusion, adsk.cam Python modules
 *
 * @module engines/Fusion360CodeGeneratorEngine
 * @milestone CAD-COMPLETE-MS0
 */

