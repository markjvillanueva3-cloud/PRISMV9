  /**
   * Validate a generated Fusion 360 script for structural correctness +
   * common authoring mistakes (missing run(), unconverted mm, missing
   * imports).
   */
  validateScript(script: string): { valid: boolean; issues: string[] } {
    const issues: string[] = [];
    if (!script.includes("def run(context):")) {
      issues.push("Missing run(context) function entry point");
    }
    if (!/import\s+adsk/.test(script)) {
      issues.push("Missing 'import adsk' — Fusion API not loaded");
    }
    // Heuristic: createByReal(N) where N >= 100 almost certainly is raw mm
    // (Fusion is internal cm — even a 1m part would be 100cm and exceptional).
    const re = /createByReal\(\s*(-?\d+(?:\.\d+)?)\s*\)/g;
    let m: RegExpExecArray | null;
    while ((m = re.exec(script)) !== null) {
      const v = Math.abs(Number(m[1]));
      if (v >= 100) {
        issues.push(
          `createByReal(${m[1]}) — value too large for cm; likely unconverted mm`,
        );
        break;
      }
    }
    return { valid: issues.length === 0, issues };
  }

