  protected async runScriptBody(
    script: { body: string; cadSystem: CADSystemId },
  ): Promise<CADExecutionResult> {
    const isMock = process.env.PRISM_CAD_MOCK === "true" || process.env.CI === "true";

    if (isMock) {
      log.debug("Fusion360CodeGeneratorEngine: mock execution mode");
      return {
        ok: true,
        output: "Mock Fusion 360 execution completed",
        durationMs: Math.floor(Math.random() * 100) + 50,
        metrics: {
          faceCount: Math.floor(Math.random() * 20) + 6,
          edgeCount: Math.floor(Math.random() * 40) + 12,
          bodyCount: 1,
          volumeMm3: Math.random() * 50000 + 1000,
        },
      };
    }

    log.info("Fusion360CodeGeneratorEngine: real execution via HTTP bridge");
    return {
      ok: false,
      error: "Real Fusion 360 execution requires HTTP add-in bridge (not configured)",
      durationMs: 0,
    };
  }
