  // ── Legacy ExtractedAction → Fusion 360 Python script API ────────────────
  //
  // These methods are the production callers' contract (cadDispatcher.ts
  // f360_generate_script / f360_from_description / f360_parametric_script /
  // f360_convert_cadquery). They emit Python directly without going through
  // the typed CADOperation pipeline because the legacy contract requires a
  // specific shape that predates UnifiedCADCodeGeneratorBase.

  /**
   * Generate a Fusion 360 Python script from an ExtractedAction sequence.
   * Used by tutorial-replay pipelines + f360_generate_script MCP action.
   */
  generateScript(
    actions: ExtractedAction[],
    options?: { component_name?: string; parametric?: boolean },
  ): Fusion360Script {
    const componentName = options?.component_name ?? "PRISM_Generated";
    const parametric = options?.parametric ?? false;
    const operations: string[] = [];
    const lines: string[] = [];

    lines.push("# AUTO-GENERATED by PRISM Fusion360CodeGeneratorEngine");
    lines.push(`# Component: ${componentName}`);
    lines.push("# Units: mm (converted to cm internally for Fusion 360)");
    lines.push("");
    lines.push("import adsk.core, adsk.fusion, traceback");
    lines.push("import math");
    lines.push("");
    lines.push("def select_edges_by_direction(body, direction='all'):");
    lines.push('    """Helper: collect edges from a body matching a direction tag."""');
    lines.push("    edges = adsk.core.ObjectCollection.create()");
    lines.push("    for edge in body.edges:");
    lines.push("        edges.add(edge)");
    lines.push("    return edges");
    lines.push("");

    let parameterCount = 0;
    const params = parametric ? this.extractParameters(actions) : [];

    if (parametric && params.length > 0) {
      lines.push("# === Parameters ===");
      for (const p of params) {
        lines.push(`${p.name} = ${p.value}  # ${p.unit ?? "mm"}`);
        parameterCount++;
      }
      lines.push("");
    }

    lines.push("def run(context):");
    lines.push("    ui = None");
    lines.push("    try:");
    lines.push("        app = adsk.core.Application.get()");
    lines.push("        ui = app.userInterface");
    lines.push("        design = adsk.fusion.Design.cast(app.activeProduct)");
    lines.push("        if not design:");
    lines.push("            if ui: ui.messageBox('No active Fusion design')");
    lines.push("            return");
    lines.push("        rootComp = design.rootComponent");
    lines.push("        bodies = []  # track created bodies for downstream ops");
    lines.push("");

    if (parametric && params.length > 0) {
      for (const p of params) {
        lines.push(
          `        design.userParameters.add('${p.name}', adsk.core.ValueInput.createByReal(${(p.value / 10).toString()}), '${p.unit ?? "mm"}', '')`,
        );
      }
      lines.push("");
    }

    for (const a of actions) {
      operations.push(a.action_type);
      const desc = (a.description || a.action_type).replace(/\n/g, " ");
      lines.push(`        # Step ${a.step_number}: ${desc}`);
      for (const ol of this.emitLegacyAction(a)) {
        lines.push(`        ${ol}`);
      }
      lines.push("");
    }

    lines.push(`        ui.messageBox('${componentName} created successfully!')`);
    lines.push("    except:");
    lines.push("        if ui:");
    lines.push("            ui.messageBox('Failed:\\n{}'.format(traceback.format_exc()))");

    return {
      script: lines.join("\n"),
      operations,
      parameter_count: parameterCount,
      script_name: `${componentName}.py`,
      estimated_complexity: this.estimateComplexity(actions),
    };
  }

