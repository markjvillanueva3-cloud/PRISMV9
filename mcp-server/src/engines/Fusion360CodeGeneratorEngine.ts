  // ── Export/Import helpers ────────────────────────────────────────────────

  private emitExport(args: Record<string, unknown>, emitter: CADEmitter, format: string): void {
    const filename = String(args.filename ?? `output.${format.toLowerCase()}`);

    emitter.line(`# Export to ${format}`);
    emitter.line("exportMgr = design.exportManager");

    switch (format) {
      case "STEP":
        emitter.line(`stepOptions = exportMgr.createSTEPExportOptions('${filename}')`);
        emitter.line("exportMgr.execute(stepOptions)");
        break;
      case "STL":
        emitter.line(`stlOptions = exportMgr.createSTLExportOptions(rootComp.bRepBodies.item(0), '${filename}')`);
        emitter.line("stlOptions.meshRefinement = adsk.fusion.MeshRefinementSettings.MeshRefinementMedium");
        emitter.line("exportMgr.execute(stlOptions)");
        break;
      case "DXF":
        emitter.line(`# DXF export from sketch`);
        emitter.line(`# sketch.saveAsDXF('${filename}')`);
        break;
      case "IGES":
        emitter.line(`igesOptions = exportMgr.createIGESExportOptions('${filename}')`);
        emitter.line("exportMgr.execute(igesOptions)");
        break;
      case "F3D":
        emitter.line(`fusionOptions = exportMgr.createFusionArchiveExportOptions('${filename}')`);
        emitter.line("exportMgr.execute(fusionOptions)");
        break;
    }
    emitter.parameter("export_filename", filename, "path", `${format} export path`);
  }

