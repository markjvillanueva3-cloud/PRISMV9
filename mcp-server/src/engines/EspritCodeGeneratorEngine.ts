/**
 * EspritCodeGeneratorEngine — DP Technology Esprit VB script generator
 * (CAD-COMPLETE-MS0/U-CADC-ESP-CODEGEN-01)
 *
 * Emits VB.NET-flavoured macros targeting Esprit's COM automation API
 * (`Esprit.Application`, `EspritDoc`, `Geometry.Create*`) so PRISM can drive
 * the Esprit CAM environment to construct sketch wireframes + extruded solids
 * from CADOperation streams.
 *
 * Note: Esprit's primary surface is CAM, but it ships with a parametric
 * geometry engine accessible via the same COM API used by `EspritCAMBridgeEngine`
 * for project introspection. This generator targets the *forward* direction —
 * synthesizing geometry/features in Esprit from PRISM-canonical operations.
 *
 * @module engines/EspritCodeGeneratorEngine
 * @milestone CAD-COMPLETE-MS0
 */

import {
  UnifiedCADCodeGeneratorBase,
  type CADEmitter,
} from "./UnifiedCADCodeGeneratorBase.js";
import type {
  CADCapabilityMatrix,
  CADExecutionResult,
  CADOperation,
  CADOperationKind,
  CADScript,
  CADSystemId,
} from "../interfaces/ICADCodeGenerator.js";

// ── Esprit-specific context ──────────────────────────────────────────────────

export interface EspritGenerationContext {
  projectName: string;
  units: "mm" | "in";
  outputDir?: string;
  targetVersion?: "2023" | "2024" | "2025";
  documentTemplate?: string;
}

// ── Supported operations ─────────────────────────────────────────────────────

const ESPRIT_SUPPORTED_OPS: ReadonlyArray<CADOperationKind> = [
  "sketch_create",
  "sketch_close",
  "sketch_line",
  "sketch_arc",
  "sketch_circle",
  "sketch_rectangle",
  "sketch_polygon",
  "sketch_point",
  "feature_extrude",
  "feature_revolve",
  "feature_hole",
  "feature_pocket",
  "feature_fillet",
  "feature_chamfer",
  "boolean_union",
  "boolean_subtract",
  "boolean_intersect",
  "import_step",
  "import_iges",
  "export_step",
  "export_iges",
  "parameter_declare",
  "custom",
];

// ── Engine ───────────────────────────────────────────────────────────────────

export class EspritCodeGeneratorEngine extends UnifiedCADCodeGeneratorBase<EspritGenerationContext> {
  readonly cadSystem: CADSystemId = "esprit";

  readonly capabilities: CADCapabilityMatrix = {
    cadSystem: this.cadSystem,
    supportedOps: new Set(ESPRIT_SUPPORTED_OPS),
    nativeLengthUnit: "mm",
    nativeAngleUnit: "deg",
    requiresSubprocess: true,
    typicalLatencyMs: 800,
    version: "2024",
  };

  private entityCounter = 0;

  protected preamble(ctx: EspritGenerationContext | undefined, emitter: CADEmitter): void {
    this.entityCounter = 0;
    const projectName = ctx?.projectName ?? "PRISM_EspritPart";
    const units = ctx?.units ?? "mm";

    emitter.line("' ═══════════════════════════════════════════════════════════════");
    emitter.line("' AUTO-GENERATED by PRISM EspritCodeGeneratorEngine");
    emitter.line(`' Project: ${projectName}`);
    emitter.line(`' Units: ${units}`);
    emitter.line(`' Target: Esprit ${ctx?.targetVersion ?? "2024"}`);
    emitter.line("' ═══════════════════════════════════════════════════════════════");
    emitter.line("");
    emitter.line("Imports DPTechnology.Esprit");
    emitter.line("");
    emitter.line("Sub Main()");
    emitter.indent = "    ";
    emitter.line("Dim oApp As Object = CreateObject(\"Esprit.Application\")");
    emitter.line("oApp.Visible = True");
    emitter.line("Dim oDoc As Object = oApp.Documents.Add()");
    emitter.line("Dim oGeo As Object = oDoc.GeometryManager");
    emitter.line("Dim oSolids As Object = oDoc.SolidsManager");
    emitter.line("Dim oFeatures As Object = oDoc.FeatureManager");
    emitter.line("");

    const unitFactor = units === "in" ? 25.4 : 1.0; // Esprit native = mm
    emitter.parameter("UNIT_FACTOR", unitFactor, units, "Conversion to mm (Esprit internal)");
    emitter.line(`Dim UNIT_FACTOR As Double = ${unitFactor}  ' ${units} → mm`);
    emitter.line("");
  }

  protected emitOp(
    op: CADOperation,
    opIndex: number,
    _ctx: EspritGenerationContext | undefined,
    emitter: CADEmitter,
  ): void {
    emitter.line(`' ── Op ${opIndex}: ${op.kind} ──`);
    const args = op.args ?? {};
    switch (op.kind) {
      case "sketch_create": {
        const plane = String(args.plane ?? "XY").toUpperCase();
        emitter.line(`Dim oSketch As Object = oGeo.CreateSketch("${plane}")`);
        emitter.parameter("sketch_plane", plane, "plane", "Sketch plane");
        break;
      }
      case "sketch_close":
        emitter.line("oGeo.CloseChain()");
        break;
      case "sketch_line": {
        const x1 = Number(args.x1 ?? 0);
        const y1 = Number(args.y1 ?? 0);
        const x2 = Number(args.x2 ?? 10);
        const y2 = Number(args.y2 ?? 0);
        const v = `line_${this.entityCounter++}`;
        emitter.line(
          `Dim ${v} As Object = oGeo.CreateLine(${x1} * UNIT_FACTOR, ${y1} * UNIT_FACTOR, ${x2} * UNIT_FACTOR, ${y2} * UNIT_FACTOR)`,
        );
        emitter.parameter(
          `${v}_length`,
          Math.sqrt((x2 - x1) ** 2 + (y2 - y1) ** 2),
          "mm",
          "Line length",
        );
        break;
      }
      case "sketch_arc": {
        const cx = Number(args.centerX ?? 0);
        const cy = Number(args.centerY ?? 0);
        const r = Number(args.radius ?? 10);
        const start = Number(args.startAngle ?? 0);
        const end = Number(args.endAngle ?? 90);
        const v = `arc_${this.entityCounter++}`;
        emitter.line(
          `Dim ${v} As Object = oGeo.CreateArc(${cx} * UNIT_FACTOR, ${cy} * UNIT_FACTOR, ${r} * UNIT_FACTOR, ${start}, ${end})`,
        );
        emitter.parameter(`${v}_radius`, r, "mm", "Arc radius");
        break;
      }
      case "sketch_circle": {
        const cx = Number(args.centerX ?? 0);
        const cy = Number(args.centerY ?? 0);
        const r = Number(args.radius ?? 10);
        const v = `circle_${this.entityCounter++}`;
        emitter.line(
          `Dim ${v} As Object = oGeo.CreateCircle(${cx} * UNIT_FACTOR, ${cy} * UNIT_FACTOR, ${r} * UNIT_FACTOR)`,
        );
        emitter.parameter(`${v}_radius`, r, "mm", "Circle radius");
        break;
      }
      case "sketch_rectangle": {
        const x = Number(args.x ?? 0);
        const y = Number(args.y ?? 0);
        const w = Number(args.width ?? 10);
        const h = Number(args.height ?? 10);
        const v = `rect_${this.entityCounter++}`;
        emitter.line(
          `Dim ${v} As Object = oGeo.CreateRectangle(${x} * UNIT_FACTOR, ${y} * UNIT_FACTOR, ${w} * UNIT_FACTOR, ${h} * UNIT_FACTOR)`,
        );
        emitter.parameter(`${v}_width`, w, "mm", "Rectangle width");
        emitter.parameter(`${v}_height`, h, "mm", "Rectangle height");
        break;
      }
      case "sketch_polygon": {
        const cx = Number(args.centerX ?? 0);
        const cy = Number(args.centerY ?? 0);
        const r = Number(args.radius ?? 10);
        const sides = Number(args.sides ?? 6);
        emitter.line(
          `oGeo.CreatePolygon(${cx} * UNIT_FACTOR, ${cy} * UNIT_FACTOR, ${r} * UNIT_FACTOR, ${sides})`,
        );
        break;
      }
      case "sketch_point": {
        const x = Number(args.x ?? 0);
        const y = Number(args.y ?? 0);
        emitter.line(`oGeo.CreatePoint(${x} * UNIT_FACTOR, ${y} * UNIT_FACTOR)`);
        break;
      }
      case "feature_extrude": {
        const depth = Number(args.depth ?? 10);
        const direction = String(args.direction ?? "positive");
        const operation = String(args.operation ?? "new_body");
        const sign = direction === "negative" ? "-" : "";
        const espritOp =
          operation === "cut" ? "Cut" : operation === "join" ? "Add" : "NewBody";
        emitter.line(`oFeatures.Extrude(${sign}${depth} * UNIT_FACTOR, "${espritOp}")`);
        emitter.parameter("extrude_depth", depth, "mm", "Extrude depth");
        break;
      }
      case "feature_revolve": {
        const angle = Number(args.angle ?? 360);
        emitter.line(`oFeatures.Revolve(${angle})`);
        emitter.parameter("revolve_angle", angle, "deg", "Revolve angle");
        break;
      }
      case "feature_hole": {
        const x = Number(args.x ?? 0);
        const y = Number(args.y ?? 0);
        const dia = Number(args.diameter ?? 5);
        const depth = Number(args.depth ?? 10);
        emitter.line(
          `oFeatures.AddHole(${x} * UNIT_FACTOR, ${y} * UNIT_FACTOR, ${dia} * UNIT_FACTOR, ${depth} * UNIT_FACTOR)`,
        );
        break;
      }
      case "feature_pocket": {
        const depth = Number(args.depth ?? 5);
        emitter.line(`oFeatures.AddPocket(${depth} * UNIT_FACTOR)`);
        emitter.parameter("pocket_depth", depth, "mm", "Pocket depth");
        break;
      }
      case "feature_fillet": {
        const r = Number(args.radius ?? 1);
        emitter.line(`oFeatures.AddFillet(${r} * UNIT_FACTOR)`);
        emitter.parameter("fillet_radius", r, "mm", "Fillet radius");
        break;
      }
      case "feature_chamfer": {
        const d = Number(args.distance ?? 1);
        emitter.line(`oFeatures.AddChamfer(${d} * UNIT_FACTOR)`);
        emitter.parameter("chamfer_distance", d, "mm", "Chamfer distance");
        break;
      }
      case "boolean_union":
        emitter.line("oSolids.Union()");
        break;
      case "boolean_subtract":
        emitter.line("oSolids.Subtract()");
        break;
      case "boolean_intersect":
        emitter.line("oSolids.Intersect()");
        break;
      case "import_step":
      case "import_iges": {
        const file = String(args.path ?? args.file ?? "input.step");
        emitter.line(`oDoc.Import("${file}")`);
        break;
      }
      case "export_step":
      case "export_iges": {
        const file = String(args.path ?? args.file ?? "output.step");
        emitter.line(`oDoc.SaveAs("${file}")`);
        break;
      }
      case "parameter_declare": {
        const name = String(args.name ?? `param_${opIndex}`);
        const value = args.value ?? 0;
        emitter.line(`Dim ${name} As Double = ${value}`);
        emitter.parameter(name, value as number | string | boolean, String(args.unit ?? ""), "Parameter");
        break;
      }
      case "custom": {
        const code = String(args.code ?? args.script ?? "");
        if (code) emitter.block(code);
        break;
      }
      default: {
        emitter.warn(`Esprit emitter has no handler for ${op.kind}`, "warn");
        emitter.line(`' [unhandled] ${op.kind}`);
      }
    }
  }

  protected epilogue(ctx: EspritGenerationContext | undefined, emitter: CADEmitter): void {
    emitter.line("");
    emitter.line("oDoc.Save()");
    if (ctx?.outputDir) {
      emitter.line(`oDoc.SaveAs(\"${ctx.outputDir}/${ctx.projectName}.esp\")`);
    }
    emitter.indent = "";
    emitter.line("End Sub");
  }

  protected scriptFilename(ctx: EspritGenerationContext | undefined): string {
    const name = ctx?.projectName ?? "PRISM_EspritPart";
    return `${name}.esprit.vb`;
  }

  protected async runScriptBody(
    _script: CADScript<string>,
  ): Promise<CADExecutionResult> {
    // Esprit COM execution requires Windows + Esprit installed; mock for CI.
    return {
      ok: false,
      error: "Esprit COM execution not yet wired (mock — runScriptBody)",
      durationMs: 0,
    };
  }
}

export const espritCodeGeneratorEngine = new EspritCodeGeneratorEngine();
