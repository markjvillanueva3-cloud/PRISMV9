function countToolChanges(ops: SequenceOperation[]): number {
  let changes = 0;
  let lastTool: string | undefined;
  for (const o of ops) {
    if (o.tool_id && o.tool_id !== lastTool) {
      if (lastTool !== undefined) changes++;
      lastTool = o.tool_id;
    }
  }
  return changes;
}

function executeStrategy(
  operations: SequenceOperation[],
  candidate: SequencingCandidate,
): SequencingResult {
  const full = intelligentSequencingEngine.sequence(operations);

  if (candidate.strategy === "MINIMAL" || candidate.strategy === "TOOL_GROUPED") {
    const filtered = full.operations.filter(
      (o) => o.type !== "thermal_wait" && o.type !== "probing",
    );
    return {
      ...full,
      operations: filtered,
      thermal_gaps_inserted: 0,
      probe_points_inserted: 0,
      tool_changes: countToolChanges(filtered),
      rules_applied: full.rules_applied.filter(
        (r) => r !== "thermal_relaxation" && r !== "probe_insertion",
      ),
    };
  }

  if (candidate.strategy === "THERMAL_SAFE") {
    const ops: SequenceOperation[] = [];
    for (const o of full.operations) {
      ops.push(o);
      if (o.type === "thermal_wait") {
        ops.push({
          id: `${o.id}-dup`,
          type: "thermal_wait",
          operation: "thermal_stabilization_extended",
        });
      }
    }
    for (let i = ops.length - 1; i >= 0; i--) {
      if (ops[i].type === "probing" && i + 1 < ops.length) {
        const next = ops[i + 1];
        if (next.type !== "probing" && next.type !== "thermal_wait") {
          ops.splice(i + 1, 0, {
            id: `probe-extra-${i}`,
            type: "probing",
            operation: "verification_probe_extra",
          });
        }
      }
    }
    return {
      ...full,
      operations: ops,
      thermal_gaps_inserted: ops.filter((o) => o.type === "thermal_wait").length,
      probe_points_inserted: ops.filter((o) => o.type === "probing").length,
    };
  }

  if (candidate.strategy === "QUALITY") {
    const hasRough = full.operations.some((o) => o.type === "roughing");
    if (!hasRough) {
      return {
        ...full,
        probe_points_inserted: 0,
        operations: full.operations.filter((o) => o.type !== "probing"),
      };
    }
    return full;
  }

  return full;
}

function score(
  candidate: SequencingCandidate,
  result: SequencingResult,
  req: OrchestratedSequenceRequest,
): Record<string, number> {
  const originalChanges = countToolChanges(req.operations);
  const savings = Math.max(0, originalChanges - result.tool_changes);
  const savingsPct = originalChanges > 0 ? savings / originalChanges : 0;

  const qualityNorm = result.sequence_quality_score / 100;

  const perf = Math.max(
    0,
    Math.min(1, 0.5 * savingsPct + 0.5 * qualityNorm),
  );

  const rulesRatio = Math.min(1, result.rules_applied.length / 10);
  const logical = Math.max(
    0,
    Math.min(1, 0.4 + 0.6 * rulesRatio),
  );

  let safety = 0.6;
  const hasRough = req.operations.some((o) => o.type === "roughing");
  const hasFinish = req.operations.some((o) => o.type === "finishing");
  if (hasRough && hasFinish) {
    if (result.thermal_gaps_inserted > 0) safety += 0.25;
    else if (req.thermal_sensitive) safety -= 0.3;
  } else if (candidate.thermal_gap_density === "extra") {
    safety -= 0.05;
  }
  if (hasRough) {
    if (result.probe_points_inserted > 0) safety += 0.1;
    if (req.precision_critical && result.probe_points_inserted === 0) safety -= 0.15;
  }
  safety = Math.max(0, Math.min(1, safety));

  const n = Math.max(1, req.operations.length);
  const sizeFactor = 1 - Math.min(1, n / 80);
  const cost = Math.max(
    0,
    Math.min(1, 0.6 * savingsPct + 0.4 * sizeFactor),
  );

  const robustness = Math.max(
    0,
    Math.min(1, 0.35 + 0.08 * candidate.rules_enabled.length),
  );

  return {
    optimal_performance: perf,
    logical_consistency: logical,
    safety,
    cost_efficiency: cost,
    robustness,
  };
}

function emptyResult(): SequencingResult {
  return {
    operations: [],
    rules_applied: [],
    thermal_gaps_inserted: 0,
    probe_points_inserted: 0,
    tool_changes: 0,
    tool_change_savings_pct: 0,
    sequence_quality_score: 0,
    warnings: ["empty operation list"],
  };
}

