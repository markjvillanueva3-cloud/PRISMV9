/**
 * IntelligentSequencingAdapter — CAMX-MS0.3 / U-CAMX08
 *
 * Wraps IntelligentSequencingEngine through PipelineDecisionOrchestrator to
 * score 5 candidate sequencing strategies across the orchestrator's 5 axes:
 *   - optimal_performance: tool-change savings + sequence quality score
 *   - logical_consistency: rule-set coverage (datum_first, rough_before_finish,
 *     hole_sequence, tool_grouping, parting_last, …)
 *   - safety: thermal-gap discipline when roughing+finishing mixed, probe
 *     verification density after roughing
 *   - cost_efficiency: tool-change reduction × avg_tool_change_sec,
 *     bias toward shorter candidate sequences
 *   - robustness: breadth of rules enabled (graceful with missing metadata)
 *
 * Candidate space (5 strategies — generated by re-invoking the core engine
 * with different rule masks and post-processing):
 *   FULL          — every rule on (datum, rough-before-finish, hole_seq,
 *                   tool_group, depth, axes, parting_last, thermal, probe, deps)
 *   MINIMAL       — only priority sort + parting_last + dependency resolution
 *                   (fastest, minimal cycle-time impact, no thermal/probe)
 *   TOOL_GROUPED  — aggressive tool grouping + deps; strips thermal/probe
 *                   (minimize tool-change count on tolerant parts)
 *   THERMAL_SAFE  — full + *extra* thermal gaps + probe-after-every-op
 *                   (hot/precision work: titanium, stainless, tight-tol)
 *   QUALITY       — datum + hole + depth + probe priority, conservative
 *                   tool-grouping (inspection-first, dim-critical runs)
 *
 * Call sites (9 pipelines — each maps to a taxonomy decision point):
 *   PrintToProgram  → "p2p.sequence_order"        (milling)
 *   PrintToProgram  → "p2p.thermal_gap_plan"      (thermal gap insertions)
 *   Turning         → "turn.bar_pull_plan"        (turning op sequencing)
 *   MultiAxis       → "mx.sequence_order"         (5-axis op order)
 *   MillTurn        → "mt.turret_index_time"      (turret index optimization)
 *   EDM             → "edm.tab_placement"         (wire EDM skim sequence)
 *   Grinding        → "gr.sequence_order"         (grinding op order)
 *   Laser           → "la.nesting_strategy"       (cut order within nest)
 *   Waterjet        → "wj.sequence_order"         (waterjet cut order)
 *   QuoteToShip     → "q2s.schedule_slot"         (machine calendar slotting)
 *
 * Output contract (exit conditions CAMX-MS0.3/U-CAMX08):
 *   ✓ IntelligentSequencing called from all pipelines (via adapter)
 *   ✓ tool_change_savings_pct reported on every decision
 *   ✓ thermal gaps inserted when roughing+finishing mixed
 */

