export type SequencingStrategy =
  | "FULL"
  | "MINIMAL"
  | "TOOL_GROUPED"
  | "THERMAL_SAFE"
  | "QUALITY";

export type PipelineKind =
  | "milling"
  | "turning"
  | "multiaxis"
  | "millturn"
  | "edm"
  | "grinding"
  | "laser"
  | "waterjet"
  | "quote";

export interface SequencingCandidate {
  id: string;
  label: string;
  strategy: SequencingStrategy;
  rules_enabled: string[];
  thermal_gap_density: "none" | "between_rough_finish" | "extra";
  probe_density: "none" | "after_roughing" | "after_every_op";
  tool_group_aggressive: boolean;
}

export interface OrchestratedSequenceRequest {
  decision_point: string;
  pipeline?: PipelineKind;
  operations: SequenceOperation[];
  /** Typical 8-15s; used for cost_efficiency scoring. */
  avg_tool_change_sec?: number;
  precision_critical?: boolean;
  thermal_sensitive?: boolean;
  objective?: "speed" | "quality" | "cost" | "balanced" | "safety";
  pipeline_stage?: string;
  caller?: string;
  explain?: boolean;
}

export interface OrchestratedSequenceDecision {
  strategy: SequencingStrategy;
  result: SequencingResult;
  tool_change_savings_pct: number;
  thermal_gaps_inserted: number;
  decision: any;
  no_candidates: boolean;
}

