  // ── Script filename ────────────────────────────────────────────────────

  protected scriptFilename(ctx: NXGenerationContext | undefined): string {
    const name = ctx?.projectName ?? "prism_part";
    const safe = name.replace(/[^a-zA-Z0-9_]/g, "_");
    return `${safe}.py`;
  }

  // ── Execution ──────────────────────────────────────────────────────────

  protected async runScriptBody(
    script: CADScript<string>,
  ): Promise<CADExecutionResult> {
    const isMock =
      process.env.PRISM_CAD_MOCK === "true" || process.env.CI === "true";

    if (isMock) {
      console.error("[DEBUG] NXCodeGeneratorEngine: mock execution mode");
      return {
        ok: true,
        durationMs: 5,
        metrics: {
          volumeMm3: 12500,
          surfaceAreaMm2: 3750,
          faceCount: 8,
          edgeCount: 18,
          vertexCount: 12,
          boundingBoxMm: [50, 50, 50],
        },
      };
    }

    // Real execution would call NX batch mode:
    // run_journal.exe -nx_part -run {script.filename}
    return {
      ok: false,
      error: "NX journal execution requires NX installation",
      durationMs: 0,
    };
  }
