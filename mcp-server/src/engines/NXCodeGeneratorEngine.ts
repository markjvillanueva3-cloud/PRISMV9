/**
 * NXCodeGeneratorEngine — U-CADC14 (PHASE-4)
 *
 * Python code generator for Siemens NX using NXOpen API.
 * Extends UnifiedCADCodeGeneratorBase for consistent interface across CAD systems.
 *
 * NXOpen Python modules:
 *   - NXOpen          — Core application, session, part access
 *   - NXOpen.UF       — User Function (legacy but still used)
 *   - NXOpen.Features — Feature creation (extrude, revolve, hole, etc.)
 *   - NXOpen.GeometricUtilities — Geometry helpers
 *   - NXOpen.Assemblies — Assembly operations
 *
 * NX uses millimeters internally (no unit conversion needed for mm).
 * For inches: multiply by 25.4 before passing to NXOpen.
 *
 * @module engines/NXCodeGeneratorEngine
 */

import {
  UnifiedCADCodeGeneratorBase,
  type CADEmitter,
} from "./UnifiedCADCodeGeneratorBase.js";
