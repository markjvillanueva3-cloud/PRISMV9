/**
 * WEDMThermalReleaseGateEngine — Thermal Balance Validation for S(x)
 *
 * Validates thermal balance in the cut zone using ASM Handbook Vol. 16
 * thermal conductivity model k(T). NOT Johnson-Cook (which is for
 * plastic deformation, not EDM spark thermal release).
 *
 * Wire EDM thermal concerns:
 * - Heat-affected zone (HAZ) depth
 * - Recast layer formation
 * - Thermal cracking
 * - Wire temperature (affects tension and wear)
 *
 * The energy balance:
 *   Q_spark = Q_wire + Q_workpiece + Q_dielectric + Q_debris
 *
 * Reference: ASM Handbook Vol. 16, Chapter 14 "Wire EDM"
 *            Table 14.2 - Thermal properties of common EDM materials
 *
 * @module WEDMThermalReleaseGateEngine
 * MS-P2.5-SAFETY/U-P2.5-SAFE-05
 */

