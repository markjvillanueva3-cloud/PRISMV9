export type EDMMaterial =
  | "steel_1045"
  | "steel_d2"
  | "steel_h13"
  | "steel_m2"
  | "tungsten_carbide"
  | "copper"
  | "aluminum_6061"
  | "titanium_ti6al4v"
  | "inconel_718"
  | "graphite";

export interface ThermalInput {
  /** Heat generated by sparks per unit time (Joules) */
  heat_release_J: number;
  /** Cooling capacity of dielectric system (Joules) */
  cooling_capacity_J: number;
  /** Workpiece material */
  material: EDMMaterial;
  /** Workpiece thickness (mm) */
  thickness_mm: number;
  /** On-time (microseconds) - affects energy per spark */
  on_time_us?: number;
  /** Off-time (microseconds) - affects cooling between sparks */
  off_time_us?: number;
  /** Measured recast depth (micrometers) - if available */
  recast_depth_um?: number;
  /** Maximum allowable recast depth (micrometers) */
  max_recast_um?: number;
}

export interface MaterialThermalProps {
  /** Thermal conductivity k (W/m·K) at room temperature */
  k_W_mK: number;
  /** Specific heat capacity Cp (J/kg·K) */
  cp_J_kgK: number;
  /** Density (kg/m³) */
  density_kg_m3: number;
  /** Melting point (°C) */
  melting_C: number;
  /** Thermal diffusivity α (m²/s) = k / (ρ·Cp) */
  alpha_m2_s: number;
  /** Typical max recast layer depth for this material (µm) */
  typical_recast_um: number;
}

export interface ThermalGateResult {
  success: boolean;
  pass: boolean;
  heat_release_J: number;
  cooling_capacity_J: number;
  thermal_ratio: number;
  estimated_recast_um: number;
  max_recast_um: number;
  material: EDMMaterial;
  material_props: MaterialThermalProps;
  hard_block: boolean;
  warnings: string[];
  summary: string;
}

