/**
 * SpecHTMLCompanionEngine — master Markdown → HTML renderer for PRISM strategic specs.
 *
 * Owns the HTML render layer for BACKEND-DEVTOOLS-RGS6 HTML-COMPANION-MS0 (HC-0..HC-5);
 * HTML-PRIMARY-MS0 (U-HPS01..07) consumes / hardens it. The contract is a *pure* function
 * `render(md, opts) → RenderResult` — no filesystem, no network — so it is equally usable
 * from the `scripts/emit-spec-html.mjs` CLI, the `prism_dev:spec_html_render` dispatcher
 * action, and unit tests.
 *
 * Self-contained: no `marked`/`markdown-it` dependency (none is installed and a strategic-spec
 * renderer must work offline + emit W3C-valid static HTML). The Markdown subset covered is the
 * one PRISM specs actually use:
 *   - ATX headings `#`..`######` → `<h1 id="slug">` … with collision-safe slugs (HC-3 anchors)
 *   - **bold** / *italic* / _italic_ / `code` / ~~strike~~  + inline `[text](url)` / `![alt](url)`
 *   - unordered (`-`/`*`/`+`) and ordered (`1.`) lists, nested by indent
 *   - GFM pipe tables with `:---` / `:---:` / `---:` column alignment
 *   - fenced code blocks (HTML-escaped); a `mermaid` fence → `<div class="mermaid">` (HC-3)
 *   - blockquotes `>` , thematic breaks `---`/`***`/`___`, paragraphs
 *   - YAML-ish frontmatter (`---` … `---`) → a metadata table at the top of the document
 *
 * Safety: every text / code-fence / attribute value is HTML-escaped; link & image URLs are
 * scheme-filtered (only http(s), mailto, tel, relative, and `#anchor` survive — `javascript:` etc.
 * are dropped). Raw HTML in the Markdown is escaped, never passed through. Oversized inputs are
 * truncated with a visible notice rather than risking OOM.
 *
 * Chrome: dark/light/auto theme via CSS custom properties + `prefers-color-scheme` (HC-2),
 * a table-of-contents sidebar built from the heading tree (HC-3), WAI-ARIA landmarks + a
 * skip-link (HC-4), and a source-hash `<meta>` the drift guard reads back (HC-5).
 *
 * References: CommonMark 0.31 (subset), GitHub-Flavored-Markdown tables, WAI-ARIA 1.2 landmark
 * roles, Thariq "HTML is the new Markdown" (2026-05-08) reconciled with Karpathy "docs are one
 * text file" — MD stays canonical, HTML is the human interface.
 */

