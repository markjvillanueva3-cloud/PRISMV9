/** Progressive enhancement: the page is fully styled without JS — this only lets a reader pin a theme. */
function themeToggleScript(): string {
  return `(function(){
  try {
    var k = "prism-spec-theme";
    var saved = localStorage.getItem(k);
    if (saved === "dark" || saved === "light") document.documentElement.setAttribute("data-theme", saved);
  } catch (e) { /* localStorage blocked — keep default theme */ }
  var b = document.getElementById("themeToggle");
  if (!b) return;
  b.addEventListener("click", function () {
    var cur = document.documentElement.getAttribute("data-theme");
    var sysDark = !!(window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches);
    var next = cur === "dark" ? "light" : cur === "light" ? "dark" : (sysDark ? "light" : "dark");
    document.documentElement.setAttribute("data-theme", next);
    b.textContent = next === "dark" ? "\\u263E dark" : "\\u2600 light";
    try { localStorage.setItem(k, next); } catch (e) { /* persistence unavailable — non-fatal */ }
  });
})();`;
}

/** Loaded only when the doc actually contains a mermaid fence. CDN-down → diagrams stay readable text. */
function mermaidScript(): string {
  return `import mermaid from "${MERMAID_CDN}";
try {
  var pinned = document.documentElement.getAttribute("data-theme");
  var sysDark = !!(window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches);
  var dark = pinned === "dark" || (pinned !== "light" && sysDark);
  mermaid.initialize({ startOnLoad: true, securityLevel: "strict", theme: dark ? "dark" : "default" });
} catch (e) { /* leave the raw mermaid text visible inside .mermaid */ }`;
}

// ─── Engine ────────────────────────────────────────────────────────────────

export class SpecHTMLCompanionEngine {
  /** Pure: Markdown string → standalone HTML document. Never throws on weird input; collects warnings. */
  render(markdown: string, opts: RenderOptions = {}): RenderResult {
    const warnings: string[] = [];
    let md = typeof markdown === "string" ? markdown : String(markdown ?? "");
    const sourceHash = createHash("sha256").update(md, "utf8").digest("hex");

    const maxBytes = opts.maxBytes && opts.maxBytes > 0 ? opts.maxBytes : DEFAULT_MAX_BYTES;
    let truncated = false;
    if (Buffer.byteLength(md, "utf8") > maxBytes) {
      md = Buffer.from(md, "utf8").subarray(0, maxBytes).toString("utf8");
      const lastNl = md.lastIndexOf("\n");
      if (lastNl > 0) md = md.slice(0, lastNl);
      truncated = true;
      warnings.push(`input exceeded ${maxBytes} bytes — truncated for safe rendering`);
    }

    const { frontmatter, body } = extractFrontmatter(md, warnings);

    const st: BlockState = { out: [], headings: [], slug: makeSlugger(), hasMermaid: false, warnings };
    try {
      renderBlocks(body, st);
    } catch (err) {
      warnings.push(`block render error: ${(err as Error).message} — emitting partial output`);
    }

    const firstH1 = st.headings.find((h) => h.level === 1)?.text;
    const title = String(opts.title || frontmatter.title || frontmatter.milestone || firstH1 || "PRISM Spec").trim() || "PRISM Spec";
    const wantToc = opts.toc !== false;
    const theme: SpecHtmlTheme = opts.theme === "dark" || opts.theme === "light" ? opts.theme : "auto";

    const tocHtml = wantToc ? renderToc(st.headings) : "";
    const fmHtml = renderFrontmatterPanel(frontmatter);
    const bodyInner = st.out.join("\n");
    const truncNotice = truncated
      ? `<div class="truncation-notice">⚠ Truncated to the first ${maxBytes.toLocaleString()} bytes for safe rendering — see the canonical <code>.md</code> for the full text.</div>\n`
      : "";

    const provenance: string[] = [`Generated ${new Date().toISOString()}`];
    if (opts.generatedBy) provenance.push(`by <code>${escapeHtml(opts.generatedBy)}</code>`);
    provenance.push("· the Markdown alongside is canonical");

    const htmlAttr = theme === "auto" ? "" : ` data-theme="${theme}"`;
    const sourceLink = opts.sourcePath ? ` <a href="${escapeHtml(escapeHtml(opts.sourcePath))}">${escapeHtml(opts.sourcePath)}</a>` : "";
    const scripts = [
      `<script>${themeToggleScript()}</script>`,
      st.hasMermaid ? `<script type="module">${mermaidScript()}</script>` : "",
    ].filter(Boolean).join("\n");

    const html = `<!DOCTYPE html>
<html lang="en"${htmlAttr}>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="SpecHTMLCompanionEngine">
<meta name="prism-source-hash" content="${sourceHash}">
<title>${escapeHtml(title)}</title>
<style>${pageStyles()}</style>
</head>
<body>
<a class="skip-link" href="#content">Skip to content</a>
<div class="layout">
<header class="doc-head">
<button id="themeToggle" class="theme-toggle" type="button" aria-label="Toggle color theme">${theme === "dark" ? "☾ dark" : theme === "light" ? "☀ light" : "◐ theme"}</button>
<h1 class="page-title">${escapeHtml(title)}</h1>
<p class="provenance">${provenance.join(" ")}</p>
</header>
${tocHtml}
<main id="content" class="doc-body" role="main">
${truncNotice}${fmHtml ? fmHtml + "\n" : ""}${bodyInner}
</main>
<footer class="doc-foot">
<p>HTML companion — the canonical document is the Markdown file alongside it.${sourceLink} Regenerate: <code>node scripts/emit-spec-html.mjs &lt;path.md&gt;</code></p>
${warnings.length ? `<p>Render warnings: ${warnings.map((w) => escapeHtml(w)).join("; ")}</p>` : ""}
</footer>
</div>
${scripts}
</body>
</html>
`;

    return {
      html,
      title,
      headings: st.headings,
      frontmatter,
      hasMermaid: st.hasMermaid,
      sourceHash,
      warnings,
      bytes: html.length,
    };
  }

  /** sha256(markdown), hex — used by the HC-5 drift guard (`emit-spec-html.mjs --check-drift`). */
  hashSource(markdown: string): string {
    return createHash("sha256").update(typeof markdown === "string" ? markdown : String(markdown ?? ""), "utf8").digest("hex");
  }

  /**
   * Has the HTML twin drifted from its source? Compares sha256(md) against the `prism-source-hash`
   * `<meta>` embedded in a previously-generated HTML. Returns true when they differ (regen needed)
   * or when the HTML carries no recorded hash.
   */
  isDrifted(markdown: string, generatedHtml: string): boolean {
    const want = this.hashSource(markdown);
    const m = /<meta\s+name="prism-source-hash"\s+content="([0-9a-f]{64})"/i.exec(String(generatedHtml ?? ""));
    if (!m) return true;
    return m[1] !== want;
  }
}

export const specHtmlCompanionEngine = new SpecHTMLCompanionEngine();
