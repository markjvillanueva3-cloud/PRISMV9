// ─── Public types ──────────────────────────────────────────────────────────

export type SpecHtmlTheme = "dark" | "light" | "auto";

export interface RenderOptions {
  /** Color theme. "auto" (default) follows `prefers-color-scheme`; "dark"/"light" pin it. */
  theme?: SpecHtmlTheme;
  /** Render a table-of-contents sidebar from headings (default true; auto-suppressed if <2 headings). */
  toc?: boolean;
  /** Document `<title>`. Defaults to frontmatter `title`/`milestone` → first H1 → "PRISM Spec". */
  title?: string;
  /** Optional "Generated by …" provenance shown under the title. */
  generatedBy?: string;
  /** Optional href to the canonical `.md` source, linked in the footer. */
  sourcePath?: string;
  /** Hard cap on input size in bytes; larger inputs are truncated with a notice. Default 16 MiB. */
  maxBytes?: number;
}

export interface SpecHeading {
  level: number;          // 1..6
  text: string;           // plain text (Markdown/HTML stripped)
  slug: string;           // unique #anchor id
}

export interface RenderResult {
  html: string;
  title: string;
  headings: SpecHeading[];
  frontmatter: Record<string, string>;
  /** Whether the source contained at least one mermaid fence (mermaid.js was embedded). */
  hasMermaid: boolean;
  /** sha256(source-markdown), hex — the drift guard compares this to its `.html.hash` sidecar. */
  sourceHash: string;
  /** Non-fatal issues encountered while rendering (malformed frontmatter, truncation, …). */
  warnings: string[];
  bytes: number;          // length of the produced HTML
}

// ─── Constants ─────────────────────────────────────────────────────────────

const DEFAULT_MAX_BYTES = 16 * 1024 * 1024;
const MERMAID_CDN = "https://cdn.jsdelivr.net/npm/mermaid@11/dist/mermaid.esm.min.mjs";
const MERMAID_EDGE_CAP = 4000;          // beyond this we warn the diagram may be slow in-browser
const SAFE_URL_SCHEMES = new Set(["http:", "https:", "mailto:", "tel:"]);
const HARD_BREAK = "";            // private-use sentinel for an intra-paragraph hard break (survives escaping)
const FENCE_LANG_TOKEN = /[^a-z0-9+#.\-]/g;

// ─── HTML escaping ─────────────────────────────────────────────────────────

const HTML_ESCAPES: Record<string, string> = {
  "&": "&amp;",
  "<": "&lt;",
  ">": "&gt;",
  '"': "&quot;",
  "'": "&#39;",
};

/** Escape text destined for an HTML text/attribute context. Call exactly once per value. */
export function escapeHtml(s: string): string {
  return String(s).replace(/[&<>"']/g, (c) => HTML_ESCAPES[c]);
}

/** Decode the handful of entities `escapeHtml` produces (so URL handling sees original chars). */
function decodeEntities(s: string): string {
  return String(s)
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'");
}

/** Sanitize a link/image URL: allow http(s)/mailto/tel, relative paths and `#anchor`; drop the rest. */
function sanitizeUrl(raw: string): string {
  const url = String(raw).trim();
  if (!url) return "";
  if (url.startsWith("#") || url.startsWith("/") || url.startsWith("./") || url.startsWith("../")) return url;
  // No scheme at all → treat as a relative path (e.g. "FILE.md", "dir/file.html").
  if (!/^[a-zA-Z][a-zA-Z0-9+.-]*:/.test(url)) return url;
  const scheme = url.slice(0, url.indexOf(":") + 1).toLowerCase();
  return SAFE_URL_SCHEMES.has(scheme) ? url : "";
}

// ─── Slug generation (collision-safe — HC-3 anchor navigation) ─────────────

function makeSlugger(): (text: string) => string {
  const seen = new Map<string, number>();
  return (text: string): string => {
    const base =
      text
        .toLowerCase()
        .replace(/<[^>]*>/g, "")
        .normalize("NFKD")
        .replace(/[̀-ͯ]/g, "")        // strip combining marks
        .replace(/[^a-z0-9 _-]+/g, "")          // ASCII-only slug body — predictable, always valid id
        .trim()
        .replace(/\s+/g, "-")
        .replace(/-+/g, "-")
        .replace(/^-+|-+$/g, "") || "section";
    const n = seen.get(base) ?? 0;
    seen.set(base, n + 1);
    return n === 0 ? base : `${base}-${n + 1}`;
  };
}

// ─── Inline rendering ──────────────────────────────────────────────────────

/**
 * Render Markdown inline syntax inside a single segment of text.
 * Strategy: lift out inline-code spans first (their contents are escaped, never further processed),
 * escape everything else, then run image/link/emphasis/strike on the escaped string. Because the
 * non-code text is escaped *before* the emphasis regexes run, nothing injected can leak markup.
 */
function renderInline(src: string): string {
  const codeSpans: string[] = [];
  // `code`, ``co`de`` — opening run of N backticks closed by another run of N (CommonMark-ish).
  let text = String(src).replace(/(`+)(.+?)\1(?!`)/g, (_m, _ticks, body) => {
    codeSpans.push(`<code>${escapeHtml(String(body).replace(/^ | $/g, ""))}</code>`);
    return `${codeSpans.length - 1}`;
  });

  text = escapeHtml(text);

  // Images  ![alt](url "title")  — handled before links (same bracket shape).
  text = text.replace(/!\[([^\]]*)\]\(\s*([^)\s]+)(?:\s+&quot;([^&]*)&quot;)?\s*\)/g, (_m, alt, url, title) => {
    const safe = sanitizeUrl(decodeEntities(url));
    if (!safe) return escapeHtml(`![${alt}]`);
    const t = title ? ` title="${escapeHtml(decodeEntities(title))}"` : "";
    return `<img src="${escapeHtml(safe)}" alt="${alt}"${t} loading="lazy">`;
  });

  // Links  [text](url "title")
  text = text.replace(/\[([^\]]+)\]\(\s*([^)\s]+)(?:\s+&quot;([^&]*)&quot;)?\s*\)/g, (_m, label, url, title) => {
    const safe = sanitizeUrl(decodeEntities(url));
    if (!safe) return label;
    const t = title ? ` title="${escapeHtml(decodeEntities(title))}"` : "";
    const rel = /^https?:/i.test(safe) ? ' rel="noopener noreferrer"' : "";
    return `<a href="${escapeHtml(safe)}"${t}${rel}>${label}</a>`;
  });

  // Bold then italic (so `**x**` isn't half-consumed by the `*x*` rule).
  text = text.replace(/\*\*([^*]+?)\*\*/g, "<strong>$1</strong>");
  text = text.replace(/__([^_]+?)__/g, "<strong>$1</strong>");
  text = text.replace(/(^|[^*\w])\*([^*\s][^*]*?)\*(?!\w)/g, "$1<em>$2</em>");
  text = text.replace(/(^|[^_\w])_([^_\s][^_]*?)_(?!\w)/g, "$1<em>$2</em>");
  text = text.replace(/~~([^~]+?)~~/g, "<del>$1</del>");

  // Restore code spans.
  text = text.replace(/(\d+)/g, (_m, i) => codeSpans[Number(i)] ?? "");
  // Intra-paragraph hard breaks (set by the block layer).
  return text.replace(new RegExp(HARD_BREAK, "g"), "<br>\n");
}

/** Plain-text projection of an inline string (heading → TOC text + slug). */
function inlineToPlainText(src: string): string {
  return String(src)
    .replace(/`+([^`]*)`+/g, "$1")
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/\*\*([^*]+?)\*\*|__([^_]+?)__/g, "$1$2")
    .replace(/\*([^*]+?)\*|_([^_]+?)_/g, "$1$2")
    .replace(/~~([^~]+?)~~/g, "$1")
    .replace(/<[^>]*>/g, "")
    .replace(new RegExp(HARD_BREAK, "g"), " ")
    .trim();
}

// ─── Frontmatter ───────────────────────────────────────────────────────────

/**
 * Pull a leading `---` … `---` block off the top. No YAML dependency: specs use it for flat
 * `key: value` (plus nested `key:` headers we fold into the parent as a readable string). If the
 * opening `---` has no closing fence within the first 250 lines we treat the whole input as body
 * and warn (the malformed-frontmatter failure mode).
 */
function extractFrontmatter(md: string, warnings: string[]): { frontmatter: Record<string, string>; body: string } {
  const empty = { frontmatter: {} as Record<string, string>, body: md };
  if (!/^---\r?\n/.test(md)) return empty;
  const lines = md.split(/\r?\n/);
  let end = -1;
  for (let i = 1; i < lines.length && i < 250; i++) {
    if (lines[i] === "---" || lines[i] === "...") { end = i; break; }
  }
  if (end === -1) {
    warnings.push("frontmatter opened with '---' but no closing '---' within 250 lines — treated as body");
    return empty;
  }
  const fm: Record<string, string> = {};
  let lastKey = "";
  for (let i = 1; i < end; i++) {
    const line = lines[i];
    if (!line.trim() || /^\s*#/.test(line)) continue;
    const kv = /^(\s*)([A-Za-z0-9_.\- ]+?):\s?(.*)$/.exec(line);
    if (kv) {
      const indent = kv[1].length;
      const key = kv[2].trim();
      const val = kv[3].trim().replace(/^["']|["']$/g, "");
      if (indent === 0) { fm[key] = val; lastKey = key; }
      else if (lastKey) {
        const piece = `${key}${val ? ": " + val : ""}`;
        fm[lastKey] = fm[lastKey] ? `${fm[lastKey]}; ${piece}` : piece;
      }
    } else if (/^\s*-\s+/.test(line) && lastKey) {
      const item = line.replace(/^\s*-\s+/, "").trim();
      fm[lastKey] = fm[lastKey] ? `${fm[lastKey]}, ${item}` : item;
    }
  }
  return { frontmatter: fm, body: lines.slice(end + 1).join("\n") };
}

// ─── Block-level parsing ───────────────────────────────────────────────────

interface BlockState {
  out: string[];
  headings: SpecHeading[];
  slug: (t: string) => string;
  hasMermaid: boolean;
  warnings: string[];
}

const RE = {
  heading: /^(#{1,6})\s+(.*?)\s*#*\s*$/,
  fence: /^\s*(`{3,}|~{3,})\s*([^\s`~]*)\s*$/,
  hr: /^\s{0,3}([-*_])(?:\s*\1){2,}\s*$/,
  ulItem: /^(\s*)([-*+])\s+(.*)$/,
  olItem: /^(\s*)(\d{1,9})[.)]\s+(.*)$/,
  blockquote: /^\s{0,3}>\s?(.*)$/,
  tableSep: /^\s*\|?\s*:?-{1,}:?\s*(\|\s*:?-{1,}:?\s*)+\|?\s*$/,
};

function isBlockStarter(line: string): boolean {
  return RE.heading.test(line) || RE.fence.test(line) || RE.hr.test(line) || RE.blockquote.test(line) || RE.ulItem.test(line) || RE.olItem.test(line);
}

function renderBlocks(md: string, st: BlockState): void {
  const lines = md.split(/\r?\n/);
  let i = 0;

  while (i < lines.length) {
    const line = lines[i];

    if (!line.trim()) { i++; continue; }

    // Fenced code block.
    const fence = RE.fence.exec(line);
    if (fence) {
      const marker = fence[1];
      const fenceChar = marker[0];
      const minLen = marker.length;
      const closeRe = new RegExp("^\\s*" + (fenceChar === "`" ? "`" : "~") + "{" + minLen + ",}\\s*$");
      const buf: string[] = [];
      i++;
      while (i < lines.length) {
        if (closeRe.test(lines[i])) { i++; break; }
        buf.push(lines[i]);
        i++;
      }
      const lang = (fence[2] || "").toLowerCase().replace(FENCE_LANG_TOKEN, "");
      if (lang === "mermaid") {
        st.hasMermaid = true;
        const graph = buf.join("\n");
        const edgeGuess = (graph.match(/-->|---|==>|-\.->/g) || []).length;
        if (edgeGuess > MERMAID_EDGE_CAP) st.warnings.push(`mermaid block is large (~${edgeGuess} edges) — in-browser render may be slow`);
        st.out.push(`<div class="mermaid">\n${escapeHtml(graph)}\n</div>`);
      } else {
        const cls = lang ? ` class="language-${lang}"` : "";
        st.out.push(`<pre><code${cls}>${escapeHtml(buf.join("\n"))}\n</code></pre>`);
      }
      continue;
    }

    // ATX heading.
    const h = RE.heading.exec(line);
    if (h) {
      const level = h[1].length;
      const rawInline = h[2];
      const plain = inlineToPlainText(rawInline) || "Section";
      const slug = st.slug(plain);
      st.headings.push({ level, text: plain, slug });
      st.out.push(
        `<h${level} id="${escapeHtml(slug)}">` +
          `<a class="anchor" href="#${escapeHtml(slug)}" aria-label="Permalink to ${escapeHtml(plain)}">#</a>` +
          renderInline(rawInline) +
          `</h${level}>`,
      );
      i++;
      continue;
    }

    // Thematic break.
    if (RE.hr.test(line)) { st.out.push("<hr>"); i++; continue; }

    // GFM table: a header row immediately followed by a delimiter row.
    if (line.includes("|") && i + 1 < lines.length && RE.tableSep.test(lines[i + 1])) {
      const headerCells = splitTableRow(line);
      const aligns = splitTableRow(lines[i + 1]).map((c) => {
        const t = c.trim();
        const l = t.startsWith(":"), r = t.endsWith(":");
        return l && r ? "center" : r ? "right" : l ? "left" : "";
      });
      i += 2;
      const bodyRows: string[][] = [];
      while (i < lines.length && lines[i].includes("|") && lines[i].trim() && !RE.fence.test(lines[i]) && !RE.heading.test(lines[i])) {
        bodyRows.push(splitTableRow(lines[i]));
        i++;
      }
      st.out.push(renderTable(headerCells, aligns, bodyRows));
      continue;
    }

    // Blockquote — consume the contiguous run, recurse on the de-quoted body.
    if (RE.blockquote.test(line)) {
      const buf: string[] = [];
      while (i < lines.length && lines[i].trim() && RE.blockquote.test(lines[i])) {
        buf.push(lines[i].replace(/^\s{0,3}>\s?/, ""));
        i++;
      }
      const inner: BlockState = { out: [], headings: st.headings, slug: st.slug, hasMermaid: false, warnings: st.warnings };
      renderBlocks(buf.join("\n"), inner);
      st.hasMermaid = st.hasMermaid || inner.hasMermaid;
      st.out.push(`<blockquote>\n${inner.out.join("\n")}\n</blockquote>`);
      continue;
    }

    // Lists (unordered / ordered), nested by indent.
    if (RE.ulItem.test(line) || RE.olItem.test(line)) {
      const { html, next } = parseList(lines, i);
      st.out.push(html);
      i = next;
      continue;
    }

    // Paragraph — accumulate until a blank line, a block-starter, or a table header.
    const para: string[] = [];
    while (i < lines.length && lines[i].trim()) {
      const l = lines[i];
      if (isBlockStarter(l)) break;
      if (l.includes("|") && i + 1 < lines.length && RE.tableSep.test(lines[i + 1])) break;
      para.push(l);
      i++;
    }
    if (para.length) {
      let joined = "";
      para.forEach((p, idx) => {
        const hard = /(\\| {2,})$/.test(p) && idx < para.length - 1;
        joined += p.replace(/\s+$/, "");
        if (idx < para.length - 1) joined += hard ? HARD_BREAK : " ";
      });
      st.out.push(`<p>${renderInline(joined)}</p>`);
    }
  }
}

function splitTableRow(row: string): string[] {
  let s = row.trim();
  if (s.startsWith("|")) s = s.slice(1);
  if (s.endsWith("|")) s = s.slice(0, -1);
  const cells: string[] = [];
  let cur = "";
  for (let i = 0; i < s.length; i++) {
    if (s[i] === "\\" && s[i + 1] === "|") { cur += "|"; i++; continue; }
    if (s[i] === "|") { cells.push(cur); cur = ""; continue; }
    cur += s[i];
  }
  cells.push(cur);
  return cells.map((c) => c.trim());
}

function renderTable(header: string[], aligns: string[], rows: string[][]): string {
  const th = header
    .map((c, k) => `<th${aligns[k] ? ` style="text-align:${aligns[k]}"` : ""}>${renderInline(c)}</th>`)
    .join("");
  const body = rows
    .map((r) => {
      const cells: string[] = [];
      for (let k = 0; k < header.length; k++) {
        const v = r[k] ?? "";
        cells.push(`<td${aligns[k] ? ` style="text-align:${aligns[k]}"` : ""}>${renderInline(v)}</td>`);
      }
      return `<tr>${cells.join("")}</tr>`;
    })
    .join("\n");
  return `<div class="table-wrap"><table>\n<thead><tr>${th}</tr></thead>\n<tbody>\n${body}\n</tbody>\n</table></div>`;
}

/**
 * Parse a (possibly nested) list starting at `lines[start]`. Returns the rendered `<ul>`/`<ol>`
 * and the index of the first line *after* the list. A more-indented item opens a sublist inside
 * the current `<li>`; a less-indented item belongs to an outer list and terminates this one.
 */
function parseList(lines: string[], start: number): { html: string; next: number } {
  const firstM = (RE.ulItem.exec(lines[start]) || RE.olItem.exec(lines[start])) as RegExpExecArray;
  const baseIndent = firstM[1].length;
  const ordered = !!RE.olItem.exec(lines[start]);
  const startNum = ordered ? parseInt((RE.olItem.exec(lines[start]) as RegExpExecArray)[2], 10) : 1;
  const items: string[] = [];
  let i = start;

  while (i < lines.length) {
    const line = lines[i];
    if (!line.trim()) {
      // One blank line may separate "loose" items — peek; bail if the list clearly ended.
      const nextItemM = i + 1 < lines.length ? (RE.ulItem.exec(lines[i + 1]) || RE.olItem.exec(lines[i + 1])) : null;
      if (nextItemM && nextItemM[1].length >= baseIndent) { i++; continue; }
      break;
    }
    const m = RE.ulItem.exec(line) || RE.olItem.exec(line);
    if (m) {
      const indent = m[1].length;
      if (indent < baseIndent) break;
      if (indent > baseIndent) {
        const sub = parseList(lines, i);
        if (items.length === 0) items.push("<li>");
        items[items.length - 1] = items[items.length - 1].replace(/<\/li>$/, "") + "\n" + sub.html;
        if (!/<\/li>$/.test(items[items.length - 1])) items[items.length - 1] += "</li>";
        i = sub.next;
        continue;
      }
      const cont: string[] = [m[3]];
      i++;
      while (i < lines.length && lines[i].trim() && !RE.ulItem.test(lines[i]) && !RE.olItem.test(lines[i]) && !isBlockStarter(lines[i])) {
        const indentOf = lines[i].match(/^(\s*)/)?.[1].length ?? 0;
        if (indentOf <= baseIndent) break;
        cont.push(lines[i].trim());
        i++;
      }
      items.push(`<li>${renderInline(cont.join(" "))}</li>`);
      continue;
    }
    // Non-item line: if it's at/under base indent the list is over; otherwise it's loose prose
    // under the previous item (rare in PRISM specs) — fold it into that <li>.
    if ((line.match(/^(\s*)/)?.[1].length ?? 0) <= baseIndent) break;
    if (items.length) {
      const last = items.length - 1;
      items[last] = items[last].replace(/<\/li>$/, ` ${renderInline(line.trim())}</li>`);
    }
    i++;
  }

  const tag = ordered ? "ol" : "ul";
  const startAttr = ordered && startNum !== 1 ? ` start="${startNum}"` : "";
  return { html: `<${tag}${startAttr}>\n${items.join("\n")}\n</${tag}>`, next: i };
}

// ─── TOC + metadata panel ──────────────────────────────────────────────────

function renderToc(headings: SpecHeading[]): string {
  const usable = headings.filter((h) => h.level >= 1 && h.level <= 4);
  if (usable.length < 2) return "";
  const items = usable
    .map((h) => `<li class="toc-l${h.level}"><a href="#${escapeHtml(h.slug)}">${escapeHtml(h.text)}</a></li>`)
    .join("\n");
  return `<nav class="toc" aria-label="Table of contents"><div class="toc-title">On this page</div><ul>\n${items}\n</ul></nav>`;
}

function renderFrontmatterPanel(fm: Record<string, string>): string {
  const keys = Object.keys(fm).filter((k) => fm[k] !== undefined && fm[k] !== "");
  if (keys.length === 0) return "";
  const rows = keys.map((k) => `<tr><th scope="row">${escapeHtml(k)}</th><td>${renderInline(fm[k])}</td></tr>`).join("\n");
  return `<details class="frontmatter" open><summary>Document metadata</summary><div class="table-wrap"><table>\n<tbody>\n${rows}\n</tbody>\n</table></div></details>`;
}

