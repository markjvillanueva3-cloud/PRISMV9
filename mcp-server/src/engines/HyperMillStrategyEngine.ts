/** Operation Goal type definition. */
export type OperationGoal = "roughing" | "finishing" | "rest_machining" | "semi_finishing";

/**
 * CSS mode for turning operations.
 * G96 = Constant Surface Speed (preferred for turning).
 * G97 = Constant RPM (used for very small/large diameters or threading).
 */
export type CSSMode = "G96" | "G97";

/**
 * Physics summary for mill-turn operations.
 * Sourced from CANONICAL_TURNING_SPEEDS/FEEDS in constants.ts.
 */
