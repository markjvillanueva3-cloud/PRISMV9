/** All mill-turn geometry types that require turning physics (CSS/TNRC). */
const MILLTURN_GEOMETRY_TYPES = new Set<GeometryType>([
  "od_profile", "id_profile", "mt_face", "groove_od", "groove_id", "groove_face",
  "thread_od", "thread_id", "parting", "bore", "recess",
  "cross_hole", "cross_slot", "off_center_feature",
]);

/**
 * Geometry types that MUST use G97 (constant RPM) — CSS forbidden.
 * Threading: spindle sync to pitch. Parting: D→0 singularity. Face→center: D→0.
 * Cross-hole/slot: C-axis live tool, not CSS turning.
 */
const G97_MANDATORY_TYPES = new Set<GeometryType>([
  "thread_od", "thread_id", "parting",
  "cross_hole", "cross_slot", "off_center_feature",
]);

/**
 * Geometry types where TNRC (G41/G42) is mandatory for dimensional accuracy.
 * Threading is excluded — TNRC must be OFF during thread cutting.
 */
const TNRC_MANDATORY_TYPES = new Set<GeometryType>([
  "od_profile", "id_profile", "mt_face", "groove_od", "groove_id", "groove_face",
  "bore", "recess",
]);

/**
 * Get turning physics summary for a mill-turn geometry type and material.
 * Sources Vc/f from CANONICAL_TURNING_SPEEDS/FEEDS and kc1.1 from CANONICAL_KIENZLE.
 *
 * @param geomType - mill-turn geometry type
 * @param isoGroup - ISO material group (P/M/K/N/S/H)
 * @param opGoal   - roughing or finishing
 * @param noseRadiusMm - insert nose radius (mm); TNRC required if > 0.2mm
 * @returns TurningPhysicsSummary
 *
 * Reference: CANONICAL_TURNING_SPEEDS (ISO/Sandvik), CANONICAL_KIENZLE (Kienzle 1957)
 */
function getTurningPhysics(
  geomType: GeometryType,
  isoGroup: string,
  opGoal: OperationGoal,
  noseRadiusMm?: number,
): TurningPhysicsSummary {
  const iso = (isoGroup?.toUpperCase() ?? "P") as ISOGroup;
  const kienzle = CANONICAL_KIENZLE[iso] ?? CANONICAL_KIENZLE.P;

  // CSS mode selection
  const cssMode: CSSMode = G97_MANDATORY_TYPES.has(geomType) ? "G97" : "G96";

  // TNRC: mandatory for profile/groove/bore; off for threading; recommended if nose > 0.2mm
  let tnrcRequired = TNRC_MANDATORY_TYPES.has(geomType);
  if (!tnrcRequired && noseRadiusMm !== undefined && noseRadiusMm > 0.2) {
    tnrcRequired = true;
  }

  // Surface speed from canonical turning speeds (roughing vs finishing)
  const speeds = CANONICAL_TURNING_SPEEDS[iso];
  const feeds = CANONICAL_TURNING_FEEDS[iso];
  const vcRecommended_m_min = opGoal === "roughing"
    ? (speeds?.rough ?? 100)
    : (speeds?.finish ?? 150);
  const feedRecommended_mm_rev = opGoal === "roughing"
    ? (feeds?.rough ?? 0.3)
    : (feeds?.finish ?? 0.15);

  const notes: string[] = [];
  if (cssMode === "G97") notes.push(`G97 (constant RPM) mandatory for ${geomType}`);
  if (tnrcRequired) notes.push("TNRC (G41/G42) active — insert nose radius compensation required");
  if (geomType === "parting") notes.push("Parting: reduce feed to 0.05-0.1 mm/rev at small diameters");
  if (geomType === "bore") notes.push("Boring bar: check deflection with BoringBarDeflectionEngine");
  if ((geomType === "cross_hole" || geomType === "cross_slot" || geomType === "off_center_feature")) {
    notes.push("C-axis live tool: Vc_eff = π×D_tool×n_live/1000, not CSS of workpiece spindle");
  }
  if (iso === "S") notes.push("Superalloy: low Vc (20-50 m/min for Ni-alloys), climb milling only on cross-features");
  if (iso === "M") notes.push("Stainless: use through-spindle coolant, avoid work hardening with light finishing passes");

  return { cssMode, tnrcRequired, vcRecommended_m_min, feedRecommended_mm_rev, kc1_1: kienzle.kc1_1, mc: kienzle.mc, notes };
}

