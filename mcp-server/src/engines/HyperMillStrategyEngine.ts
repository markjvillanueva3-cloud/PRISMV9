/** Hyper Mill Strategy Engine engine/manager. */
export class HyperMillStrategyEngine {
  private calcCount = 0;
  private lastInput: StrategyInput | null = null;

  /**
   * Recommend the best hyperMILL machining strategy for the given inputs.
   */
  calculate(input: StrategyInput): StrategyRecommendation {
    this.calcCount++;
    this.lastInput = input;

    const warnings: string[] = [];
    const { geometryType, operationGoal, wallAngleDeg, hasPreviousRoughing } = input;

    // Filter strategies matching geometry + goal
    let candidates = STRATEGIES.filter(
      (s) =>
        s.suitableFor.geometry.includes(geometryType) &&
        s.suitableFor.goal.includes(operationGoal),
    );

    /** If.
     * @param candidates.length - candidates.length
     * @returns void
     */
    if (candidates.length === 0) {
      // Fallback: match by goal only
      candidates = STRATEGIES.filter((s) =>
        s.suitableFor.goal.includes(operationGoal),
      );
      warnings.push(
        `No exact match for geometry '${geometryType}' — showing closest goal match`,
      );
    }

    // Sort by priority first, then apply slope-dependent overrides
    candidates.sort((a, b) => b.priority - a.priority);

    // Slope-dependent selection for 3D finishing
    if (
      operationGoal === "finishing" &&
      wallAngleDeg !== undefined &&
      candidates.length > 1
    ) {
      /** If.
       * @param wallAngleDeg - wall angle deg
       * @returns void
       */
      if (wallAngleDeg > 60) {
        // Steep walls: prefer Z Level
        const zLevel = candidates.find((c) =>
          c.cycle.includes("Z Level"),
        );
        /** If.
         * @param zLevel - z level
         * @returns void
         */
        if (zLevel) {
          candidates = [zLevel, ...candidates.filter((c) => c !== zLevel)];
          warnings.push("Steep wall detected (>60°) — Z Level strategies preferred");
        }
      } else if (wallAngleDeg < 20) {
        // Flat areas: prefer Plane Machining or Equidistant
        const flat = candidates.find(
          (c) => c.cycle.includes("Plane") || c.cycle.includes("Equidistant"),
        );
        /** If.
         * @param flat - flat
         * @returns void
         */
        if (flat) {
          candidates = [flat, ...candidates.filter((c) => c !== flat)];
          warnings.push("Flat area detected (<20°) — planar strategy preferred");
        }
      }
    }

    // Rest machining requires previous roughing
    /** If.
     * @param operationGoal - operation goal
     * @returns void
     */
    if (operationGoal === "rest_machining" && !hasPreviousRoughing) {
      warnings.push(
        "Rest machining selected but no previous roughing indicated — ensure a roughing cycle exists",
      );
    }

    // Material-specific warnings
    /** If.
     * @param input.materialGroup - input.material group
     * @returns void
     */
    if (input.materialGroup === "S") {
      warnings.push(
        "Superalloy (ISO S): reduce stepover to 60% of standard, use climb milling only",
      );
    }
    /** If.
     * @param input.materialGroup - input.material group
     * @returns void
     */
    if (input.materialGroup === "H") {
      warnings.push(
        "Hardened steel (ISO H): use small stepdown, high speed, low feed per tooth",
      );
    }

    const best = candidates[0];

    /** If.
     * @param !best - !best
     * @returns void
     */
    if (!best) {
      return {
        strategyName: "Manual Selection Required",
        hyperMillCycle: "N/A",
        description: "No matching strategy found for the given inputs.",
        suggestedStepdown: null,
        suggestedStepover: null,
        cuttingMode: "climb",
        warnings: ["No matching hyperMILL cycle found — review inputs"],
        confidence: 0,
        source: "document:hypermill-manual",
      };
    }

    // Attach turning physics for mill-turn geometry types (HM-REV-MS7 U-HMR38)
    const turningPhysics = MILLTURN_GEOMETRY_TYPES.has(geometryType)
      ? getTurningPhysics(geometryType, input.materialGroup ?? "P", operationGoal, input.noseRadiusMm)
      : undefined;

    return {
      strategyName: best.cycle,
      hyperMillCycle: best.cycle,
      description: best.description,
      suggestedStepdown: best.stepdownFactor,
      suggestedStepover: best.stepoverFactor,
      cuttingMode: best.cuttingMode,
      warnings,
      confidence: warnings.length === 0 ? 0.9 : 0.75,
      source: "document:hypermill-manual-en-{1,2,3,4}",
      turningPhysics,
    };
  }

  /**
   * List all mill-turn geometry types and their default CSS mode.
   * Useful for hyperMILL post-processor configuration.
   * HM-REV-MS7 U-HMR38.
   */
  listMillTurnGeometryTypes(): Array<{ geometryType: GeometryType; cssMode: CSSMode; tnrcMandatory: boolean }> {
    return Array.from(MILLTURN_GEOMETRY_TYPES).map((gt) => ({
      geometryType: gt,
      cssMode: G97_MANDATORY_TYPES.has(gt) ? "G97" : "G96",
      tnrcMandatory: TNRC_MANDATORY_TYPES.has(gt),
    }));
  }

  /** List all available hyperMILL strategies. */
  listStrategies(): Array<{ cycle: string; geometry: GeometryType[]; goal: OperationGoal[] }> {
    return STRATEGIES.map((s) => ({
      cycle: s.cycle,
      geometry: s.suitableFor.geometry,
      goal: s.suitableFor.goal,
    }));
  }

  /** Stats.
   * @returns strategy engine stats
   */
  stats(): StrategyEngineStats {
    return { calculations: this.calcCount, lastInput: this.lastInput };
  }

  /** Clear.
   * @returns void
   */
  clear(): void {
    this.calcCount = 0;
    this.lastInput = null;
  }
}

/** Hyper Mill Strategy Engine constant.
 */
export const hyperMillStrategyEngine = new HyperMillStrategyEngine();
