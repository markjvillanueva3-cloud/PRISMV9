/**
 * CimcoVerificationBridgeEngine — CIMCO Edit 2026 + Machine Simulation ↔ PRISM bridge.
 * =============================================================================
 *
 * SPINE-1 of the CIMCO integration (CIMCO-INTEGRATION-MS0 / U-CIMCO-BRIDGE-ENGINE).
 * The single in-process surface every galaxy calls to query the verified CIMCO
 * inventory and evaluate Machine-Simulation reports. CIMCO is PRISM's fleet
 * program/post **verification + simulation oracle** (wiki
 * [[cimco-verification-simulation-integration]]).
 *
 * Design (no logic duplication):
 *   - The three index JSONs under `state/shared/cimco/` are generated artifacts of
 *     the canonical `.mjs` indexers (`scripts/cimco-machine-index.mjs`,
 *     `cimco-post-index.mjs`, `cimco-tool-index.mjs`). This engine READS that data
 *     (fail-soft) — it does NOT re-parse `.mcfg`/`.js`/`.tmlib` (that stays in the
 *     canonical generators).
 *   - `evaluateSimulationReport()` is a FAITHFUL TypeScript port of
 *     `scripts/cimco-control-map.mjs#parseSimulationReport` (the canonical pass/fail
 *     gate). The `.mjs` remains canonical for the CLI; this port exists so the gate
 *     is callable in-process. A parity test (`CimcoVerificationBridgeEngine.test.ts`)
 *     locks the contract against the same fixtures the `.mjs` test uses. If the
 *     canonical rule changes, BOTH must change — the test will catch drift.
 *
 * UNITS-FIRST: every machine/tool result carries its units-resolution status. 44/86
 * vendor `.mcfg` omit `Header.Unit` → flagged units-UNRESOLVED. Never assume units —
 * a mismatch is a 25.4× scale error (CLAUDE.md §SAFETY RAILS / units-guard).
 *
 * Verification provenance: a CIMCO-sim CLEAN result is "conformance-clean, NOT
 * controller-verified" — it proves kinematics/collision/limits, NOT byte-exact
 * controller behavior (that is the golden round-trip harness's job).
 *
 * Authored 2026-06-02 — slot:echo (post-processor). Wired via `prism_cimco`.
 */

