/** One machine def from machine-index.json (`scripts/cimco-machine-index.mjs`). */
export interface CimcoMachineEntry {
  file: string;
  displayName: string | null;
  orientation: string | null; // "Lathe" | "Horizontal" | "Vertical" | "unknown"
  unit: string | null; // "mm" | "inch" | "unknown" (may be INFERRED — see unitSource)
  unitsResolved: boolean; // true ONLY when Header.Unit was declared; an inferred unit stays false
  // Units provenance (machine-index schema 1.1.0, U-CIMCO-MCFG-UNITS-INFER). SAFETY: never trust
  // `unit` alone — an "inferred-magnitude" unit is a best-guess (only ever "mm"), NOT a declaration.
  // A live-run clearance gate must require unitSource==="declared" OR (inferred AND operator-verified).
  unitSource?: "declared" | "inferred-magnitude" | "unknown";
  unitsInferred?: boolean;
  inferenceConfidence?: "high" | "medium" | null;
  maxLinearRange?: number | null; // max linear-axis travel (the inference magnitude); null if none
  axes?: string[];
  axisCount?: number;
  collisionPairs?: number;
  hasRevolver?: boolean;
  toolchangePositions?: number;
  maxCuttingFeedrate?: number | null;
  warnings?: string[];
}

interface MachineIndex {
  schemaVersion: string;
  machineCount: number;
  byOrientation: Record<string, number>;
  byUnit: Record<string, number>;
  byUnitSource?: Record<string, number>; // {declared, inferred-magnitude, unknown} (schema 1.1.0)
  unresolvedUnits: string[]; // filenames NOT authoritatively declaring Header.Unit (= inferred + unknown)
  unitsInferred?: string[]; // subset of unresolvedUnits whose unit was magnitude-inferred (best-guess mm)
  unitsUnknown?: string[]; // subset with neither a declaration nor a usable magnitude (never use blind)
  machines: CimcoMachineEntry[];
}

