import { describe, it, expect, beforeAll } from "vitest";
import { z } from "zod";

import { registerSessionDispatcher } from "../tools/dispatchers/sessionDispatcher.js";

type Handler = (args: { action: string; params?: Record<string, unknown> }) => Promise<{
  content: Array<{ type: "text"; text: string }>;
}>;

let invoke: (action: string, params?: Record<string, unknown>) => Promise<Record<string, unknown>>;

beforeAll(() => {
  let captured: Handler | undefined;
  const fakeServer = {
    tool: (
      _name: string,
      _desc: string,
      _schema: { action: z.ZodEnum; params: z.ZodOptional<z.ZodRecord<z.ZodString, z.ZodAny>> },
      handler: Handler,
    ) => {
      captured = handler;
    },
  };
  registerSessionDispatcher(fakeServer);
  if (!captured) throw new Error("registerSessionDispatcher did not register the prism_session tool");
  const h = captured;
  invoke = async (action, params = {}) => {
    const res = await h({ action, params });
    return JSON.parse(res.content[0].text) as Record<string, unknown>;
  };
});

const SOURCE = [
  "DREAM: memory: remember to import kc from constants.ts",
  "DREAM: skill: path=ops/foo.md | scaffolds a foo",
  "just a normal line, ignored",
  'DREAM: fact: { "type": "preference", "key": "editor", "value": "vim" }',
  "DREAM: fact: not-valid-json",          // matches the DREAM: prefix but body fails JSON → malformed bucket
].join("\n");

// NOTE: the dispatcher wraps every response in slimResponse() (responseSlimmer.ts),
// which DROPS empty arrays + null/undefined keys. So a scan that produces no markers
// (or no malformed) returns a `result` with those keys ABSENT, not `[]`. The tests
// below reflect that real dispatcher-wide contract.
describe("prism_session::dream_scan (DreamMarkerScannerEngine round-trip)", () => {
  it("dream_scan parses valid DREAM: markers + buckets a malformed one", async () => {
    const r = await invoke("dream_scan", { source: SOURCE });
    expect(r.success).toBe(true);
    const result = r.result as { markers: Array<{ kind: string }>; malformed: unknown[]; total_lines_scanned: number };
    expect(result.total_lines_scanned).toBe(5);
    // 3 valid markers (memory, skill, fact); the bad-JSON fact lands in malformed[].
    expect(result.markers.length).toBe(3);
    expect(result.markers.map((m) => m.kind).sort()).toEqual(["fact", "memory", "skill"]);
    expect(result.malformed.length).toBe(1);
  });

  it("dream_scan on a marker-free source yields zero markers (empty array slimmed away)", async () => {
    const r = await invoke("dream_scan", { source: "nothing to see\nhere either" });
    expect(r.success).toBe(true);
    const result = r.result as { markers?: unknown[]; total_lines_scanned: number };
    // scan ran over both lines, found nothing → markers/malformed slimmed out entirely.
    expect(result.total_lines_scanned).toBe(2);
    expect((result.markers ?? []).length).toBe(0);
  });

  it("dream_markers_to_proposals adapts scanned markers → DreamArtifactBundle proposals", async () => {
    const scanned = await invoke("dream_scan", { source: SOURCE });
    const markers = (scanned.result as { markers: unknown[] }).markers;
    const r = await invoke("dream_markers_to_proposals", {
      markers,
      opts: {
        slot_soul_path: "state/shared/slot-souls/bravo.md",
        skill_root: ".claude/commands",
        source_path: "state/shared/handoffs/HANDOFF-test.md",
      },
    });
    expect(r.success).toBe(true);
    const proposals = r.proposals as Array<{
      proposal_id: string; target_path: string; mutation_type: string; risk_class: string; provenance: string;
    }>;
    expect(proposals.length).toBe(3);
    // skill marker → a "write" proposal under skill_root (concrete field assertions, not toBeDefined).
    const skill = proposals.find((p) => p.risk_class === "skill");
    expect(skill?.mutation_type).toBe("write");
    expect(skill?.target_path).toBe(".claude/commands/ops/foo.md");
    // memory + fact markers → "append" proposals targeting the soul path.
    const mem = proposals.filter((p) => p.risk_class === "memory");
    expect(mem.length).toBe(2);
    expect(mem.every((p) => p.mutation_type === "append")).toBe(true);
    expect(mem.every((p) => p.target_path === "state/shared/slot-souls/bravo.md")).toBe(true);
    // provenance must carry the source_path the caller supplied (round-trip fidelity).
    expect(proposals[0].provenance).toContain("HANDOFF-test.md");
  });
});
