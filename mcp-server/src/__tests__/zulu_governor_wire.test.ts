import { describe, it, expect, beforeAll } from "vitest";
import { z } from "zod";

import { registerSessionDispatcher } from "../tools/dispatchers/sessionDispatcher.js";

type Handler = (args: { action: string; params?: Record<string, unknown> }) => Promise<{
  content: Array<{ type: "text"; text: string }>;
}>;

let invoke: (action: string, params?: Record<string, unknown>) => Promise<Record<string, unknown>>;

beforeAll(() => {
  let captured: Handler | undefined;
  const fakeServer = {
    tool: (
      _name: string,
      _desc: string,
      _schema: { action: z.ZodEnum; params: z.ZodOptional<z.ZodRecord<z.ZodString, z.ZodAny>> },
      handler: Handler,
    ) => {
      captured = handler;
    },
  };
  registerSessionDispatcher(fakeServer);
  if (!captured) throw new Error("registerSessionDispatcher did not register the prism_session tool");
  const h = captured;
  invoke = async (action, params = {}) => {
    const res = await h({ action, params });
    return JSON.parse(res.content[0].text) as Record<string, unknown>;
  };
});

// A minimal SlotSoul-shaped object — the governor only reads refuse_list /
// domain_filter / hermes_role. Cast through unknown to avoid coupling the test
// to every SlotSoul field.
function soul(partial: Record<string, unknown>): Record<string, unknown> {
  return { slot: "bravo", refuse_list: [], domain_filter: "", hermes_role: "", ...partial };
}

describe("prism_session::zulu_authority_check (ZuluFleetGovernorEngine round-trip)", () => {
  it("rule 1 — refuse-list hit vetoes the op (authorized:false + matched_refuse)", async () => {
    const r = await invoke("zulu_authority_check", {
      request: { slot: "bravo", task_text: "please inline-physics-constants in the kc table", operation: "assign" },
      soul: soul({ refuse_list: ["inline-physics-constants"], domain_filter: "mill", hermes_role: "specialist-mill" }),
    });
    expect(r.success).toBe(true);
    const v = r.verdict as Record<string, unknown>;
    expect(v.authorized).toBe(false);
    expect(v.matched_refuse).toBe("inline-physics-constants");
    expect(String(v.reason)).toMatch(/refuse-rule-veto/);
  });

  it("rule 2 — domain match grants positive authority (authorized:true + matched_domain)", async () => {
    const r = await invoke("zulu_authority_check", {
      request: { slot: "bravo", task_text: "optimize the milling feed for the pocket", operation: "assign" },
      soul: soul({ domain_filter: "mill|milling", hermes_role: "specialist-mill" }),
    });
    const v = r.verdict as Record<string, unknown>;
    expect(v.authorized).toBe(true);
    expect(v.matched_domain).toBe(true);
    expect(String(v.reason)).toMatch(/domain-match/);
  });

  it("rule 3 — domain set but task out of role → reject (authorized:false)", async () => {
    const r = await invoke("zulu_authority_check", {
      request: { slot: "bravo", task_text: "program a lathe turning cycle", operation: "assign" },
      soul: soul({ domain_filter: "mill|milling", hermes_role: "specialist-mill" }),
    });
    const v = r.verdict as Record<string, unknown>;
    expect(v.authorized).toBe(false);
    expect(String(v.reason)).toMatch(/domain-mismatch/);
  });

  it("rule 4 — no domain filter + orchestrator role → cleared", async () => {
    const r = await invoke("zulu_authority_check", {
      request: { slot: "zulu", task_text: "rebalance the fleet queue", operation: "assign" },
      soul: soul({ domain_filter: "", hermes_role: "fleet-orchestrator" }),
    });
    const v = r.verdict as Record<string, unknown>;
    expect(v.authorized).toBe(true);
    expect(String(v.reason)).toMatch(/orchestrator-role/);
  });

  it("rule 4 — no domain filter + non-orchestrator role → rejected", async () => {
    const r = await invoke("zulu_authority_check", {
      request: { slot: "bravo", task_text: "do a thing", operation: "assign" },
      soul: soul({ domain_filter: "", hermes_role: "specialist-mill" }),
    });
    const v = r.verdict as Record<string, unknown>;
    expect(v.authorized).toBe(false);
    expect(String(v.reason)).toMatch(/not-orchestrator/);
  });

  it("informational op (bus-send) with no soul is allowed (no control granted)", async () => {
    const r = await invoke("zulu_authority_check", {
      request: { slot: "bravo", task_text: "broadcast status", operation: "bus-send" },
      soul: null,
    });
    const v = r.verdict as Record<string, unknown>;
    expect(v.authorized).toBe(true);
    expect(String(v.reason)).toMatch(/informational-op-no-soul-required/);
  });

  it("zulu_authority_check_render renders the verdict to markdown", async () => {
    const checked = await invoke("zulu_authority_check", {
      request: { slot: "bravo", task_text: "optimize milling feed", operation: "assign" },
      soul: soul({ domain_filter: "mill", hermes_role: "specialist-mill" }),
    });
    const r = await invoke("zulu_authority_check_render", { verdict: checked.verdict });
    expect(r.success).toBe(true);
    expect(String(r.markdown)).toMatch(/^\[AUTH (OK|DENY)\]/);
  });
});
