/** Get profiles by brand */
export function getLathesByBrand(brand: string): LatheHardeningProfile[] {
  return ALL_LATHE_PROFILES.filter(p => p.brand.toLowerCase() === brand.toLowerCase());
}

/** Get profiles by controller family */
export function getLathesByController(family: LatheControllerFamily): LatheHardeningProfile[] {
  return ALL_LATHE_PROFILES.filter(p => p.controller_family === family);
}

/** Get profiles with specific capability */
export function getLathesWithCapability(capability: keyof LatheHardeningProfile): LatheHardeningProfile[] {
  return ALL_LATHE_PROFILES.filter(p => (p as any)[capability] === true);
}

/** Get controller knowledge by family */
