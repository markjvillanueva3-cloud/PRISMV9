/** Controller family (defined here to avoid circular import) */
export type LatheControllerFamily =
  | "fanuc" | "okuma" | "mazak" | "haas" | "siemens" | "dmg" | "hurco" | "doosan";

export interface LatheHardeningProfile {
  machine_id: string;
  brand: string;
  model: string;
  controller_family: LatheControllerFamily;
  controller_model: string;

  // Capacity
  max_bar_od_mm: number;
  max_turning_diameter_mm: number;
  max_turning_length_mm: number;

  // Spindle
  max_spindle_rpm: number;
  spindle_power_kw: number;
  spindle_torque_nm?: number;
  spindle_bore_mm?: number;

  // Capabilities
  live_tooling: boolean;
  sub_spindle: boolean;
  y_axis: boolean;
  c_axis: boolean;
  b_axis?: boolean;
  tailstock: boolean;
  bar_feeder_capable: boolean;

  // Turret
  turret_stations: number;
  turret_type: "BOT" | "VDI" | "BMT" | "hybrid";
  tool_change_sec: number;

  // AI Hardening Metadata
  sf_scale_factor: number;
  primary_application: string;
  controller_dialect_notes: string[];
  known_quirks: string[];
  recommended_operations: string[];
}

export interface ControllerKnowledgeBase {
  family: LatheControllerFamily;
  css_syntax: string;
  threading_syntax: string;
  tnrc_mode: string;
  recovery_procedure: string;
  macro_support: string;
  notable_features: string[];
}

