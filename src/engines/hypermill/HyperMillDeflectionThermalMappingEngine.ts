/**
 * HyperMillDeflectionThermalMappingEngine — Deflection + Thermal Parameter Mapping
 *
 * U-HKC42: Maps hyperMILL CAM parameters to their downstream deflection and thermal
 * physics engines. Each mapping captures which CAM parameter drives which physical
 * effect, the physics chain, material sensitivity, and the applicable limit/threshold.
 *
 * Target engines:
 *   - ToolDeflectionEngine       — cantilever beam bending: delta = FL³/3EI
 *   - PartDeflectionEngine       — workpiece compliance under cutting forces
 *   - ThermalWearCouplingEngine  — coupled ODE (RK4) Usui wear, temperature rise
 *   - CuttingTemperatureEngine   — flash temperature at chip-tool interface
 *
 * Material sensitivity classification:
 *   - "high"   — Ti-6Al-4V, Inconel 718, Waspaloy, hardened steel (>45 HRC)
 *   - "medium" — stainless steel, alloy steel, cast iron, tool steel
 *   - "low"    — 6061-T6 aluminum, brass, copper, plastics
 *
 * @domain CAM-DeflectionThermal-Mapping
 * @milestone HM-KC-MS8/U-HKC42
 */

// ── Interface ──────────────────────────────────────────────────────────────────

export interface DeflectionThermalMapping {
  /** Unique identifier for this mapping entry */
  parameterId: string;
  /** CAM domain this parameter belongs to (e.g., "3d_milling", "turning") */
  parameterDomain: string;
  /** The downstream physics engine this parameter feeds */
  targetEngine: "ToolDeflectionEngine" | "PartDeflectionEngine" | "ThermalWearCouplingEngine" | "CuttingTemperatureEngine";
  /** Physical effect category */
  mappingType: "deflection_limit" | "thermal_limit" | "wear_rate" | "temperature_check";
  /** Physics derivation chain for this mapping */
  physicsChain: string;
  /** Limit value or threshold string (optional — not all params have hard limits) */
  limitValue?: string;
  /** Material sensitivity classification */
  materialSensitivity: "high" | "medium" | "low";
  /** Confidence level of this mapping (0.0–1.0 as string) */
  confidenceLevel: string;
}

