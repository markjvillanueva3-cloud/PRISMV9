// ── Summary ───────────────────────────────────────────────────────────────────

function buildSummary() {
  const deflectionMappings = DEFLECTION_THERMAL_MAPPINGS.filter(
    (m) => m.mappingType === "deflection_limit"
  ).length;

  const thermalMappings = DEFLECTION_THERMAL_MAPPINGS.filter(
    (m) =>
      m.mappingType === "thermal_limit" ||
      m.mappingType === "wear_rate" ||
      m.mappingType === "temperature_check"
  ).length;

  const byDomain: Record<string, number> = {};
  for (const m of DEFLECTION_THERMAL_MAPPINGS) {
    byDomain[m.parameterDomain] = (byDomain[m.parameterDomain] ?? 0) + 1;
  }

  const byEngine: Record<string, number> = {};
  for (const m of DEFLECTION_THERMAL_MAPPINGS) {
    byEngine[m.targetEngine] = (byEngine[m.targetEngine] ?? 0) + 1;
  }

  const byMaterialSensitivity: Record<string, number> = {};
  for (const m of DEFLECTION_THERMAL_MAPPINGS) {
    byMaterialSensitivity[m.materialSensitivity] =
      (byMaterialSensitivity[m.materialSensitivity] ?? 0) + 1;
  }

  return {
    totalMappings: DEFLECTION_THERMAL_MAPPINGS.length,
    deflectionMappings,
    thermalMappings,
    byDomain,
    byEngine,
    byMaterialSensitivity,
  };
}

export const DEFLECTION_THERMAL_MAPPING_SUMMARY = buildSummary();

// ── Engine Class ──────────────────────────────────────────────────────────────

/**
 * HyperMillDeflectionThermalMappingEngine
 *
 * Provides query and analysis methods over the deflection + thermal parameter
 * mapping catalog. All methods are pure (no I/O, no side effects).
 *
 * Usage:
 *   const engine = new HyperMillDeflectionThermalMappingEngine();
 *   const tiMappings = engine.getMappingsByMaterialSensitivity("high");
 *   const deflOnly  = engine.getDeflectionMappings();
 */
export class HyperMillDeflectionThermalMappingEngine {
  /**
   * Returns all mappings targeting a specific physics engine.
   *
   * @param targetEngine - The downstream engine name to filter by
   * @returns Filtered array of DeflectionThermalMapping entries
   */
  getMappingsByEngine(
    targetEngine: DeflectionThermalMapping["targetEngine"]
  ): DeflectionThermalMapping[] {
    return DEFLECTION_THERMAL_MAPPINGS.filter((m) => m.targetEngine === targetEngine);
  }

  /**
   * Returns all deflection-type mappings (mappingType === "deflection_limit").
   *
   * @returns Array of deflection mappings
   */
  getDeflectionMappings(): DeflectionThermalMapping[] {
    return DEFLECTION_THERMAL_MAPPINGS.filter((m) => m.mappingType === "deflection_limit");
  }

  /**
   * Returns all thermal-type mappings (thermal_limit, wear_rate, temperature_check).
   *
   * @returns Array of thermal mappings
   */
  getThermalMappings(): DeflectionThermalMapping[] {
    return DEFLECTION_THERMAL_MAPPINGS.filter(
      (m) =>
        m.mappingType === "thermal_limit" ||
        m.mappingType === "wear_rate" ||
        m.mappingType === "temperature_check"
    );
  }

  /**
   * Returns mappings for a specific CAM parameter domain.
   *
   * @param domain - e.g., "3d_milling", "turning", "drilling"
   * @returns Filtered array of mappings
   */
  getMappingsByDomain(domain: string): DeflectionThermalMapping[] {
    return DEFLECTION_THERMAL_MAPPINGS.filter((m) => m.parameterDomain === domain);
  }

  /**
   * Returns mappings for a specific material sensitivity level.
   *
   * @param sensitivity - "high" | "medium" | "low"
   * @returns Filtered array of mappings
   */
  getMappingsByMaterialSensitivity(
    sensitivity: DeflectionThermalMapping["materialSensitivity"]
  ): DeflectionThermalMapping[] {
    return DEFLECTION_THERMAL_MAPPINGS.filter((m) => m.materialSensitivity === sensitivity);
  }

  /**
   * Returns a summary of the full mapping catalog with counts per dimension.
   *
   * @returns The pre-built summary object
   */
  getSummary(): typeof DEFLECTION_THERMAL_MAPPING_SUMMARY {
    return DEFLECTION_THERMAL_MAPPING_SUMMARY;
  }

  /**
   * Returns all mappings for a given mapping type.
   *
   * @param mappingType - "deflection_limit" | "thermal_limit" | "wear_rate" | "temperature_check"
   * @returns Filtered array of mappings
   */
  getMappingsByType(
    mappingType: DeflectionThermalMapping["mappingType"]
  ): DeflectionThermalMapping[] {
    return DEFLECTION_THERMAL_MAPPINGS.filter((m) => m.mappingType === mappingType);
  }
}

/** Singleton instance for direct use */
export const deflectionThermalMappingEngine = new HyperMillDeflectionThermalMappingEngine();
