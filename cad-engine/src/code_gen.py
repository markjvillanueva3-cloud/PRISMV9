"""CadQuery Code Generator — CC-MS3.

Assembles translated features into a complete CadQuery script with:
  - Imports
  - Parameter declarations (fully parameterized)
  - Feature sequence (ordered operations)
  - Export call (STEP file)
  - Provenance comments linking back to source video/timestamp
"""

from __future__ import annotations

import os
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

from feature_translator import FeatureTranslator, TranslatedOp
from param_template import ParamTemplateGenerator, ParamDef


class CodeGenerator:
    """Generates complete CadQuery scripts from knowledge schema feature trees."""

    def __init__(self) -> None:
        self._translator = FeatureTranslator()
        self._param_gen = ParamTemplateGenerator()

    def generate(
        self,
        knowledge: dict,
        output_path: Optional[str] = None,
        part_name: Optional[str] = None,
    ) -> GeneratedScript:
        """Generate a CadQuery script from extracted knowledge.

        Args:
            knowledge: Extracted knowledge dict (knowledge_schema_v2 format).
                       Must contain 'cad' domain with 'features'.
            output_path: Optional path to write the script file.
            part_name: Optional name for the part (used in file naming).

        Returns:
            GeneratedScript with code, params, and metadata.
        """
        # Extract features from knowledge
        cad_data = knowledge.get("cad", knowledge.get("domains", {}).get("cad", {}))
        features = cad_data.get("features", [])

        if not features:
            raise ValueError("No CAD features found in knowledge data")

        # Extract provenance info
        video_id = knowledge.get("video_id", knowledge.get("source_id", "unknown"))
        title = knowledge.get("title", part_name or "generated_part")

        # Step 1: Extract parameters
        params = self._param_gen.extract_params(features)

        # Step 2: Translate features to CadQuery ops
        ops = self._translator.translate_tree(features)

        # Step 3: Assemble code
        code = self._assemble(
            ops=ops,
            params=params,
            part_name=_safe_name(part_name or title),
            video_id=video_id,
            title=title,
        )

        result = GeneratedScript(
            code=code,
            params=params,
            feature_count=len(features),
            op_count=len(ops),
            part_name=part_name or title,
            video_id=video_id,
        )

        # Write to file if path given
        if output_path:
            Path(output_path).parent.mkdir(parents=True, exist_ok=True)
            Path(output_path).write_text(code, encoding="utf-8")
            result.output_path = output_path

        return result

    def generate_from_features(
        self,
        features: list[dict],
        part_name: str = "part",
        video_id: str = "unknown",
    ) -> GeneratedScript:
        """Generate from a raw feature list (without full knowledge wrapper)."""
        knowledge = {
            "video_id": video_id,
            "title": part_name,
            "cad": {"features": features},
        }
        return self.generate(knowledge, part_name=part_name)

    def _assemble(
        self,
        ops: list[TranslatedOp],
        params: list[ParamDef],
        part_name: str,
        video_id: str,
        title: str,
    ) -> str:
        """Assemble all sections into a complete script."""
        sections: list[str] = []

        # Header with provenance
        sections.append(self._header(part_name, video_id, title))

        # Imports
        all_imports = {"cadquery as cq"}
        for op in ops:
            all_imports.update(op.imports)
        sections.append(self._imports(all_imports))

        # Parameters
        param_block = self._param_gen.generate_param_block(params)
        sections.append(param_block)

        # Build sequence
        sections.append(self._build_sequence(ops, params))

        # Export
        sections.append(self._export(part_name))

        return "\n\n".join(sections) + "\n"

    def _header(self, part_name: str, video_id: str, title: str) -> str:
        ts = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        return (
            f'"""Auto-generated CadQuery script — {title}\n'
            f"\n"
            f"Generated by PRISM Parametric Code Generator (CC-MS3)\n"
            f"Source: video_id={video_id}\n"
            f"Generated at: {ts}\n"
            f"\n"
            f"All dimensions are fully parameterized.\n"
            f"Modify parameters below to customize the part.\n"
            f'"""\n'
        )

    def _imports(self, import_set: set[str]) -> str:
        lines = sorted(f"import {imp}" for imp in import_set)
        return "\n".join(lines)

    def _build_sequence(
        self, ops: list[TranslatedOp], params: list[ParamDef]
    ) -> str:
        lines = [
            "# " + "=" * 68,
            "# Build sequence",
            "# " + "=" * 68,
            "",
        ]

        # Substitute parameter names into code
        param_map = {p.name: p.name for p in params}

        for i, op in enumerate(ops):
            # Comment with provenance
            if op.comment:
                lines.append(f"# Step {i + 1}: {op.comment}")
            if op.provenance_note:
                lines.append(f"#   Provenance: {op.provenance_note}")

            # Code (substitute literal values with param names where possible)
            code = _substitute_params(op.code, params)
            lines.append(code)
            lines.append("")

        return "\n".join(lines)

    def _export(self, part_name: str) -> str:
        safe = _safe_name(part_name)
        return (
            "# " + "=" * 68 + "\n"
            "# Export\n"
            "# " + "=" * 68 + "\n"
            "\n"
            f'cq.exporters.export(result, "{safe}.step")\n'
            f'print(f"Exported {safe}.step")\n'
        )


class GeneratedScript:
    """Result of code generation."""

    def __init__(
        self,
        code: str,
        params: list[ParamDef],
        feature_count: int,
        op_count: int,
        part_name: str,
        video_id: str,
    ):
        self.code = code
        self.params = params
        self.feature_count = feature_count
        self.op_count = op_count
        self.part_name = part_name
        self.video_id = video_id
        self.output_path: Optional[str] = None

    def __repr__(self) -> str:
        return (
            f"GeneratedScript(part={self.part_name!r}, "
            f"features={self.feature_count}, ops={self.op_count}, "
            f"params={len(self.params)})"
        )


def _safe_name(name: str) -> str:
    """Convert a name to a safe filename/identifier."""
    result = ""
    for ch in name.lower().strip():
        if ch.isalnum() or ch == "_":
            result += ch
        elif ch in (" ", "-", "."):
            result += "_"
    return result or "part"


def _substitute_params(code: str, params: list[ParamDef]) -> str:
    """Attempt to substitute literal values with parameter names.

    This is a best-effort substitution — it replaces exact numeric
    matches in the code with the parameter variable name.
    """
    for p in params:
        if isinstance(p.value, (int, float)):
            # Format value same way as translator
            if isinstance(p.value, float):
                if p.value == int(p.value):
                    literal = str(int(p.value))
                else:
                    literal = f"{p.value:.4g}"
            else:
                literal = str(p.value)

            # Replace in code (only exact matches in function args)
            code = code.replace(f"({literal})", f"({p.name})")
            code = code.replace(f"({literal},", f"({p.name},")
            code = code.replace(f", {literal})", f", {p.name})")
            code = code.replace(f", {literal},", f", {p.name},")
    return code
