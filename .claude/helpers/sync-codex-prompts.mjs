#!/usr/bin/env node
/**
 * sync-codex-prompts.mjs — mirror PRISM slash commands into Codex's custom-prompts dir.
 *
 * Codex CLI exposes `~/.codex/prompts/<name>.md` as a `/<name>` command. PRISM's
 * slash commands are authored as `H:/PRISM/.claude/commands/<name>.md` (project) and
 * `~/.claude/commands/<name>.md` (global). This script writes a *thin shim* for each
 * into `~/.codex/prompts/`: a one-line description + a pointer at the canonical PRISM
 * spec + an adaptation note (Codex has no `Skill` tool / hooks / `Agent` subagents —
 * read the spec and execute the steps directly, treating AGENTS.md as your CLAUDE.md).
 * The shims are GENERATED — re-running overwrites them; hand edits go to the canonical
 * spec, not here.
 *
 * Scope (default: "project" — the PRISM-specific command set):
 *   --project   ~/PRISM/.claude/commands/*.md            (default)
 *   --all       project ∪ ~/.claude/commands/*.md         (everything; ~500 files)
 *   --curated   only the high-traffic set (CRITICAL_SET below)
 *   --dry-run   print what would be written, write nothing
 *
 * Always also writes `~/.codex/prompts/prism.md` — a meta-pointer at the full catalog
 * (`H:/PRISM/state/shared/CLAUDE-CODEX-COMMAND-BRIDGE.md`) so the long tail is reachable.
 *
 * Idempotent. Marks each generated file with a header so a future cleanup can find them.
 * Run after editing the PRISM command set, or wire from the same trigger as
 * `sync-cli-context-files.mjs`.
 *
 * @module helpers/sync-codex-prompts
 */

import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync, statSync, rmSync } from "node:fs";
import { join, basename, extname } from "node:path";
import { homedir } from "node:os";
import { fileURLToPath } from "node:url";

const HOME = homedir().replace(/\\/g, "/");
const SELF = fileURLToPath(import.meta.url).replace(/\\/g, "/");
const REPO_ROOT = SELF.replace(/\/\.claude\/helpers\/[^/]+$/, ""); // .../H:/prism
const PROJECT_CMDS = `${REPO_ROOT}/.claude/commands`;
const GLOBAL_CMDS = `${HOME}/.claude/commands`;
const PROMPTS_DIR = `${HOME}/.codex/prompts`;
const BRIDGE_DOC = `${REPO_ROOT}/state/shared/CLAUDE-CODEX-COMMAND-BRIDGE.md`;
const SPEC_PREFIX = "H:/PRISM/.claude/commands"; // canonical, repo-rooted (audit/doctrine use uppercase PRISM)

const GENERATED_MARKER = "<!-- GENERATED by .claude/helpers/sync-codex-prompts.mjs — do not edit; edit the PRISM spec instead -->";

// The high-traffic PRISM commands (the "CRITICAL COMMANDS" tables across CLAUDE.md / AGENTS.md /
// .codex/AGENTS.md / the command bridge). Always shimmed even in --curated mode.
const CRITICAL_SET = [
  "startup", "handoff", "precompact", "checkin", "scrutinize", "dedup", "forge-triple", "forge4", "rgs6",
  "pdf-learn", "video-learn", "shop-knowledge", "wire-edm-studio", "lathe-studio", "quote-to-ship",
  "auto-speed-feed", "program-optimize", "system-viz", "build-state", "smart", "forge-audit", "dispatch-format",
  "auto-commit", "print-to-program", "full-job", "machine-harden", "envelope-sync", "run-continuous",
];

function parseArgs(argv) {
  const out = { scope: "project", dryRun: false };
  for (const a of argv) {
    if (a === "--all") out.scope = "all";
    else if (a === "--curated") out.scope = "curated";
    else if (a === "--project") out.scope = "project";
    else if (a === "--dry-run" || a === "-n") out.dryRun = true;
  }
  return out;
}

/** First markdown heading / first non-empty non-frontmatter line of a command spec → a one-line summary. */
function firstSummaryLine(src) {
  const lines = src.split(/\r?\n/);
  let i = 0;
  // skip a leading YAML frontmatter block
  if (lines[0]?.trim() === "---") {
    i = 1;
    while (i < lines.length && lines[i].trim() !== "---") i++;
    i++; // past the closing ---
  }
  // skip HTML comment lines + blanks
  for (; i < lines.length; i++) {
    const t = lines[i].trim();
    if (!t || (t.startsWith("<!--") && t.endsWith("-->"))) continue;
    // a `# Title — subtitle` heading: take the whole thing minus the leading #'s
    if (t.startsWith("#")) return t.replace(/^#+\s*/, "").slice(0, 200);
    return t.slice(0, 200);
  }
  return "";
}

/** Build the shim body for one PRISM command. */
function shimFor(name, summary, sourceLabel) {
  const spec = `${SPEC_PREFIX}/${name}.md`;
  return [
    GENERATED_MARKER,
    "",
    `# /${name}${summary ? ` — ${summary}` : ""}`,
    "",
    `This is the PRISM \`/${name}\` slash command. The canonical, authoritative spec lives in the repo` +
      (sourceLabel === "global" ? " (global command, mirrored here for Codex)" : "") + ":",
    "",
    `> **${spec}**`,
    "",
    `**Read that file and execute its steps.** It is written for Claude Code — adapt to Codex as you go:`,
    `- a \`Skill(...)\` / \`/<name>\` invocation → just perform the steps it describes;`,
    `- a Claude \`Agent({subagent_type:...})\` spawn → spawn a Codex sub-agent for that subtask, or do it inline;`,
    `- "CLAUDE.md" → \`H:/PRISM/AGENTS.md\` (the repo doctrine Codex auto-loads) and \`H:/PRISM/CODEX.md\`;`,
    `- Claude UserPromptSubmit/Stop hooks → call the \`prism\` MCP server + \`codex-self-awareness.mjs\` proactively;`,
    `- shell: prefix with \`rtk\` for token economy; route physics to \`prism_calc\`, safety to \`prism_safety\`.`,
    "",
    `If \`${spec}\` is missing on disk, fall back to the catalog: \`H:/PRISM/state/shared/CLAUDE-CODEX-COMMAND-BRIDGE.md\`.`,
    "",
  ].join("\n");
}

function listCommandFiles(dir) {
  if (!existsSync(dir)) return [];
  try {
    return readdirSync(dir)
      .filter((f) => extname(f).toLowerCase() === ".md")
      .filter((f) => !/^_/.test(f) && !/\.bak/i.test(f) && !/^README/i.test(f))
      .map((f) => ({ name: basename(f, ".md"), path: join(dir, f) }));
  } catch {
    return [];
  }
}

function main() {
  const { scope, dryRun } = parseArgs(process.argv.slice(2));
  // project commands take precedence on a name collision
  const project = listCommandFiles(PROJECT_CMDS);
  const projectNames = new Set(project.map((c) => c.name));
  const globalOnly = listCommandFiles(GLOBAL_CMDS).filter((c) => !projectNames.has(c.name));

  let selected;
  if (scope === "all") {
    selected = [...project.map((c) => ({ ...c, src: "project" })), ...globalOnly.map((c) => ({ ...c, src: "global" }))];
  } else if (scope === "curated") {
    const byName = new Map([...globalOnly.map((c) => [c.name, { ...c, src: "global" }]), ...project.map((c) => [c.name, { ...c, src: "project" }])]);
    selected = CRITICAL_SET.map((n) => byName.get(n)).filter(Boolean);
  } else {
    // project (default) — plus any CRITICAL_SET member that only exists globally
    const projSel = project.map((c) => ({ ...c, src: "project" }));
    const projSelNames = new Set(projSel.map((c) => c.name));
    const extras = globalOnly.filter((c) => CRITICAL_SET.includes(c.name) && !projSelNames.has(c.name)).map((c) => ({ ...c, src: "global" }));
    selected = [...projSel, ...extras];
  }

  if (!dryRun) mkdirSync(PROMPTS_DIR, { recursive: true });

  // Sweep stale generated shims that no longer correspond to a selected command
  // (so renamed/removed PRISM commands don't leave dangling /-commands in Codex).
  const selectedNames = new Set(selected.map((c) => c.name));
  selectedNames.add("prism"); // the meta-pointer
  let swept = 0;
  if (existsSync(PROMPTS_DIR)) {
    for (const f of readdirSync(PROMPTS_DIR)) {
      if (extname(f).toLowerCase() !== ".md") continue;
      const p = join(PROMPTS_DIR, f);
      let head = "";
      try { head = readFileSync(p, "utf8").slice(0, 200); } catch { continue; }
      if (!head.includes(GENERATED_MARKER)) continue; // never touch a user-authored prompt
      if (!selectedNames.has(basename(f, ".md"))) {
        if (!dryRun) rmSync(p, { force: true });
        swept++;
      }
    }
  }

  let written = 0;
  for (const c of selected) {
    let summary = "";
    try { summary = firstSummaryLine(readFileSync(c.path, "utf8")); } catch { /* keep summary empty */ }
    const out = join(PROMPTS_DIR, `${c.name}.md`);
    const body = shimFor(c.name, summary, c.src);
    if (!dryRun) {
      // skip-unchanged
      let existing = "";
      try { existing = readFileSync(out, "utf8"); } catch { /* new */ }
      if (existing !== body) { writeFileSync(out, body); written++; }
    } else { written++; }
  }

  // The /prism meta-pointer at the full catalog (covers the long tail).
  const metaBody = [
    GENERATED_MARKER,
    "",
    "# /prism — PRISM command catalog & doctrine pointer",
    "",
    "PRISM has hundreds of slash commands. The ones most relevant to Codex are shimmed into this",
    "`~/.codex/prompts/` dir as `/<name>` commands; the **full catalog** (with Codex-side equivalents) is:",
    "",
    "> **H:/PRISM/state/shared/CLAUDE-CODEX-COMMAND-BRIDGE.md**  ·  registry: `state/shared/claude-codex-command-registry.json`",
    "",
    "To run any PRISM `/foo` the way PRISM intends, read `H:/PRISM/.claude/commands/foo.md` (the canonical spec).",
    "",
    "Doctrine: `H:/PRISM/AGENTS.md` (auto-loaded) · `H:/PRISM/CODEX.md` (Codex-native twin of CLAUDE.md) ·",
    "`H:/PRISM/.codex/AGENTS.md` (compact spawn bundle) · `H:/PRISM/state/shared/CLAUDE-CODEX-MCP-DIRECTIVE.md`.",
    "Self-awareness: `node H:/PRISM/.claude/helpers/codex-self-awareness.mjs` · commands: `codex-command-awareness.mjs`.",
    "Regenerate these shims: `node H:/PRISM/.claude/helpers/sync-codex-prompts.mjs [--project|--all|--curated]`.",
    "",
  ].join("\n");
  if (!dryRun) {
    let existingMeta = "";
    try { existingMeta = readFileSync(join(PROMPTS_DIR, "prism.md"), "utf8"); } catch { /* new */ }
    if (existingMeta !== metaBody) { writeFileSync(join(PROMPTS_DIR, "prism.md"), metaBody); written++; }
  } else { written++; }

  console.log(JSON.stringify({
    ok: true,
    scope,
    dryRun,
    promptsDir: PROMPTS_DIR,
    candidates: selected.length + 1, // + the meta pointer
    written,
    sweptStale: swept,
    bridgeDoc: existsSync(BRIDGE_DOC) ? BRIDGE_DOC : "(missing — run scripts/index/build-command-bridge.mjs)",
  }, null, 2));
}

main();
