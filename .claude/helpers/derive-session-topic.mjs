#!/usr/bin/env node
/**
 * derive-session-topic.mjs — Session-aware topic derivation
 *
 * Replaces the broken global-git-log topic logic in precompact-handoff.mjs +
 * enforce-handoff-topic.mjs that mis-attributed peer chats' work to this chat.
 *
 * Priority order (highest → lowest signal of THIS chat's actual work):
 *   1. Existing HANDOFF-{sessionId}-{topic}.md → reuse most-recently-modified
 *   2. State markers in mcp-server/data/state/{*}-state.json where
 *      last_updated_by === sessionId AND mtime within freshness window
 *   3. Recent git commits attributed to THIS chat by [SCOPE] in subject
 *      (skips peer commits — only counts ones likely written by us)
 *   4. CURRENT_POSITION.md milestone marker (shared, lowest priority)
 *   5. Branch last segment (work/foo-ms0 → foo-ms0)
 *
 * Returns: { topic: string|null, source: string, debug: string[] }
 *
 * USAGE (programmatic):
 *   import { deriveSessionTopic } from "./derive-session-topic.mjs";
 *   const { topic, source } = deriveSessionTopic(sessionId);
 *
 * USAGE (CLI for debugging):
 *   node derive-session-topic.mjs <sessionId>
 */

import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";

const HANDOFFS_DIR = path.resolve("H:/prism/state/shared/handoffs");
const STATE_DIR = path.resolve("H:/prism/mcp-server/data/state");
const POSITION_FILE = path.resolve("H:/prism/state/CURRENT_POSITION.md");
const PRISM_ROOT = path.resolve("H:/prism");

// State markers older than this are ignored (avoid resurrecting stale claims)
const STATE_FRESHNESS_MS = 6 * 60 * 60 * 1000; // 6 hours
// Existing handoff files older than this are ignored as topic source
const HANDOFF_FRESHNESS_MS = 24 * 60 * 60 * 1000; // 24 hours

function sanitizeTopic(t) {
  if (!t) return null;
  const cleaned = String(t).replace(/[^a-zA-Z0-9-]/g, "-").replace(/-+/g, "-").slice(0, 30);
  return cleaned.length > 0 ? cleaned.toLowerCase() : null;
}

function runGit(args) {
  const r = spawnSync("git", args, {
    cwd: PRISM_ROOT, encoding: "utf-8", windowsHide: true, timeout: 3000,
  });
  return r.status === 0 ? (r.stdout || "").trim() : "";
}

// Auto-generated handoff signature — STATE field set by precompact-handoff.mjs
const AUTOGEN_STATE_MARKERS = [
  "Pre-compact snapshot",
  "compacting — read per-agent handoff",
];

function isAutoGeneratedHandoff(filePath) {
  try {
    const content = fs.readFileSync(filePath, "utf-8");
    const stateMatch = content.match(/## STATE\s*\r?\n([\s\S]*?)(?=\r?\n##|\r?\n$)/);
    const state = stateMatch?.[1]?.trim() || "";
    return AUTOGEN_STATE_MARKERS.some(m => state.startsWith(m));
  } catch { return false; }
}

/**
 * Find existing handoff files for this session, classified by manual vs auto-generated.
 * Returns { manual: [{file, topic, mtime}, ...], auto: [...] } sorted newest-first.
 */
function classifyExistingHandoffs(sessionId, debug) {
  const result = { manual: [], auto: [] };
  if (!sessionId || !fs.existsSync(HANDOFFS_DIR)) return result;
  try {
    const files = fs.readdirSync(HANDOFFS_DIR);
    const prefix = `HANDOFF-${sessionId}-`;
    for (const f of files) {
      if (!f.startsWith(prefix) || !f.endsWith(".md")) continue;
      const filePath = path.join(HANDOFFS_DIR, f);
      const stat = fs.statSync(filePath);
      if (Date.now() - stat.mtimeMs > HANDOFF_FRESHNESS_MS) continue;
      const topic = f.slice(prefix.length, -3); // strip ".md"
      const entry = { file: f, topic, mtime: stat.mtimeMs };
      if (isAutoGeneratedHandoff(filePath)) {
        result.auto.push(entry);
      } else {
        result.manual.push(entry);
      }
    }
    result.manual.sort((a, b) => b.mtime - a.mtime);
    result.auto.sort((a, b) => b.mtime - a.mtime);
    debug.push(`handoffs: ${result.manual.length} manual + ${result.auto.length} auto for ${sessionId}`);
    return result;
  } catch (e) {
    debug.push(`handoffs: ERROR ${e.message}`);
    return result;
  }
}

/**
 * Signal 2: Scan state markers for ones attributed to this session.
 * Returns the milestoneId of the most-recently-touched one.
 */
function findStateMarkerTopic(sessionId, debug) {
  if (!sessionId || !fs.existsSync(STATE_DIR)) return null;
  try {
    const files = fs.readdirSync(STATE_DIR).filter(f => f.endsWith("-state.json"));
    const matches = [];
    for (const f of files) {
      try {
        const stat = fs.statSync(path.join(STATE_DIR, f));
        if (Date.now() - stat.mtimeMs > STATE_FRESHNESS_MS) continue;
        const j = JSON.parse(fs.readFileSync(path.join(STATE_DIR, f), "utf-8"));
        if (j.last_updated_by !== sessionId) continue;
        if (!j.milestoneId) continue;
        matches.push({ file: f, milestoneId: j.milestoneId, mtime: stat.mtimeMs });
      } catch { /* skip malformed */ }
    }
    matches.sort((a, b) => b.mtime - a.mtime);
    debug.push(`signal2: found ${matches.length} state marker(s) attributed to ${sessionId}`);
    if (matches.length === 0) return null;
    debug.push(`signal2: winner=${matches[0].file} milestone=${matches[0].milestoneId}`);
    return matches[0].milestoneId;
  } catch (e) {
    debug.push(`signal2: ERROR ${e.message}`);
    return null;
  }
}

/**
 * Signal 3 & 4: Last-resort topic from global git log + position file + branch.
 * Same logic as the original extractTopicSlug — used only when signals 1+2 fail.
 */
function findGlobalFallbackTopic(debug) {
  // Recent commit subject scope
  const recent = runGit(["log", "--oneline", "-1", "--format=%s"]);
  if (recent) {
    const m1 = recent.match(/\[(?:MAIN\]\s*)?([A-Z][\w-]+-MS\d+)/i);
    if (m1?.[1]) {
      debug.push(`signal3: commit-scope=${m1[1]}`);
      return m1[1];
    }
    const m2 = recent.match(/^([A-Z][\w-]+-MS\d+)/i);
    if (m2?.[1]) {
      debug.push(`signal3: commit-leading=${m2[1]}`);
      return m2[1];
    }
  }
  // Position file
  try {
    const pos = fs.readFileSync(POSITION_FILE, "utf-8");
    const m = pos.match(/(?:Last\s+Milestone|Current|##)\s*:?\s*([A-Z][\w-]+-MS\d+)/i);
    if (m?.[1]) {
      debug.push(`signal4: position=${m[1]}`);
      return m[1];
    }
  } catch { /* ignore */ }
  // Branch last segment
  const branch = runGit(["symbolic-ref", "--short", "HEAD"]);
  if (branch) {
    const last = branch.split("/").pop();
    if (last && last !== "main" && last !== "master" && last !== "develop") {
      debug.push(`signal5: branch=${last}`);
      return last;
    }
  }
  debug.push("signal3-5: no global fallback matched");
  return null;
}

/**
 * Main entry point. Priority order:
 *   1. MANUAL existing handoff (the chat deliberately chose this topic)
 *   2. State markers attributed to this session (active milestone work)
 *   3. AUTO-generated existing handoff (last precompact run — preserve continuity)
 *   4. Global fallback (commit/position/branch)
 *
 * Manual handoffs win over state markers because /handoff is a deliberate user
 * intent. State markers win over auto-generated handoffs to break the circular
 * trap where a previous bad precompact poisoned the topic.
 */
export function deriveSessionTopic(sessionId) {
  const debug = [];

  const handoffs = classifyExistingHandoffs(sessionId, debug);

  // Signal 1: manual handoff (deliberate user intent)
  if (handoffs.manual.length > 0) {
    const winner = handoffs.manual[0];
    debug.push(`signal1-MANUAL: winner=${winner.file} topic=${winner.topic}`);
    return { topic: sanitizeTopic(winner.topic), source: "manual-handoff", debug };
  }

  // Signal 2: state markers attributed to this session
  const fromState = findStateMarkerTopic(sessionId, debug);
  if (fromState) {
    return { topic: sanitizeTopic(fromState), source: "state-marker", debug };
  }

  // Signal 3: auto-generated handoff (preserve continuity from prior compact)
  if (handoffs.auto.length > 0) {
    const winner = handoffs.auto[0];
    debug.push(`signal3-AUTO: winner=${winner.file} topic=${winner.topic}`);
    return { topic: sanitizeTopic(winner.topic), source: "auto-handoff", debug };
  }

  // Signal 4: global fallback (commit/position/branch)
  const fromGlobal = findGlobalFallbackTopic(debug);
  if (fromGlobal) {
    return { topic: sanitizeTopic(fromGlobal), source: "global-fallback", debug };
  }

  return { topic: null, source: "none", debug };
}

// CLI for debugging
if (import.meta.url === `file://${process.argv[1].replace(/\\/g, "/")}` ||
    process.argv[1]?.endsWith("derive-session-topic.mjs")) {
  const sessionId = process.argv[2];
  if (!sessionId) {
    console.error("Usage: derive-session-topic.mjs <sessionId>");
    process.exit(1);
  }
  const result = deriveSessionTopic(sessionId);
  console.log(JSON.stringify(result, null, 2));
}
