#!/usr/bin/env node
// tier: T4
/**
 * Session Cost Summary — Stop Hook
 *
 * At session end, reads hook-telemetry.jsonl, filters to the current
 * session, and appends a per-session summary to state/shared/TOKEN_USAGE_LOG.json.
 * Turns "are these hooks working?" into a measurable question.
 *
 * Metrics captured per session:
 *  - cache hits (denies) per hook type
 *  - cache misses (records) per hook type
 *  - capability-reminder fires
 *  - rough token savings estimate (denies * avg-bytes-saved)
 *
 * Savings estimate is intentionally conservative — just a gut-check number,
 * not a precise measurement. Real tool I/O bytes are not available here.
 *
 * Never blocks on errors; log append is best-effort.
 *
 * Related: AGI-INFRA SESS-COST (Phase A extension).
 */

import { promises as fs } from "node:fs";
import path from "node:path";
import { createInterface } from "node:readline";

const CACHE_DIR = "H:/prism/.claude/cache";
const TELEMETRY_FILE = `${CACHE_DIR}/hook-telemetry.jsonl`;
const LOG_CANDIDATES = [
  "H:/prism-agi-infra-a/state/shared/TOKEN_USAGE_LOG.json",
  "H:/prism/state/shared/TOKEN_USAGE_LOG.json",
];
const MAX_LOG_ENTRIES = 500; // rolling cap

// Conservative byte estimates per cache-hit-avoided tool call
const BYTES_SAVED = {
  "file-read-cache": 4000, // average file read
  "grep-result-cache": 2500, // average grep output
  "bash-result-cache": 1500, // average bash output
  "capability-reminder": 0, // adds context, doesn't remove
};

async function readStdin() {
  return new Promise((resolve) => {
    let data = "";
    const rl = createInterface({ input: process.stdin });
    rl.on("line", (l) => (data += l + "\n"));
    rl.on("close", () => resolve(data));
  });
}

async function readTelemetry() {
  try {
    const raw = await fs.readFile(TELEMETRY_FILE, "utf8");
    const lines = raw.split("\n").filter((l) => l.trim());
    return lines
      .map((l) => {
        try { return JSON.parse(l); } catch { return null; }
      })
      .filter((e) => e !== null);
  } catch {
    return [];
  }
}

async function resolveLogPath() {
  for (const p of LOG_CANDIDATES) {
    try {
      await fs.access(path.dirname(p));
      return p;
    } catch {
      // try next
    }
  }
  return null;
}

async function loadLog(logPath) {
  try {
    const raw = await fs.readFile(logPath, "utf8");
    const parsed = JSON.parse(raw);
    if (parsed && Array.isArray(parsed.sessions)) return parsed;
  } catch {
    // create fresh
  }
  return {
    schemaVersion: "1.0",
    purpose: "Rolling per-session token savings log from PRISM cache hooks. Generated by session-cost-summary.mjs Stop hook.",
    sessions: [],
  };
}

async function saveLog(logPath, log) {
  // Trim rolling window
  if (log.sessions.length > MAX_LOG_ENTRIES) {
    log.sessions = log.sessions.slice(-MAX_LOG_ENTRIES);
  }
  try {
    await fs.writeFile(logPath, JSON.stringify(log, null, 2), "utf8");
  } catch {
    // non-fatal
  }
}

function summarize(events, sessionId) {
  const mine = events.filter((e) => {
    if (!sessionId) return true; // no session id → include all recent
    return e.session_id === sessionId;
  });

  const byHook = {};
  for (const e of mine) {
    if (!e.hook || !e.event) continue;
    const hook = e.hook;
    if (!byHook[hook]) {
      byHook[hook] = { deny: 0, miss: 0, fired: 0 };
    }
    if (e.event === "deny") byHook[hook].deny += 1;
    else if (e.event === "miss-recorded") byHook[hook].miss += 1;
    else if (e.event === "fired") byHook[hook].fired += 1;
  }

  let bytesSaved = 0;
  for (const [hook, counts] of Object.entries(byHook)) {
    bytesSaved += (counts.deny || 0) * (BYTES_SAVED[hook] || 0);
  }

  return { events_in_session: mine.length, byHook, bytesSaved };
}

async function main() {
  // Stop hook receives JSON on stdin but we only need session_id from it
  const raw = await readStdin();
  let event = {};
  try {
    event = JSON.parse(raw);
  } catch {
    // empty / malformed: still write a best-effort summary
  }
  const sessionId =
    event.session_id || event.sessionId || process.env.CLAUDE_SESSION_ID || null;

  const telemetry = await readTelemetry();
  const summary = summarize(telemetry, sessionId);
  if (summary.events_in_session === 0) process.exit(0);

  const logPath = await resolveLogPath();
  if (!logPath) process.exit(0);

  const log = await loadLog(logPath);
  log.sessions.push({
    ts: new Date().toISOString(),
    session_id: sessionId,
    events: summary.events_in_session,
    by_hook: summary.byHook,
    bytes_saved_estimate: summary.bytesSaved,
  });
  log.lastUpdated = new Date().toISOString();
  await saveLog(logPath, log);
  process.exit(0);
}

main().catch(() => process.exit(0));
