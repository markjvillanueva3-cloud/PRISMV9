#!/usr/bin/env node
// tier: T4
/**
 * claude-brief-precompact.mjs — PreCompact hook
 *
 * Awareness backbone protection during conversation compaction.
 *
 * Compaction squeezes the conversation history; without protection, the
 * SessionStart-injected CLAUDE-BRIEF.md content gets summarized away and
 * future-Claude loses the architectural context (process priority, JM fleet,
 * gaps, build doctrine). The post-compact SessionStart hook would re-inject,
 * but only if the conversation immediately reaches a SessionStart event —
 * inside an in-progress conversation that compacts mid-stream, the brief
 * needs to survive in the compacted form.
 *
 * This hook fires on PreCompact and outputs `additionalContext` that the
 * compactor sees. The instructions tell the compactor to PRESERVE a small
 * awareness anchor in the compacted summary: where the brief lives, the
 * three top facts (process priority, current branch, top gap), and the
 * Build Doctrine pre-build checklist as a one-liner.
 *
 * Output is intentionally tiny (<1KB) — we're not re-injecting the brief,
 * we're just ensuring the compacted summary has a foothold to refer back
 * to the brief on disk.
 */
import { shouldSkipHook as _hp_shouldSkip } from "../helpers/hook-profile.mjs";
import { existsSync, readFileSync, statSync } from "node:fs";

const BRIEF = "H:/prism/state/shared/CLAUDE-BRIEF.md";
const BUILD_CONTEXT = "H:/prism/state/shared/PRISM-BUILD-CONTEXT.md";
const BUILD_VISION = "H:/prism/state/shared/PRISM-BUILD-VISION.md";
const GAPS = "H:/prism/state/shared/AUDIT-PRIORITIZED-GAPS.md";

function emit(additionalContext) {
  // PreCompact is not a valid hookEventName per the harness schema (only
  // PreToolUse/UserPromptSubmit/PostToolUse/PostToolBatch are accepted).
  // For PreCompact, emit via top-level systemMessage so the compactor still
  // sees the awareness anchor without firing a hook_non_blocking_error.
  process.stdout.write(JSON.stringify({
    continue: true,
    systemMessage: additionalContext,
  }));
}

function readSafe(p) {
  try { return existsSync(p) ? readFileSync(p, "utf8") : ""; } catch { return ""; }
}

function ageHours(p) {
  if (!existsSync(p)) return Infinity;
  return (Date.now() - statSync(p).mtimeMs) / (1000 * 60 * 60);
}

function topGap(text) {
  const m = text.match(/^##\s+1\.\s+\*\*([^*]+)\*\*/m);
  return m ? m[1].trim() : "see AUDIT-PRIORITIZED-GAPS.md";
}

(async () => {
  if (await _hp_shouldSkip("claude-brief-precompact")) {
    process.exit(0);
  }
  try {
    const briefAge = ageHours(BRIEF);
    const gapText = readSafe(GAPS);
    const gap1 = topGap(gapText);

    const anchor = `**AWARENESS BACKBONE — PRESERVE THIS IN COMPACTED SUMMARY**

Three auto-injected files survive on disk and are the source of truth for PRISM:
- \`H:/prism/state/shared/CLAUDE-BRIEF.md\` (${briefAge === Infinity ? "missing" : briefAge.toFixed(1) + "h old"}) — what we have (process priority mill > lathe > WEDM, CAM tier-1 priority Fusion > hyperMILL > Mastercam > Esprit, JM fleet, AI hierarchy, gaps)
- \`H:/prism/state/shared/PRISM-BUILD-CONTEXT.md\` — what we're building (last 7d commits, peer claims, per-chat handoffs, queued next)
- \`H:/prism/state/shared/PRISM-BUILD-VISION.md\` — what we're trying to build (per-component max-value vision, audit-mapped gaps, build doctrine pointers per component)

These are auto-regenerated by SessionStart hook + drift monitor. If the post-compact Claude needs context that this summary doesn't cover, READ those three files directly — they are current. Do NOT re-derive PRISM architecture from compacted conversation memory; trust the files.

Top current gap (from latest audit): ${gap1}

Build Doctrine: before any new engine/script/hook, (1) check what we have in CLAUDE-BRIEF, (2) check active claims in PRISM-BUILD-CONTEXT, (3) check the relevant component section in PRISM-BUILD-VISION, (4) run \`duplicationGuardEngine.mustCheckBeforeCreating()\`. If proposing a feature not in the vision spec, add it to \`mcp-server/scripts/build-vision-spec.json\` first.`;

    emit(anchor);
    process.exit(0);
  } catch (err) {
    process.exit(0);
  }
})();
